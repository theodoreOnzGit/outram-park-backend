#!/bin/sh
# gh:#1416 fix wall/region deck: in.wallregion + wallregion_traj.csv / wallregion_thermo.txt.
# 354-pebble D/d = 6 bed settled (pebble_bed_settled.csv). NO fix wall/gran: the
# only walls are four fix wall/region, one per style:
#   h  harmonic  cylinder-z interior (axis 0,0 radius 0.030, z 0..0.4)   -> the real wall + floor
#   a  lj93      block interior  +-0.0325 x +-0.0325, z -0.002..0.4
#   b  lj126     cylinder-z interior radius 0.034, z -0.05..0.3
#   c  colloid   block interior  +-0.05, z -0.003..0.3
# thermo every 100 steps: step, ke, then f_X (energy) and f_X[1..3] (wall force).
# Usage: ./make_wallregion_deck.sh <lmp_serial> <outdir>
set -eu
lmp=$(realpath "$1"); out=$2
here=$(cd "$(dirname "$0")" && pwd)
mkdir -p "$out"; cd "$out"
sh "$here/csv2data.sh" "$here/pebble_bed_settled.csv" wallregion.data 0.01 2500 -0.005 0.35 > /dev/null
cat > "$here/in.wallregion" <<'DECK'
# gh:#1416 fix wall/region cross-code deck (generated by make_wallregion_deck.sh)
atom_style	granular
atom_modify	map array
boundary	f f f
newton		off
communicate	single vel yes
units		si
neighbor	0.003 bin
neigh_modify	delay 0
read_data	wallregion.data
fix 		m1 all property/global youngsModulus peratomtype 5.0e6
fix 		m2 all property/global poissonsRatio peratomtype 0.3
fix 		m3 all property/global coefficientRestitution peratomtypepair 1 0.5
fix 		m4 all property/global coefficientFriction peratomtypepair 1 0.3
pair_style	gran model hertz tangential history
pair_coeff	* *
timestep	5e-6
region		rh cylinder z 0.0 0.0 0.030 0.0 0.4 units box
region		ra block -0.0325 0.0325 -0.0325 0.0325 -0.002 0.4 units box
region		rb cylinder z 0.0 0.0 0.034 -0.05 0.3 units box
region		rc block -0.05 0.05 -0.05 0.05 -0.003 0.3 units box
fix		grav all gravity 9.81 vector 0 0 -1
fix		h all wall/region rh harmonic 5.0 0.0 0.012
fix		a all wall/region ra lj93 1.0e-5 0.008 0.009
fix		b all wall/region rb lj126 1.0e-6 0.010 0.012
fix		c all wall/region rc colloid 1.0e-9 0.001 0.011
fix		integr all nve/sphere
dump		d1 all custom 100 dump.wallregion id x y z vx vy vz omegax omegay omegaz
dump_modify	d1 sort id
thermo_style	custom step ke f_h f_h[1] f_h[2] f_h[3] f_a f_a[1] f_a[2] f_a[3] f_b f_b[1] f_b[2] f_b[3] f_c f_c[1] f_c[2] f_c[3]
thermo_modify	format float %.17g lost ignore norm no
thermo		100
run		2000
DECK
cp "$here/in.wallregion" in.wallregion
"$lmp" -in in.wallregion > log.wallregion 2>&1
# thermo rows only
awk '/^ *Step/ {f=1; next} /^Loop time/ {f=0} f && NF==18 {print}' log.wallregion > "$here/wallregion_thermo.txt"
sh "$here/dump2traj.sh" dump.wallregion "$here/wallregion_traj.csv"
echo done; wc -l "$here/wallregion_thermo.txt"
