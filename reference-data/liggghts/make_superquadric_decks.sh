#!/bin/sh
# Generate the gh:#1415 superquadric cross-code decks in.sq_drop and in.sq_collide
# beside this script. They need an lmp_serial built with
# -DSUPERQUADRIC_ACTIVE_FLAG -DNONSPHERICAL_ACTIVE_FLAG (recipe:
# crates/outram-park-fork-liggghts/upstream_source/README.md). One continuous run:
# frames are written with `run N pre no`. Atom sort is off and the neighbour list
# is rebuilt every step (`every 1 check no`), so a pair's contact history lives
# exactly while the bounding spheres overlap. Convert the frame dumps with
# sq2csv.sh, e.g.
#   lmp_serial -in in.sq_drop > log.txt && ./sq2csv.sh sq_drop.csv dump.F1 dump.F500 ...
set -eu
here=$(cd "$(dirname "$0")" && pwd)
cd "$here"
header() {
cat <<EOF
# gh:#1415 superquadric cross-code deck (generated by make_superquadric_decks.sh; see
# crates/outram-park-fork-liggghts/docs/verification-and-validation.md, section 4.17).
atom_style	superquadric
atom_modify	map array sort 0 0
boundary	f f f
newton		off
communicate	single vel yes
units		si
region		reg block -0.05 0.05 -0.05 0.05 -0.005 0.15 units box
create_box	1 reg
neighbor	0.002 bin
neigh_modify	delay 0 every 1 check no
fix 		m1 all property/global youngsModulus peratomtype 1.0e7
fix 		m2 all property/global poissonsRatio peratomtype 0.3
fix 		m3 all property/global coefficientRestitution peratomtypepair 1 0.5
fix 		m4 all property/global coefficientFriction peratomtypepair 1 0.4
pair_style	gran model hertz tangential history surface superquadric
pair_coeff	* *
timestep	1e-5
EOF
}
frames() {
prev=0
for s in "$@"; do
  if [ "$prev" -eq 0 ]; then echo "run $s"; else echo "run $((s - prev)) pre no"; fi
  echo "write_dump all custom dump.F$s id x y z vx vy vz omegax omegay omegaz quat1 quat2 quat3 quat4 modify sort id"
  prev=$s
done
}
# sq_drop: one cube-like superquadric (n1 = n2 = 6, half-axes 4, 3, 2.5 mm), tilted
# and spinning, falls onto a zplane wall, bounces, rocks and slides.
{ header; cat <<'EOF'
fix		zwall all wall/gran model hertz tangential history surface superquadric primitive type 1 zplane 0.0
fix		grav all gravity 9.81 vector 0 0 -1
create_atoms	1 single 0.0 0.0 0.008 units box
set		atom 1 shape 0.004 0.003 0.0025 blockiness 6 6 density 2500 quat_direct 0.9 0.3 0.2 0.1
set		atom 1 vx 0.1 vy 0. vz -0.5 omegax 3. omegay -2. omegaz 5.
fix		integr all nve/superquadric
thermo_style	custom step atoms
thermo		1000
thermo_modify	lost ignore norm no
EOF
frames 1 500 1000 1500 2000 3000 4000 6000 8000 10000; } > in.sq_drop
# sq_collide: two different superquadrics (a cube-like blob n1 = n2 = 6 and a
# rounded blob n1 = 4, n2 = 3) meet obliquely with spin; no gravity, no walls.
{ header; cat <<'EOF'
create_atoms	1 single -0.006 0.0 0.05 units box
create_atoms	1 single 0.006 0.0015 0.051 units box
set		atom 1 shape 0.004 0.003 0.0025 blockiness 6 6 density 2500 quat_direct 0.9 0.3 0.2 0.1
set		atom 2 shape 0.0035 0.003 0.004 blockiness 4 3 density 1500 quat_direct 0.7 -0.2 0.5 0.4
set		atom 1 vx 0.4 vy 0. vz 0. omegax 0. omegay 4. omegaz 0.
set		atom 2 vx -0.4 vy 0. vz 0. omegax 2. omegay 0. omegaz -3.
fix		integr all nve/superquadric
thermo_style	custom step atoms
thermo		1000
thermo_modify	lost ignore norm no
EOF
frames 1 200 400 600 800 1000 1200 1500 2000 3000; } > in.sq_collide
