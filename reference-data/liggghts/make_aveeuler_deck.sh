#!/bin/sh
# gh:#1418 fix ave/euler deck: in.aveeuler + aveeuler_thermo.txt generator.
# Settled 354-pebble bed (pebble_bed_settled.csv) in the +-0.035 m box under
# tilted gravity; ave/euler nevery 100 cell_size_relative 3 parallel no; thermo
# every 500 steps prints, for the 2x2x11 = 44 cells, f_ae columns 4 (vol_fr),
# 5-7 (v_av xyz), and 1-3 (centres) with %.17g.
# Usage: ./make_aveeuler_deck.sh <lmp_serial> <outdir>
set -eu
lmp=$(realpath "$1"); out=$2
here=$(cd "$(dirname "$0")" && pwd)
mkdir -p "$out"; cd "$out"
sh "$here/csv2data.sh" "$here/pebble_bed_settled.csv" aveeuler.data 0.01 2500 -0.005 0.35 > /dev/null
sed -i 's/^-1.0 1.0 xlo xhi/-0.035 0.035 xlo xhi/; s/^-1.0 1.0 ylo yhi/-0.035 0.035 ylo yhi/' aveeuler.data
cat > in.aveeuler <<'EOF'
# gh:#1418 fix ave/euler cross-code deck (generated by make_aveeuler_deck.sh)
atom_style	granular
atom_modify	map array
boundary	f f f
newton		off
communicate	single vel yes
units		si
neighbor	0.003 bin
neigh_modify	delay 0
read_data	aveeuler.data
fix 		m1 all property/global youngsModulus peratomtype 5.0e6
fix 		m2 all property/global poissonsRatio peratomtype 0.3
fix 		m3 all property/global coefficientRestitution peratomtypepair 1 0.5
fix 		m4 all property/global coefficientFriction peratomtypepair 1 0.3
pair_style	gran model hertz tangential history
pair_coeff	* *
timestep	5e-6
fix		cyl all wall/gran model hertz tangential history primitive type 1 zcylinder 0.030 0. 0.
fix		zwall all wall/gran model hertz tangential history primitive type 1 zplane 0.0
fix		grav all gravity 9.81 vector 0.6 0 -0.8
fix		integr all nve/sphere
fix		ae all ave/euler nevery 100 cell_size_relative 3 parallel no
EOF
printf 'thermo_style custom step' >> in.aveeuler
for i in $(seq 1 44); do for j in 1 2 3 4 5 6 7; do printf ' f_ae[%d][%d]' $i $j >> in.aveeuler; done; done
echo >> in.aveeuler
cat >> in.aveeuler <<'EOF'
thermo_modify format float %.17g lost ignore norm no
thermo 500
run 2000
EOF
"$lmp" -in in.aveeuler > log.aveeuler 2>&1
awk '/^ +Step/{f=1;next} /^Loop time/{f=0} f' log.aveeuler > "$here/aveeuler_thermo.txt"
cp in.aveeuler "$here/in.aveeuler"
cp in.aveeuler "$here/in.aveeuler"
