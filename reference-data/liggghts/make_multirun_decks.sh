#!/bin/sh
# Generate the gh:#1510 multi-`run` decks beside this script from the
# single-run decks they split. Every `run` here is a plain `run` (pre yes), so
# LIGGGHTS re-runs `lmp->init()` and `Verlet::setup()` at each one; that is
# what these decks test (GranularSystem::begin_run).
#   in.mesh_servo_2run         in.mesh_servo, run 10000 + run 10000
#   in.mesh_servo_torque_2run  in.mesh_servo_torque, run 10000 + run 10000
#   in.mesh_servo_modify       in.mesh_servo, run 8000; fix_modify target_val,
#                              ctrlParam, vel_max; run 6000; fix_modify
#                              integrate stop; run 6000
#   in.mesh_servo_auto_modify  in.mesh_servo_auto, run 10000; fix_modify ratio;
#                              run 10000
#   in.pour_pack_runs          in.pour_pack with every frame a plain `run`
#                              (in.pour_pack uses `run N pre no`)
#   in.rotating_plate_2run     in.rotating_plate, run 5000 + run 5000
#   in.mover_wiggle_2run       in.mover_wiggle, run 5000 + run 5000
# Run each with run_deck_thermo.sh (servo decks) or as in.pour_pack (pour2csv.sh).
set -eu
here=$(cd "$(dirname "$0")" && pwd)
cd "$here"

# $1 source deck, $2 new name, $3 header line; stdin: the lines that replace
# the source's final `run 20000`
split() {
  {
    echo "$3"
    grep -v '^#' "in.$1" | grep -v '^run' | sed "s/dump\.$1 /dump.$2 /"
    cat
  } > "in.$2"
}

split mesh_servo mesh_servo_2run \
  "# gh:#1510: in.mesh_servo split into two runs (init + Verlet::setup at step 10000), no fix_modify." <<'EOF'
run		10000
run		10000
EOF

split mesh_servo_torque mesh_servo_torque_2run \
  "# gh:#1510: in.mesh_servo_torque split into two runs (init + Verlet::setup at step 10000), no fix_modify." <<'EOF'
run		10000
run		10000
EOF

split mesh_servo mesh_servo_modify \
  "# gh:#1510: in.mesh_servo in three runs; fix_modify of the servo (MeshModuleStressServo::modify_param) between them." <<'EOF'
run		8000
fix_modify	plate servo/target_val 0.15 servo/ctrlParam 0.5 0.4 0.0002 servo/vel_max 0.03
run		6000
fix_modify	plate servo/integrate stop
run		6000
EOF

split mesh_servo_auto mesh_servo_auto_modify \
  "# gh:#1510: in.mesh_servo_auto in two runs; fix_modify servo/ratio between them." <<'EOF'
run		10000
fix_modify	plate servo/ratio 0.0001
run		10000
EOF

split rotating_plate rotating_plate_2run \
  "# gh:#1510: in.rotating_plate split into two runs (move/mesh rotate across a set-up)." <<'EOF'
run		5000
run		5000
EOF

split mover_wiggle mover_wiggle_2run \
  "# gh:#1510: in.mover_wiggle split into two runs (move/mesh wiggle across a set-up)." <<'EOF'
run		5000
run		5000
EOF

sed 's/ pre no$//' in.pour_pack \
  | sed '1,2c\
# gh:#1510: in.pour_pack with every frame a plain `run` (init + Verlet::setup\
# at each), generated by make_multirun_decks.sh.' > in.pour_pack_runs
