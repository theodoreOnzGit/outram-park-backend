#!/usr/bin/env bash
# Proves that boon-lay's copy of RustBCA (crates/boon-lay/src/rustbca/) is
# no_std + alloc, by compiling that exact module tree as a `#![no_std]` library.
#
# Why a separate harness: boon-lay itself is a std crate, so building boon-lay
# (for any target, wasm32-unknown-unknown included, which HAS std) cannot show
# that the module avoids std. Here the tree is mounted with #[path] inside a
# throwaway `#![no_std]` crate whose only dependencies are the no_std ones the
# module declares (rand + rand_distr without default features, petir, serde,
# anyhow), so any `std::` path, `println!`, LazyLock, or f64 method that only
# std provides fails to compile. The `rustbca-std` feature is declared but never
# enabled, so the std-gated layer is compiled out exactly as in boon-lay's
# default build.
#
# The harness lives under target/ (gitignored) with its own [workspace], lock
# file and target dir. Versions are read from the root [workspace.dependencies]
# so they cannot drift from boon-lay's.
#
# Usage: scripts/check-rustbca-no-std.sh            (host target)
#        JOBS=6 scripts/check-rustbca-no-std.sh     (default 6 jobs)
# Also checks wasm32-unknown-unknown and any installed bare-metal target
# (x86_64-unknown-none, thumbv7em-none-eabihf), and says which were skipped.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
JOBS="${JOBS:-6}"
H="$ROOT/target/rustbca-no-std-check"
mkdir -p "$H/src"

ver() { # version string of a root [workspace.dependencies] entry
    sed -n "s/^$1 = { *version = \"\([^\"]*\)\".*/\1/p; s/^$1 = \"\([^\"]*\)\".*/\1/p" "$ROOT/Cargo.toml" | head -n1
}
RAND="$(ver rand)"; RAND_DISTR="$(ver rand_distr)"; SERDE="$(ver serde)"; ANYHOW="$(ver anyhow)"
for v in RAND RAND_DISTR SERDE ANYHOW; do
    [ -n "${!v}" ] || { echo "could not read the $v version from $ROOT/Cargo.toml" >&2; exit 2; }
done

cat > "$H/Cargo.toml" <<EOF
[package]
name = "rustbca-no-std-check"
version = "0.0.0"
edition = "2024"
publish = false

[workspace]

[lib]
path = "src/lib.rs"

[features]
# Declared so cfg(feature = "rustbca-std") is a known name; never enabled.
rustbca-std = []

[dependencies]
petir = { path = "$ROOT/crates/petir", default-features = false }
rand = { version = "$RAND", default-features = false, features = ["chacha", "alloc"] }
rand_distr = { version = "$RAND_DISTR", default-features = false, features = ["alloc"] }
serde = { version = "$SERDE", default-features = false, features = ["derive", "alloc"] }
anyhow = { version = "$ANYHOW", default-features = false }
EOF

cat > "$H/src/lib.rs" <<EOF
//! Generated by scripts/check-rustbca-no-std.sh. Not part of the workspace.
#![no_std]
extern crate alloc;

#[path = "$ROOT/crates/boon-lay/src/rustbca/mod.rs"]
pub mod rustbca;
EOF

run() {
    echo "== cargo check --release -j $JOBS $*"
    (cd "$H" && cargo check --release -j "$JOBS" --lib "$@")
}

run
INSTALLED="$(rustup target list --installed 2>/dev/null || true)"
for t in wasm32-unknown-unknown x86_64-unknown-none thumbv7em-none-eabihf; do
    if grep -qx "$t" <<<"$INSTALLED"; then
        run --target "$t"
    else
        echo "== SKIPPED $t (target not installed)"
    fi
done
echo "rustbca no_std + alloc check: PASSED"
