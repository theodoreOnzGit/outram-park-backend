// zotero-html-entities.mjs — generate the HTML named character reference
// table used by kovan-literature's port of Zotero.Utilities.unescapeHTML
// (crates/kovan-literature/src/zotero/framework/html_entities.rs; GitHub
// #749).
//
// Upstream's unescapeHTML, under Node (the translation-server), parses its
// argument with jsdom and returns the document's textContent
// (utilities.js:699-722), so the table that matters is the one jsdom's HTML
// parser (parse5) uses: the WHATWG list of 2231 names, 106 of them legacy
// forms without the semicolon.
//
// The names are taken from Python's html.entities.html5 (the same WHATWG
// list) and EVERY one is checked against jsdom by parsing "&name" and reading
// textContent; the script fails if any differs. Usage:
//
//   ZOTERO_TS=/path/to/translation-server node scripts/zotero-html-entities.mjs
//
// (ZOTERO_TS defaults to <main checkout>/vendor/translation-server, whose
// node_modules supplies jsdom.)

import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { createRequire } from "node:module";

const REPO = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const TS = process.env.ZOTERO_TS
	|| [path.join(REPO, "vendor/translation-server"), path.resolve(REPO, "../../../vendor/translation-server")]
		.find((p) => fs.existsSync(path.join(p, "node_modules/jsdom")));
const require = createRequire(path.join(TS, "package.json"));
const { JSDOM } = require("jsdom");

const table = JSON.parse(execFileSync("python3", ["-c",
	"import json, html.entities as e; print(json.dumps(e.html5))"]).toString());
const names = Object.keys(table).sort();

const bad = [];
for (const name of names) {
	// A leading "x": whitespace at the very start of a document is dropped by
	// the parser (before-html/before-head insertion modes), which would hide
	// &Tab; and &NewLine;.
	const got = new JSDOM("x&" + name).window.document.documentElement.textContent.slice(1);
	if (got !== table[name]) bad.push([name, table[name], got]);
}
if (bad.length) {
	console.error("jsdom disagrees with the WHATWG list on", bad.length, "names:", bad.slice(0, 10));
	process.exit(1);
}

const esc = (s) => [...s].map((c) => `\\u{${c.codePointAt(0).toString(16).toUpperCase()}}`).join("");
const jsdomVersion = require("jsdom/package.json").version;
let out = `// Generated by scripts/zotero-html-entities.mjs; do not edit.
//
// The WHATWG HTML named character references (https://html.spec.whatwg.org/
// multipage/named-characters.html; the HTML Standard is CC BY 4.0), as listed
// in Python's html.entities.html5, each checked against jsdom ${jsdomVersion} (the
// HTML parser behind Zotero.Utilities.unescapeHTML in the Zotero
// translation-server). Names without a trailing ";" are the legacy forms the
// parser also accepts. Sorted by name (byte order) for binary search.

/// Every named character reference: (name, replacement).
pub const NAMED: &[(&str, &str)] = &[
`;
for (const name of [...names].sort((a, b) => (Buffer.from(a) < Buffer.from(b) ? -1 : 1))) {
	out += `    ("${name}", "${esc(table[name])}"),\n`;
}
out += "];\n\n/// The longest name, in characters.\n";
out += `pub const MAX_NAME_LEN: usize = ${Math.max(...names.map((n) => n.length))};\n`;
const dest = path.join(REPO, "crates/kovan-literature/src/zotero/framework/html_entities.rs");
fs.writeFileSync(dest, out);
console.log("wrote", dest, names.length, "names, all checked against jsdom", jsdomVersion);
