#[test]
fn the_parser_equals_strtold_then_narrow_on_every_case() {
    let mut n_differs_from_std = 0;
    for (s, bits) in CASES {
        let got = parse_foam_f64(s).expect("a number").to_bits();
        assert_eq!(got, *bits, "{s}");
        if s.parse::<f64>().expect("a number").to_bits() != *bits {
            n_differs_from_std += 1;
        }
    }
    // the set really does contain the double-rounding cases that Rust's parser reads differently
    assert_eq!(n_differs_from_std, 149);
}
