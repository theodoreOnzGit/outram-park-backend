/// A request to a k_eff worker (gh:#1571).
#[derive(Clone)]
pub enum KReq {
    /// Process these of `study`'s jobs, posting each product.
    Process { study: Study, jobs: Vec<usize> },
    /// Another worker's product of job `job`.
    Product { job: usize, data: bugis::web_demo::link::Floats },
    /// Every product has arrived: build the model of `study`.
    Assemble { study: Study },
    /// Sample a run's initial source.
    Source { cfg: KeffConfig, epoch: u32 },
    /// Transport a chunk.
    Chunk { cfg: KeffConfig, data: bugis::web_demo::link::Floats, epoch: u32 },
    /// The material map of a slice of `study`'s assembled geometry (the
    /// drawing rule: what the solver sees), `px` pixels across.
    Raster { study: Study, view: View, px: usize },
}

/// What a k_eff worker posts.
#[derive(Clone)]
pub enum KEv {
    Started { job: usize },
    /// A product: its words and, if read back from the cache, when it was made.
    Product { job: usize, secs: f64, data: bugis::web_demo::link::Floats, cached_ms: Option<f64> },
    Assembled(Assembly),
    Source { sites: bugis::web_demo::link::Floats, seed: u64, mesh: [f64; 9], epoch: u32 },
    ChunkDone { data: bugis::web_demo::link::Floats, secs: f64, epoch: u32 },
    /// A request failed (`epoch` 0: not a run's).
    Failed { message: String, epoch: u32 },
    /// A slice's material map (`raster`).
    Raster { view: View, w: usize, h: usize, ids: Vec<u8> },
}

/// Which slice the tab draws.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum View {
    /// x-y through the core's mid-height.
    Plan,
    /// x-z through the axis, the whole vessel and shield.
    Elevation,
}

#[cfg_attr(not(target_arch = "wasm32"), allow(dead_code))] // the wire is the browser's; tested natively
impl View {
    pub fn code(self) -> f64 {
        match self {
            View::Plan => 0.0,
            View::Elevation => 1.0,
        }
    }
    pub fn from_code(x: f64) -> View {
        if x == 1.0 {
            View::Elevation
        } else {
            View::Plan
        }
    }
    /// The slice's centre and full widths, cm.
    pub fn frame(self, study: &Study) -> (outram_mc_libs::geometry::position::Position, outram_mc_libs::geometry::plot::PlotBasis, [f64; 2]) {
        use outram_mc_libs::geometry::plot::PlotBasis;
        use outram_mc_libs::geometry::position::Position;
        let mid = m::H_CORE / 2.0;
        let r = if study.shield { m::SHIELD_COVER_R + 4.0 * m::INCH } else { m::R_VESSEL_OUT + 4.0 * m::INCH };
        match self {
            View::Plan => (Position::new(0.0, 0.0, mid), PlotBasis::Xy, [2.0 * r, 2.0 * r]),
            View::Elevation => {
                let h = if study.shield { m::SHIELD_HEIGHT + 2.0 * m::SHIELD_BASE_THICKNESS } else { m::H_CORE + 120.0 };
                (Position::new(0.0, 0.0, mid), PlotBasis::Xz, [2.0 * r, h])
            }
        }
    }
}

/// The material map of `view` of `study`'s geometry, `px` pixels across:
/// per pixel the material's index + 1, 0 for void, 254 for an overlap, 255
/// outside the model. Sampled from the assembled CSG
/// (`geometry::plot::SlicePlot::id_map`, the port of OpenMC's plotter).
pub fn raster(study: &Study, view: View, px: usize) -> (usize, usize, Vec<u8>) {
    use outram_mc_libs::geometry::plot::{SliceHit, SlicePlot};
    let (origin, basis, width) = view.frame(study);
    let w = px.clamp(16, 1024);
    let h = ((w as f64) * width[1] / width[0]).round().clamp(16.0, 2048.0) as usize;
    let plot = SlicePlot { origin, basis, width, pixels: [w, h], level: None, show_overlaps: true, meshlines: None };
    let g = study.geometry();
    let ids = plot
        .id_map(&g)
        .hits
        .iter()
        .map(|hit| match *hit {
            SliceHit::Found { material: Some(i), .. } => (i + 1).min(253) as u8,
            SliceHit::Found { material: None, .. } => 0,
            SliceHit::Overlap => 254,
            SliceHit::NotFound => 255,
        })
        .collect();
    (w, h, ids)
}

