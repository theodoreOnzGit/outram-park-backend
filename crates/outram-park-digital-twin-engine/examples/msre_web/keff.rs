//! **The worker side of the Core k_eff tab** (gh:#1571): the MSRE N-1
//! full-core Monte Carlo on a pool of workers, on the browser pipeline
//! promoted to `dhoby_ghaut::mc_web` (gh:#1572).
//!
//! The model is `outram_mc_libs::vv::msre_n1::Study`, the V&V record's
//! default as one library call (natural Mo, the whole TM-0728 shield, the
//! dimensions following temperature, U-234/U-236 in the salt), or its
//! shield-off ablation. Each worker:
//! 1. processes its share of the [`jobs`] (each planned nuclide at its
//!    temperature, then the graphite 30P law by LEAPR and, with the shield,
//!    the water's H in H₂O law) through the shared processed-data cache
//!    (`processed_cache::DataStore`: the browser's IndexedDB, or this
//!    engine's memory natively), posting each product's exact words;
//! 2. takes every other worker's products, relayed by the page;
//! 3. assembles the model ([`KeffWorker::assemble`]): every product offered
//!    to its store under the key it would have made itself, then each
//!    nuclide built through the store as any demo builds one, so a nuclide
//!    here is `Nuclide::from_tape_with_speed`'s bit for bit (the cache's own
//!    tests pin that);
//! 4. answers the page's source and chunk requests on that model
//!    (`dhoby_ghaut::mc_web::pool::csg_source` / `csg_chunk`, surface
//!    tracking), so a run is `run_keff_csg_par`'s answer bit for bit for any
//!    number of workers.
//!
//! Research, education and V&V only. NOT VALIDATED: the model's N-1 k sits
//! +1726 ± 23 pcm above ORNL-4233's (the record,
//! `crates/outram-mc-libs/verification_and_validation/msre_n1_first_criticality/README.md`).

