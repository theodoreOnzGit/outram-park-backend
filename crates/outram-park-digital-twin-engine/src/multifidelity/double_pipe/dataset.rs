/// One dataset row: what rung 3 loads.
#[derive(Debug, Clone, PartialEq)]
pub struct DatasetRow {
    /// Point id.
    pub id: String,
    /// Its split (fixed before any run).
    pub split: Split,
    /// x.
    pub input: DoublePipeInput,
    /// The CFD's outputs.
    pub output: DoublePipeOutput,
    /// The remaining numeric columns, in [`COLUMNS`] order from `q_cold`.
    pub extra: Vec<f64>,
}

fn header() -> String {
    let mut s = String::new();
    for l in PROVENANCE.lines() {
        let _ = writeln!(s, "# {l}");
    }
    s
}

/// The nine outputs as SI numbers, in [`output_from_si`]'s order.
#[must_use]
pub fn output_si(y: &DoublePipeOutput) -> [f64; 9] {
    [
        y.ua.get::<watt_per_kelvin>(),
        y.q.get::<watt>(),
        y.effectiveness.get::<ratio>(),
        y.t_hot_out.get::<kelvin>(),
        y.t_cold_out.get::<kelvin>(),
        y.dp_hot.get::<pascal>(),
        y.dp_cold.get::<pascal>(),
        y.nu_hot.get::<ratio>(),
        y.nu_cold.get::<ratio>(),
    ]
}

/// A [`DoublePipeOutput`] from the nine SI numbers of [`output_si`]'s order.
#[must_use]
pub fn output_from_si(v: &[f64]) -> DoublePipeOutput {
    DoublePipeOutput {
        ua: ThermalConductance::new::<watt_per_kelvin>(v[0]),
        q: Power::new::<watt>(v[1]),
        effectiveness: Ratio::new::<ratio>(v[2]),
        t_hot_out: ThermodynamicTemperature::new::<kelvin>(v[3]),
        t_cold_out: ThermodynamicTemperature::new::<kelvin>(v[4]),
        dp_hot: Pressure::new::<pascal>(v[5]),
        dp_cold: Pressure::new::<pascal>(v[6]),
        nu_hot: Ratio::new::<ratio>(v[7]),
        nu_cold: Ratio::new::<ratio>(v[8]),
    }
}

/// One record's CSV row (shortest round-trip floats).
#[must_use]
pub fn record_row(id: &str, split: Split, r: &CfdRecord) -> String {
    let x = r.input.to_si();
    let (qh, qc) = r.input.flow_rates();
    let mut v: Vec<String> = vec![id.to_string(), split.as_str().to_string()];
    v.extend(x.iter().map(f64::to_string));
    v.push(qh.to_string());
    v.push(qc.to_string());
    v.extend(output_si(&r.output).iter().map(f64::to_string));
    for f in [
        r.q_cold.get::<watt>(),
        r.ua_lmtd.get::<watt_per_kelvin>(),
        r.c_hot.get::<watt_per_kelvin>(),
        r.c_cold.get::<watt_per_kelvin>(),
        r.nu_mesh[0],
        r.nu_mesh[1],
        r.g_per_length[0],
        r.g_per_length[1],
        eps_ntu(&r.input, r.output.ua),
    ] {
        v.push(f.to_string());
    }
    for c in r.cells {
        v.push(c.to_string());
    }
    v.push(r.layers.to_string());
    v.push(r.flow_steps.to_string());
    v.push(r.energy_passes.to_string());
    v.push(format!("{:.2}", r.wall_seconds));
    v.join(",")
}

/// The dataset CSV for `(id, split, record)` rows.
#[must_use]
pub fn write_records(rows: &[(String, Split, CfdRecord)]) -> String {
    let mut s = header();
    s.push_str(&COLUMNS.join(","));
    s.push('\n');
    for (id, sp, r) in rows {
        s.push_str(&record_row(id, *sp, r));
        s.push('\n');
    }
    s
}

/// The profiles CSV.
#[must_use]
pub fn write_profiles(rows: &[(String, Split, CfdRecord)]) -> String {
    let mut s = header();
    s.push_str("id,layer,z [m],q_inner [W],q_outer [W],area_inner [m2],area_outer [m2],t_bulk_hot [K],t_bulk_cold [K],t_wall_inner [K],t_wall_outer [K],nu_hot_local [-],nu_cold_local [-]\n");
    for (id, _, r) in rows {
        let p = &r.profiles;
        let (nh, nc) = (p.nu_hot(), p.nu_cold());
        for l in 0..p.z.len() {
            let _ = writeln!(
                s,
                "{id},{l},{},{},{},{},{},{},{},{},{},{},{}",
                p.z[l], p.q_inner[l], p.q_outer[l], p.area_inner[l], p.area_outer[l], p.t_bulk_hot[l], p.t_bulk_cold[l], p.t_wall_inner[l], p.t_wall_outer[l], nh[l], nc[l]
            );
        }
    }
    s
}

/// Why a dataset could not be parsed.
#[derive(Debug, Clone, PartialEq)]
pub struct DatasetError(pub String);

impl std::fmt::Display for DatasetError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "dataset: {}", self.0)
    }
}

impl std::error::Error for DatasetError {}

/// Parse a dataset CSV written by [`write_records`].
///
/// # Errors
/// A header that is not [`COLUMNS`], a bad split, or a bad number.
pub fn parse_records(csv: &str) -> Result<Vec<DatasetRow>, DatasetError> {
    let mut lines = csv.lines().filter(|l| !l.starts_with('#') && !l.trim().is_empty());
    let head = lines.next().ok_or_else(|| DatasetError("empty".into()))?;
    if head != COLUMNS.join(",") {
        return Err(DatasetError(format!("header {head:?}")));
    }
    let mut out = Vec::new();
    for l in lines {
        let f: Vec<&str> = l.split(',').collect();
        if f.len() != COLUMNS.len() {
            return Err(DatasetError(format!("{} fields in {l:?}", f.len())));
        }
        let split = Split::parse(f[1]).ok_or_else(|| DatasetError(format!("split {:?}", f[1])))?;
        let nums: Vec<f64> = f[2..].iter().map(|v| v.parse::<f64>().map_err(|e| DatasetError(format!("{v:?}: {e}")))).collect::<Result<_, _>>()?;
        out.push(DatasetRow {
            id: f[0].to_string(),
            split,
            input: DoublePipeInput::si(nums[0], nums[1], nums[2], nums[3]),
            output: output_from_si(&nums[6..15]),
            extra: nums[15..].to_vec(),
        });
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn output_round_trips_and_bad_csv_is_refused() {
        let v = [1.2, 25.0, 0.55, 322.0, 327.0, 0.2, 0.1, 5.0, 6.0];
        assert_eq!(output_si(&output_from_si(&v)), v);
        assert!(parse_records("").is_err());
        assert!(parse_records("a,b\n").is_err());
        let mut ok = COLUMNS.join(",");
        ok.push('\n');
        assert_eq!(parse_records(&ok).unwrap().len(), 0);
        let bad = format!("{ok}T01,training,1\n");
        assert!(parse_records(&bad).is_err());
        let row: Vec<String> = std::iter::once("T01".to_string()).chain(std::iter::once("nope".into())).chain((0..31).map(|i| i.to_string())).collect();
        assert!(parse_records(&format!("{ok}{}\n", row.join(","))).is_err());
        assert!(header().lines().all(|l| l.starts_with("# ")));
        assert!(!DatasetError("x".into()).to_string().is_empty());
        let rows = load_committed();
        assert_eq!(rows.len(), 44);
        assert_eq!(rows.iter().filter(|r| r.split == Split::HeldOut).count(), 8);
        // The committed split is the design's.
        for (r, p) in rows.iter().zip(crate::multifidelity::double_pipe::design::design_grid()) {
            assert_eq!((r.id.as_str(), r.split, r.input), (p.id.as_str(), p.split, p.input));
        }
        assert!(COMMITTED_CSV.lines().take(7).all(|l| l.starts_with("# ")));
        assert!(COMMITTED_ONE_D_CSV.lines().filter(|l| !l.starts_with('#')).count() == 45);
    }
}
