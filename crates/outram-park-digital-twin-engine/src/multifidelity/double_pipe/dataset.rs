/// The committed dataset, parsed: 44 rows, x, split and CFD outputs (the
/// rung-3 entry point).
///
/// # Panics
/// Never for the committed file (pinned by this module's tests);
/// justified because the file is compiled in.
#[must_use]
pub fn load_committed() -> Vec<DatasetRow> {
    match parse_records(COMMITTED_CSV) {
        Ok(v) => v,
        Err(e) => panic!("committed dataset: {e}"),
    }
}

