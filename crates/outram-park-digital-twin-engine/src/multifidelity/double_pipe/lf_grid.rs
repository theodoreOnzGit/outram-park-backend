//! The low-fidelity level for co-kriging (gh:#1190, epic gh:#1177): the TUAS
//! 1-D model at **nominal θ** (uncalibrated, TUAS's textbook correlations)
//! on a dense grid, committed as `lf_grid.csv` so the MFK test does not
//! re-run 375 TUAS marches.
//!
//! **The grid, fixed before any MFK run** (V&V record
//! `crates/raffles/verification_and_validation/smt_kriging_gh1190.md`,
//! "Double pipe"):
//!
//! - Re_hot: 5 levels geometric in [10, 90] (10, √300, 30, √2700, 90);
//! - Re_cold: 5 levels geometric in [5, 45] (5, √75, 15, √675, 45);
//! - k_wall: 1, 10, 100 W/(m K) (TUAS wall levels, `one_d::WALL_K_LEVELS`;
//!   16 is left out, nothing is asked there);
//! - L: 0.10, 0.15, 0.20, 0.25, 0.30 m.
//!
//! The geometric Re levels are the uniform grid in ln Re, and they happen to
//! contain the held-out points' Re coordinates (which are geometric
//! midpoints, `design::held_out`). That puts **low-fidelity** values at the
//! held-out x, which is how co-kriging is meant to be used (the cheap model
//! is evaluated wherever it is wanted); the held-out **CFD** outputs, the
//! check, are not read by anything here.
use std::fmt::Write as _;
use std::sync::atomic::{AtomicUsize, Ordering};
use std::sync::Mutex;

use super::dataset::{output_from_si, output_si};
use super::one_d::{self, OneDError};
use super::{DoublePipeInput, DoublePipeOutput, Theta};

/// Re_hot levels.
#[must_use]
pub fn re_hot_levels() -> [f64; 5] {
    [10.0, 300.0_f64.sqrt(), 30.0, 2700.0_f64.sqrt(), 90.0]
}

/// Re_cold levels.
#[must_use]
pub fn re_cold_levels() -> [f64; 5] {
    [5.0, 75.0_f64.sqrt(), 15.0, 675.0_f64.sqrt(), 45.0]
}

/// k_wall levels \[W/(m K)\].
pub const K_WALL_LEVELS: [f64; 3] = [1.0, 10.0, 100.0];
/// Length levels \[m\].
pub const LENGTH_LEVELS: [f64; 5] = [0.10, 0.15, 0.20, 0.25, 0.30];

/// The 375 grid points, Re_hot slowest, L fastest.
#[must_use]
pub fn design() -> Vec<DoublePipeInput> {
    let mut out = Vec::with_capacity(375);
    for rh in re_hot_levels() {
        for rc in re_cold_levels() {
            for k in K_WALL_LEVELS {
                for l in LENGTH_LEVELS {
                    out.push(DoublePipeInput::si(rh, rc, k, l));
                }
            }
        }
    }
    out
}

/// Runs the 1-D model at nominal θ at every point, on `threads` threads
/// (each run is deterministic, so the result does not depend on the thread
/// count). Results in input order; `progress` gets one line per point.
///
/// # Errors
/// The first 1-D failure, with its index.
pub fn run(points: &[DoublePipeInput], threads: usize, progress: fn(&str)) -> Result<Vec<DoublePipeOutput>, String> {
    let next = AtomicUsize::new(0);
    let out: Mutex<Vec<Option<Result<DoublePipeOutput, OneDError>>>> = Mutex::new(vec![None; points.len()]);
    std::thread::scope(|s| {
        for _ in 0..threads.max(1) {
            s.spawn(|| loop {
                let i = next.fetch_add(1, Ordering::SeqCst);
                if i >= points.len() {
                    break;
                }
                let t0 = std::time::Instant::now();
                let r = one_d::try_evaluate(&points[i], &Theta::nominal());
                progress(&format!("{i} {:?} {:.1} s", points[i].to_si(), t0.elapsed().as_secs_f64()));
                if let Ok(mut g) = out.lock() {
                    g[i] = Some(r);
                }
            });
        }
    });
    let v = out.into_inner().map_err(|e| e.to_string())?;
    v.into_iter().enumerate().map(|(i, r)| r.ok_or_else(|| format!("{i}: not run"))?.map_err(|e| format!("{i}: {e}"))).collect()
}

/// Provenance line written at the top of the CSV.
pub const PROVENANCE: &str = "# gh:#1190: TUAS 1-D double pipe at nominal theta (uncalibrated) on the 5x5x3x5 grid of multifidelity::double_pipe::lf_grid.\n# Generated by: cargo run --release -p outram-park-digital-twin-engine --example double_pipe_lf_grid\n";

/// Header row: the four inputs then [`output_si`]'s nine outputs, SI.
pub const HEADER: &str = "re_hot,re_cold,k_wall_W_per_mK,length_m,ua_W_per_K,q_W,effectiveness,t_hot_out_K,t_cold_out_K,dp_hot_Pa,dp_cold_Pa,nu_hot,nu_cold";

/// The CSV (shortest round-trip floats, so it parses back bit for bit).
#[must_use]
pub fn write_csv(points: &[DoublePipeInput], outputs: &[DoublePipeOutput]) -> String {
    let mut s = String::from(PROVENANCE);
    s.push_str(HEADER);
    s.push('\n');
    for (x, y) in points.iter().zip(outputs) {
        let row: Vec<String> = x.to_si().iter().chain(output_si(y).iter()).map(f64::to_string).collect();
        let _ = writeln!(s, "{}", row.join(","));
    }
    s
}

/// Parses [`write_csv`]'s output.
///
/// # Errors
/// A row that is not 13 numbers.
pub fn parse_csv(csv: &str) -> Result<Vec<(DoublePipeInput, DoublePipeOutput)>, String> {
    csv.lines()
        .filter(|l| !l.starts_with('#') && !l.starts_with("re_hot") && !l.trim().is_empty())
        .map(|l| {
            let v: Vec<f64> = l.split(',').map(|t| t.trim().parse::<f64>().map_err(|e| format!("{l}: {e}"))).collect::<Result<_, _>>()?;
            if v.len() != 13 {
                return Err(format!("{l}: {} columns", v.len()));
            }
            Ok((DoublePipeInput::si(v[0], v[1], v[2], v[3]), output_from_si(&v[4..])))
        })
        .collect()
}

/// The committed grid (`verification_and_validation/double_pipe_mfk_gh1190/lf_grid.csv`).
pub const COMMITTED_CSV: &str = include_str!("../../../verification_and_validation/double_pipe_mfk_gh1190/lf_grid.csv");

/// [`COMMITTED_CSV`], parsed.
///
/// # Errors
/// [`parse_csv`]'s; never for the committed file (pinned by a test).
pub fn load_committed() -> Result<Vec<(DoublePipeInput, DoublePipeOutput)>, String> {
    parse_csv(COMMITTED_CSV)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The committed grid is the design, in order, and two of its rows (the
    /// cheapest and a held-out-like interior point) regenerate bit for bit;
    /// the CSV writer round-trips.
    #[test]
    fn the_committed_low_fidelity_grid_regenerates() {
        let rows = load_committed().unwrap();
        let d = design();
        assert_eq!(rows.len(), 375);
        for (r, x) in rows.iter().zip(&d) {
            assert_eq!(r.0.to_si().map(f64::to_bits), x.to_si().map(f64::to_bits));
        }
        let pick = [d.len() - 5, 3 * 75 + 2 * 15 + 3 + 2];
        let pts: Vec<DoublePipeInput> = pick.iter().map(|i| d[*i]).collect();
        let fresh = run(&pts, 2, |_| {}).unwrap();
        for (k, i) in pick.iter().enumerate() {
            assert_eq!(output_si(&fresh[k]).map(f64::to_bits), output_si(&rows[*i].1).map(f64::to_bits), "row {i}");
        }
        let again = parse_csv(&write_csv(&pts, &fresh)).unwrap();
        assert_eq!(again[1].1, fresh[1]);
        assert!(parse_csv("1,2,3").is_err());
    }
}
