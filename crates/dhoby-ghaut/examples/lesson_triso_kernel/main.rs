//! **The data of the Fission products chapter "TRISO kernel: how fission
//! products leave a bare UO2 sphere"** (maintainer design 2026-10-20):
//! every number those pages in `docs/site/science/fission-products/` take
//! from the workspace's code, written to `kernel-data.js` there.
//!
//! ```bash
//! RUSTUP_TOOLCHAIN=1.95 cargo run --release --ignore-rust-version -p dhoby-ghaut --example lesson_triso_kernel [out_dir]
//! ```
//!
//! In dhoby-ghaut because it calls boon-lay, tampines and nee_soon, which
//! dhoby-ghaut already depends on (`kernel.rs` says which call serves what).
//!
//! **Predictions, written 2026-10-20 before the first run:**
//!
//! - The code's diffusion lumping, found from `diffusion_coefficient`'s
//!   output alone over Z = 1..100, is exactly five classes: {Se, Kr, Te, I,
//!   Xe}, {Rb, Cs}, {Sr, Ba, Eu}, {Pd, Ag}, and everything else at the
//!   nominal value. Every element plates out under TRISO-ATOPS's routing
//!   except the noble gases.
//! - boon-lay's CRP-6 Monte Carlo agrees with Booth's series at the same D
//!   to within 3 standard errors at every point.
//! - Booth's R/B falls as mu^-1 at large mu (slope -1/2 against lambda): the
//!   fitted log-log slope over mu = 1e2..1e4 is -1 within 0.01.
//! - At HTR-10's core-average power the kernel's own centre-to-surface
//!   temperature rise is a few kelvin (under 10 K), and tampines' particle
//!   solution agrees with the profile integrated here to within 0.5 K.
//!
//! **Results, 2026-10-20 (first run; predictions above unedited), all as
//! predicted:**
//!
//! - Five classes: 88 elements at the nominal value, {Se, Kr, Te, I, Xe},
//!   {Rb, Cs}, {Sr, Ba, Eu}, {Pd, Ag}. Not plating out: He, Ne, Ar, Kr, Xe,
//!   Rn (the noble gases).
//! - CRP-6 Monte Carlo (Cs-137, 4000 atoms, HTR-10 kernel radius) against
//!   Booth at D t / a^2 = 0.002, 0.01, 0.04, 0.15: at 1200 C 0.1435/0.1454,
//!   0.3088/0.3085, 0.5610/0.5570, 0.8590/0.8613; at 1400 C 0.1417/0.1454,
//!   0.3190/0.3085, 0.5570/0.5570, 0.8612/0.8613; worst 1.44 standard
//!   errors.
//! - HTR-10 core average 4.4436e-2 W per particle, kernel power density
//!   6.7893e8 W/m3; the kernel's centre-to-surface rise 1.763 K (surface
//!   1000 K) and 2.231 K (1300 K) here, 1.770 and 2.239 K in tampines'
//!   particle solution (which takes k at each layer's mean temperature).
//! - The R/B slope is checked in `check-fission.js`.
//!
//! Driver glue (`main`, `native::run`, formatting): writes what `kernel.rs`
//! computes; its output is checked by `check-fission.js`. Research,
//! education and V&V only (`RESPONSIBLE_USE.md`).

#[cfg(not(any(target_arch = "wasm32", target_os = "android")))]
#[path = "kernel.rs"]
mod kernel;

#[cfg(any(target_arch = "wasm32", target_os = "android"))]
fn main() {}

#[cfg(not(any(target_arch = "wasm32", target_os = "android")))]
fn main() -> Result<(), String> {
    native::run()
}

#[cfg(not(any(target_arch = "wasm32", target_os = "android")))]
mod native {
    use petir::mathf::RealMath;
    use super::kernel::*;
    use boon_lay::prelude::decay_library::DecayLibrary;
    use boon_lay::Nuclide;
    use std::fmt::Write as _;

    fn arr(v: impl IntoIterator<Item = f64>) -> String {
        let s: Vec<String> = v.into_iter().map(|x| format!("{x:.6e}")).collect();
        format!("[{}]", s.join(","))
    }

    pub fn run() -> Result<(), String> {
        let out_dir = std::env::args().nth(1).unwrap_or_else(|| {
            concat!(env!("CARGO_MANIFEST_DIR"), "/../../docs/site/science/fission-products").to_string()
        });
        let mut js = String::new();
        writeln!(js, "// The data of the Fission products chapter \"TRISO kernel\".").unwrap();
        writeln!(js, "// GENERATED by crates/dhoby-ghaut/examples/lesson_triso_kernel/main.rs:").unwrap();
        writeln!(js, "//   RUSTUP_TOOLCHAIN=1.95 cargo run --release --ignore-rust-version -p dhoby-ghaut --example lesson_triso_kernel").unwrap();
        writeln!(js, "// Do not edit; checked by check-fission.js. Sources: boon-lay (TRISO-ATOPS groups, diffusion").unwrap();
        writeln!(js, "// correlations, plate-out routing, Booth, CRP-6 Monte Carlo, decay library), tampines (fresh UO2").unwrap();
        writeln!(js, "// conductivity, HTR-10 pebble and particle), nee_soon (HTR-10 power and fuel elements), outram-mc-libs").unwrap();
        writeln!(js, "// (HTR-10 TRISO radii). SI units: m, s, K, W, m^2/s.").unwrap();
        writeln!(js, "window.KERNEL_DATA = {{").unwrap();

        // The code's lumping.
        let t_c: Vec<f64> = (0..=80).map(|i| 400.0 + 20.0 * i as f64).collect();
        let classes = d_classes(&t_c, 100);
        println!("{} diffusion classes over Z = 1..100:", classes.len());
        write!(js, "  elements: [").unwrap();
        for z in 1..=100u32 {
            let c = classes.iter().position(|c| c.members.contains(&z)).expect("every z is in a class");
            write!(js, "{{ z: {z}, sym: \"{}\", group: \"{}\", plates: {}, dClass: {c} }},", SYMBOLS[z as usize], group_name(z), plates_out(z)).unwrap();
        }
        writeln!(js, "],").unwrap();
        writeln!(js, "  tC: {},", arr(t_c.iter().copied())).unwrap();
        writeln!(js, "  dClasses: [").unwrap();
        for c in &classes {
            let names: Vec<&str> = c.members.iter().map(|&z| SYMBOLS[z as usize]).collect();
            println!("  {} members: {}{}", c.members.len(), names.iter().take(12).cloned().collect::<Vec<_>>().join(" "), if names.len() > 12 { " ..." } else { "" });
            writeln!(js, "    {{ members: [{}], kernel: {}, graphite: {} }},", c.members.iter().map(|z| z.to_string()).collect::<Vec<_>>().join(","), arr(c.kernel.iter().copied()), arr(c.graphite.iter().copied())).unwrap();
        }
        writeln!(js, "  ],").unwrap();
        let plating: Vec<&str> = (1..=100u32).filter(|&z| !plates_out(z)).map(|z| SYMBOLS[z as usize]).collect();
        println!("  do NOT plate out: {}", plating.join(" "));

        // Booth curves on the reduced variables.
        let xs: Vec<f64> = (0..=60).map(|i| 10f64.r_powf(-6.0 + 7.0 * i as f64 / 60.0)).collect();
        let mus: Vec<f64> = (0..=60).map(|i| 10f64.r_powf(-2.0 + 6.0 * i as f64 / 60.0)).collect();
        // Full precision: check-fission.js compares the page's own series
        // with these to 1e-9 (at 7 figures the first run's gate failed on
        // the storage rounding alone).
        let full = |v: Vec<f64>| format!("[{}]", v.iter().map(|x| format!("{x:e}")).collect::<Vec<_>>().join(","));
        writeln!(js, "  booth: {{ x: {}, f: {}, mu: {}, rb: {} }},", full(xs.clone()), full(xs.iter().map(|&x| booth_fraction(x)).collect()), full(mus.clone()), full(mus.iter().map(|&m| booth_rb(m)).collect())).unwrap();

        // boon-lay's CRP-6 kernel Monte Carlo against Booth, Cs-137 in the
        // HTR-10 kernel, at reduced times chosen before the run.
        let a = outram_mc_libs::pebble_beds::fhr_pebble::TrisoSpec::HTR10_LI2014.kernel / 100.0;
        writeln!(js, "  kernelRadius: {a:.6e},").unwrap();
        write!(js, "  mcBooth: [").unwrap();
        for (k, t_c) in [1200.0, 1400.0].iter().enumerate() {
            for (j, x) in [0.002, 0.01, 0.04, 0.15].iter().enumerate() {
                let d0 = mc_vs_booth(Nuclide::Cs137, a, *t_c, 1.0, 1, 1).0;
                let time = x * a * a / d0;
                let n = 4000;
                let (d, mc, booth) = mc_vs_booth(Nuclide::Cs137, a, *t_c, time, n, 100 + (10 * k + j) as u64);
                let se = (booth * (1.0 - booth) / n as f64).sqrt();
                println!("  Cs-137 {t_c} C, D {d:.3e}, t {time:.3e} s (Dt/a2 {x}): MC {mc:.4} Booth {booth:.4} ({:+.2} se)", (mc - booth) / se);
                write!(js, "{{ tC: {t_c}, d: {d:.6e}, time: {time:.6e}, x: {x}, n: {n}, mc: {mc:.6e}, booth: {booth:.6e} }},").unwrap();
            }
        }
        writeln!(js, "],").unwrap();

        // The kernel's temperature at HTR-10's core-average power.
        let (q, p) = htr10_kernel_power_density();
        println!("  HTR-10 core average: {p:.4e} W per particle, q''' {q:.4e} W/m3 in the kernel");
        writeln!(js, "  power: {{ perParticle: {p:.6e}, qKernel: {q:.6e}, perPebble: {:.6e} }},", tampines::pebble_bed::Pebble::htr10().particles_per_pebble).unwrap();
        write!(js, "  profiles: [").unwrap();
        for ts in [1000.0, 1300.0] {
            let prof = sphere_profile(q, a, ts, 200, k_uo2);
            let (tc_t, ts_t) = tampines_particle(p, ts);
            // tampines' kernel rise alone (centre minus kernel surface).
            println!("  surface {ts} K: centre rise {:.4} K here, {:.4} K in tampines' particle (kernel part)", prof[0].1 - ts, tc_t - ts_t);
            write!(js, "{{ tSurf: {ts}, r: {}, t: {}, tampinesRise: {:.6e} }},", arr(prof.iter().step_by(10).map(|p| p.0)), arr(prof.iter().step_by(10).map(|p| p.1)), tc_t - ts_t).unwrap();
        }
        writeln!(js, "],").unwrap();
        writeln!(js, "  kUo2: {{ t: {}, k: {} }},", arr((0..=17).map(|i| 300.0 + 100.0 * i as f64)), arr((0..=17).map(|i| k_uo2(300.0 + 100.0 * i as f64)))).unwrap();

        // Half-lives for the R/B fingerprint: the noble-gas isotopes the
        // library carries among a candidate list.
        let lib = DecayLibrary::new();
        write!(js, "  rbIsotopes: [").unwrap();
        for n in [Nuclide::Kr85m, Nuclide::Kr87, Nuclide::Kr88, Nuclide::Kr89, Nuclide::Kr90, Nuclide::Xe133, Nuclide::Xe135, Nuclide::Xe135m, Nuclide::Xe137, Nuclide::Xe138, Nuclide::Xe139] {
            match half_life_s(&lib, n) {
                Some(t) => write!(js, "{{ name: \"{:?}\", t12: {t:.6e} }},", n).unwrap(),
                None => println!("  {n:?}: no half-life in the library, left out"),
            }
        }
        writeln!(js, "]").unwrap();
        writeln!(js, "}};").unwrap();
        let path = std::path::Path::new(&out_dir).join("kernel-data.js");
        std::fs::write(&path, js).map_err(|e| format!("{}: {e}", path.display()))?;
        println!("wrote {}", path.display());
        Ok(())
    }
}
