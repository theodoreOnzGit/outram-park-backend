//! **The data of the Fission products chapter "Barriers: from bare kernel to
//! TRISO"** (maintainer design 2026-10-20), written to `barrier-data.js` in
//! `docs/site/science/fission-products/`.
//!
//! ```bash
//! RUSTUP_TOOLCHAIN=1.95 cargo run --release --ignore-rust-version -p dhoby-ghaut --example lesson_barriers [out_dir]
//! ```
//!
//! - Per-layer D for Ag-110m, Cs-137, Sr-90 and Kr-85 in the kernel, buffer,
//!   PyC and SiC, from boon-lay's Lagrangian walker (`layers.rs`), and the
//!   TRISO-ATOPS graphite and SiC-Ag correlations, 600-1800 °C.
//! - HTR-10 TRISO layer thicknesses from `TrisoSpec::HTR10_LI2014`, and the
//!   diffusion time scale l^2/D across each layer.
//!
//! **Predictions, written 2026-10-20 before the first run:**
//!
//! - For Ag, Cs and Sr, the SiC layer's crossing time exceeds the IPyC
//!   layer's by at least a factor 10 at every temperature from 800 to
//!   1600 °C (carbon leaks metals; SiC holds them better).
//! - Kr's IPyC crossing time exceeds a year at 1000 °C (carbon holds gases).
//! - Kr in the buffer has no coefficient (a `todo!()` in boon-lay).
//!
//! What the run gave is in `check-fission.js` and the page.
//!
//! Driver glue (`main`, `native::run`): writes what `layers.rs` computes;
//! its output is checked by `check-fission.js`. Research, education and V&V
//! only (`RESPONSIBLE_USE.md`).

#[cfg(not(any(target_arch = "wasm32", target_os = "android")))]
#[path = "layers.rs"]
mod layers;

#[cfg(any(target_arch = "wasm32", target_os = "android"))]
fn main() {}

#[cfg(not(any(target_arch = "wasm32", target_os = "android")))]
fn main() -> Result<(), String> {
    native::run()
}

#[cfg(not(any(target_arch = "wasm32", target_os = "android")))]
mod native {
    use super::layers::*;
    use boon_lay::prelude::{diffusion_coefficient, diffusion_coefficient_sic_ag};
    use boon_lay::Nuclide;
    use std::fmt::Write as _;
    use uom::si::diffusion_coefficient::square_meter_per_second;
    use uom::si::f64::ThermodynamicTemperature;
    use uom::si::thermodynamic_temperature::degree_celsius;

    fn arr(v: impl IntoIterator<Item = Option<f64>>) -> String {
        let s: Vec<String> = v.into_iter().map(|x| x.map_or("null".to_string(), |x| format!("{x:.6e}"))).collect();
        format!("[{}]", s.join(","))
    }

    pub fn run() -> Result<(), String> {
        let out_dir = std::env::args().nth(1).unwrap_or_else(|| {
            concat!(env!("CARGO_MANIFEST_DIR"), "/../../docs/site/science/fission-products").to_string()
        });
        let t_c: Vec<f64> = (0..=24).map(|i| 600.0 + 50.0 * i as f64).collect();
        let mut js = String::new();
        writeln!(js, "// The data of the Fission products chapter \"Barriers\".").unwrap();
        writeln!(js, "// GENERATED by crates/dhoby-ghaut/examples/lesson_barriers/main.rs:").unwrap();
        writeln!(js, "//   RUSTUP_TOOLCHAIN=1.95 cargo run --release --ignore-rust-version -p dhoby-ghaut --example lesson_barriers").unwrap();
        writeln!(js, "// Do not edit; checked by check-fission.js. D in m^2/s (null: boon-lay has no value there),").unwrap();
        writeln!(js, "// thicknesses in m (TrisoSpec::HTR10_LI2014), temperatures in °C.").unwrap();
        writeln!(js, "window.BARRIER_DATA = {{").unwrap();
        writeln!(js, "  tC: {},", arr(t_c.iter().map(|&t| Some(t)))).unwrap();
        write!(js, "  thickness: {{").unwrap();
        for (name, l) in htr10_thicknesses() {
            write!(js, " \"{name}\": {l:.6e},").unwrap();
        }
        writeln!(js, " }},").unwrap();
        writeln!(js, "  walker: [").unwrap();
        for (name, n) in [("Ag", Nuclide::Ag110m), ("Cs", Nuclide::Cs137), ("Sr", Nuclide::Sr90), ("Kr", Nuclide::Kr85)] {
            for (lname, layer) in layers() {
                let d: Vec<Option<f64>> = t_c.iter().map(|&t| walker_d(layer, n, t)).collect();
                if d.iter().all(|x| x.is_none()) {
                    println!("  {name} in {lname}: no coefficient in boon-lay");
                }
                writeln!(js, "    {{ el: \"{name}\", layer: \"{lname}\", d: {} }},", arr(d)).unwrap();
            }
        }
        writeln!(js, "  ],").unwrap();
        let temp = |c: f64| ThermodynamicTemperature::new::<degree_celsius>(c);
        writeln!(js, "  atops: [").unwrap();
        for (name, z) in [("Ag", 47u32), ("Cs", 55), ("Sr", 38), ("Kr", 36)] {
            let g: Vec<Option<f64>> = t_c.iter().map(|&t| Some(diffusion_coefficient(z, temp(t), temp(t)).graphite.get::<square_meter_per_second>())).collect();
            writeln!(js, "    {{ el: \"{name}\", layer: \"graphite\", d: {} }},", arr(g)).unwrap();
        }
        let s: Vec<Option<f64>> = t_c.iter().map(|&t| Some(diffusion_coefficient_sic_ag(temp(t)).get::<square_meter_per_second>())).collect();
        writeln!(js, "    {{ el: \"Ag\", layer: \"SiC\", d: {} }},", arr(s)).unwrap();
        writeln!(js, "  ]").unwrap();
        writeln!(js, "}};").unwrap();

        // The predictions, printed for the record.
        let th = htr10_thicknesses();
        let (ipyc, sic) = (th[2].1, th[3].1);
        for (name, n) in [("Ag", Nuclide::Ag110m), ("Cs", Nuclide::Cs137), ("Sr", Nuclide::Sr90), ("Kr", Nuclide::Kr85)] {
            for t in [800.0, 1000.0, 1200.0, 1400.0, 1600.0] {
                let tp = walker_d(boon_lay::lagrangian_decay_simulator::lagrangian_diffusion::temperature_dependent_collisions::TrisoPebbleLayerMaterial::PyC, n, t).map(|d| crossing_time(ipyc, d));
                let ts = walker_d(boon_lay::lagrangian_decay_simulator::lagrangian_diffusion::temperature_dependent_collisions::TrisoPebbleLayerMaterial::SiC, n, t).map(|d| crossing_time(sic, d));
                println!("  {name} {t} C: IPyC {:?} s, SiC {:?} s", tp.map(|x| format!("{x:.3e}")), ts.map(|x| format!("{x:.3e}")));
            }
        }
        let path = std::path::Path::new(&out_dir).join("barrier-data.js");
        std::fs::write(&path, js).map_err(|e| format!("{}: {e}", path.display()))?;
        println!("wrote {}", path.display());
        Ok(())
    }
}
