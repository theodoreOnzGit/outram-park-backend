/// Natively: `--rung <name>`, the twin of the URL query; `--headless <rung>`
/// prints that rung's default calculation as CSV with no window.
#[cfg(all(not(target_os = "android"), not(target_arch = "wasm32")))]
fn main() -> Result<(), String> {
    let args: Vec<String> = std::env::args().collect();
    if let Some(i) = args.iter().position(|a| a == "--headless") {
        let name = args.get(i + 1).map(String::as_str).unwrap_or("failure");
        let rung = dhoby_ghaut::web_demo::lesson::parse::<rungs::Rung>(name)
            .ok_or_else(|| format!("unknown rung '{name}'"))?;
        return headless(rung);
    }
    if let Some(i) = args.iter().position(|a| a == "--record-walks") {
        let path = args.get(i + 1).ok_or("--record-walks needs an output path")?;
        return record_walks(path);
    }
    let rung: rungs::Rung =
        dhoby_ghaut::web_demo::lesson::from_query(&dhoby_ghaut::web_demo::platform::query_pairs());
    eframe::run_native(
        "TRISO-ATOPS demo",
        eframe::NativeOptions::default(),
        Box::new(move |cc| Ok(Box::new(app::TrisoApp::new(cc, rung)))),
    )
    .map_err(|e| e.to_string())
}

/// Writes `atops-walk-recorded.js`, the demo's own headless release and
/// source-term CSVs that the ATOPS concept walks quote (gh:#1207):
/// `cargo run --release -p dhoby-ghaut --example triso_atops_web --
/// --record-walks docs/site/science/fission-products/atops-walk-recorded.js`.
/// CLI glue: its output is checked by `check-concepts.js`, and
/// `headless_csv` is reached by the `headless_release_has_both_hours` test.
#[cfg(all(not(target_os = "android"), not(target_arch = "wasm32")))]
fn record_walks(path: &str) -> Result<(), String> {
    let release = headless_csv(rungs::Rung::Release)?;
    let source = headless_csv(rungs::Rung::SourceTerm)?;
    let js = format!(
        "// GENERATED by `triso_atops_web --record-walks` (gh:#1207); do not edit.\n\
         // The demo's headless release rung (default controls) and its recorded source term.\n\
         window.ATOPS_WALK_RECORDED={{command:\"--headless release\",csv:{:?},sourceTerm:{:?}}};\n",
        release, source
    );
    std::fs::write(path, js).map_err(|e| format!("{path}: {e}"))?;
    println!("wrote {path}");
    Ok(())
}

/// One rung's default calculation (the app's default controls) as CSV:
/// `series,label,x,y` rows, then `scalar,index,value` rows.
#[cfg(all(not(target_os = "android"), not(target_arch = "wasm32")))]
fn headless(rung: rungs::Rung) -> Result<(), String> {
    print!("{}", headless_csv(rung)?);
    Ok(())
}

/// The CSV of [`headless`], as a string (also what `--record-walks` stores).
#[cfg(all(not(target_os = "android"), not(target_arch = "wasm32")))]
fn headless_csv(rung: rungs::Rung) -> Result<String, String> {
    use engine::Request;
    use std::fmt::Write as _;
    let mut out_csv = String::new();
    let req = match rung {
        rungs::Rung::Triso => Request::Slice { id: 1, geometry: 0, cells: 200 },
        rungs::Rung::Decay => Request::Decay { id: 1, nuclide: 0, t_over_half: 1.0 },
        rungs::Rung::Walk => Request::WalkCheck { id: 1, temp_c: 1200.0 },
        rungs::Rung::Layers => Request::Layers { id: 1, nuclide: 0, temp_c: 1600.0 },
        rungs::Rung::Failure => Request::Failure {
            id: 1,
            irr_c: 776.0,
            hold_c: 1800.0,
            hours: 500.0,
            cursor_h: 500.0,
        },
        rungs::Rung::Chemistry => Request::Chemistry { id: 1, o2_kpa: 21.3, steam_kpa: 5.0, h2_kpa: 0.0 },
        rungs::Rung::Release => Request::Release {
            id: 1,
            irr_c: 776.0,
            hold_c: 1800.0,
            hours: 500.0,
            f_hm: 1.0e-4,
            k_plate: 7.5e-5,
            k_clean: 8.77e-5,
            // The app's default: HTR-10's 1 %/day primary-helium leakage
            // (Liu & Cao 2002, Section 2.4.1).
            k_leak: 0.01 / 86_400.0,
        },
        rungs::Rung::SourceTerm => {
            let _ = writeln!(out_csv, "nuclide,released_bq,core_bq");
            for (n, bq, core) in recorded::RELEASE {
                let _ = writeln!(out_csv, "{n},{bq:e},{core:e}");
            }
            return Ok(out_csv);
        }
    };
    let mut out = Vec::new();
    engine::Engine::default().serve(req, &mut |e| out.push(e));
    match out.pop() {
        Some(engine::Event::Frame(f)) if rung == rungs::Rung::Release => {
            // Every nuclide at the start of the hold (hour 0: the end of
            // the 40-year normal operation at the irradiation temperature)
            // and at its end (gh:#1207 added the hour-0 rows and the last
            // two columns, for the ATOPS concept walks).
            let (n, p) = engine::release_dims(&f);
            let hours = f.series.first().map(|s| s.xs.clone()).unwrap_or_default();
            let _ = writeln!(out_csv, "nuclide,group,source_atoms_per_s,circulating_bq,plated_bq,hps_bq,leaked_atoms,graphite_bq,release_atoms_per_s,hour");
            for pt in [0, p.saturating_sub(1)] {
                for i in 0..n {
                    let lam = engine::release_header(&f, i, 1);
                    let v = |k| engine::release_value(&f, i, pt, k);
                    let _ = writeln!(out_csv, 
                        "{},{},{:e},{:e},{:e},{:e},{:e},{:e},{:e},{}",
                        f.names[i],
                        engine::GROUPS[f.tags[i] as usize].replace(',', ";"), // a CSV field: no commas
                        v(engine::rel::S),
                        lam * v(engine::rel::C),
                        lam * v(engine::rel::P),
                        lam * v(engine::rel::H),
                        v(engine::rel::LEAKED),
                        lam * v(engine::rel::G),
                        v(engine::rel::R),
                        hours.get(pt).copied().unwrap_or(f64::NAN)
                    );
                }
            }
            Ok(out_csv)
        }
        Some(engine::Event::Frame(f)) => {
            let _ = writeln!(out_csv, "kind,label,x,y");
            for s in &f.series {
                for (x, y) in s.xs.iter().zip(&s.ys) {
                    let _ = writeln!(out_csv, "series,\"{}\",{x:e},{y:e}", s.label);
                }
            }
            for (i, v) in f.scalars.iter().enumerate() {
                let _ = writeln!(out_csv, "scalar,{i},,{v:e}");
            }
            Ok(out_csv)
        }
        Some(engine::Event::Error(e)) => Err(e),
        None => Err("no answer".into()),
    }
}

/// In the browser this module runs twice: on the page, where it starts the
/// egui app, and in the Web Worker (`web/triso_atops/worker.js`), where there
/// is no `window` and it serves the engine instead.
#[cfg(target_arch = "wasm32")]
fn main() {
    use eframe::wasm_bindgen::JsCast as _;
    eframe::WebLogger::init(log::LevelFilter::Info).ok();
    if js_sys::global()
        .dyn_ref::<web_sys::DedicatedWorkerGlobalScope>()
        .is_some()
    {
        dhoby_ghaut::web_demo::link::worker_main::<engine::Engine>();
        return;
    }
    let rung: rungs::Rung =
        dhoby_ghaut::web_demo::lesson::from_query(&dhoby_ghaut::web_demo::platform::query_pairs());
    let web_options = eframe::WebOptions {
        renderer: eframe::Renderer::Wgpu,
        ..Default::default()
    };
    wasm_bindgen_futures::spawn_local(async move {
        let document = web_sys::window()
            .expect("no window")
            .document()
            .expect("no document");
        let canvas = document
            .get_element_by_id("triso_canvas")
            .expect("no #triso_canvas")
            .dyn_into::<web_sys::HtmlCanvasElement>()
            .expect("#triso_canvas is not a canvas");
        let started = eframe::WebRunner::new()
            .start(
                canvas,
                web_options,
                Box::new(move |cc| Ok(Box::new(app::TrisoApp::new(cc, rung)))),
            )
            .await;
        if let Some(el) = document.get_element_by_id("loading") {
            match started {
                Ok(()) => el.remove(),
                Err(e) => el.set_inner_html(&format!("<p>Failed to start: {e:?}</p>")),
            }
        }
    });
}

#[cfg(all(test, not(target_os = "android"), not(target_arch = "wasm32")))]
mod walk_record_tests {
    /// `--record-walks` stores this CSV for the ATOPS concept walks, which
    /// read rows at hour 0 (end of normal operation) and at the end of the
    /// hold: both must be there for every nuclide, and the source term must
    /// list the recorded nuclides.
    #[test]
    fn headless_release_has_both_hours() {
        let csv = super::headless_csv(super::rungs::Rung::Release).unwrap();
        let mut lines = csv.lines();
        assert!(lines.next().unwrap().ends_with(",release_atoms_per_s,hour"));
        let rows: Vec<&str> = lines.collect();
        assert!(rows.len() >= 2 && rows.len() % 2 == 0);
        assert!(rows.iter().any(|r| r.starts_with("Cs-137,") && r.ends_with(",0")));
        // Ten columns on every row: a group name with a comma would split.
        assert!(rows.iter().all(|r| r.split(',').count() == 10), "{rows:?}");
        let last_hour = rows.last().unwrap().rsplit(',').next().unwrap().parse::<f64>().unwrap();
        assert!(last_hour > 0.0);
        let st = super::headless_csv(super::rungs::Rung::SourceTerm).unwrap();
        assert!(st.starts_with("nuclide,released_bq,core_bq\n") && st.contains("Cs-137,"));
    }
}
