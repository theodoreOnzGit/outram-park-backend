/// Quote a CSV field the way Python's `QUOTE_MINIMAL` does: only when the field
/// contains the delimiter, a quote, or a line break; embedded quotes doubled.
fn csv_field(value: &str) -> String {
    let needs_quotes =
        value.contains(',') || value.contains('"') || value.contains('\n') || value.contains('\r');
    if needs_quotes {
        format!("\"{}\"", value.replace('"', "\"\""))
    } else {
        value.to_string()
    }
}

/// Join one CSV record, terminated CRLF (see the module docs).
fn csv_row(fields: &[String]) -> String {
    let joined: Vec<String> = fields.iter().map(|f| csv_field(f)).collect();
    format!("{}\r\n", joined.join(","))
}

/// Render `baseline_repositories.csv`.
pub fn baseline_csv(base_stats: &[RepoStats]) -> String {
    let mut out = csv_row(&[
        "repository".into(),
        "ref".into(),
        "first_commit".into(),
        "last_commit".into(),
        "total_lines".into(),
        "code_lines".into(),
        "active_days".into(),
        "rust_files".into(),
        "ai_assistance".into(),
    ]);
    for stats in base_stats {
        if stats.missing {
            out.push_str(&csv_row(&[
                stats.key.clone(),
                String::new(),
                String::new(),
                String::new(),
                String::new(),
                String::new(),
                String::new(),
                String::new(),
                "MISSING".into(),
            ]));
            continue;
        }
        out.push_str(&csv_row(&[
            stats.key.clone(),
            stats.reference.clone(),
            stats.first.clone(),
            stats.last.clone(),
            stats.lines.total.to_string(),
            stats.lines.code.to_string(),
            stats.days.len().to_string(),
            stats.lines.files.to_string(),
            stats.note.clone(),
        ]));
    }
    out
}

/// Render `agentic_crates.csv`.
pub fn agentic_csv(crate_rows: &[CrateStats]) -> String {
    let mut out = csv_row(&[
        "crate".into(),
        "class".into(),
        "upstream".into(),
        "total_lines".into(),
        "code_lines_in_backend".into(),
        "preagentic_baseline_code_lines".into(),
        "agentic_code_lines".into(),
        "cargo_toml_description".into(),
    ]);
    for row in crate_rows {
        out.push_str(&csv_row(&[
            row.display.clone(),
            row.class.key().to_string(),
            row.upstream.clone().unwrap_or_default(),
            row.total_lines.to_string(),
            row.raw_code_lines.to_string(),
            row.baseline_code_lines.to_string(),
            row.code_lines.to_string(),
            row.description.clone(),
        ]));
    }
    out
}

