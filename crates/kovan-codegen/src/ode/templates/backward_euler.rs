/// One step of the implicit **backward (implicit) Euler** method for
/// `dy/dt = f(t, y)`.
///
/// Backward Euler is defined by `y_{n+1} = y_n + h f(t_{n+1}, y_{n+1})`, an
/// implicit equation in the unknown `y_{n+1}`. This template solves that
/// equation with a Newton iteration whose derivative is obtained by a
/// forward finite difference (so the caller need not supply `df/dy`). Backward
/// Euler is A-stable — it stays bounded for stiff decay problems at any step
/// size — and first-order accurate (global error `O(h)`).
///
/// # Arguments
/// * `f` — right-hand side `f(t, y)`.
/// * `t`, `y` — current time and state.
/// * `h` — step size.
///
/// # Returns
/// `Some(y_{n+1})` on convergence of the inner Newton solve, or `None` if the
/// finite-difference derivative underflows or the inner solve fails to converge.
///
/// Generated by kovan-codegen (docs/kovan.md § "Numerical Methods → ODE
/// Solvers"). Deterministic template; depends only on `core`/`std` `f64`.
pub fn backward_euler_step<F>(f: &F, t: f64, y: f64, h: f64) -> Option<f64>
where
    F: Fn(f64, f64) -> f64,
{
    let t1 = t + h;
    let mut yn = y; // initial guess: previous state
    for _ in 0..100 {
        // Residual of the implicit relation, and its finite-difference slope.
        let g = yn - y - h * f(t1, yn);
        let eps = 1e-8 * (1.0 + yn.abs());
        let g_eps = (yn + eps) - y - h * f(t1, yn + eps);
        let dg = (g_eps - g) / eps;
        if dg.abs() < 1e-300 {
            return None;
        }
        let step = g / dg;
        yn -= step;
        if step.abs() <= 1e-13 * (1.0 + yn.abs()) {
            return Some(yn);
        }
    }
    None
}

/// Integrate `dy/dt = f(t, y)` from `(t0, y0)` for `n` steps of size `h` with
/// backward Euler, returning the `(t, y)` trajectory (length `n + 1`).
/// Returns `None` if any implicit step fails to converge.
pub fn backward_euler_integrate<F>(
    f: F,
    t0: f64,
    y0: f64,
    h: f64,
    n: usize,
) -> Option<Vec<(f64, f64)>>
where
    F: Fn(f64, f64) -> f64,
{
    let mut out = Vec::with_capacity(n + 1);
    let mut t = t0;
    let mut y = y0;
    out.push((t, y));
    for _ in 0..n {
        y = backward_euler_step(&f, t, y, h)?;
        t += h;
        out.push((t, y));
    }
    Some(out)
}
