/// Solve the 1-D Poisson equation `-u''(x) = s(x)` on `[x0, x1]` with Dirichlet
/// boundary conditions by **second-order central finite differences** on a
/// uniform grid, resolving the resulting tridiagonal system with the **Thomas
/// algorithm** (`O(n)`).
///
/// The domain is split into `n_cells` equal intervals, giving `n_cells + 1`
/// nodes at spacing `dx = (x1 - x0) / n_cells`. Interior nodes use the standard
/// stencil `(-u_{i-1} + 2 u_i - u_{i+1}) / dx^2 = s(x_i)`; the two boundary
/// nodes are pinned to `u_left` and `u_right`. The scheme is second-order
/// accurate (`O(dx^2)`).
///
/// # Arguments
/// * `x0`, `x1`   — domain endpoints (`x1 > x0`).
/// * `n_cells`    — number of cells (`>= 2`); yields `n_cells + 1` nodes.
/// * `source`     — source term `s(x)` (the right-hand side of `-u'' = s`).
/// * `u_left`     — Dirichlet value at `x0`.
/// * `u_right`    — Dirichlet value at `x1`.
///
/// # Returns
/// `Some((xs, us))` with the node coordinates and the solution values, or
/// `None` if `n_cells < 2` or `x1 <= x0`.
///
/// Generated by kovan-codegen (docs/kovan.md § "Numerical Methods → PDE
/// Infrastructure"). Deterministic template; depends only on `core`/`std` `f64`.
pub fn solve_poisson_1d<S>(
    x0: f64,
    x1: f64,
    n_cells: usize,
    source: S,
    u_left: f64,
    u_right: f64,
) -> Option<(Vec<f64>, Vec<f64>)>
where
    S: Fn(f64) -> f64,
{
    if n_cells < 2 || x1 <= x0 {
        return None;
    }
    let n_nodes = n_cells + 1;
    let dx = (x1 - x0) / n_cells as f64;
    let inv_dx2 = 1.0 / (dx * dx);
    let xs: Vec<f64> = (0..n_nodes).map(|i| x0 + i as f64 * dx).collect();

    // Tridiagonal system for interior unknowns u_1 .. u_{n_nodes-2}.
    let m = n_nodes - 2;
    let mut lower = vec![0.0; m]; // sub-diagonal
    let mut diag = vec![0.0; m];
    let mut upper = vec![0.0; m]; // super-diagonal
    let mut rhs = vec![0.0; m];
    for k in 0..m {
        let i = k + 1; // node index
        lower[k] = -inv_dx2;
        diag[k] = 2.0 * inv_dx2;
        upper[k] = -inv_dx2;
        rhs[k] = source(xs[i]);
    }
    // Fold the Dirichlet boundary values into the first/last equations: the
    // known u_left/u_right multiply the eliminated off-diagonal coefficients.
    rhs[0] += inv_dx2 * u_left;
    rhs[m - 1] += inv_dx2 * u_right;

    let interior = thomas_solve(&lower, &diag, &upper, &rhs)?;

    let mut us = vec![0.0; n_nodes];
    us[0] = u_left;
    us[n_nodes - 1] = u_right;
    us[1..(n_nodes - 1)].copy_from_slice(&interior);
    Some((xs, us))
}

/// Solve a tridiagonal system `T x = d` by the Thomas algorithm (`O(n)`),
/// where `sub`, `diag`, `sup` are the sub-/main-/super-diagonals. `sub[0]` and
/// `sup[n-1]` are unused. Returns `None` on a zero pivot.
fn thomas_solve(sub: &[f64], diag: &[f64], sup: &[f64], d: &[f64]) -> Option<Vec<f64>> {
    let n = diag.len();
    if n == 0 {
        return Some(Vec::new());
    }
    let mut c = vec![0.0; n]; // modified super-diagonal
    let mut e = vec![0.0; n]; // modified right-hand side
    if diag[0] == 0.0 {
        return None;
    }
    c[0] = sup[0] / diag[0];
    e[0] = d[0] / diag[0];
    for i in 1..n {
        let denom = diag[i] - sub[i] * c[i - 1];
        if denom == 0.0 {
            return None;
        }
        c[i] = sup[i] / denom;
        e[i] = (d[i] - sub[i] * e[i - 1]) / denom;
    }
    let mut x = vec![0.0; n];
    x[n - 1] = e[n - 1];
    for i in (0..n - 1).rev() {
        x[i] = e[i] - c[i] * x[i + 1];
    }
    Some(x)
}
