/// Find a root of `f` in `[a, b]` by the **regula falsi** (false-position)
/// method.
///
/// Like bisection it keeps a sign-changing bracket `[a, b]`, but instead of the
/// midpoint it takes the x-intercept of the secant line through the endpoints:
/// `c = b - f(b) (b - a) / (f(b) - f(a))`. It always retains a bracket (so it is
/// robust like bisection) and is usually faster, though on strongly convex or
/// concave functions one endpoint can stagnate — the Illinois and Pegasus
/// variants cure that stagnation (catalogued but not yet generated).
///
/// # Arguments
/// * `f`        — continuous function whose root is sought.
/// * `a`, `b`   — bracket endpoints; **must** satisfy `f(a) * f(b) <= 0`.
/// * `tol`      — absolute tolerance: stop when `|f(c)| <= tol`.
/// * `max_iter` — iteration cap.
///
/// # Returns
/// `Some(root)` on convergence, otherwise `None` (invalid bracket, degenerate
/// secant, or non-convergence).
///
/// Generated by kovan-codegen (docs/kovan.md § "Numerical Methods → Root
/// Finding"). Deterministic template; depends only on `core`/`std` `f64`.
pub fn regula_falsi<F>(f: F, a: f64, b: f64, tol: f64, max_iter: usize) -> Option<f64>
where
    F: Fn(f64) -> f64,
{
    let mut a = a;
    let mut b = b;
    let mut fa = f(a);
    let mut fb = f(b);
    if fa * fb > 0.0 {
        return None;
    }
    for _ in 0..max_iter {
        let denom = fb - fa;
        if denom.abs() < 1e-300 {
            return None;
        }
        let c = b - fb * (b - a) / denom;
        let fc = f(c);
        if fc.abs() <= tol {
            return Some(c);
        }
        if fa * fc < 0.0 {
            b = c;
            fb = fc;
        } else {
            a = c;
            fa = fc;
        }
    }
    None
}
