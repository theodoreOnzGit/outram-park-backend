/// Find a root of `f` in `[a, b]` by **Brent's** method.
///
/// Brent's method combines the guaranteed convergence of bisection with the
/// speed of the secant method and inverse quadratic interpolation. It keeps a
/// bracket `[a, b]` with `f(a) * f(b) <= 0` and, at each step, attempts an
/// interpolation step, falling back to a bisection step whenever the interpolant
/// would leave the bracket or fail to shrink it fast enough. It converges
/// superlinearly without ever losing the bracket. This is the classic Brent
/// (1973) / `zeroin` formulation.
///
/// # Arguments
/// * `f`        — continuous function whose root is sought.
/// * `a`, `b`   — bracket endpoints; **must** satisfy `f(a) * f(b) <= 0`.
/// * `tol`      — absolute tolerance on `x`.
/// * `max_iter` — iteration cap.
///
/// # Returns
/// `Some(root)` on convergence, otherwise `None` (invalid bracket or
/// non-convergence).
///
/// Generated by kovan-codegen (docs/kovan.md § "Numerical Methods → Root
/// Finding"). Deterministic template; depends only on `core`/`std` `f64`.
pub fn brent<F>(f: F, a: f64, b: f64, tol: f64, max_iter: usize) -> Option<f64>
where
    F: Fn(f64) -> f64,
{
    let mut a = a;
    let mut b = b;
    let mut fa = f(a);
    let mut fb = f(b);
    if fa * fb > 0.0 {
        return None;
    }
    // Ensure |f(b)| <= |f(a)| so that `b` is the best current estimate.
    if fa.abs() < fb.abs() {
        std::mem::swap(&mut a, &mut b);
        std::mem::swap(&mut fa, &mut fb);
    }
    let mut c = a;
    let mut fc = fa;
    let mut d = c; // penultimate iterate; read only after `mflag` is cleared.
    let mut mflag = true;
    for _ in 0..max_iter {
        if fb == 0.0 || (b - a).abs() <= tol {
            return Some(b);
        }
        let mut s;
        if fa != fc && fb != fc {
            // Inverse quadratic interpolation through (a, b, c).
            s = a * fb * fc / ((fa - fb) * (fa - fc))
                + b * fa * fc / ((fb - fa) * (fb - fc))
                + c * fa * fb / ((fc - fa) * (fc - fb));
        } else {
            // Secant step through (a, b).
            s = b - fb * (b - a) / (fb - fa);
        }
        // Accept the interpolation step only if it is well behaved; otherwise
        // bisect. These are the standard five Brent guard conditions.
        let lo = (3.0 * a + b) / 4.0;
        let outside = !((s > lo && s < b) || (s < lo && s > b));
        let slow_mflag = mflag && (s - b).abs() >= (b - c).abs() / 2.0;
        let slow_secant = !mflag && (s - b).abs() >= (c - d).abs() / 2.0;
        let tiny_mflag = mflag && (b - c).abs() < tol;
        let tiny_secant = !mflag && (c - d).abs() < tol;
        if outside || slow_mflag || slow_secant || tiny_mflag || tiny_secant {
            s = 0.5 * (a + b);
            mflag = true;
        } else {
            mflag = false;
        }
        let fs = f(s);
        d = c;
        c = b;
        fc = fb;
        if fa * fs < 0.0 {
            b = s;
            fb = fs;
        } else {
            a = s;
            fa = fs;
        }
        if fa.abs() < fb.abs() {
            std::mem::swap(&mut a, &mut b);
            std::mem::swap(&mut fa, &mut fb);
        }
    }
    None
}
