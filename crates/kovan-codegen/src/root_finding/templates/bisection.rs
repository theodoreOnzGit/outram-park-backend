/// Find a root of `f` in the bracket `[a, b]` by **bisection**.
///
/// Bisection repeatedly halves a bracket `[a, b]` on which `f` changes sign
/// (`f(a) * f(b) <= 0`), keeping the sub-half that still brackets a root. It is
/// unconditionally convergent for a continuous `f` with a sign change and
/// converges linearly: the bracket width halves each iteration, so after `n`
/// steps the root is known to within `(b - a) / 2^n`.
///
/// # Arguments
/// * `f`        — continuous function whose root is sought.
/// * `a`, `b`   — bracket endpoints; **must** satisfy `f(a) * f(b) <= 0`.
/// * `tol`      — absolute tolerance on the bracket half-width (stop when the half-width is at or below `tol`).
/// * `max_iter` — hard cap on iterations.
///
/// # Returns
/// `Some(root)` (the final bracket midpoint) if a sign change is present and the
/// tolerance is met within `max_iter` steps, otherwise `None` (invalid bracket
/// or non-convergence).
///
/// Generated by kovan-codegen (docs/kovan.md § "Numerical Methods → Root
/// Finding"). Deterministic template; depends only on `core`/`std` `f64`.
pub fn bisection<F>(f: F, a: f64, b: f64, tol: f64, max_iter: usize) -> Option<f64>
where
    F: Fn(f64) -> f64,
{
    let mut lo = a;
    let mut hi = b;
    let mut flo = f(lo);
    let fhi = f(hi);
    if flo * fhi > 0.0 {
        return None;
    }
    for _ in 0..max_iter {
        let mid = 0.5 * (lo + hi);
        let fmid = f(mid);
        if (hi - lo).abs() * 0.5 <= tol || fmid == 0.0 {
            return Some(mid);
        }
        if flo * fmid <= 0.0 {
            hi = mid;
        } else {
            lo = mid;
            flo = fmid;
        }
    }
    None
}
