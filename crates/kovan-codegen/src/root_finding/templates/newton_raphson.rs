/// Find a root of `f` by the **Newton–Raphson** method.
///
/// Newton's method linearises `f` at the current iterate and steps to that
/// linear model's root: `x_{k+1} = x_k - f(x_k) / f'(x_k)`. Near a simple root
/// it converges quadratically (the number of correct digits roughly doubles
/// each step). It requires the analytic derivative `df` and a starting guess
/// `x0`; it may diverge if `x0` is far from a root or if `f'` vanishes on the
/// iteration path.
///
/// # Arguments
/// * `f`        — function whose root is sought.
/// * `df`       — its derivative `f'`.
/// * `x0`       — initial guess.
/// * `tol`      — absolute tolerance: stop when `|f(x)| <= tol` or the Newton step magnitude is at or below `tol`.
/// * `max_iter` — iteration cap.
///
/// # Returns
/// `Some(root)` on convergence, or `None` if the derivative underflows
/// (`|f'| < 1e-300`, which would divide by zero) or `max_iter` is exceeded.
///
/// Generated by kovan-codegen (docs/kovan.md § "Numerical Methods → Root
/// Finding"). Deterministic template; depends only on `core`/`std` `f64`.
pub fn newton_raphson<F, DF>(f: F, df: DF, x0: f64, tol: f64, max_iter: usize) -> Option<f64>
where
    F: Fn(f64) -> f64,
    DF: Fn(f64) -> f64,
{
    let mut x = x0;
    for _ in 0..max_iter {
        let fx = f(x);
        if fx.abs() <= tol {
            return Some(x);
        }
        let dfx = df(x);
        if dfx.abs() < 1e-300 {
            return None;
        }
        let step = fx / dfx;
        x -= step;
        if step.abs() <= tol {
            return Some(x);
        }
    }
    None
}
