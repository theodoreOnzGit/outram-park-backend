/// Find a root of `f` by the **secant** method.
///
/// The secant method approximates Newton's derivative with a finite difference
/// over the two most recent iterates:
/// `x_{k+1} = x_k - f(x_k) (x_k - x_{k-1}) / (f(x_k) - f(x_{k-1}))`.
/// It needs no analytic derivative and converges superlinearly (order about
/// 1.618, the golden ratio) near a simple root, but — unlike bisection — does
/// not maintain a bracket and can diverge.
///
/// # Arguments
/// * `f`        — function whose root is sought.
/// * `x0`, `x1` — two distinct initial iterates.
/// * `tol`      — absolute tolerance: stop when `|f(x)| <= tol` or the step is at or below `tol`.
/// * `max_iter` — iteration cap.
///
/// # Returns
/// `Some(root)` on convergence, or `None` if the secant denominator underflows
/// (`|f(x_k) - f(x_{k-1})| < 1e-300`) or `max_iter` is exceeded.
///
/// Generated by kovan-codegen (docs/kovan.md § "Numerical Methods → Root
/// Finding"). Deterministic template; depends only on `core`/`std` `f64`.
pub fn secant<F>(f: F, x0: f64, x1: f64, tol: f64, max_iter: usize) -> Option<f64>
where
    F: Fn(f64) -> f64,
{
    let mut a = x0;
    let mut b = x1;
    let mut fa = f(a);
    let mut fb = f(b);
    for _ in 0..max_iter {
        if fb.abs() <= tol {
            return Some(b);
        }
        let denom = fb - fa;
        if denom.abs() < 1e-300 {
            return None;
        }
        let c = b - fb * (b - a) / denom;
        a = b;
        fa = fb;
        b = c;
        fb = f(c);
        if (b - a).abs() <= tol {
            return Some(b);
        }
    }
    None
}
