// A working declarative macro, defined here so the crate compiles and tests it.
// `#[macro_export]` lifts it to the crate root: call it as
// `kovan_codegen::kovan_fixed_point!(...)`.
/// Declarative fixed-point loop, expanded at compile time (no dependencies).
///
/// `kovan_fixed_point!(x0, tol, max_iter, g)` iterates `x = g(x)` from `x0`
/// until `|g(x) - x| <= tol` or `max_iter` iterations elapse, evaluating to
/// `Option<f64>` (`Some(root)` on convergence, `None` otherwise). This is the
/// canonical example of KOVAN's declarative-macro strategy: pure compile-time
/// expansion, zero dependencies, Android/offline friendly.
#[macro_export]
macro_rules! kovan_fixed_point {
    ($x0:expr, $tol:expr, $max_iter:expr, $g:expr) => {{
        let g = $g;
        let mut x: f64 = $x0;
        let mut converged = None;
        for _ in 0..$max_iter {
            let xn = g(x);
            if (xn - x).abs() <= $tol {
                converged = Some(xn);
                break;
            }
            x = xn;
        }
        converged
    }};
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn declarative_macro_finds_dottie_number() {
        // x = cos(x) -> Dottie number, via the compile-time-expanded macro.
        let r: Option<f64> = kovan_fixed_point!(1.0_f64, 1e-12, 500, |x: f64| x.cos());
        let r = r.unwrap();
        assert!((r - 0.739_085_133_215_160_6).abs() < 1e-10, "got {r}");
    }

    #[test]
    fn scaffold_is_deterministic_and_nonempty() {
        for k in [
            MacroKind::Declarative,
            MacroKind::Derive,
            MacroKind::Attribute,
            MacroKind::Procedural,
            MacroKind::BuildRs,
        ] {
            let a = generate_macro_scaffold(k);
            assert_eq!(a, generate_macro_scaffold(k));
            assert!(!a.is_empty());
        }
    }

    #[test]
    fn declarative_scaffold_contains_the_macro() {
        assert!(generate_macro_scaffold(MacroKind::Declarative)
            .contains("macro_rules! kovan_fixed_point"));
    }
}
