/// Solve the dense linear system `A x = b` by **LU decomposition with partial
/// pivoting** (Gaussian elimination).
///
/// The `n x n` matrix `A` is reduced to upper-triangular form in a working copy
/// using row interchanges that place the largest-magnitude available pivot on
/// the diagonal (partial pivoting, for numerical stability). The right-hand side
/// is transformed in lockstep, then the triangular system is resolved by back
/// substitution. This is equivalent to forming `P A = L U` and solving
/// `L U x = P b`. Cost is `O(n^3)`.
///
/// # Arguments
/// * `a` — row-major `n x n` coefficient matrix (`a[i][j]` is row `i`, col `j`).
/// * `b` — right-hand-side vector of length `n`.
///
/// # Returns
/// `Some(x)` with the solution vector, or `None` if the dimensions are
/// inconsistent or the matrix is singular (a zero pivot column is encountered).
///
/// Generated by kovan-codegen (docs/kovan.md § "Numerical Methods → Linear
/// Solvers"). Deterministic template; depends only on `core`/`std` `f64`.
pub fn lu_solve(a: &[Vec<f64>], b: &[f64]) -> Option<Vec<f64>> {
    let n = b.len();
    if a.len() != n || a.iter().any(|row| row.len() != n) {
        return None;
    }
    let mut m: Vec<Vec<f64>> = a.to_vec();
    let mut x = b.to_vec();
    for k in 0..n {
        // Partial pivot: pick the row (>= k) with the largest |m[i][k]|.
        let mut piv = k;
        let mut best = m[k][k].abs();
        for (i, row) in m.iter().enumerate().skip(k + 1) {
            let v = row[k].abs();
            if v > best {
                best = v;
                piv = i;
            }
        }
        if best == 0.0 {
            return None; // singular matrix
        }
        if piv != k {
            m.swap(k, piv);
            x.swap(k, piv);
        }
        // Eliminate column k below the diagonal. Snapshot the pivot row (it is
        // invariant over the elimination sweep) so the borrow checker allows
        // mutating the rows beneath it.
        let pivot_row = m[k].clone();
        let pivot = pivot_row[k];
        let xk = x[k];
        for i in (k + 1)..n {
            let factor = m[i][k] / pivot;
            m[i][k] = 0.0;
            for (mij, &pkj) in m[i].iter_mut().zip(pivot_row.iter()).skip(k + 1) {
                *mij -= factor * pkj;
            }
            x[i] -= factor * xk;
        }
    }
    // Back substitution on the upper-triangular system.
    for i in (0..n).rev() {
        let mut sum = x[i];
        for (mij, xj) in m[i].iter().zip(x.iter()).skip(i + 1) {
            sum -= mij * xj;
        }
        x[i] = sum / m[i][i];
    }
    Some(x)
}
