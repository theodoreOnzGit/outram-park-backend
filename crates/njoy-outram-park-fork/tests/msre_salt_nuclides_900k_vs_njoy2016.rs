//! MSRE N-C2 (gh:#1127, epic gh:#1125): the salt nuclides at 900 K, this
//! port against NJOY2016, **word for word**. Verification; research,
//! education and V&V only.
//!
//! # Methodology (pre-registered on gh:#1127, 2026-11-09)
//!
//! **Nuclides**, ENDF/B-VIII.0:
//! - Li-6 (325), Li-7 (328), Be-9 (425), F-19 (925), from `reference-data/endf/`;
//! - Zr-90 (4025), Zr-91 (4028), Zr-92 (4031), Zr-94 (4037), Zr-96 (4043),
//!   from the submodule's `endf/endf-b-viii.0/`.
//!
//! Li, Be and F carry no resonance parameters (LRU = 0). Every Zr isotope has
//! an MLBW resolved range (LRF = 2) and an LRU = 2 unresolved range; Zr-91
//! has LFW = 1.
//!
//! **Oracle:** NJOY2016 `ac5adf5` (2016.79), running the deck RECONR (0.001),
//! then BROADR (900 K), then PURR (20 bands, 64 ladders), then ACER (suffix
//! `.90`). The decks, the BROADR PENDFs (tape22) and the ACE tables (tape24)
//! are in the submodule at `reference-njoy/endf-b-viii.0/900K/`, generated by
//! `verification_and_validation/msre_salt_nuclides_900k/make_njoy_900k.sh`.
//! 900 K is a standard library temperature within 2 % of the MSRE fuel band,
//! 908-936 K.
//!
//! **Comparisons, per nuclide:**
//! 1. **PENDF after BROADR.** `reconr` then `broaden_result(900 K)`, through
//!    PENDF text, against NJOY's tape22. Every MF=3 section must have the same
//!    QI and the same `(E, σ)` pairs, bit for bit, and no section may appear
//!    on one side only. The MT=1 points below and above `thnmax`
//!    (`broadr::broadening_limit`) are counted and printed. An identical
//!    result with zero points below `thnmax` would verify no broadening at
//!    all; that is the root CLAUDE.md lesson.
//! 2. **Whole ACE table.** `build_deck` with
//!    `AceDeck::default().without_heatr().with_purr(20, 64, 10_000).with_temperature(900.0)`
//!    against NJOY's tape24, through `acer::compare`: header, NXS, JXS and
//!    every XSS word.
//!
//! **Pass criterion:** identical. There is no tolerance.
//!
//! # Results (2026-11-09, develop e3cbf1ec6 + this change)
//!
//! | Nuclide | thnmax (eV) | MT=1 points below / above | PENDF | ACE |
//! |---|---|---|---|---|
//! | Li-6 | 1.7516e6 | 590 / 207 | identical | identical |
//! | Li-7 | 5.4627e5 | 593 / 197 | identical | identical |
//! | Be-9 | 6.6715e5 | 474 / 170 | identical | **differs**: see below |
//! | F-19 | 1.1584e5 | 1213 / 1121 | identical | identical |
//! | Zr-90 | 2.0000e5 | 13282 / 168 | identical | identical |
//! | Zr-91 | 2.6150e4 | 17373 / 259 | identical | identical |
//! | Zr-92 | 1.2100e5 | 14002 / 181 | identical | identical |
//! | Zr-94 | 8.9400e4 | 11137 / 222 | identical | identical |
//! | Zr-96 | 9.6000e4 | 5879 / 175 | identical | identical |
//!
//! "Identical" means NXS, JXS and every XSS word for the ACE, and every MF=3
//! word for the PENDF. Every nuclide has hundreds to thousands of points
//! below `thnmax`, so broadening is verified, not just the unbroadened copy.
//!
//! **Be-9:**
//! - The XSS is 14 124 words here against NJOY2016's 202 021. NXS(5) (NR)
//!   is 0 against 1, and NXS(7) (particle types) 0 against 4.
//! - MT=16's TYR is 0 against 2, and its LAND/DLW entry is missing: the
//!   port's `acelf6` refuses MF=6 `LAW = 7`.
//! - YP and the charged-particle blocks are missing: `acelcp`'s
//!   documented unported branches.
//! - ESZ, SIG, AND, GPD and every photon block are identical.
//!
//! So **this port's Be-9 table carries no (n,2n) neutrons**, real
//! multiplication in an MSRE core. A Be-9 table from this port must not be
//! used for MSRE transport until LAW = 7 is ported; use NJOY2016's.
//!
//! Predictions (gh:#1127):
//! - Zr: predicted identical at the lowest confidence; all five are.
//! - Light-nuclide ACE: predicted identical; wrong for Be-9.
//!
//! Runtime: 57 s for the nine nuclides, release build.

use njoy_outram_park_fork::acer::compare::compare;
use njoy_outram_park_fork::acer::read::{self, AceFileType};
use njoy_outram_park_fork::acer::{build_deck, AceDeck};
use njoy_outram_park_fork::broadr::{broadening_limit, broaden_result};
use njoy_outram_park_fork::endf::records::SectionCursor;
use njoy_outram_park_fork::endf::tape::Tape;
use njoy_outram_park_fork::reconr::{reconr, ReconrConfig};
use njoy_outram_park_fork::reference_data::{ace_reference_file_or_skip, reference_endf_or_skip};

const T_K: f64 = 900.0;
const DIR: &str = "reference-njoy/endf-b-viii.0/900K";

/// Where a nuclide's ENDF tape lives.
enum TapeHome {
    /// `reference-data/endf/` in this repository.
    Repo,
    /// The submodule's `endf/endf-b-viii.0/`.
    Submodule,
}

/// Read a nuclide's tape, or `None` (a skip) when it is not on this machine.
fn tape(file: &str, home: &TapeHome) -> Option<Tape> {
    let path = match home {
        TapeHome::Repo => reference_endf_or_skip(file, "msre-salt-900k")?,
        TapeHome::Submodule => {
            ace_reference_file_or_skip(&format!("endf/endf-b-viii.0/{file}"), "msre-salt-900k")?
        }
    };
    Some(Tape::read_file(&path).expect("ENDF tape"))
}

/// Compare one nuclide's PENDF and ACE with NJOY2016's. Returns the list of
/// differences (empty when identical) and the MT=1 counts below and above
/// `thnmax`; `None` when its data is absent here.
fn compare_nuclide(file: &str, home: TapeHome, mat: i32, name: &str) -> Option<(Vec<String>, usize, usize, f64)> {
    let tape = tape(file, &home)?;
    let pendf_path = ace_reference_file_or_skip(&format!("{DIR}/{name}.pendf.gz"), name)?;
    let ace_path = ace_reference_file_or_skip(&format!("{DIR}/{name}.ace.gz"), name)?;
    let theirs = Tape::read_file(&pendf_path).expect("NJOY PENDF");

    let r0 = reconr(&tape, &ReconrConfig { mat, tolerance: 1.0e-3, temperature: 0.0 }).expect("RECONR");
    let thnmax = broadening_limit(&r0);
    let broadened = broaden_result(&r0, T_K);
    let ours = broadened.clone().through_pendf_text();

    let mut diffs = Vec::new();
    let mut their_mts = Vec::new();
    let mut below = 0;
    let mut above = 0;
    for sec in theirs.sections().iter().filter(|s| s.key.mat == mat && s.key.mf == 3) {
        let mt = sec.key.mt;
        their_mts.push(mt);
        let mut cur = SectionCursor::new(&sec.rows);
        let _ = cur.read_cont().expect("HEAD");
        let t = cur.read_tab1().expect("TAB1");
        if mt == 1 {
            below = t.pairs.iter().filter(|p| p.0 < thnmax).count();
            above = t.pairs.len() - below;
        }
        match ours.sections.iter().find(|s| s.mt.number() == mt) {
            None => diffs.push(format!("PENDF MT={mt}: missing in ours")),
            Some(s) if s.pairs != t.pairs || s.qi != t.head.c2 => {
                let first = s.pairs.iter().zip(&t.pairs).position(|(a, b)| a != b);
                diffs.push(format!(
                    "PENDF MT={mt}: ours {} points, NJOY {}; first differing pair {first:?}; QI {} vs {}",
                    s.pairs.len(),
                    t.pairs.len(),
                    s.qi,
                    t.head.c2
                ));
            }
            Some(_) => {}
        }
    }
    for s in &ours.sections {
        if !their_mts.contains(&s.mt.number()) {
            diffs.push(format!("PENDF MT={}: extra in ours", s.mt.number()));
        }
    }

    let bytes = std::fs::read(&ace_path).expect("read NJOY's ACE");
    let mut tables = read::read_library_from_bytes(bytes, &format!("{name}.ace.gz")).expect("NJOY ACE parses");
    let njoy = tables.pop().expect("one table");
    let deck = AceDeck::default().without_heatr().with_purr(20, 64, 10_000).with_temperature(T_K);
    let ace = build_deck(&tape, mat, &broadened, njoy.header.kt_mev, 90, &deck).expect("ACER");
    let ours_ace = read::parse_type1(&ace.to_raw(AceFileType::Type1Ascii).unwrap().to_type1_string()).unwrap();
    let c = compare(&ours_ace, &njoy);
    if !c.identical() {
        for line in c.report_lines() {
            diffs.push(format!("ACE {line}"));
        }
    }
    Some((diffs, below, above, thnmax))
}

/// Run one nuclide and report it; the assertion is made by the caller.
fn report(file: &str, home: TapeHome, mat: i32, name: &str) -> Option<Vec<String>> {
    let (diffs, below, above, thnmax) = compare_nuclide(file, home, mat, name)?;
    println!(
        "N-C2 {name}: thnmax {thnmax:.4e} eV, MT=1 points below {below}, above {above}; {}",
        if diffs.is_empty() { "PENDF and ACE identical to NJOY2016".to_string() } else { format!("{} differences", diffs.len()) }
    );
    for d in diffs.iter().take(80) {
        println!("N-C2 {name}:   {d}");
    }
    Some(diffs)
}

/// N-C2, light salt nuclides (no resonance parameters): Li-6, Li-7 and
/// F-19 must be identical in PENDF and ACE.
#[test]
fn light_salt_nuclides_at_900k_are_njoy2016s_word_for_word() {
    let mut failed = Vec::new();
    for (file, mat, name) in [
        ("n-003_Li_006-ENDF8.0.endf", 325, "Li6"),
        ("n-003_Li_007-ENDF8.0.endf", 328, "Li7"),
        ("n-009_F_019-ENDF8.0.endf", 925, "F19"),
    ] {
        if let Some(d) = report(file, TapeHome::Repo, mat, name) {
            if !d.is_empty() {
                failed.push(name);
            }
        }
    }
    assert!(failed.is_empty(), "differ from NJOY2016: {failed:?}");
}

/// N-C2, Be-9: a **known, open difference** (gh:#1127, tracked in its own
/// issue). Its PENDF is NJOY2016's in every MF=3 word, and that is gated.
/// Its ACE is not. `acer::acelf6` refuses MF=6 `LAW = 7` neutrons
/// (`src/acer/acelf6.rs`, the `7 => return Ok(None)` arm), so MT=16 (n,2n)
/// is written with TYR = 0 and no distribution. `acelcp` also writes no
/// charged-particle production. NJOY2016 converts LAW = 7 into ACE law 61
/// (`acefc.f90:7369` onward) and writes four particle types.
///
/// This test asserts the difference is **still exactly that**: every ACE
/// difference lies in NXS/JXS, TYR, LAND, LDLW, DLW, YP or the whole XSS.
/// Nothing in ESZ, SIG, AND or the photon blocks may differ.
///
/// When LAW = 7 is ported, this test fails. Move Be-9 into
/// [`light_salt_nuclides_at_900k_are_njoy2016s_word_for_word`] then.
#[test]
fn be9_differs_from_njoy2016_only_by_the_unported_law7_and_particle_blocks() {
    let Some((diffs, below, _above, _thnmax)) =
        compare_nuclide("n-004_Be_009-ENDF8.0.endf", TapeHome::Repo, 425, "Be9")
    else {
        return;
    };
    println!("N-C2 Be9: MT=1 points below thnmax {below}; {} ACE rows differ", diffs.len());
    assert!(below > 0, "broadening must be exercised");
    assert!(
        diffs.iter().all(|d| d.starts_with("ACE ")),
        "Be-9's PENDF must be NJOY2016's word for word: {diffs:#?}"
    );
    let expected = ["NXS", "JXS", "TYR", "LAND", "LDLW", "DLW", "YP", "XSS, whole table", "VERDICT"];
    let structural: Vec<&String> = diffs
        .iter()
        .filter(|d| d.contains("DIFFERENT") || d.contains("VERDICT"))
        .collect();
    assert!(!structural.is_empty(), "Be-9's ACE is now identical: promote it to the identical gate");
    for d in &structural {
        let block = d.trim_start_matches("ACE ").split_whitespace().next().unwrap_or("");
        assert!(
            expected.iter().any(|e| d.trim_start_matches("ACE ").starts_with(e)) || block == "VERDICT:",
            "Be-9 differs in a block outside the known LAW = 7 / particle gap: {d}"
        );
    }
}

/// N-C2, the zirconium isotopes (MLBW resolved + LRU = 2 unresolved).
#[test]
fn zirconium_isotopes_at_900k_are_njoy2016s_word_for_word() {
    let mut failed = Vec::new();
    for (a, mat) in [("090", 4025), ("091", 4028), ("092", 4031), ("094", 4037), ("096", 4043)] {
        let file = format!("n-040_Zr_{a}-ENDF8.0.endf");
        let name = format!("Zr{a}");
        if let Some(d) = report(&file, TapeHome::Submodule, mat, &name) {
            if !d.is_empty() {
                failed.push(name);
            }
        }
    }
    assert!(failed.is_empty(), "differ from NJOY2016: {failed:?}");
}
