/// gh:#1487 ablations: the wall bridges carry the agreement (judged on x, v,
/// omega and f only, so the trivially different liquid columns do not count).
/// Dry spheres on
/// the Easo plane deck (no bridge can form) and the Washino mesh deck without
/// `liquidtransfer` (a dry facet) each miss their upstream run by far more than
/// the ported model does.
#[test]
fn wall_bridge_ablations_miss_upstream() {
    for (name, with, without) in [
        ("easo_plane", Case::EasoPlane, Case::EasoPlaneDry),
        ("washino_mesh", Case::WashinoMesh, Case::WashinoMeshDryWall),
    ] {
        let w = compare(with).worst_rel_motion;
        let wo = compare(without).worst_rel_motion;
        println!("{name}: ported {w:e}, ablated {wo:e}");
        assert!(wo > 1e3 * w.max(1e-15), "{name}: ablation does not miss ({w:e} vs {wo:e})");
    }
}

/// gh:#1487: the wall state the decks leave behind, and the walls
/// `with_capillary` refuses. After the liquid-mesh deck the facet the fast
/// sphere ruptured from holds more liquid than it started with (that sphere
/// had more), the other facet is untouched, and the slow sphere is still
/// bridged. Refused: a box, a one-sided wall, a tilted plane, two particle
/// types with walls, and `liquidtransfer` without a capillary model.
#[test]
fn wall_bridge_state_and_refusals() {
    let (mut sys, _) = system(Case::WashinoMesh);
    sys.run(40_000);
    let lc = sys.mesh_liquid_content(0).to_vec();
    println!("facet liquid content after the run: {lc:?}, wall bridges {}", sys.wall_bridge_count());
    assert_eq!(lc.len(), 2);
    assert!(lc[0] > 0.1, "facet 0 gains the rupture's liquid: {}", lc[0]);
    assert_eq!(lc[1], 0.1, "facet 1 untouched");
    assert_eq!(sys.wall_bridge_count(), 1, "the slow sphere stays bridged");
    assert!(sys.mesh_liquid_content(7).is_empty());

    let params = CapillaryParams::easo(0.072, 1e-3, 0.0, 0.01, 2.0, 0.1).unwrap();
    let model = || {
        GranularContactModel::hertz_history(GranularMaterial::new(1.0e7, 0.3, 0.9, 0.5).unwrap())
            .with_cohesion(GranularCohesion::Capillary(params))
            .with_materials(
                MaterialTable::new(&[(1.0e7, 0.3), (1.0e7, 0.3)], &[&[0.9, 0.9], &[0.9, 0.9]], &[&[0.5, 0.5], &[0.5, 0.5]])
                    .unwrap(),
            )
    };
    let ps = || {
        vec![
            particle(Vec3::new(0.0, 0.0, 0.01), Vec3::zero(), Vec3::zero(), 0.01, 2500.0),
            particle(Vec3::new(0.05, 0.0, 0.01), Vec3::zero(), Vec3::zero(), 0.01, 2500.0),
        ]
    };
    let cfg = LiggghtsNeighbor::new(Vec3::new(-0.2, -0.2, -0.05), Vec3::new(0.2, 0.2, 0.4), 0.004).unwrap();
    let try_walls = |walls: Vec<Boundary>, types: Option<Vec<usize>>| {
        let mut s = GranularSystem::new(ps(), walls, model(), Vec3::zero(), 1e-6).unwrap();
        if let Some(t) = types {
            s = s.with_particle_types(t).unwrap();
        }
        s.with_liggghts_neighbor_order(cfg).with_capillary()
    };
    let zplane = || Boundary::plane(Vec3::zero(), Vec3::new(0.0, 0.0, 1.0)).unwrap();
    assert!(try_walls(vec![zplane()], None).is_ok());
    assert!(try_walls(vec![Boundary::cylinder(Vec3::zero(), Vec3::new(0.0, 0.0, 1.0), 0.1).unwrap()], None).is_ok());
    assert!(try_walls(vec![zplane()], Some(vec![0, 1])).is_err());
    assert!(try_walls(vec![], Some(vec![0, 1])).is_ok());
    let tilted = Boundary::plane(Vec3::zero(), Vec3::new(0.0, 0.6, 0.8)).unwrap();
    assert!(try_walls(vec![tilted], None).is_err());
    let one_sided = Boundary::wall(Vec3::zero(), Vec3::new(0.0, 0.0, 1.0)).unwrap();
    assert!(try_walls(vec![one_sided], None).is_err());
    let aabb = Boundary::aabb(Vec3::new(-0.1, -0.1, -0.1), Vec3::new(0.1, 0.1, 0.1)).unwrap();
    assert!(try_walls(vec![aabb], None).is_err());
    // liquidtransfer needs the capillary state and a mesh
    let mesh = || {
        MovingBoundary::new(
            WallGeometry::Mesh(MeshWall::from_ascii_stl(STL_FLOOR).unwrap()),
            Vec3::zero(),
            Vec3::zero(),
            Vec3::zero(),
        )
    };
    let dry = GranularSystem::new(ps(), vec![], model(), Vec3::zero(), 1e-6)
        .unwrap()
        .with_moving_walls(vec![mesh()]);
    assert!(dry.with_mesh_liquid_transfer(0, 0.001, 0.1).is_err());
    let wet = GranularSystem::new(ps(), vec![], model(), Vec3::zero(), 1e-6)
        .unwrap()
        .with_moving_walls(vec![mesh()])
        .with_liggghts_neighbor_order(cfg)
        .with_capillary()
        .unwrap();
    assert!(wet.clone().with_mesh_liquid_transfer(1, 0.001, 0.1).is_err());
    assert!(wet.clone().with_mesh_liquid_transfer(0, 0.0, 0.1).is_err());
    assert!(wet.with_mesh_liquid_transfer(0, 0.001, 0.1).is_ok());
}
