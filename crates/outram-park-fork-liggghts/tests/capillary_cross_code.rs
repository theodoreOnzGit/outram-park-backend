//! # Liquid-bridge cohesion (`easo/capillary/viscous`, `washino/capillary/viscous`) against LIGGGHTS-PUBLIC
//!
//! gh:#1411. Decks `reference-data/liggghts/in.cap_*` (LIGGGHTS-PUBLIC
//! `3d5c00f2`, built read-only from the shared upstream build; regenerate with
//! `reference-data/liggghts/run_capillary.sh`), dumps converted by
//! `dump2cap.sh` to `cap_*.csv` (`%.17g`).
//!
//! ## Methodology
//! Six cases, each a full trajectory compared on every sampled frame, all 14
//! columns per particle (`x y z v omega f L flux`; `L` is
//! `surfaceLiquidContent`, `flux` `liquidFlux`):
//! * `cap_easo_pair` / `cap_washino_pair`: two 10 mm spheres, Hertz + history,
//!   approach, bridge forms, rebound, stretch, rupture (Easo third branch;
//!   Washino also forms bridges out of contact);
//! * `cap_easo_hard`: unequal spheres/two types, `maxSeparationDistanceRatio
//!   1.1`, rupture through the first (hard-limit) branch, `tangential_reduce on`;
//! * `cap_washino_limit`: `limitLiquidContent`, `modifyLbVolume`,
//!   `maxLiquidContent` overwriting the separation ratio, unequal spheres;
//! * `cap_easo_bed` / `cap_washino_bed`: 84 pebbles of the settled bed, no
//!   walls, no gravity, bridges forming, stretching, rupturing and
//!   re-forming.
//! The port runs `GranularSystem::with_liggghts_neighbor_order(..)
//! .with_capillary()`. ~~Walls are not ported (Easo/Washino wall bridges), so no
//! deck has one.~~ **CORRECTED 2026-11-12 (gh:#1487):** wall bridges are
//! ported; the four wall decks are below.
//!
//! ## Prediction (written before the first run, 2026-11-11)
//! Bit-identical, as the multicontact decks: every formula is translated in
//! upstream's order. The only place a last-ulp difference may enter is
//! `exp`/`pow`/`log`/`cbrt`/`sin`/`cos` (PETIR libm vs glibc, accepted under
//! gh:#1455 provided it is proved to be the only cause). A bridge-state flip
//! by one step would show as a gross difference, not an ulp one.
//!
//! ## Result
//! 2026-11-11, release, rustc 1.99.1, upstream `3d5c00f2` g++ (all 14 columns,
//! every sampled frame):
//!
//! | case | frames | values bit-identical | worst ulp |
//! |---|---|---|---|
//! | `easo_pair` | 201 | 5628 / 5628 | 0 |
//! | `easo_hard` (2 types, hard-limit rupture, `tangential_reduce`) | 201 | 5628 / 5628 | 0 |
//! | `easo_bed` (84 pebbles) | 17 | 19992 / 19992 | 0 |
//! | `washino_pair` | 201 | 5620 / 5628 | 4 (first at step 1890) |
//! | `washino_limit` | 201 | 5606 / 5628 | 2 (first at step 1740) |
//! | `washino_bed` (84 pebbles) | 17 | 19601 / 19992 | 1118 (rel. 1.3e-15, first at step 500) |
//!
//! **Easo: bit-identical in all three cases.** **Washino: last-ulp
//! differences, cause PROVED to be libm only.** With `r_sin`, `r_cos`,
//! `r_cbrt` of `capillary.rs` temporarily swapped for `f64::sin/cos/cbrt`
//! (which call glibc, the libm LIGGGHTS links), all three Washino cases are
//! 5628/5628, 5628/5628 and 19992/19992 bit-identical (A/B run 2026-11-11, then
//! reverted: PETIR maths stays, gh:#1455). Easo uses none of the three
//! (`exp`, `log`, `pow` agree bit for bit). The bed's 1118 ulp is the same
//! 1-ulp seed amplified over 4000 steps of 84 interacting pebbles. The pins in
//! each test hold the counts above.
//!
//! **First run missed (0.24 % in the first-contact force) and the cause was the
//! test input, not the port**: the decks give `contactAngle` in degrees
//! (`createContactAngle`, `global_properties.cpp`: `v * M_PI / 180`) and the
//! deck's 0.3 had been fed as radians. Found by printing the contact angle,
//! the capillary and viscous terms from a COPY of the upstream header built
//! in the scratchpad (the shared build untouched); the terms agreed with the
//! port once the angle was converted.
//!
//! ## Particle-wall bridges (gh:#1487)
//!
//! ### Methodology
//! Four more decks, `in.cap_{easo,washino}_{plane,mesh}` (same upstream build,
//! regenerated by `run_capillary.sh`). Each holds two d = 10 mm spheres over
//! the wall at `z = 0`, both with tangential velocity and three-component spin,
//! 50 mm apart (no pair bridge). Sphere 1 is fast: it bridges (Easo at contact,
//! Washino out of contact), rebounds and ruptures at `d_max`. Sphere 2 is slow
//! and stays bridged. The walls:
//! * `plane`: a `zplane` primitive wall (dry);
//! * `easo_mesh`: `plate_square.stl` (dry);
//! * `washino_mesh`: `plate_square.stl` as `mesh/surface/liquidtransfer
//!   wall_thickness 0.001 initial_liquid_content 0.1`, so the facet film enters
//!   the bridge and the rupture moves liquid to the facet.
//!
//! `maxSeparationDistanceRatio 2.0` puts `d_max` inside a wall's close range
//! `(1.1 * 2.0 - 1) r`. With a smaller ratio the history would be zeroed before
//! the rupture branch is reached. 40 000 steps of 1 us, compared every 200
//! steps, all 14 columns. Port: `GranularSystem::new(.., [plane], ..)` or
//! `with_moving_walls([mesh])`, then `with_capillary()` and, for the liquid
//! mesh, `with_mesh_liquid_transfer(0, 0.001, 0.1)`.
//!
//! ### Prediction (posted on #1487 before the first run, 2026-11-12)
//! All four bit-identical; any residue Washino-only, last-ulp, libm.
//!
//! ### Result
//! 2026-11-12, release, rustc 1.99.1:
//!
//! | case | values bit-identical | worst ulp |
//! |---|---|---|
//! | `easo_plane` | 5628 / 5628 | 0 |
//! | `easo_mesh` | 5628 / 5628 | 0 |
//! | `washino_plane` | 5624 / 5628 | 8 (rel. 1.7e-19, first at step 3800) |
//! | `washino_mesh` (liquid facet) | 5622 / 5628 | 2 (rel. 1.7e-19, first at step 4000) |
//!
//! Easo is bit-identical on the first run. The Washino residue is libm only:
//! with the same temporary glibc swap as above (`r_sin`/`r_cos`/`r_cbrt` ->
//! `f64::sin/cos/cbrt`), all ten decks in this file were 100 % bit-identical
//! (A/B 2026-11-12, then reverted; pins below, gh:#1455). Ablations,
//! `wall_bridge_ablations_miss_upstream`, on `x v omega f` only: with dry
//! spheres the Easo plane deck misses by 8.9e-2 of the column scale, and the
//! Washino mesh without `liquidtransfer` misses by 5.1e-3, so the wall bridges
//! and the facet film carry the agreement.

