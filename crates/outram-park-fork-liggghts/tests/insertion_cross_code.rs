//! # Particle insertion (`fix insert/pack`, `insert/rate/region`) against LIGGGHTS-PUBLIC
//!
//! gh:#1414 (child of #1405; differential issue #1406, prio-3 row "Rust pour
//! via insert/pack vs a LIGGGHTS pour").
//!
//! ## Methodology
//!
//! Three decks (`reference-data/liggghts/in.pour_pack`, `in.pour_poly`,
//! `in.pour_rate`, generated by `make_pour_decks.sh`) pour into the `D/d = 6`
//! cylinder of `in.pebble_bed` (R = 30 mm, floor, Hertz + history, `E = 5e6`,
//! `nu = 0.3`, `e = 0.5`, `mu = 0.3`, `dt = 5 us`, `neighbor 0.003 bin`):
//!
//! * `pour_pack`: `particletemplate/sphere` (r = 5 mm, rho = 2500) in a
//!   one-template `particledistribution/discrete`, `insert/pack ... insert_every
//!   1000 overlapcheck yes all_in yes vel constant 0 0 -0.1 particles_in_region
//!   200`, cylinder region `z 0 0 0.028 0.05 0.32`.
//! * `pour_poly`: two templates (r = 5 mm and 3.5 mm, 70/30 **mass** %), `vel
//!   uniform` (consumes the fix's RNG every trial), target `volumefraction_region
//!   0.2` (a random-number rounding per step): exercises the mass-to-number
//!   weight conversion, the volume-sorted order, the exact-number remainder
//!   draw and the neighbour cut radius of the largest *future* particle.
//! * `pour_rate`: `insert/rate/region nparticles 120 particlerate 8000`.
//!
//! Each is one continuous LIGGGHTS run (frames written with `run N pre no`, so
//! no set-up in between) dumped with `%.17g` at steps 1, 1000, 1001, 6001,
//! 10001, 20000, 24000, 26000 and 30000 (`pour_*.csv`; `pour2csv.sh`). This
//! test builds the same system from nothing (empty ensemble, the box, the
//! deck's neighbour settings via `with_liggghts_neighbor_order`), attaches the
//! translated insertion fix, runs to each frame and compares `x y z vx vy vz
//! omega` of every particle (matched by id) on their bit patterns.
//!
//! ## Prediction (written before the first comparison run, 2026-11-11)
//!
//! * **Insertion is bit-identical wherever it acts**: same RNG stream, same
//!   operation order, so every position, velocity and mass at the insertion
//!   steps (1, 1001, 6001, ...) matches to the last bit, as does the *count* of
//!   particles at every frame.
//! * **Free flight** (no contacts until the first particle reaches the floor
//!   or the cylinder wall, ~step 20 000) is the same arithmetic, so frames
//!   1 .. 10 001 are bit-identical.
//! * **After first contact** (frames 20 000+) a particle's force is a sum over
//!   contacts whose order the neighbour-list translation reproduces
//!   (`tests/pair_gran_local_cross_code.rs`), and insertion adds atoms at the
//!   end of the local list and forces a rebuild (and sort at step 1000/2000...)
//!   exactly as upstream does, so I predict bit-identity there too; if it
//!   breaks, the first broken frame and its size are the finding. Pass
//!   criterion for frames from 20 000: identical particle counts and every
//!   field within `1e-8` relative to the largest magnitude of that field
//!   (workspace round-off allowance), with the measured values printed.
//!
//! ## Result
//!
//! Printed by `--nocapture` and recorded in
//! `verification_and_validation/insertion/README.md`.

use outram_park_fork_liggghts::boundary::Boundary;
use outram_park_fork_liggghts::granular::{GranularContactModel, GranularMaterial};
use outram_park_fork_liggghts::granular_system::GranularSystem;
use outram_park_fork_liggghts::insert::{
    Axis, InsertFix, InsertMode, InsertVelocity, InsertRegion, PackTarget,
    ParticleDistributionDiscrete, ParticleTemplateSphere, Rate, RateTotal,
};
use outram_park_fork_liggghts::neighbor_list::LiggghtsNeighbor;
use outram_park_fork_liggghts::particle::Vec3;
use uom::si::f64::{Length, MassDensity, Velocity};
use uom::si::{length::meter, mass_density::kilogram_per_cubic_meter, velocity::meter_per_second};

const FRAMES: [u64; 9] = [1, 1000, 1001, 6001, 10001, 20000, 24000, 26000, 30000];
const BOX_LO: Vec3 = Vec3 {
    x: -0.035,
    y: -0.035,
    z: -0.005,
};
const BOX_HI: Vec3 = Vec3 {
    x: 0.035,
    y: 0.035,
    z: 0.35,
};

fn read(name: &str) -> Option<String> {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../reference-data/liggghts")
        .join(name);
    std::fs::read_to_string(path).ok()
}

fn m(v: f64) -> Length {
    Length::new::<meter>(v)
}

fn template(seed: i32, r: f64) -> ParticleTemplateSphere {
    ParticleTemplateSphere::new(
        seed,
        1,
        m(r),
        MassDensity::new::<kilogram_per_cubic_meter>(2500.0),
    )
    .unwrap()
}

fn region() -> InsertRegion {
    InsertRegion::cylinder(Axis::Z, m(0.0), m(0.0), m(0.028), m(0.05), m(0.32)).unwrap()
}

fn vz(v: f64) -> Velocity {
    Velocity::new::<meter_per_second>(v)
}

fn fix_for(deck: &str) -> InsertFix {
    let (mode, dist, vel) = match deck {
        "pour_pack" => (
            InsertMode::Pack(PackTarget::Particles(200)),
            ParticleDistributionDiscrete::new(
                15485867,
                true,
                vec![(template(15485863, 0.005), 1.0)],
            )
            .unwrap(),
            None,
        ),
        "pour_poly" => (
            InsertMode::Pack(PackTarget::VolumeFraction(0.2)),
            ParticleDistributionDiscrete::new(
                15485867,
                true,
                vec![
                    (template(15485863, 0.005), 0.7),
                    (template(49979687, 0.0035), 0.3),
                ],
            )
            .unwrap(),
            Some(InsertVelocity::Uniform {
                v: Vec3::new(0.0, 0.0, -0.1),
                fluct: Vec3::new(0.02, 0.02, 0.02),
            }),
        ),
        "pour_rate" => (
            InsertMode::RateRegion {
                total: Some(RateTotal::Particles(120)),
                rate: Rate::Particles(8000.0),
                dt: 5e-6,
            },
            ParticleDistributionDiscrete::new(
                15485867,
                true,
                vec![(template(15485863, 0.005), 1.0)],
            )
            .unwrap(),
            None,
        ),
        "pour_block" => (
            InsertMode::Pack(PackTarget::Mass(0.1)),
            ParticleDistributionDiscrete::new(
                15485867,
                false,
                vec![(template(15485863, 0.004), 1.0)],
            )
            .unwrap(),
            Some(InsertVelocity::Gaussian {
                v: Vec3::new(0.0, 0.0, -0.1),
                fluct: Vec3::new(0.03, 0.03, 0.03),
            }),
        ),
        "pour_nocheck" => (
            InsertMode::Pack(PackTarget::Particles(6)),
            ParticleDistributionDiscrete::new(
                15485867,
                true,
                vec![(template(15485863, 0.005), 1.0)],
            )
            .unwrap(),
            None,
        ),
        _ => unreachable!(),
    };
    let block = deck == "pour_block";
    let reg = if block {
        InsertRegion::block(
            Vec3::new(-0.016, -0.016, 0.05),
            Vec3::new(0.016, 0.016, 0.3),
        )
        .unwrap()
    } else {
        region()
    };
    let mut f = InsertFix::new(mode, 32452843, dist, reg, 1000, BOX_LO, BOX_HI)
        .unwrap()
        .with_overlap_check(deck != "pour_nocheck")
        .with_all_in(!block);
    if block {
        f = f
            .with_exact_number(false)
            .with_omega(Vec3::new(1.0, 2.0, 3.0));
    }
    match vel {
        Some(v) => f.with_velocity(v),
        None => f.with_constant_velocity(vz(0.0), vz(0.0), vz(-0.1)),
    }
}

fn system(deck: &str) -> GranularSystem {
    let material = GranularMaterial::new(5.0e6, 0.3, 0.5, 0.3).unwrap();
    let boundaries = vec![
        Boundary::cylinder(Vec3::zero(), Vec3::new(0.0, 0.0, 1.0), 0.030).unwrap(),
        Boundary::wall(Vec3::zero(), Vec3::new(0.0, 0.0, 1.0)).unwrap(),
    ];
    let mut sys = GranularSystem::new(
        Vec::new(),
        boundaries,
        GranularContactModel::hertz_history(material),
        Vec3::new(0.0, 0.0, -9.81),
        5e-6,
    )
    .unwrap();
    // attach first: the neighbour cut radius includes the largest particle the
    // fix can still insert (PairGran::init_style), and the ensemble is empty
    sys.add_insertion(fix_for(deck)).unwrap();
    sys.with_liggghts_neighbor_order(LiggghtsNeighbor::new(BOX_LO, BOX_HI, 0.003).unwrap())
}

/// Rows of `pour_*.csv` for one step: `[id, x, y, z, vx, vy, vz, wx, wy, wz]`.
fn frame_rows(csv: &str, step: u64) -> Vec<[f64; 10]> {
    csv.lines()
        .skip(1)
        .filter_map(|l| {
            let v: Vec<f64> = l.split(',').map(|x| x.parse().unwrap()).collect();
            (v[0] as u64 == step).then(|| {
                let mut r = [0.0; 10];
                r.copy_from_slice(&v[1..11]);
                r
            })
        })
        .collect()
}

/// Per-frame statistics: (particles, bit-identical particles, worst relative
/// difference over all fields, worst absolute position difference).
fn compare(deck: &str) -> Option<Vec<(u64, usize, usize, f64, f64)>> {
    compare_with(deck, deck, false)
}

/// [`compare`] of the system built for deck `fix` against the reference
/// `reference.csv`; with `runs`, every frame after the first ends a LIGGGHTS
/// `run`, so `GranularSystem::begin_run` is called before stepping on (the
/// reference deck uses plain `run` instead of `run N pre no`, gh:#1510).
fn compare_with(
    reference: &str,
    fix: &str,
    runs: bool,
) -> Option<Vec<(u64, usize, usize, f64, f64)>> {
    let deck = reference;
    let csv = read(&format!("{reference}.csv"))?;
    let mut sys = system(fix);
    let mut out = Vec::new();
    let mut at = 0u64;
    for &step in &FRAMES {
        if runs && at > 0 {
            sys.begin_run().expect("run set-up");
        }
        sys.run((step - at) as usize);
        at = step;
        let rows = frame_rows(&csv, step);
        let ours = sys.particles();
        assert_eq!(ours.len(), rows.len(), "{deck} step {step}: particle count");
        let mut identical = 0;
        let mut worst_rel = 0.0f64;
        let mut worst_pos = 0.0f64;
        // scale per field for the relative measure
        let mut scale = [0.0f64; 9];
        for r in &rows {
            for k in 0..9 {
                scale[k] = scale[k].max(r[1 + k].abs());
            }
        }
        for r in &rows {
            let p = &ours[r[0] as usize - 1];
            let mine = [
                p.position.x,
                p.position.y,
                p.position.z,
                p.velocity.x,
                p.velocity.y,
                p.velocity.z,
                p.angular_velocity.x,
                p.angular_velocity.y,
                p.angular_velocity.z,
            ];
            let mut same = true;
            for k in 0..9 {
                let theirs = r[1 + k];
                if mine[k].to_bits() != theirs.to_bits() {
                    same = false;
                    if scale[k] > 0.0 {
                        worst_rel = worst_rel.max((mine[k] - theirs).abs() / scale[k]);
                    }
                    if k < 3 {
                        worst_pos = worst_pos.max((mine[k] - theirs).abs());
                    }
                }
            }
            if same {
                identical += 1;
            }
        }
        out.push((step, rows.len(), identical, worst_rel, worst_pos));
    }
    Some(out)
}

fn report(deck: &str) {
    let Some(stats) = compare(deck) else {
        eprintln!("skipping: reference-data/liggghts/{deck}.csv not present");
        return;
    };
    println!("{deck}: step, particles, bit-identical, worst rel, worst |dx| [m]");
    for (step, n, same, rel, pos) in &stats {
        println!("  {step:6} {n:5} {same:5}  {rel:.3e}  {pos:.3e}");
    }
    for (step, n, same, rel, _) in &stats {
        if *step <= 10001 {
            assert_eq!(
                same, n,
                "{deck} step {step}: insertion + free flight must be bit-identical"
            );
        } else {
            assert!(
                *rel <= 1e-8,
                "{deck} step {step}: worst relative difference {rel:e} (bit-identical {same}/{n})"
            );
        }
    }
}

