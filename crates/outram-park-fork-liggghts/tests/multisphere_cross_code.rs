//! # Multisphere (rigid clump) particles against LIGGGHTS-PUBLIC
//!
//! gh:#1415 (child of #1405).
//!
//! ## Methodology
//!
//! Two decks (`reference-data/liggghts/in.ms_drop`, `in.ms_collide`,
//! generated by `make_multisphere_decks.sh`). Shared settings:
//! * box `[-0.05, 0.05]^2 x [-0.005, 0.15]` m, `f f f`;
//! * `atom_modify sort 0 0`, `neighbor 0.002 bin`;
//! * Hertz + `tangential history`, `E = 1e7`, `nu = 0.3`, `e = 0.5`,
//!   `mu = 0.4`;
//! * `dt = 1e-5`, a `zplane 0` `wall/gran` and gravity.
//!
//! The decks:
//!
//! * **`ms_drop`**: one 3-sphere clump of `particletemplate/multisphere`
//!   (`ntry 100000`, rho = 2500) inserted by `insert/pack ... all_in yes`.
//!   It starts with `vel 0.1 0 -0.5`, `omega 3 -2 5` and
//!   `orientation constant 0.5 0.5 0.5 0.5`, then falls onto the plane,
//!   bounces, rolls and slides. Frames at steps 1, 1000, 4000, 5000, 6000,
//!   8000, 10000, 12000 and 15000.
//! * **`ms_collide`**: the same clump (type 1) and a 4-sphere clump (type 2,
//!   rho = 1500, `orientation constant 0.5 0.5 -0.5 0.5`), each from its own
//!   `insert/pack`, fly at each other at `+-0.6 m/s` and collide obliquely
//!   (step ~4700), then fall to the plane. Frames at steps 1, 2000, 4000, 5000,
//!   6000, 7000, 8000, 10000, 12000 and 15000.
//!
//! Each is one continuous LIGGGHTS run (`run N pre no`), dumped with `%.17g`
//! and converted by `pour2csv.sh`. The test builds the same system from an
//! empty ensemble, attaches the translated templates and insertion fixes, runs
//! to each frame, and compares `x y z vx vy vz omega` of every member atom
//! (matched by id) on their bit patterns.
//!
//! **Prediction (posted on gh:#1415 before the first run):** both decks are
//! bit-identical in every field at every frame.
//!
//! ## Result (2026-11-13, Rust 1.99.1, LIGGGHTS-PUBLIC 3d5c00f2)
//!
//! **Bit-identical.** `ms_drop`: 27 / 27 atom-frames (243 values).
//! `ms_collide`: 70 / 70 atom-frames (630 values). Both include the Monte-Carlo
//! template, the insertion, the wall contacts, the clump-clump contacts and
//! the rigid-body integration. Asserted bit-identical.
//!
//! ## Second pass (2026-11-14)
//!
//! `in.ms_ke` (`compute ke/multisphere`, `erotate/multisphere`), `in.ms_flags`
//! (template `fflag`/`tflag`), `in.ms_orient` (`orientation random`) and
//! `in.ms_lost` (lost atoms and bodies). Every one is bit-identical; each test
//! states its numbers, and `second_pass_gates_fail_when_ablated` shows that
//! each gate misses with its option switched off. V&V 4.16.1.

