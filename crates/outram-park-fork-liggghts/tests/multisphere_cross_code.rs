/// **`fix massflow/mesh` with clumps** (gh:#1491 item 4): `in.ms_massflow`,
/// four clumps (one mass-based distribution over both templates, 60/40 %,
/// `insert/pack ... particles_in_region 4 all_in yes`) fall at 1 m/s through
/// the 0.3 m square `plate_square.stl` at `z = 0`. The plate is counted by
/// `massflow/mesh ... vec_side 0 0 -1 count once`, and the floor is at
/// `z = -0.12`. Upstream weights each counted member atom's `rmass` (the clump
/// mass) and its count by `volumeweight_ms`. A clump that is half across
/// therefore counts as a fraction: upstream prints `1.684...` particles at
/// step 4500, and the total reaches `4.0000000000000009`, not 4, because the
/// weights are Monte-Carlo fractions.
///
/// Compared: every atom at steps 1, 2000, 4000, 6000, 8000, 10000 and 12000,
/// and the counted mass and count (`f_mf[1]`, `f_mf[2]`) at all 25 thermo
/// steps (`ms_massflow_thermo.txt`, `%.17g`). The rates `f_mf[3..4]` depend on
/// when thermo evaluates them (every `run` boundary adds a line), so they are
/// not compared here; `massflow_mesh_cross_code.rs` covers them.
///
/// **Prediction (2026-11-13, before the first run):** bit-identical.
/// **Result:** bit-identical. 98/98 atom-frames, 25/25 thermo lines, final
/// mass `0.0034334348125000013` kg, count `4.0000000000000009`.
#[test]
fn ms_massflow_matches_liggghts() {
    use outram_park_fork_liggghts::massflow::{MassFlowConfig, MassFlowMesh};
    use outram_park_fork_liggghts::mesh_wall::MeshWall;
    let (Some(csv), Some(thermo), Some(stl)) = (
        read("ms_massflow.csv"),
        read("ms_massflow_thermo.txt"),
        read("plate_square.stl"),
    ) else {
        eprintln!("skipping: reference-data/liggghts/ms_massflow* not present");
        return;
    };
    let lo = Vec3::new(-0.2, -0.2, -0.2);
    let hi = Vec3::new(0.2, 0.2, 0.2);
    let material = GranularMaterial::new(1.0e7, 0.3, 0.5, 0.4).unwrap();
    let floor = Boundary::wall(Vec3::new(0.0, 0.0, -0.12), Vec3::new(0.0, 0.0, 1.0)).unwrap();
    let mut sys = GranularSystem::new(
        Vec::new(),
        vec![floor],
        GranularContactModel::hertz_history(material),
        Vec3::new(0.0, 0.0, -9.81),
        1e-5,
    )
    .unwrap();
    let dist = ParticleDistributionDiscrete::new_multisphere(
        15485867,
        true,
        vec![(clump1(), 0.6), (clump2(), 0.4)],
    )
    .unwrap();
    let reg = InsertRegion::block(Vec3::new(-0.05, -0.05, 0.03), Vec3::new(0.05, 0.05, 0.08)).unwrap();
    let fix = InsertFix::new(InsertMode::Pack(PackTarget::Particles(4)), 32452843, dist, reg, 0, lo, hi)
        .unwrap()
        .with_all_in(true)
        .with_velocity(outram_park_fork_liggghts::insert::InsertVelocity::Constant(Vec3::new(0.0, 0.0, -1.0)))
        .with_omega(Vec3::new(1.0, 2.0, 3.0));
    sys.add_insertion(fix).unwrap();
    let mut cfg = LiggghtsNeighbor::new(lo, hi, 0.002).unwrap();
    cfg.sort_every = 0;
    let mut sys = sys.with_liggghts_neighbor_order(cfg);
    let mf = sys.add_massflow_mesh(
        MassFlowMesh::new(
            MeshWall::from_ascii_stl(&stl).unwrap(),
            MassFlowConfig {
                vec_side: Vec3::new(0.0, 0.0, -1.0),
                once: true,
                point_at_outlet: None,
                inside_out: false,
                skin: 0.002,
            },
        )
        .unwrap(),
    );
    let rows: Vec<Vec<f64>> = csv
        .lines()
        .skip(1)
        .map(|l| l.split(',').map(|x| x.parse().unwrap()).collect())
        .collect();
    let thermo: Vec<Vec<f64>> = thermo
        .lines()
        .map(|l| l.split_whitespace().map(|x| x.parse().unwrap()).collect())
        .collect();
    let frames = [1u64, 2000, 4000, 6000, 8000, 10000, 12000];
    let mut checkpoints: Vec<u64> = thermo.iter().map(|t| t[0] as u64).chain(frames).collect();
    checkpoints.sort_unstable();
    checkpoints.dedup();
    let (mut total, mut same, mut th_same) = (0, 0, 0);
    let mut at = 0;
    for step in checkpoints {
        sys.run((step - at) as usize);
        at = step;
        if let Some(t) = thermo.iter().find(|t| t[0] as u64 == step) {
            if step > 0
                && sys.massflow_vector(mf, 0).to_bits() == t[2].to_bits()
                && sys.massflow_vector(mf, 1).to_bits() == t[3].to_bits()
            {
                th_same += 1;
            } else if step > 0 {
                println!(
                    "thermo step {step}: ({}, {}) vs ({}, {})",
                    sys.massflow_vector(mf, 0),
                    sys.massflow_vector(mf, 1),
                    t[2],
                    t[3]
                );
            }
        }
        for r in rows.iter().filter(|r| r[0] as u64 == step) {
            let p = &sys.particles()[r[1] as usize - 1];
            let mine = [
                p.position.x,
                p.position.y,
                p.position.z,
                p.velocity.x,
                p.velocity.y,
                p.velocity.z,
                p.angular_velocity.x,
                p.angular_velocity.y,
                p.angular_velocity.z,
            ];
            total += 1;
            if (0..9).all(|k| mine[k].to_bits() == r[2 + k].to_bits()) {
                same += 1;
            }
        }
    }
    let n_thermo = thermo.len() - 1;
    println!(
        "ms_massflow: {same}/{total} atom-frames, {th_same}/{n_thermo} thermo lines bit-identical; \
         final mass {} kg, count {}",
        sys.massflow_vector(mf, 0),
        sys.massflow_vector(mf, 1)
    );
    assert_eq!(total, 98);
    assert_eq!(same, total, "atom frames not bit-identical");
    assert_eq!(th_same, n_thermo, "massflow totals not bit-identical");
}

/// The clump bookkeeping the cross-code comparison does not show directly:
/// gravity acts on the body, not on its atoms; the two clumps are separate
/// bodies; no intra-clump pair is in the list (the atoms overlap by
/// construction and would otherwise blow the clump apart). ~~A second run
/// set-up is refused.~~ **CORRECTED 2026-11-14 (gh:#1415):** a second run
/// set-up is ported (`ms_rerun_matches_liggghts`).
#[test]
fn clump_bookkeeping() {
    let mut sys = system("ms_collide");
    sys.run(1);
    let ms = sys.multisphere().expect("clumps inserted");
    assert_eq!(ms.bodies().len(), 2);
    assert_eq!(ms.bodies()[0].nrigid, 3);
    assert_eq!(ms.bodies()[1].nrigid, 4);
    assert_eq!((ms.bodies()[0].id, ms.bodies()[1].id), (1, 2));
    for i in 0..7 {
        assert_eq!(ms.body_of(i), Some(usize::from(i >= 3)));
    }
    let w: f64 = (0..3).map(|i| ms.volume_weight(i)).sum();
    assert!((w - 1.0).abs() < 1e-12);
    // members overlap but feel no force from each other: the body stays rigid
    let d0 = sys.particles()[0].position.sub(sys.particles()[1].position).norm();
    sys.run(3000);
    let d1 = sys.particles()[0].position.sub(sys.particles()[1].position).norm();
    assert!((d0 - d1).abs() < 1e-12, "{d0} {d1}");
    sys.begin_run().unwrap();
}

