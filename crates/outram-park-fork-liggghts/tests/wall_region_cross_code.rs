//! # `fix wall/region` (lj93, lj126, colloid, harmonic) against upstream (gh:#1416)
//!
//! ## Methodology
//!
//! Deck `reference-data/liggghts/in.wallregion` (generated by
//! `make_wallregion_deck.sh`; LIGGGHTS-PUBLIC `3d5c00f2`): the settled 354-pebble
//! bed (`pebble_bed_settled.csv`), Hertz/history pair contacts, gravity, and NO
//! `fix wall/gran`: the only walls are four `fix wall/region` (one per style,
//! interior `cylinder`/`block` regions, `units box`):
//! `h` harmonic (eps 5, cutoff 0.012, cylinder r 0.030, the real wall and
//! floor), `a` lj93, `b` lj126, `c` colloid. 2000 steps, `dump` every 100 steps
//! (`wallregion_traj.csv`, 21 frames x 354 x 9) and `thermo` every 100 steps of
//! `ke`, each fix's energy scalar and its force-on-wall vector (`%.17g`,
//! `wallregion_thermo.txt`). This test runs [`ForceFix::WallRegion`]
//! (`InsertRegion::surface_interior`) on the same bed and compares every value
//! as bits.
//!
//! ## Prediction (written before the run, 2026-11-11)
//!
//! All operations are plain double arithmetic in upstream's order, plus
//! `pow(sigma, n)` and, for colloid, `log`: both are the platform glibc in
//! upstream and in Rust's `std`, so **everything bit-identical**. If not, the
//! only accepted cause is a last-ulp `pow`/`log` difference (gh:#1455).
//!
//! **CORRECTED 2026-11-12 (epic gh:#1336):** the port's `pow`/`log` are no
//! longer `std`: the no-platform-libm gate moved `force_fixes.rs` to
//! PETIR's `r_powf`/`r_ln`. Re-run the same day on PETIR's maths: both tests
//! still pass, every compared value bit-identical.
//!
//! ## Result
//!
//! See the printed counts (`--nocapture`) and
//! ~~`verification_and_validation/wall_region.md`~~
//! `verification_and_validation/force_fixes.md`, section `fix wall/region`
//! (**CORRECTED 2026-11-12**: `wall_region.md` does not exist).

use outram_park_fork_liggghts::force_fixes::{ForceFix, WallRegionStyle};
use outram_park_fork_liggghts::granular::{GranularContactModel, GranularMaterial};
use outram_park_fork_liggghts::granular_system::GranularSystem;
use outram_park_fork_liggghts::insert::{Axis, InsertRegion};
use outram_park_fork_liggghts::neighbor_list::LiggghtsNeighbor;
use outram_park_fork_liggghts::particle::{Particle, Vec3};
use uom::si::f64::{Length, Mass, ThermodynamicTemperature};
use uom::si::{length::meter, mass::kilogram, thermodynamic_temperature::kelvin};

const R_P: f64 = 0.005;

fn read(name: &str) -> Option<String> {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../reference-data/liggghts")
        .join(name);
    std::fs::read_to_string(path).ok()
}

fn particles(csv: &str) -> Vec<Particle> {
    let mass = 2500.0 * 4.0 / 3.0 * std::f64::consts::PI * R_P * R_P * R_P;
    csv.lines()
        .skip(1)
        .filter(|l| !l.trim().is_empty())
        .map(|l| {
            let v: Vec<f64> = l.split(',').map(|x| x.parse().unwrap()).collect();
            Particle::new(
                Vec3::new(v[1], v[2], v[3]),
                Vec3::new(v[4], v[5], v[6]),
                Vec3::zero(),
                Mass::new::<kilogram>(mass),
                Length::new::<meter>(R_P),
                ThermodynamicTemperature::new::<kelvin>(300.0),
            )
            .unwrap()
        })
        .collect()
}

fn wall(
    n: usize,
    region: InsertRegion,
    style: WallRegionStyle,
    epsilon: f64,
    sigma: f64,
    cutoff: f64,
) -> ForceFix {
    ForceFix::WallRegion {
        group: vec![true; n],
        region,
        style,
        epsilon,
        sigma,
        cutoff,
        ewall: [0.0; 4],
    }
}

fn cyl(radius: f64, lo: f64, hi: f64) -> InsertRegion {
    let m = Length::new::<meter>;
    InsertRegion::cylinder(Axis::Z, m(0.0), m(0.0), m(radius), m(lo), m(hi)).unwrap()
}

fn system(init: &str) -> GranularSystem {
    let ps = particles(init);
    let n = ps.len();
    let fixes = vec![
        wall(n, cyl(0.030, 0.0, 0.4), WallRegionStyle::Harmonic, 5.0, 0.0, 0.012),
        wall(
            n,
            InsertRegion::block(
                Vec3::new(-0.0325, -0.0325, -0.002),
                Vec3::new(0.0325, 0.0325, 0.4),
            )
            .unwrap(),
            WallRegionStyle::Lj93,
            1.0e-5,
            0.008,
            0.009,
        ),
        wall(n, cyl(0.034, -0.05, 0.3), WallRegionStyle::Lj126, 1.0e-6, 0.010, 0.012),
        wall(
            n,
            InsertRegion::block(
                Vec3::new(-0.05, -0.05, -0.003),
                Vec3::new(0.05, 0.05, 0.3),
            )
            .unwrap(),
            WallRegionStyle::Colloid,
            1.0e-9,
            0.001,
            0.011,
        ),
    ];
    let material = GranularMaterial::new(5.0e6, 0.3, 0.5, 0.3).unwrap();
    GranularSystem::new(
        ps,
        vec![],
        GranularContactModel::hertz_history(material),
        Vec3::new(0.0, 0.0, -9.81),
        5e-6,
    )
    .unwrap()
    .with_liggghts_neighbor_order(
        LiggghtsNeighbor::new(
            Vec3::new(-1.0, -1.0, -0.005),
            Vec3::new(1.0, 1.0, 0.35),
            0.003,
        )
        .unwrap(),
    )
    .with_force_fixes(fixes)
}

fn run(max_step: usize) -> (usize, usize, usize, usize, f64) {
    let (Some(init), Some(traj), Some(thermo)) = (
        read("pebble_bed_settled.csv"),
        read("wallregion_traj.csv"),
        read("wallregion_thermo.txt"),
    ) else {
        eprintln!("skipping: reference data not present");
        return (0, 0, 0, 0, 0.0);
    };
    let mut sys = system(&init);
    let thermo_rows: Vec<Vec<f64>> = thermo
        .lines()
        .filter(|l| !l.trim().is_empty())
        .map(|l| l.split_whitespace().map(|x| x.parse().unwrap()).collect())
        .collect();
    let mut done = 0usize;
    let (mut total, mut same, mut ttotal, mut tsame) = (0, 0, 0, 0);
    let mut worst = 0.0f64;
    for row in traj.lines().skip(1).filter(|l| !l.trim().is_empty()) {
        let v: Vec<f64> = row.split(',').map(|x| x.parse().unwrap()).collect();
        let step = v[0] as usize;
        if step > max_step {
            break;
        }
        sys.run(step - done);
        done = step;
        for (i, p) in sys.particles().iter().enumerate() {
            let o = 1 + 9 * i;
            let ours = [
                p.position.x,
                p.position.y,
                p.position.z,
                p.velocity.x,
                p.velocity.y,
                p.velocity.z,
                p.angular_velocity.x,
                p.angular_velocity.y,
                p.angular_velocity.z,
            ];
            for k in 0..9 {
                total += 1;
                if ours[k].to_bits() == v[o + k].to_bits() {
                    same += 1;
                } else {
                    let scale = v[o + k].abs().max(1e-300);
                    worst = worst.max(((ours[k] - v[o + k]) / scale).abs());
                }
            }
        }
        // thermo: step ke then (E, Fx, Fy, Fz) for h, a, b, c
        let t = thermo_rows
            .iter()
            .find(|r| r[0] as usize == step)
            .expect("thermo row");
        let mut cols = Vec::new();
        for fx in sys.force_fixes() {
            if let ForceFix::WallRegion { ewall, .. } = fx {
                cols.extend_from_slice(ewall);
            }
        }
        for (k, c) in cols.iter().enumerate() {
            ttotal += 1;
            if c.to_bits() == t[2 + k].to_bits() {
                tsame += 1;
            } else {
                let scale = t[2 + k].abs().max(1e-300);
                worst = worst.max(((c - t[2 + k]) / scale).abs());
            }
        }
    }
    eprintln!(
        "wall/region: trajectory {same}/{total}, thermo (E, F on wall) {tsame}/{ttotal} bit-identical, worst rel {worst:e}"
    );
    (same, total, tsame, ttotal, worst)
}

/// The whole deck: positions, velocities, spins of 354 pebbles at 21 frames and
/// the four fixes' energy and wall force at 21 thermo rows, as bits. Result:
/// see `verification_and_validation/wall_region.md`.
#[test]
fn wall_region_four_styles_match_liggghts() {
    let (same, total, tsame, ttotal, _) = run(usize::MAX);
    assert_eq!(same, total);
    assert_eq!(tsame, ttotal);
}

/// Every style exerted a force during the run (the comparison is not vacuous).
#[test]
fn wall_region_all_styles_active() {
    let Some(init) = read("pebble_bed_settled.csv") else {
        return;
    };
    let mut sys = system(&init);
    sys.run(100);
    for fx in sys.force_fixes() {
        if let ForceFix::WallRegion { ewall, style, .. } = fx {
            assert!(
                ewall[0] != 0.0 || ewall[3] != 0.0,
                "{style:?} wall had no contact"
            );
        }
    }
}
