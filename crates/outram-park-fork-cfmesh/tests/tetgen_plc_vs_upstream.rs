//! TetGen port, stage 5 (gh:#1794, epic gh:#1789): the whole `-p` route
//! (`tetgen::tetrahedralize_plc`: boundary recovery, `carveholes`,
//! Steiner-point suppression, `recoverdelaunay`, `smooth_vertices`,
//! `improve_mesh`, `jettisonnodes`, the output) against the **unmodified**
//! upstream binary.
//!
//! **Methodology.** Reference: TetGen 1.6.0 (libigl/tetgen `e05aca7df74e`),
//! the `tetgen` binary of the upstream clone, run as `tetgen -pz`,
//! `-pzY` on every case and `-pzA`, `-pzAY` on the three with volume holes
//! or regions, **without `-Q`** (stage 4: `-Q` changes upstream's control
//! flow), x86_64, glibc 2.39. Its `.node`, `.ele`, `.face` and `.edge`
//! files are committed gzipped in `test_data/tetgen_plc/` (the inputs are
//! stage 3's and stage 4's, plus `fuel_pin_hole` and `fuel_pin_regions`).
//! The port renders [`TetgenOutput`] with upstream's `fprintf` formats
//! (`%.17g` included) and the same `# Generated by tetgen -<sw> <file> `
//! line. **Pass criterion: every file equal byte for byte.** No tolerance.
//!
//! **Results (2026-11-26):** 48 / 48 runs, 192 / 192 files identical. The
//! per-case table and the `improve_mesh` reach counts are in
//! `verification_and_validation/tetgen_plc_gh1794/README.md`.

use outram_park_fork_cfmesh::tetgen::mesh::{DUMMYPOINT, NULL_POINT};
use outram_park_fork_cfmesh::tetgen::{
    tetrahedralize_plc, to_volume_mesh, PlcInput, Switches, TetgenOutput,
};
use std::collections::BTreeSet;
use std::path::PathBuf;

/// Inflate a `gzip -n` file (10-byte header, 8-byte trailer).
fn gunzip(bytes: &[u8]) -> Vec<u8> {
    assert!(
        bytes.len() > 18 && bytes[0] == 0x1f && bytes[1] == 0x8b,
        "not gzip"
    );
    assert_eq!(bytes[3], 0, "gzip -n expected (no name/extra flags)");
    miniz_oxide::inflate::decompress_to_vec(&bytes[10..bytes.len() - 8]).expect("inflate")
}

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("test_data")
}

fn read_gz(dir: &str, name: &str) -> Option<String> {
    let p = root().join(dir).join(format!("{name}.gz"));
    let b = std::fs::read(&p).ok()?;
    Some(String::from_utf8(gunzip(&b)).unwrap())
}

/// The committed input of a case and its file name.
fn input(case: &str) -> (PlcInput, String) {
    for dir in ["tetgen_meshsurface", "tetgen_recoverboundary", "tetgen_plc"] {
        let (mut plc, name) = if let Some(t) = read_gz(dir, &format!("{case}.poly")) {
            (PlcInput::read_poly(&t).unwrap(), format!("{case}.poly"))
        } else if let Some(t) = read_gz(dir, &format!("{case}.smesh")) {
            (PlcInput::read_smesh(&t).unwrap(), format!("{case}.smesh"))
        } else {
            continue;
        };
        if let Some(e) = read_gz(dir, &format!("{case}.edge")) {
            plc.read_edge(&e).unwrap();
        }
        return (plc, name);
    }
    panic!("no input for {case}");
}

