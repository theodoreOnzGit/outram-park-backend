/// The cases run with `-A` too (volume holes or regions).
const REGION_CASES: [&str; 3] = ["example", "box_hole", "fuel_pin_regions"];

fn runs() -> Vec<(&'static str, &'static str)> {
    let mut v = Vec::new();
    for sw in ["pz", "pzY"] {
        for c in CASES {
            v.push((c, sw));
        }
    }
    for sw in ["pzA", "pzAY"] {
        for c in REGION_CASES {
            v.push((c, sw));
        }
    }
    v
}

fn run(case: &str, sw: &str) -> (TetgenOutput, String, std::time::Duration, [u64; 64]) {
    let (plc, file) = input(case);
    let b = Switches::parse(sw).unwrap().behavior();
    let t0 = std::time::Instant::now();
    let r = tetrahedralize_plc(&plc, &b).unwrap_or_else(|e| panic!("{case} -{sw}: {e:?}"));
    let dt = t0.elapsed();
    (
        r.output.unwrap(),
        format!("tetgen -{sw} {file} "),
        dt,
        r.mesh.reach5,
    )
}

/// The four files, as the port writes them.
fn files(out: &TetgenOutput, cmd: &str) -> [(&'static str, Option<String>); 4] {
    [
        ("node", Some(out.node_text(cmd))),
        ("ele", Some(out.ele_text(cmd))),
        ("face", out.face_text(cmd)),
        ("edge", Some(out.edge_text(cmd))),
    ]
}

/// Every run's `.node`, `.ele`, `.face`, `.edge` equal upstream's byte for
/// byte, and the 64 stage 5 reach counters (`tg5`, from the instrumented
/// build of `stage5_reach.patch`, which writes the same files) equal the
/// port's `TetgenMesh::reach5`. `TETGEN_PLC_WRITE=<dir>` writes the port's
/// files (to diff).
#[test]
fn plc_output_matches_upstream_byte_for_byte() {
    let write = std::env::var("TETGEN_PLC_WRITE").ok();
    let mut bad = Vec::new();
    let mut nfiles = 0;
    for (case, sw) in runs() {
        let (out, cmd, dt, reach) = run(case, sw);
        let theirs: Vec<u64> = read_gz("tetgen_plc", &format!("{case}.{sw}.reach5"))
            .unwrap()
            .split_whitespace()
            .map(|x| x.parse().unwrap())
            .collect();
        if theirs[..] != reach[..] {
            bad.push(format!("{case}.{sw}.reach5: ours {:?}", &reach[..34]));
        }
        let mut same = 0;
        for (ext, text) in files(&out, &cmd) {
            let theirs = read_gz("tetgen_plc", &format!("{case}.{sw}.{ext}"));
            if let (Some(d), Some(t)) = (&write, &text) {
                std::fs::write(format!("{d}/{case}.{sw}.{ext}"), t).unwrap();
            }
            nfiles += 1;
            if text == theirs {
                same += 1;
            } else {
                bad.push(format!("{case}.{sw}.{ext}"));
            }
        }
        println!(
            "{case:17} -{sw:5} nodes {:5} tets {:6} faces {:5} edges {:5} files {same}/4  {:8.3} ms",
            out.points.len(),
            out.tets.len(),
            out.faces.as_ref().map_or(0, |f| f.len()),
            out.edges.len(),
            dt.as_secs_f64() * 1e3
        );
    }
    assert!(
        bad.is_empty(),
        "{} of {nfiles} files differ: {bad:?}",
        bad.len()
    );
}

/// The comparison can fail: one choice of `improve_mesh` perturbed (the
/// largest dihedral angle it accepts, `-o/176` instead of upstream's 177)
/// changes `pebble -pz`'s `.ele`.
#[test]
fn the_comparison_can_fail() {
    let (plc, file) = input("pebble");
    let mut b = Switches::parse("pz").unwrap().behavior();
    b.optmaxdihedral = 176.0;
    let out = tetrahedralize_plc(&plc, &b).unwrap().output.unwrap();
    let cmd = format!("tetgen -pz {file} ");
    assert_ne!(
        Some(out.ele_text(&cmd)),
        read_gz("tetgen_plc", "pebble.pz.ele")
    );
}

/// The volume a PLC encloses, from its facets alone. A facet's region is
/// its polygons (three or more vertices) taken by nesting depth (the area
/// inside an even number of them), minus the components that hold one of
/// its hole points; the region's outward side is found by ray parity (a
/// point just off it, crossing the facet regions an odd number of times,
/// is inside; a facet with the same parity on both sides bounds nothing),
/// and the divergence theorem gives the volume.
/// Only the facets whose marker `keep` accepts take part (one closed
/// surface, or nested ones, at a time: see [`domain_volume`]).
fn plc_volume(plc: &PlcInput, keep: &dyn Fn(i32) -> bool) -> f64 {
    type V = [f64; 3];
    let sub = |a: V, b: V| [a[0] - b[0], a[1] - b[1], a[2] - b[2]];
    let cross = |a: V, b: V| {
        [
            a[1] * b[2] - a[2] * b[1],
            a[2] * b[0] - a[0] * b[2],
            a[0] * b[1] - a[1] * b[0],
        ]
    };
    let dot = |a: V, b: V| a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
    let first = plc.firstnumber as usize;
    // Facet region: polygons (as point lists), area vectors, plane, axes.
    struct Region {
        polys: Vec<Vec<V>>,
        depth: Vec<usize>,
        removed: Vec<bool>,
        n: V,
        p0: V,
        ax: (usize, usize),
    }
    let newell = |p: &[V]| {
        let mut a = [0.0; 3];
        for k in 0..p.len() {
            let c = cross(p[k], p[(k + 1) % p.len()]);
            a = [a[0] + 0.5 * c[0], a[1] + 0.5 * c[1], a[2] + 0.5 * c[2]];
        }
        a
    };
    let inside2 = |poly: &[V], ax: (usize, usize), x: V| {
        let (u, v) = ax;
        let mut c = false;
        let n = poly.len();
        for k in 0..n {
            let (a, b) = (poly[k], poly[(k + 1) % n]);
            if (a[v] > x[v]) != (b[v] > x[v]) {
                let t = (x[v] - a[v]) / (b[v] - a[v]);
                if x[u] < a[u] + t * (b[u] - a[u]) {
                    c = !c;
                }
            }
        }
        c
    };
    // A point just inside polygon `p`, next to the middle of its first
    // edge: inside another polygon only if `p` is nested in it.
    let near_edge = |p: &[V], n: V, ax: (usize, usize)| {
        let m = [
            (p[0][0] + p[1][0]) / 2.0,
            (p[0][1] + p[1][1]) / 2.0,
            (p[0][2] + p[1][2]) / 2.0,
        ];
        let e = sub(p[1], p[0]);
        let d = cross(n, e);
        let ld = dot(d, d).sqrt();
        let le = dot(e, e).sqrt();
        let h = 1e-6 * le;
        for s in [1.0, -1.0] {
            let x = [
                m[0] + s * h * d[0] / ld,
                m[1] + s * h * d[1] / ld,
                m[2] + s * h * d[2] / ld,
            ];
            if inside2(p, ax, x) {
                return x;
            }
        }
        m
    };
    let mut regions = Vec::new();
    for (k, f) in plc.facets.iter().enumerate() {
        let m = plc.facet_markers.as_ref().map_or(0, |v| v[k]);
        if !keep(m) {
            continue;
        }
        let polys: Vec<Vec<V>> = f
            .polygons
            .iter()
            .filter(|p| p.len() >= 3)
            .map(|p| p.iter().map(|&i| plc.points[i as usize - first]).collect())
            .collect();
        if polys.is_empty() {
            continue;
        }
        let n = newell(&polys[0]);
        let an = [n[0].abs(), n[1].abs(), n[2].abs()];
        let ax = if an[0] >= an[1] && an[0] >= an[2] {
            (1, 2)
        } else if an[1] >= an[2] {
            (2, 0)
        } else {
            (0, 1)
        };
        let depth: Vec<usize> = polys
            .iter()
            .enumerate()
            .map(|(i, p)| {
                let x = near_edge(p, n, ax);
                polys
                    .iter()
                    .enumerate()
                    .filter(|(j, q)| *j != i && inside2(q, ax, x))
                    .count()
            })
            .collect();
        let mut r = Region {
            removed: vec![false; polys.len()],
            depth,
            polys,
            n,
            p0: [0.0; 3],
            ax,
        };
        r.p0 = r.polys[0][0];
        // A hole point removes the innermost polygon component holding it.
        for h in &f.holes {
            let mut best: Option<(usize, usize)> = None;
            for (i, p) in r.polys.iter().enumerate() {
                if inside2(p, ax, *h) && best.is_none_or(|(_, d)| r.depth[i] > d) {
                    best = Some((i, r.depth[i]));
                }
            }
            if let Some((i, _)) = best {
                r.removed[i] = true;
            }
        }
        regions.push(r);
    }
    // Is x (on the region's plane) in the region?
    let in_region = |r: &Region, x: V| {
        let mut best: Option<(usize, usize)> = None;
        for (i, p) in r.polys.iter().enumerate() {
            if inside2(p, r.ax, x) && best.is_none_or(|(_, d)| r.depth[i] > d) {
                best = Some((i, r.depth[i]));
            }
        }
        match best {
            Some((i, d)) => d % 2 == 0 && !r.removed[i],
            None => false,
        }
    };
    let dir = [0.5773, 0.6123, 0.5401];
    let hits = |o: V| {
        let mut c = 0;
        for r in &regions {
            let den = dot(r.n, dir);
            if den.abs() < 1e-14 {
                continue;
            }
            let t = dot(r.n, sub(r.p0, o)) / den;
            if t > 1e-12 {
                let x = [o[0] + t * dir[0], o[1] + t * dir[1], o[2] + t * dir[2]];
                if in_region(r, x) {
                    c += 1;
                }
            }
        }
        c
    };
    let mut vol = 0.0;
    for r in &regions {
        // The region's area vector, components by depth parity, each
        // polygon's own area oriented like the first's.
        let mut a = [0.0; 3];
        for (i, p) in r.polys.iter().enumerate() {
            let mut ai = newell(p);
            if dot(ai, r.n) < 0.0 {
                ai = [-ai[0], -ai[1], -ai[2]];
            }
            // Component i = polygon i minus its children; kept if its depth
            //   is even and no hole point removed it.
            let keep = r.depth[i] % 2 == 0 && !r.removed[i];
            let s = if keep { 1.0 } else { 0.0 };
            a = [a[0] + s * ai[0], a[1] + s * ai[1], a[2] + s * ai[2]];
            // Its children (depth + 1, inside it) are cut out of it.
            for (j, q) in r.polys.iter().enumerate() {
                if keep && r.depth[j] == r.depth[i] + 1 && inside2(p, r.ax, near_edge(q, r.n, r.ax))
                {
                    let mut aj = newell(q);
                    if dot(aj, r.n) < 0.0 {
                        aj = [-aj[0], -aj[1], -aj[2]];
                    }
                    a = [a[0] - aj[0], a[1] - aj[1], a[2] - aj[2]];
                }
            }
        }
        if dot(a, a) == 0.0 {
            continue;
        }
        // A point of the region: a fan-triangle centroid inside it.
        let x = r
            .polys
            .iter()
            .map(|p| near_edge(p, r.n, r.ax))
            .find(|&c| in_region(r, c))
            .expect("a point inside the facet region");
        let ln = dot(r.n, r.n).sqrt();
        let eps = 1e-7;
        let behind = [
            x[0] - eps * r.n[0] / ln,
            x[1] - eps * r.n[1] / ln,
            x[2] - eps * r.n[2] / ln,
        ];
        let front = [
            x[0] + eps * r.n[0] / ln,
            x[1] + eps * r.n[1] / ln,
            x[2] + eps * r.n[2] / ln,
        ];
        // n points out if just behind it is inside (odd parity) and just
        //   in front outside; a facet with the domain on neither side (the
        //   caps of a hole on the hull) or both bounds nothing.
        let sign = match (hits(behind) % 2 == 1, hits(front) % 2 == 1) {
            (true, false) => 1.0,
            (false, true) => -1.0,
            _ => 0.0,
        };
        vol += sign * dot(r.p0, a) / 3.0;
    }
    vol
}

/// The volume of a case's domain, from how each input was built: the
/// outer surface (all facets but the internal ones, which have the domain
/// on both sides: `example`'s facet 9, the `facet_wall*` wall 7, the
/// `fin_box` fin 8, the meshed pebble's sphere 3, `fuel_pin_regions`' pin
/// wall 3), less the closed shell around a volume hole when that shell
/// shares facets with the hull (`fuel_pin_hole`: pin wall 3 and caps 5, 6;
/// `box_hole`'s cube is nested inside, which the parity already counts as
/// a cavity).
fn domain_volume(case: &str, plc: &PlcInput) -> f64 {
    let internal: &[i32] = match case {
        "example" => &[9],
        "facet_wall" | "facet_wall2" => &[7],
        "fin_box" => &[8],
        "pebble" | "fuel_pin_regions" | "fuel_pin_hole" => &[3],
        _ => &[],
    };
    let outer = plc_volume(plc, &|m| !internal.contains(&m));
    if case == "fuel_pin_hole" {
        outer - plc_volume(plc, &|m| [3, 5, 6].contains(&m))
    } else {
        outer
    }
}

/// Upstream-free checks of the whole route, on every case and switch: the
/// tetrahedra fill exactly the volume the PLC encloses net of its holes
/// (relative 1e-9); every tetrahedron is positively oriented (exact
/// `orient3d < 0`, TetGen's convention); every boundary face of the
/// tetrahedral mesh is an output subface (`.face`). And the export to a
/// [`outram_park_fork_cfmesh::volume_mesh::VolumeMesh`] is closed, keeps
/// every tetrahedron and puts every boundary face in a marker patch.
#[test]
fn plc_mesh_fills_the_domain() {
    for (case, sw) in runs() {
        let (plc, _) = input(case);
        let b = Switches::parse(sw).unwrap().behavior();
        let r = tetrahedralize_plc(&plc, &b).unwrap();
        let m = &r.mesh;
        let out = r.output.as_ref().unwrap();
        // Orientation, on the mesh itself.
        for t in m.tets.iter().take(m.tetpool.maxitems) {
            if t.v[0] == NULL_POINT || t.v[3] == DUMMYPOINT {
                continue;
            }
            let o = m
                .pred
                .orient3d(m.xyz(t.v[0]), m.xyz(t.v[1]), m.xyz(t.v[2]), m.xyz(t.v[3]));
            assert!(
                o < 0.0,
                "{case} -{sw}: tet {:?} not positively oriented",
                t.v
            );
        }
        // Volume.
        let pt = |i: i32| out.points[(i - out.firstindex) as usize];
        let mut v = 0.0;
        for t in &out.tets {
            let (a, b, c, d) = (pt(t[0]), pt(t[1]), pt(t[2]), pt(t[3]));
            let u = [b[0] - a[0], b[1] - a[1], b[2] - a[2]];
            let w = [c[0] - a[0], c[1] - a[1], c[2] - a[2]];
            let z = [d[0] - a[0], d[1] - a[1], d[2] - a[2]];
            let det = u[0] * (w[1] * z[2] - w[2] * z[1]) - u[1] * (w[0] * z[2] - w[2] * z[0])
                + u[2] * (w[0] * z[1] - w[1] * z[0]);
            v += det.abs() / 6.0;
        }
        // Hull-sliver peeling (`lawsonflip3d` after `carveholes`) removes
        //   tetrahedra between two boundary triangles of different facets,
        //   and flips those triangles: the mesh then encloses the PLC volume
        //   less the peeled slivers' (sphere -pz: 534 slivers).
        let expect = domain_volume(case, &plc) - m.hull_sliver_volume;
        assert!(
            ((v - expect) / expect).abs() < 1e-9,
            "{case} -{sw}: tet volume {v} != PLC volume {expect}"
        );
        // Boundary faces are subfaces.
        let key = |mut k: [i32; 3]| {
            k.sort_unstable();
            k
        };
        let subfaces: BTreeSet<[i32; 3]> = out
            .faces
            .as_ref()
            .unwrap()
            .iter()
            .map(|f| key(*f))
            .collect();
        let mut seen: std::collections::BTreeMap<[i32; 3], u32> = Default::default();
        for t in &out.tets {
            for f in [
                [t[0], t[1], t[2]],
                [t[0], t[1], t[3]],
                [t[1], t[2], t[3]],
                [t[0], t[2], t[3]],
            ] {
                *seen.entry(key(f)).or_default() += 1;
            }
        }
        for (f, n) in &seen {
            if *n == 1 {
                assert!(
                    subfaces.contains(f),
                    "{case} -{sw}: boundary face {f:?} is no subface"
                );
            }
        }
        // The VolumeMesh export.
        let vm = to_volume_mesh(out, None);
        assert_eq!(vm.n_cells, out.tets.len());
        vm.validate()
            .unwrap_or_else(|e| panic!("{case} -{sw}: {e}"));
        assert!(
            vm.patches.iter().all(|p| p.name.starts_with("marker_")),
            "{case}"
        );
        println!(
            "{case:17} -{sw:5} volume {v:.12} (PLC less peeled slivers {expect:.12}, slivers {:.3e}), {} cells, {} patches",
            m.hull_sliver_volume,
            vm.n_cells,
            vm.patches.len()
        );
    }
}
