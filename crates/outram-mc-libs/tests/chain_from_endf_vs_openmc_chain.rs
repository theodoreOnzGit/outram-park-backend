#![cfg(feature = "std")]
//! **`Chain.from_endf`'s decay half against OpenMC's own chain** (gh:#1621).
//!
//! Methodology: build a chain with
//! `njoy_outram_park_fork::hdf5::depletion_chain_from_endf::from_endf` from
//! the ENDF/B-VIII.0 decay sublibrary alone (NNDC, `reference-data/ace`,
//! gh:#1627), and compare every nuclide with OpenMC's `chain_endfb80`
//! (built by OpenMC's `Chain.from_endf` from the same sublibrary, packaged
//! as `openmc-endf-8-depletion-lib-a`/`-b`; its reactions are not public, so
//! only the decay half is compared: half-life, decay energy, and each decay
//! mode's type, target and branching ratio).
//!
//! Prediction, written before the run: half-life and decay energy equal
//! **exactly** for every nuclide in both (both parse the same ENDF text to
//! the same doubles and add the three mean energies in the same order);
//! decay modes equal on at least 99 % of nuclides, any difference coming
//! from the OpenMC version that built the packaged chain.
//!
//! Results, measured 2026-11-17:
//!
//! - 3820 nuclides in each chain, the same 3820.
//! - **Half-life and decay energy: equal exactly on all 3820** (prediction
//!   held).
//! - **Decay modes: equal on 3525 (92.3 %), so the 99 % prediction FAILED.**
//!   The 295 differences are all explained, and none is a port defect:
//!   - **127: only the spontaneous-fission target.** Ours has no target, as
//!     `e4febe9`'s `from_endf` sets (`elif 'sf' in type_: target = None`);
//!     the packaged chain gives `sf` a nuclide (the parent, or the
//!     preceding β daughter), the rule of the older OpenMC that built it.
//!     No type or other target differs anywhere.
//!   - **168: only branching ratios, by at most 9.0e-7 absolute** (Ba-114).
//!     The packaged ratios carry fewer digits than the tape (As-77:
//!     0.9966713 against the tape's 0.99667134) and put the remainder on
//!     the last mode, where `e4febe9` leaves a set within `isclose` of 1
//!     alone and otherwise corrects the largest.
//! - So this reference cannot be matched exactly by a faithful port of the
//!   current upstream; a chain generated by OpenMC `e4febe9` itself is the
//!   reference still needed (gh:#1626, needs OpenMC run).
//!
//! Gates: half-life and energy exact (a prediction); no type or target
//! difference other than the sf rule (a prediction, structural); ratio
//! differences ≤ 1e-6 absolute, **chosen after seeing 9.0e-7**, so a
//! regression pin and not evidence.

