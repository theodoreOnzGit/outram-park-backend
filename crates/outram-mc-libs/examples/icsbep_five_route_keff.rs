fn load_endf(name: &str) -> Nuclide {
    // The lattice's full tier (`--full-nuclides`, GitHub #533) names nuclides
    // this study's own table does not carry; they come from the LCT-008 model's
    // full tape list, the one `lct008_keff.rs` loads by default.
    let file = TAPES
        .iter()
        .chain(lct008_model::TAPES.iter())
        .find(|(n, _)| *n == name)
        .expect("known nuclide")
        .1;
    let p = reference_endf(file).unwrap_or_else(|| panic!("missing reference tape {file}"));
    Nuclide::from_endf_file_with_speed(&p, name, TEMP_K, outram_mc_libs::vv::bench_speed())
        .unwrap_or_else(|e| panic!("from_endf_file_with_speed({name}): {e}"))
}

fn load_ace(dir: &Path, name: &str) -> Nuclide {
    let p = dir.join("293.6K").join(format!("{name}.ace"));
    let n = Nuclide::from_ace_file(&p, name)
        .unwrap_or_else(|e| panic!("from_ace_file({}): {e}", p.display()));
    if let Some(why) = n.dbrc_unavailable_reason() {
        eprintln!(
            "    {name}: DBRC OFF -- {why}\n{}",
            Nuclide::zero_kelvin_companion_report(&p)
        );
    }
    n
}

/// The geometry a case's solver sees, as CSG. Godiva runs as a bare
/// homogeneous sphere through `run_keff` (no CSG), so it is drawn as the
/// one-sphere CSG of the same radius; every other case is drawn from the
/// very `Geometry` its runs use.
fn drawable(c: &Case) -> Geometry {
    match &c.model {
        Model::Csg(g, _) => g.clone(),
        Model::Sphere(r) => Geometry {
            surfaces: vec![SurfaceKind::Sphere(Sphere { x0: 0.0, y0: 0.0, z0: 0.0, r: *r, bc: BoundaryType::Vacuum })],
            cells: vec![Cell::material(
                1,
                vec![RegionToken::HalfSpace { surface_idx: 0, sense: HalfSpaceSense::Inside }],
                0,
                TEMP_K,
            )],
            universes: vec![Universe { id: 0, cell_indices: vec![0] }],
            lattices: vec![],
            root_universe: 0,
        },
    }
}

