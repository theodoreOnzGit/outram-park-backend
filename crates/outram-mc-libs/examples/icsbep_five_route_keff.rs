/// H in H₂O at [`TEMP_K`] regenerated by LEAPR from the ENDF/B-VIII.0 deck
/// compiled into `njoy-outram-park-fork` (maintainer direction 2026-10-14:
/// LEAPR always runs; the published `tsl-*.endf` tapes are oracles), through
/// [`ThermalScattering::from_embedded_leapr_deck`]: the deck's own 293.6 K
/// block, its tape read back and baked by `from_tape`, exactly as `--sab-tsl`
/// bakes the published one. The browser benchmark demos call the same
/// function. CLI glue: the library function is reached by
/// `tests/thermal_h2o_leapr_vs_tsl.rs`.
fn h_in_h2o_from_leapr() -> ThermalScattering {
    use njoy_outram_park_fork::leapr::decks::SabMaterial;
    let t0 = Instant::now();
    let law = ThermalScattering::from_embedded_leapr_deck(SabMaterial::HInH2O, TEMP_K, "c_H_in_H2O")
        .expect("H(H2O) S(a,b) from LEAPR");
    eprintln!("    H1: S(a,b) regenerated by LEAPR at {TEMP_K} K in {:.1} s", t0.elapsed().as_secs_f64());
    law
}

