//! **Four ICSBEP cases on outram-mc, by nuclear-data route** — the outram-mc
//! half of the five-route study
//! (`verification_and_validation/icsbep/five_route_keff/`).
//!
//! | route | transport | nuclear data | this program's `--route` |
//! |---|---|---|---|
//! | 1 | OpenMC | NJOY2016 ACE -> HDF5 | — (`openmc_inputs/icsbep_openmc.py`) |
//! | 2 | OpenMC | Rust-NJOY ACE -> HDF5 | — (same script) |
//! | 3 | outram-mc | NJOY2016 ACE | `ace --ace-dir <njoy lib>` |
//! | 4 | outram-mc | Rust NJOY, ENDF read directly | `endf` |
//! | 5 | outram-mc | Rust-NJOY ACE | `ace --ace-dir <rust lib>` |
//!
//! # Why one driver and not a flag on each existing example
//!
//! The models are the ones in `godiva_keff_endf_local.rs`, `jemima_keff.rs`,
//! `hst009_keff.rs` and `lct008_ace_roundtrip.rs`, transcribed here with their
//! atom densities and radii unchanged (each constant block cites its source).
//! A route flag on four programs would have meant four copies of the ACE-loading
//! and per-seed CSV code; this way there is one, and every case × route row in
//! the study's CSV is written by the same lines. The per-case examples keep
//! their own ablation knobs and V&V gates, which this program does not repeat.
//!
//! # Physics carried, per route — the same default-on set everywhere it can be
//!
//! - **URR probability tables.** ENDF route: built at construction
//!   (`with_urr_probability_tables(.., 20, 16, 2000)`, the crate default). ACE
//!   routes: read from the table's UNR block — NJOY2016's `purr 20/64` or the
//!   port's `build_full_with_purr(20, 64, 10000)`. Same bins, **different ladder
//!   and sample counts**; stated, not hidden.
//! - **DBRC, E <= 1 keV, every nuclide with 0 K elastic.** ENDF route: from
//!   RECONR's 0 K grid. ACE routes: from the `0K/` companion table next to each
//!   `293.6K/` table, paired by `Nuclide::from_ace_file`.
//! - **S(a,b) H in H2O** on H-1 in water-bearing materials (HST-009, LCT-008s).
//!   ~~ENDF route: `ThermalScattering::from_endf_file` on `tsl-HinH2O.endf`
//!   (this crate's own emission grid).~~ **CHANGED 2026-10-14 (maintainer
//!   direction: LEAPR always runs, `tsl-*.endf` tapes are oracles only):** ENDF
//!   route: the law is **regenerated by LEAPR** from the ENDF/B-VIII.0 deck
//!   compiled into `njoy-outram-park-fork` (`tsl-HinH2O.leapr`, its 293.6 K
//!   block, the deck's own constants), then `ThermalScattering::from_tape` on
//!   LEAPR's tape (this crate's own emission grid). `--sab-tsl` reads the
//!   published `tsl-HinH2O.endf` instead, as an A/B oracle. ACE routes:
//!   `ThermalScattering::from_ace` on the library's `HinH2O.ace` (IFENG = 0,
//!   64 bins x 16 cosines); in the Rust library that table is also made from
//!   the LEAPR deck (`write_ace_library --thermal-leapr`), in NJOY2016's from
//!   the published tape.
//!
//! Every run prints, and writes to the CSV, how many nuclides carry URR and
//! DBRC and whether S(a,b) is attached, so a route that silently lost a term
//! shows in the data rather than in the residual.
//!
//! # LCT-008 is the case-1 LATTICE, on its full nuclide list
//!
//! `lct008` runs the model `lct008_keff.rs` runs (shared through
//! `common/lct008_model.rs`); see [`lct008_lattice_case`]. A
//! homogenised-sphere case (`lct008s`) existed briefly on 2026-09-28/29 and
//! was **deleted 2026-09-29 at the maintainer's direction** because it was the
//! wrong model.
//!
//! ~~It runs on that example's `--cheap-nuclides` tier (11 nuclides);
//! `--full-nuclides` (route `endf` only) was a study arm.~~ **CHANGED
//! 2026-10-14 (maintainer direction): the FULL nuclide list (`TAPES`, 35
//! nuclides) is the default on every route**, the ACE routes included (their
//! libraries carry all 35, `five_route_keff/nuclides.tsv`). Its CSV rows are
//! labelled case **`lct008-full`** (35 nuclides: case 1 uses 35 of
//! `TAPES`' 36), so they never pool with the 11-nuclide
//! rows recorded before, which keep the label `lct008`. `--cheap-nuclides` is
//! the explicit ablation back to the 11-nuclide tier (label `lct008`);
//! `--full-nuclides` is accepted and changes nothing.
//!
//! # Usage
//!
//! ```text
//! RAYON_NUM_THREADS=8 cargo run --release -p outram-mc-libs --features endf-pebble-cases \
//!     --example icsbep_five_route_keff -- --case godiva --route endf \
//!     --seeds 1,2,3 --csv out.csv --label route4 [--ace-dir DIR] [--threads 8] \
//!     [--particles 5000 --inactive 40 --active 120] [--commit SHA]
//! ```
//!
//! One CSV row is **appended per seed as soon as it finishes**, so a launcher
//! can resume by asking only for the seeds not yet in the file.
//!
//! # `--accept`: the acceptance check (GitHub #859)
//!
//! `--accept <summary_keff.csv> [--allowance-pcm 200] [--accept-record out.csv]`
//! turns a run into a pass/fail check for continuous integration, on any
//! operating system: the mean `k` of this run's seeds is compared with the
//! **recorded route-1 `k`** (OpenMC on NJOY2016 data) of the same case, read
//! from the committed campaign summary, never retyped.
//!
//! - **Why route 1 and not the benchmark k.** The check is the
//!   reduced-statistics form of the study's code-to-code criterion, so it is
//!   judged against the same reference. It is also the only one the four
//!   cases can all meet for a reason that is physics and not luck: on the
//!   recorded data Jemima sits at −406 ± 17 pcm and HEU-SOL-THERM-009 at
//!   +334 ± 22 pcm from its benchmark k on OpenMC itself (benchmark values
//!   1.0000 ± 0.0030 and 0.9990 ± 0.0043, cited in `vv::jemima` and
//!   `vv::hst009`; corrected 2026-10-14, this line first measured from
//!   `k = 1` and named the lattice, which is +174 ± 5 pcm from its 1.0007).
//! - **Pass criterion.** `|k_run − k_route1| <= allowance` (200 pcm by
//!   default), and the run must be able to tell: three combined standard
//!   errors must fit inside the allowance, otherwise the verdict is
//!   `UNRESOLVED` and the process fails too. A check that cannot fail checks
//!   nothing.
//! - **Run size.** The acceptance scripts pass `--particles 5000 --inactive
//!   40 --active 120` for every case. For the lattice that is smaller than
//!   the campaign's 10 000 × [250 + 400] (maintainer direction, 2026-10-13:
//!   acceptance is seeing it run on every platform, not validation). Its
//!   source is then not fully converged: 16 seeds gave +70 ± 28 pcm against
//!   route 1 (i9-13900K, 14 threads, 2026-10-13) where the campaign size
//!   gives −8 ± 9. Inside the allowance, and not a number to quote for the
//!   lattice's `k`.
//! - **Record.** `--accept-record` appends one CSV row (operating system,
//!   architecture, case, seeds, settings, `k`, reference, difference,
//!   verdict, commit), which is what the acceptance-test record cites.
//!
//! Results by environment:
//! `verification_and_validation/acceptance_testing/README.md`.

