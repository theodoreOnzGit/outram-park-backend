//! # Tutorial 4: one TRISO particle, and the k-infinity of its unit cell
//!
//! **Five concentric spheres, a cube and a mirror** (beginner API
//! `outram_mc_libs::model`, epic gh #925; repeated structures #926; the
//! tutorial list and its decisions on #943). Tutorial 3 nested three
//! spheres; a TRISO fuel particle is five, built the same way. New in this
//! lesson:
//!
//! - **a TRISO particle with the same `.filled_with` / `.containing` API**,
//!   kernel outwards, **one `.containing` per statement** (maintainer, #926
//!   and #943, 2026-10-17): kernel, buffer, inner pyrolytic carbon (IPyC),
//!   silicon carbide (SiC), outer pyrolytic carbon (OPyC);
//! - **graphite and silicon carbide** as bound media:
//!   `.bound_in(Moderator::Graphite(..))`, `.bound_in(Moderator::SiliconCarbide)`;
//! - **boron as a contaminant whose ppm says what it is per**: per uranium
//!   atom in the kernel, **per carbon atom** in graphite
//!   (`PpmOf::PerHostAtom`, decided on #943);
//! - **a cube** (`Cube::with_packing_fraction`, or `Cube::side`) and **a
//!   reflective boundary on the outermost shape**
//!   (`.boundary(Boundary::Reflective)`, decided on #943): one particle in a
//!   mirrored cube is an infinite simple-cubic array of particles, so its k
//!   is a **k-infinity**;
//! - **counting from the assembled geometry** (`assembled.census()`): the
//!   particle count and packing fraction the solver will see, not the ones
//!   you typed (the HTR-10 history: a lattice held 8240 particles while the
//!   model reported 8340, gh:#316, +353 pcm).
//!
//! ```text
//! cargo run --release -p outram-mc-libs --example tutorial_triso_particle            # MCSettings::Fast (smoke test)
//! cargo run --release -p outram-mc-libs --example tutorial_triso_particle -- --auto  # MCSettings::Auto (hours)
//! cargo run --release -p outram-mc-libs --example tutorial_triso_particle -- --seeds 8  # + 8 pooled seeds
//! cargo run --release -p outram-mc-libs --example tutorial_triso_particle -- --geometry-only  # draw and count only
//! cargo run --release -p outram-mc-libs --example tutorial_triso_particle -- --seeds-only 8  # 8 seeds in parallel, no diagnostics
//! ```
//!
//! (Tutorials refactor existing examples where one fits (#943). None does
//! here, checked: `triso_delta_tracking.rs` is a random packing with delta
//! tracking, the natural base for tutorial 5; `triso_four_methods.rs`,
//! `triso_stochastic_media.rs`, `triso_stochastic_gpu.rs` and
//! `triso_gpu_benchmark.rs` compare double-heterogeneity methods;
//! `htr10_fuel_zone_kinf.rs` is a random packing with the coatings smeared
//! into the matrix and its own recorded study; `fhr_pebble_quickstart.rs`
//! is an FHR pebble. So this file is new; it reuses their **numbers**: the
//! radii of `outram_blender::csg::triso_particle::TrisoRadii::HTR10` and
//! the compositions of `outram_mc_libs::pebble_beds::htr10`.)
//!
//! ## The case: the HTR-10 TRISO particle
//!
//! | layer | outer radius \[cm\] | material | density \[g/cm³\] |
//! |---|---|---|---|
//! | kernel | 0.0250 | UO2, 17 wt % U-235, + 4 ppm natural B per U atom | 10.4 |
//! | buffer | 0.0340 | porous carbon, + 1.3 ppm B per C atom | 1.1 |
//! | IPyC | 0.0380 | pyrolytic carbon, + 1.3 ppm B per C atom | 1.9 |
//! | SiC | 0.0415 | silicon carbide | 3.18 |
//! | OPyC | 0.0455 | pyrolytic carbon, + 1.3 ppm B per C atom | 1.9 |
//! | matrix (the cube) | side 0.19876 | graphite, + 1.3 ppm B per C atom | 1.73 |
//!
//! - **Radii:** IAEA-TECDOC-1382 part 2, which states the coating
//!   thicknesses twice in two units (0.09 / 0.04 / 0.035 / 0.04 mm), and Li,
//!   Yu & Wei (2014) Table 2 agree (`TrisoRadii::HTR10`'s doc).
//! - **Compositions:** `pebble_beds::htr10` (TECDOC-1382 Table 4-2 and Li
//!   2014 Table 2): enrichment by weight, the densities above, boron as
//!   natural boron by **atom** ppm (maintainer, gh:#424), on every graphite
//!   layer and not on SiC, exactly as `htr10::fuel_pebble_materials` places
//!   it.
//! - **Thermal laws:** reactor graphite at 30 % porosity on every graphite
//!   layer (the HTR-10 choice recorded on `nee_soon`'s `GraphiteLaw`, made
//!   on density, not to match k); Si in SiC and C in SiC on the SiC layer;
//!   the kernel free gas. All regenerated by LEAPR from the ENDF/B-VIII.0
//!   decks.
//! - **Packing:** HTR-10's 8335 particles in a 2.5 cm fuel zone
//!   (TECDOC-1382; Li 2014), packing fraction `8335 (0.0455/2.5)^3 =
//!   0.050248`, here as a **regular** array: a reflective cube of side
//!   `(V_particle / pf)^(1/3) = 0.19876 cm` around one particle. HTR-10's
//!   real packing is random; random packing is tutorial 5.
//! - **Temperature:** 293.6 K everywhere (the room temperature of tutorials
//!   1 to 3; not an HTR-10 operating state).
//!
//! **What this k-infinity is not.** It is an infinite regular lattice of
//! fuel particles in matrix graphite: no fuel-free pebble shell, no dummy
//! graphite balls, no reflector, no leakage. No published HTR-10 number is
//! this quantity. The crate has **no recorded value for this cell** (checked
//! 2026-10-18: `htr10_fuel_zone_kinf.rs` is the nearest, a randomly packed
//! fuel zone with the coatings smeared and TECDOC Table 4-38 densities, a
//! different problem; it is not compared).
//!
//! ## What this checks (V&V methodology)
//!
//! Each check can fail; nothing is tuned.
//!
//! 1. **The particle is the crate's TRISO.** The assembled model's five
//!    shells (surfaces, region tokens, fills) are those of
//!    `build_triso_particle(TrisoRadii::HTR10)`, and the matrix cell is
//!    `outside(OPyC)` inside the cube. Transport bit-identity of this
//!    lowering is pinned without nuclear data by
//!    `tests/model_repeated_structures.rs`.
//! 2. **Counted from the geometry:** `census()` must place exactly one
//!    particle, at the packing fraction asked for (to 1e-12).
//! 3. **No leakage:** with every face reflective, P_FNL and P_TNL must be 1.
//! 4. **The six-factor product against k:** within 4σ (it telescopes to
//!    production over absorption plus leakage; the (n,xn) gain is small).
//! 5. **Pictures** of the assembled geometry (crate HARD RULE): x-y and x-z
//!    through the centre, and a zoom on every layer, written to
//!    `target/tutorials/triso_particle/` (gitignored).
//!
//! ## Results
//!
//! 2026-10-18, ENDF/B-VIII.0 from `reference-data/endf/`. Hardware: Intel
//! i9-13900K (32 logical cores, shared with other jobs; these runs pinned
//! to 4 of them), 62.5 GiB RAM, Linux, CPU only.
//!
//! | check | result |
//! |---|---|
//! | 1. lowering | the five shells identical to `build_triso_particle(TrisoRadii::HTR10)` |
//! | 2. census | 1 particle; packing fraction 5.024811 % as asked; kernel 0.83350 % of the volume. Stacked 3 x 3 x 3: 27 particles, same fraction |
//! | 3. leakage | P_FNL = P_TNL = 1.00000 ± 0.00000 |
//! | 4. six factors | product 1.56197 ± 0.00093 against k: −186 ± 193 pcm (−0.96σ) |
//! | **Fast (the default), seed 1** | **`k_inf = 1.56384 ± 0.00169`** (batch means 0.00137): a **SMOKE TEST**, not a result to quote (120 active cycles fall short of Brown's "a few hundred"; the run's own note says so). 95 inactive cycles (watcher: stationary at 1000 per cycle by cycle 30, at 5000 by cycle 95) + 120 active of 5000. Two runs gave the same bits |
//!
//! - **Six factors (Fast):** η 2.0244, f 0.9777, p 0.6596, ε 1.1964.
//!   Thermal (below 0.625 eV) flux is 18.5 % in the kernel, 18.9 % in
//!   the matrix, peaking per lethargy near 0.08 to 0.10 eV (a Maxwellian
//!   hardened by absorption).
//! - **No recorded value exists for this cell** (see above), so k is
//!   reported, not compared. Nothing was tuned.
//! - **Why Fast is the default** (maintainer, 2026-10-18: "do fast lah
//!   not auto"). Data 64 to 69 s (13 nuclides, 3 LEAPR laws, parallel).
//!   Transport with diagnostics on Fast: **3764 to 3884 s
//!   single-threaded**, about 5.5 s per generation of 1000 and 27 s per
//!   generation of 5000 (roughly 5 ms per history):
//!   in a 0.199 cm mirrored cube a thermal neutron, whose mean free path in
//!   graphite is a few cm, crosses or reflects off the faces thousands of
//!   times per history. Auto (250 × 10 000 active) would be about 3.8 h at
//!   that rate on one core (`--auto`); a first Auto run was stopped at
//!   1 h 38 min and gave no number. Independent seeds on several cores,
//!   without diagnostics (`--seeds-only N`), are the cheaper route to
//!   more statistics; not run for this record.

use std::path::PathBuf;
use std::time::Instant;

use outram_mc_libs::geometry::plot::PlotBasis;
use outram_mc_libs::geometry::position::Position;
use outram_mc_libs::geometry::surface::SurfaceKind;
use outram_mc_libs::geometry::triso_particle::{build_triso_particle, TrisoMaterials, TrisoRadii};
use outram_mc_libs::model::prelude::*;
use outram_mc_libs::pebble_beds::htr10;
use outram_mc_libs::perf_report::HardwareInfo;
use outram_mc_libs::stats::ensemble::{consecutive_seeds, default_workers, run_seeds, EnsembleReport};
use uom::si::f64::{Length, MassDensity, Ratio, ThermodynamicTemperature};
use uom::si::length::centimeter;
use uom::si::mass_density::gram_per_cubic_centimeter;
use uom::si::ratio::{part_per_million, percent, ratio};
use uom::si::thermodynamic_temperature::kelvin;

/// The fuel zone HTR-10's particle count is given for (TECDOC-1382; Li
/// 2014) \[cm\], and that count.
const FUEL_ZONE_R_CM: f64 = 2.5;
const PARTICLES_PER_PEBBLE: f64 = 8335.0;
const T_K: f64 = 293.6;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let args: Vec<String> = std::env::args().collect();
    let auto = args.iter().any(|a| a == "--auto");
    let geometry_only = args.iter().any(|a| a == "--geometry-only");
    let arg = |name: &str| {
        args.iter()
            .position(|a| a == name)
            .and_then(|i| args.get(i + 1))
            .cloned()
    };
    let n_seeds: usize = arg("--seeds").and_then(|s| s.parse().ok()).unwrap_or(0);
    let data = match arg("--endf") {
        Some(dir) => NuclearData::endf_folder(&PathBuf::from(dir)),
        None => NuclearData::workspace_reference(),
    };
    let data = match data {
        Ok(d) => d,
        Err(e) => {
            println!("No ENDF tapes: {e}. Clone with the reference data, or pass --endf <folder>.");
            return Ok(());
        }
    };

    // ── 1. The model and its components ────────────────────────────────────
    let mut model = Model::new(data);
    let kernel_c = model.component("Kernel");
    let coatings_c = model.component("Coatings");
    let matrix_c = model.component("Matrix");

    // ── 2. Materials (pebble_beds::htr10's numbers, with their sources) ─────
    let g_cc = MassDensity::new::<gram_per_cubic_centimeter>;
    let ppm = Ratio::new::<part_per_million>;
    let graphite_law = Moderator::Graphite(GraphiteKind::ReactorPorosity30);
    // Natural boron as atoms per carbon atom (gh:#424), added on top.
    let boron_in_carbon = Contaminant::ppm(
        ppm(htr10::B_PPM_GRAPHITE),
        Basis::Atom,
        PpmOf::PerHostAtom,
        Placement::AddOn,
    );
    let carbon = |rho: f64, name: &str| {
        Material::from_fractions(
            Basis::Atom,
            [(Element::Carbon.natural(), Ratio::new::<ratio>(1.0))],
        )
        .density(g_cc(rho))
        .contaminant(Element::Boron.natural(), boron_in_carbon)
        .bound_in(graphite_law)
        .named(name)
    };
    let uo2 = Material::fuel(
        HeavyMetal::Uranium(Enrichment::by_weight(
            FissileUranium::U235,
            Ratio::new::<ratio>(htr10::ENRICHMENT_WT),
        )),
        FuelForm::Oxide,
    )
    .density(g_cc(htr10::RHO_UO2))
    // Natural boron as atoms per uranium atom ("of uranium", Li 2014 Table 2).
    .contaminant(
        Element::Boron.natural(),
        Contaminant::ppm(
            ppm(htr10::B_PPM_URANIUM),
            Basis::Atom,
            PpmOf::HeavyMetal,
            Placement::AddOn,
        ),
    )
    .named("UO2 kernel");
    let buffer = carbon(htr10::RHO_BUFFER, "buffer carbon");
    let pyc = carbon(htr10::RHO_PYC, "pyrolytic carbon");
    let sic = Material::from_fractions(
        Basis::Atom,
        [
            (Element::Silicon.natural(), Ratio::new::<ratio>(0.5)),
            (Element::Carbon.natural(), Ratio::new::<ratio>(0.5)),
        ],
    )
    .density(g_cc(htr10::RHO_SIC))
    .bound_in(Moderator::SiliconCarbide)
    .named("silicon carbide");
    let matrix = carbon(htr10::RHO_GRAPHITE, "matrix graphite");

    // ── 3. The particle: kernel outwards, one `.containing` per statement ──
    let r = TrisoRadii::HTR10;
    let cm = Length::new::<centimeter>;
    let kernel = Sphere::radius(cm(r.kernel))
        .filled_with(uo2)
        .in_component(kernel_c);
    let buffer_ball = Sphere::radius(cm(r.buffer))
        .filled_with(buffer)
        .in_component(coatings_c)
        .containing(kernel);
    let ipyc = Sphere::radius(cm(r.ipyc))
        .filled_with(pyc.clone())
        .in_component(coatings_c)
        .containing(buffer_ball);
    let sic_ball = Sphere::radius(cm(r.sic))
        .filled_with(sic)
        .in_component(coatings_c)
        .containing(ipyc);
    let opyc = Sphere::radius(cm(r.opyc))
        .filled_with(pyc)
        .in_component(coatings_c)
        .containing(sic_ball);

    // ── 4. The unit cell: a reflective cube at HTR-10's packing fraction ───
    let pf = PARTICLES_PER_PEBBLE * (r.opyc / FUEL_ZONE_R_CM).powi(3);
    let cube = Cube::with_packing_fraction(&opyc, Ratio::new::<ratio>(pf));
    // The same cube by its side, the other way the decision allows:
    // `Cube::side(cm(a))`.
    let a = cube.sides_cm()[0];
    println!(
        "HTR-10 packing: {PARTICLES_PER_PEBBLE} particles in a {FUEL_ZONE_R_CM} cm zone = {:.5} %; cube side {a:.6} cm",
        100.0 * pf
    );
    let unit_cell = cube
        .filled_with(matrix.clone())
        .in_component(matrix_c)
        .containing(opyc);
    // A copy of the model before its shape goes in, for the aside in step 6.
    let mut stacked = model.clone();
    model.add(unit_cell.clone().boundary(Boundary::Reflective));
    let room_temperature = Temperature::Uniform(ThermodynamicTemperature::new::<kelvin>(T_K));
    model.set_temperature(room_temperature);

    // ── 5. Check: the particle is the crate's TRISO; count what is there ───
    let assembled = model.assemble()?;
    let hand = build_triso_particle(
        Position::ZERO,
        r,
        TrisoMaterials {
            kernel: 0,
            buffer: 1,
            ipyc: 2,
            sic: 3,
            opyc: 2,
            matrix: 4,
        },
        T_K,
        1,
        0,
        0,
    );
    let same_shells = hand
        .surfaces
        .iter()
        .zip(&assembled.geometry.surfaces)
        .all(|(h, a)| match (h, a) {
            (SurfaceKind::Sphere(p), SurfaceKind::Sphere(q)) => {
                (p.x0, p.y0, p.z0, p.r, p.bc) == (q.x0, q.y0, q.z0, q.r, q.bc)
            }
            _ => false,
        })
        && hand.cells[..5]
            .iter()
            .zip(&assembled.geometry.cells)
            .all(|(h, a)| h.region == a.region && h.fill == a.fill);
    println!("The five shells are build_triso_particle(TrisoRadii::HTR10)'s: {same_shells}");
    assert!(
        same_shells,
        "the tutorial's particle must lower to the crate's TRISO"
    );

    let census = assembled.census()?;
    println!("\nWhat the assembled geometry holds:\n{census}");
    let particles = census.copies(kernel_c);
    let particle_fraction =
        (census.volume(kernel_c) + census.volume(coatings_c)) / census.total_volume();
    let got_pf = particle_fraction.get::<ratio>();
    println!(
        "  particles: {particles}; packing fraction {:.6} % (asked {:.6} %); kernel volume fraction {:.5} %",
        100.0 * got_pf,
        100.0 * pf,
        census.volume_fraction(kernel_c).get::<percent>()
    );
    assert_eq!(particles, 1, "one particle in the unit cell");
    assert!(
        (got_pf / pf - 1.0).abs() < 1e-12,
        "packing fraction from the geometry"
    );
    for m in &assembled.resolved {
        println!(
            "  {}: {:.5} g/cm3",
            m.name,
            m.report.total_density.get::<gram_per_cubic_centimeter>()
        );
    }

    // ── 6. Look at it before running it (crate HARD RULE) ───────────────────
    let out =
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../target/tutorials/triso_particle");
    std::fs::create_dir_all(&out)?;
    for (basis, name) in [
        (PlotBasis::Xy, "triso_cell_xy.png"),
        (PlotBasis::Xz, "triso_cell_xz.png"),
    ] {
        let title = format!(
            "TRISO unit cell, {} slice through the centre (side {a:.4} cm)",
            basis.name()
        );
        assembled
            .draw_slice(basis, 800, &title)
            .write_png(out.join(name))?;
        println!("drew {}", out.join(name).display());
    }
    // Zooms down to every layer, on the +x axis: a window three layer
    // thicknesses wide, centred on the layer.
    let edges = [0.0, r.kernel, r.buffer, r.ipyc, r.sic, r.opyc];
    let names = ["kernel", "buffer", "ipyc", "sic", "opyc"];
    let particle_zoom = assembled.draw_window(
        PlotBasis::Xy,
        Position::ZERO,
        [2.2 * r.opyc, 2.2 * r.opyc],
        800,
        "TRISO particle (x-y, 0.1 cm window)",
    );
    particle_zoom.write_png(out.join("triso_particle_xy.png"))?;
    println!("drew {}", out.join("triso_particle_xy.png").display());
    for i in 0..5 {
        let (lo, hi) = (edges[i], edges[i + 1]);
        let w = if i == 0 { 2.4 * hi } else { 3.0 * (hi - lo) };
        let centre = if i == 0 { 0.0 } else { 0.5 * (lo + hi) };
        let title = format!(
            "{}: {:.4} to {:.4} cm ({:.0} um), x-y, {:.3} cm window",
            names[i],
            lo,
            hi,
            1e4 * (hi - lo),
            w
        );
        let file = format!("triso_zoom_{}_{}.png", i + 1, names[i]);
        assembled
            .draw_window(
                PlotBasis::Xy,
                Position::new(centre, 0.0, 0.0),
                [w, w],
                800,
                &title,
            )
            .write_png(out.join(&file))?;
        println!("drew {}", out.join(&file).display());
    }

    // Aside: the same unit cell stacked 3 x 3 x 3 (`Lattice::copies_of`), the
    // repeated structure tutorials 5 to 8 build on. Drawn and counted, not
    // run: with reflective faces it is the same infinite array as the
    // single cell (`tests/model_repeated_structures.rs` checks the two k
    // agree).
    let block = Cube::side(cm(3.0 * a))
        .filled_with(matrix)
        .in_component(matrix_c)
        .containing_lattice(Lattice::copies_of(unit_cell, [3, 3, 3]))
        .boundary(Boundary::Reflective);
    stacked.add(block);
    stacked.set_temperature(room_temperature);
    let stacked = stacked.assemble()?;
    let stacked_census = stacked.census()?;
    println!(
        "\nStacked 3 x 3 x 3: the assembled lattice places {} particles; packing fraction {:.6} %",
        stacked_census.copies(kernel_c),
        100.0
            * ((stacked_census.volume(kernel_c) + stacked_census.volume(coatings_c))
                / stacked_census.total_volume())
            .get::<ratio>()
    );
    assert_eq!(
        stacked_census.copies(kernel_c),
        27,
        "27 particles in the 3 x 3 x 3 lattice"
    );
    for (basis, name) in [
        (PlotBasis::Xy, "triso_lattice_xy.png"),
        (PlotBasis::Xz, "triso_lattice_xz.png"),
    ] {
        let title = format!(
            "The unit cell stacked 3 x 3 x 3, {} slice through the centre",
            basis.name()
        );
        stacked
            .draw_slice(basis, 800, &title)
            .write_png(out.join(name))?;
        println!("drew {}", out.join(name).display());
    }
    // Off the centre plane: a slice at z = a (the top layer's centres).
    stacked
        .draw_window(
            PlotBasis::Xy,
            Position::new(0.0, 0.0, a),
            [3.3 * a, 3.3 * a],
            800,
            &format!("The 3 x 3 x 3 lattice, x-y at z = {a:.4} cm (top layer)"),
        )
        .write_png(out.join("triso_lattice_xy_top.png"))?;
    println!("drew {}", out.join("triso_lattice_xy_top.png").display());

    if geometry_only {
        return Ok(());
    }

    // ── 7. Run k-infinity, with diagnostics ─────────────────────────────────
    let diagnostics =
        Diagnostics::default().with_spectrum_per_component(&model, EnergyGrid::default_spectrum());
    // Fast by default (maintainer, 2026-10-18: "do fast lah not auto"):
    // a SMOKE TEST, 120 active cycles of 5000, which the result's own notes
    // say falls short of Brown's "a few hundred". Auto (250 x 10 000) is
    // about 3.8 h on one core for this cell; ask for it with --auto.
    let preset = if auto {
        MCSettings::Auto
    } else {
        MCSettings::Fast
    };
    let t = Instant::now();
    let nuclides = assembled.load_nuclides(model.data())?;
    let data_s = t.elapsed().as_secs_f64();
    println!(
        "  data {data_s:.1} s ({} nuclides, processed in parallel)",
        nuclides.len()
    );

    // ~~The beginner run is single-threaded (bit for bit `run_keff_csg`)~~
    // CORRECTED 2026-10-18 (gh #955): the beginner run is multi-threaded on
    // rayon's pool (RAYON_NUM_THREADS sets its size; k is the same on any
    // number of threads). This tiny mirrored cube makes each thermal
    // history cross or reflect off its faces thousands of times: the Fast
    // run with diagnostics took 3884 s on one thread (i9-13900K).
    // Independent seeds side by side, without diagnostics, are another
    // route to more statistics: `--seeds-only N` (Fast's size, 5000 per
    // cycle, 100 inactive fixed, 120 active; a stated size, not the
    // watcher's), each seed on one thread (`single_thread`).
    if let Some(n) = arg("--seeds-only").and_then(|s| s.parse::<usize>().ok()) {
        let workers = arg("--workers")
            .and_then(|s| s.parse().ok())
            .unwrap_or_else(default_workers);
        let t = Instant::now();
        let ks = run_seeds(&consecutive_seeds(n), workers, |seed| {
            let r = assembled
                .keff_with(
                    &nuclides,
                    &KeffSettings::new(
                        MCSettings::Custom(CustomRun {
                            particles: 5000,
                            inactive: 100,
                            active: 120,
                            seed,
                        }),
                        None,
                    )
                    .single_thread(),
                )
                .expect("a seed run");
            (r.keff().mean, r.keff().std)
        });
        let rep = EnsembleReport::from_runs(ks);
        println!(
            "\n{n} seeds x Custom {{ 5000 per cycle, 100 inactive, 120 active }}, no diagnostics ({:.0} s on {workers} workers; {}):",
            t.elapsed().as_secs_f64(),
            HardwareInfo::detect().headline()
        );
        println!(
            "  k_inf = {:.5} ± {:.5} (sd per run {:.0} pcm)",
            rep.mean,
            rep.sem,
            rep.sd * 1e5
        );
        print!("{}", rep.consistency_summary("k"));
        return Ok(());
    }

    let t = Instant::now();
    let run = assembled.keff_with(
        &nuclides,
        &KeffSettings::new(preset, Some(diagnostics.clone())),
    )?;
    let run_s = t.elapsed().as_secs_f64();
    println!("\n{run}");
    println!(
        "  wall time: data {data_s:.1} s ({} nuclides, processed in parallel), transport with diagnostics {run_s:.1} s on {} thread(s)\n  hardware: {}",
        nuclides.len(),
        run.provenance.threads,
        HardwareInfo::detect().headline()
    );

    // ── 8. Read the results ────────────────────────────────────────────────
    let k = run.keff();
    let sigma = k.std.max(run.provenance.sigma_batch_means.unwrap_or(0.0));
    let sf = run.six_factors()?;
    println!(
        "\nSix factors ({} eV / {} eV):",
        sf.edges_ev.0, sf.edges_ev.1
    );
    for (name, e) in [
        ("eta", sf.eta),
        ("f", sf.f),
        ("p", sf.p),
        ("epsilon", sf.epsilon),
        ("P_FNL", sf.p_fnl),
        ("P_TNL", sf.p_tnl),
        ("product", sf.k_from_factors),
        ("P (track-length k)", sf.k_tracklength),
    ] {
        println!("  {name:<20} {:.5} ± {:.5}", e.mean, e.std);
    }
    for (c, label) in [
        (kernel_c, "kernel"),
        (coatings_c, "coatings"),
        (matrix_c, "matrix"),
    ] {
        let s = run.spectrum(Region::Component(c))?;
        let below: f64 = s
            .flux
            .iter()
            .enumerate()
            .filter(|(j, _)| s.edges_ev[j + 1] <= sf.edges_ev.0 * (1.0 + 1e-9))
            .map(|(_, f)| f.mean)
            .sum();
        let thermal_peak = s
            .per_lethargy
            .iter()
            .enumerate()
            .filter(|(j, _)| s.edges_ev[j + 1] <= 1.0)
            .max_by(|a, b| a.1.mean.total_cmp(&b.1.mean))
            .map_or(0.0, |(j, _)| (s.edges_ev[j] * s.edges_ev[j + 1]).sqrt());
        println!(
            "  spectrum in the {label:<8}: {:.1} % of its flux below {} eV; thermal peak per lethargy near {thermal_peak:.3e} eV",
            100.0 * below / s.total_in_grid.mean,
            sf.edges_ev.0
        );
    }
    let report = run.diagnostics_report_titled("HTR-10 TRISO unit cell (k-infinity)");
    report.write_zip(out.join("triso_cell.zip"))?;
    println!(
        "wrote {} ({} files)",
        out.join("triso_cell.zip").display(),
        report.files().len()
    );

    // ── 9. The checks (V&V) ────────────────────────────────────────────────
    let z = |a: f64, sa: f64, b: f64, sb: f64| (a - b) / (sa * sa + sb * sb).sqrt();
    println!(
        "\nk_inf = {k} (batch means σ {:.5}); no recorded value for this cell exists to compare with",
        run.provenance.sigma_batch_means.unwrap_or(f64::NAN)
    );
    let zf = z(sf.k_from_factors.mean, sf.k_from_factors.std, k.mean, sigma);
    println!(
        "  six-factor product - k = {:+.0} ± {:.0} pcm ({zf:+.2} sigma)",
        (sf.k_from_factors.mean - k.mean) * 1e5,
        (sf.k_from_factors.std.powi(2) + sigma.powi(2)).sqrt() * 1e5
    );
    assert!(
        sf.undefined_because.is_none(),
        "a graphite cell is thermal: six factors defined"
    );
    for (name, e) in [("P_FNL", sf.p_fnl), ("P_TNL", sf.p_tnl)] {
        assert!(
            (e.mean - 1.0).abs() <= 4.0 * e.std.max(1e-12),
            "{name} = {} ± {}: every face is reflective, nothing may leak",
            e.mean,
            e.std
        );
    }
    assert!(
        zf.abs() <= 4.0,
        "six-factor product and k disagree by {zf:.2} sigma"
    );

    // ── 10. Optional: pooled seeds ─────────────────────────────────────────
    if n_seeds > 1 {
        let p = &run.provenance;
        let workers = arg("--workers")
            .and_then(|s| s.parse().ok())
            .unwrap_or_else(default_workers);
        let t = Instant::now();
        let ks = run_seeds(&consecutive_seeds(n_seeds), workers, |seed| {
            let r = assembled
                .keff_with(
                    &nuclides,
                    &KeffSettings::new(
                        MCSettings::Custom(CustomRun {
                            particles: p.active_particles,
                            inactive: p.inactive_cycles,
                            active: p.active_cycles,
                            seed,
                        }),
                        None,
                    ),
                )
                .expect("a seed run");
            (r.keff().mean, r.keff().std)
        });
        let rep = EnsembleReport::from_runs(ks);
        println!(
            "\n{n_seeds} seeds x Custom {{ {} per cycle, {} inactive, {} active }} ({:.0} s on {workers} workers):",
            p.active_particles,
            p.inactive_cycles,
            p.active_cycles,
            t.elapsed().as_secs_f64()
        );
        println!(
            "  k_inf = {:.5} ± {:.5} (sd per run {:.0} pcm); the single run is {:+.2} sigma from it",
            rep.mean,
            rep.sem,
            rep.sd * 1e5,
            z(k.mean, sigma, rep.mean, rep.sem)
        );
        print!("{}", rep.consistency_summary("k"));
    }
    Ok(())
}
