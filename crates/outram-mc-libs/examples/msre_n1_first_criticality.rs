fn flag(args: &[String], name: &str) -> Option<String> {
    args.iter().position(|a| a == name).and_then(|i| args.get(i + 1).cloned())
}

fn draw(dir: &PathBuf, dims: m::Dims, ends: m::Ends, shield: m::Shield, rods: [bool; 3]) {
    std::fs::create_dir_all(dir).expect("plot dir");
    let mut mats = m::materials_with_ends(m::MoTreatment::Omitted, m::REFERENCE_TEMPERATURE_F, dims);
    let shielded = shield == m::Shield::Tm0728Cylinder;
    let g = if shielded {
        let g = m::geometry_with_shield(m::TEMPERATURE_K, m::TEMPERATURE_K, dims, ends, mats.len());
        mats.extend(m::shield_materials());
        g
    } else {
        m::geometry_with_ends(m::TEMPERATURE_K, m::TEMPERATURE_K, dims, ends)
    };
    let rodded = rods.iter().any(|&r| r);
    let g = if rodded {
        let g = m::geometry_with_rods(g, dims, rods, mats.len(), m::TEMPERATURE_K);
        mats.extend(m::rod_materials());
        g
    } else {
        g
    };
    let hot = dims != m::Dims::COLD;
    let tm0730 = ends == m::Ends::Tm0730;
    let colours = [
        Rgb::new(220, 60, 40),
        Rgb::new(70, 70, 70),
        Rgb::new(160, 160, 200),
        Rgb::new(240, 170, 40),
        Rgb::new(150, 90, 60),
        Rgb::new(240, 120, 90),
        Rgb::new(200, 100, 160),
        Rgb::new(90, 140, 90),
        Rgb::new(120, 60, 140),
        Rgb::new(110, 110, 120),
        Rgb::new(60, 130, 200),
        Rgb::new(30, 30, 30),
        Rgb::new(255, 255, 0),
    ];
    let labels: Vec<String> = mats.iter().map(|(n, _)| n.to_ascii_uppercase()).collect();
    let palette: Vec<(Rgb, &str)> = colours.iter().zip(&labels).map(|(c, l)| (*c, l.as_str())).collect();
    let mid = m::H_CORE / 2.0;
    let o = m::OPENING_OFFSET;
    let (up, lo) = if tm0730 {
        (m::TM0730_TOP_HEIGHT_IN * m::INCH, m::TM0730_BOTTOM.iter().map(|x| x.1).sum::<f64>() * m::INCH)
    } else {
        (m::upper_plenum_height(), m::lower_plenum_height())
    };
    let z_top = m::H_CORE + up + m::T_HEAD;
    let z_bot = -lo - m::T_HEAD;
    let mut slices: Vec<(&str, Position, PlotBasis, [f64; 2], &str)> = vec![
        ("msre_n1_xy_core", Position::new(0.0, 0.0, mid), PlotBasis::Xy, [160.0, 160.0],
         "MSRE N-1 FULL CORE, X-Y AT MID-HEIGHT Z = 81.28 CM: 55.25 IN GRAPHITE, CAN, DOWNCOMER, VESSEL"),
        ("msre_n1_xy_centre", Position::new(0.0, 0.0, mid), PlotBasis::Xy, [24.0, 24.0],
         "MSRE N-1 CENTRE, X-Y: THREE 2 IN THIMBLES AND THE SAMPLE BASKET IN 2.5 IN OPENINGS AT (+-2, +-2) IN"),
        ("msre_n1_xy_stringer", Position::new(-4.0 * m::INCH, -4.0 * m::INCH, mid), PlotBasis::Xy, [6.0, 6.0],
         "MSRE N-1 ONE STRINGER, X-Y: 2 IN GRAPHITE, FOUR HALF-STADIUM 1.2 X 0.4 IN PASSAGES"),
        ("msre_n1_xz", Position::new(0.0, o, (z_top + z_bot) / 2.0), PlotBasis::Xz, [160.0, z_top - z_bot + 4.0],
         "MSRE N-1 X-Z AT Y = +2 IN (THROUGH TWO THIMBLES): CORE 64 IN, PLENUMS 10.0 / 10.5 FT3, 1 IN HEADS"),
        ("msre_n1_xz_top", Position::new(20.0, o, m::H_CORE), PlotBasis::Xz, [70.0, 50.0],
         "MSRE N-1 X-Z AT Y = +2 IN, TOP OF CORE: THIMBLES INTO THE UPPER PLENUM, CAN, DOWNCOMER, VESSEL"),
    ];
    if shielded {
        // Inside the vessel the shielded build is the default cell for cell
        // (`tm0728_shield_wraps_the_default_vessel`): draw only the shield.
        slices.clear();
        let w = 2.0 * m::SHIELD_R_OUT + 10.0;
        let zc = (z_top + z_bot) / 2.0;
        slices.push(("msre_n1_shield_xz", Position::new(0.0, o, zc), PlotBasis::Xz, [w, m::SHIELD_HEIGHT + 10.0],
            "MSRE N-1 X-Z IN THE THERMAL SHIELD (TM-0728 5.3.10.1): 151 IN HIGH, 93 / 125 IN ID / OD, CENTRED ON THE VESSEL"));
        slices.push(("msre_n1_shield_xy", Position::new(0.0, 0.0, mid), PlotBasis::Xy, [w, w],
            "MSRE N-1 X-Y AT MID-HEIGHT IN THE SHIELD: VOID, 1 IN 304 PLATE, 14 IN BALLS + WATER, 1 IN 304 PLATE"));
        slices.push(("msre_n1_shield_wall", Position::new(m::SHIELD_R_IN + 8.0 * m::INCH, 0.0, mid), PlotBasis::Xy, [60.0, 60.0],
            "MSRE N-1 SHIELD WALL, X-Y: INNER PLATE, BALL ANNULUS, OUTER PLATE"));
    }
    if rodded {
        // Outside the thimbles the rodded build is the default cell for cell
        // (`control_rods_fill_their_thimbles_with_tm0728_poison`): draw the rods.
        slices.clear();
        let (x2, y2) = m::OPENINGS[0];
        slices.push(("msre_n1_rods_centre", Position::new(0.0, 0.0, mid), PlotBasis::Xy, [24.0, 24.0],
            "MSRE N-1 CENTRE, X-Y, RODS IN: GD2O3-AL2O3 POISON IN INCONEL ELEMENTS (TM-0728 TABLE 5.4) IN THE THREE THIMBLES"));
        slices.push(("msre_n1_rods_one", Position::new(x2, y2, mid), PlotBasis::Xy, [6.0, 6.0],
            "MSRE N-1 ROD 2, X-Y: SHELL 0.790/1.140 IN, 0.020 IN INCONEL, CERAMIC 0.84/1.08 IN, THIMBLE 2 IN OD"));
        slices.push(("msre_n1_rods_xz", Position::new(0.0, o, (z_top + z_bot) / 2.0), PlotBasis::Xz, [24.0, z_top - z_bot + 4.0],
            "MSRE N-1 X-Z AT Y = +2 IN, RODS IN ALL THE WAY: POISON THROUGH THE CORE AND UPPER PLENUM (ORNL-4233 TABLE 4 CASE)"));
    }
    for (stem, origin, basis, width, title) in slices {
        let px = if width[0] > 100.0 { 1600 } else { 1000 };
        let px = if width[1] > 4.0 * width[0] { 600 } else { px };
        let plot = SlicePlot {
            origin,
            basis,
            width,
            pixels: [px, (px as f64 * width[1] / width[0]).round() as usize],
            level: None,
            show_overlaps: true,
            meshlines: None,
        };
        let title = if hot { format!("{title} [HOT DIMENSIONS, 1181 F]") } else { title.to_string() };
        let title = if tm0730 { format!("{title} [TM-0730 END REGIONS]") } else { title };
        let title = if shielded { format!("{title} [TM-0728 SHIELD]") } else { title };
        let title = if rodded { format!("{title} [RODS {rods:?}]") } else { title };
        let (_raw, img) = render_material_slice(&g, &plot, &palette, &title);
        let path = dir.join(format!("{stem}{}{}{}.png", if hot { "_hot" } else { "" }, if tm0730 { "_tm0730" } else { "" }, if shielded && !stem.contains("shield") { "_shield" } else { "" }));
        img.write_png(&path).expect("write png");
        eprintln!("  drew {}", path.display());
    }
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    // `--hot-dims`: graphite and INOR-8 expanded from 70 F to the run
    // temperature (TM-0728 §5.3 coefficients; N-1 residual, gh:#1128).
    let hot_dims = args.iter().any(|a| a == "--hot-dims");
    // `--ends tm0730`: ORNL-TM-0730 Table 3.1's homogenised end regions in
    // place of the volume-equivalent salt plenums (N-1 residual, gh:#1128).
    let ends = match flag(&args, "--ends").as_deref().unwrap_or("volume") {
        "volume" => m::Ends::VolumeEquivalent,
        "tm0730" => m::Ends::Tm0730,
        other => panic!("--ends must be volume|tm0730, got {other}"),
    };
    // `--shield tm0728`: the thermal shield's cylinder around the vessel
    // (TM-0728 §5.3.10.1; N-1 residual, gh:#1128). Default: vacuum.
    let shield = match flag(&args, "--shield").as_deref().unwrap_or("none") {
        "none" => m::Shield::Omitted,
        "tm0728" | "tm0728-drained" | "tm0728-packed" => m::Shield::Tm0728Cylinder,
        other => panic!("--shield must be none|tm0728|tm0728-drained|tm0728-packed, got {other}"),
    };
    // `--shield tm0728-drained`: the same cylinder with the ball annulus's
    // water removed, an ablation splitting the shield's worth (gh:#1128).
    let drained = flag(&args, "--shield").as_deref() == Some("tm0728-drained");
    // `--shield tm0728-packed`: the ball annulus at random close packing,
    // the steel TM-0728's 70 tons imply (an input sensitivity, gh:#1128).
    let packed = flag(&args, "--shield").as_deref() == Some("tm0728-packed");
    let graphite_law = flag(&args, "--graphite-law").unwrap_or_else(|| "30p".to_string());
    let axial_csv: Option<PathBuf> = flag(&args, "--axial-csv").map(PathBuf::from);
    // `--rods none|1|2|3|1-2-3`: control rods inserted all the way through
    // the core (TM-0728 Table 5.4 elements; ORNL-4233 Table 4's calculated
    // case), for the rod worth (gh:#1128). Default: none, every recorded run.
    let rods_spec = flag(&args, "--rods").unwrap_or_else(|| "none".to_string());
    let rods = m::rods_inserted(&rods_spec);
    let rodded = rods.iter().any(|&r| r);
    if let Some(d) = flag(&args, "--draw") {
        let dims = if hot_dims {
            m::Dims::hot(m::REFERENCE_TEMPERATURE_F, m::GRAPHITE_EXPANSION_PER_F, m::INOR8_EXPANSION_PER_F)
        } else {
            m::Dims::COLD
        };
        draw(&PathBuf::from(d), dims, ends, shield, rods);
        return;
    }
    let mo = match flag(&args, "--mo").as_deref().unwrap_or("omitted") {
        "omitted" => m::MoTreatment::Omitted,
        "mo95" => m::MoTreatment::Mo95Equivalent,
        "natural" => m::MoTreatment::Natural,
        other => panic!("--mo must be omitted|mo95|natural, got {other}"),
    };
    let num = |n: &str, d: usize| flag(&args, n).map(|v| v.parse().expect("number")).unwrap_or(d);
    let (np, ni, na) = (num("--particles", 20_000), num("--inactive", 100), num("--active", 200));
    let threads = num("--threads", std::thread::available_parallelism().map_or(1, |n| n.get()));
    let seeds: Vec<u64> = {
        let s = flag(&args, "--seeds").unwrap_or_else(|| "1".into());
        match s.split_once('-') {
            Some((a, b)) => (a.parse().expect("seed")..=b.parse().expect("seed")).collect(),
            None => vec![s.parse().expect("seed")],
        }
    };
    let csv = PathBuf::from(flag(&args, "--csv").unwrap_or_else(|| "target/msre_n1_keff.csv".into()));
    // `--temp-f`: the isothermal temperature (MSRE N-3, gh:#1129); the salt
    // density follows `vv::msre_n1::SALT_EXPANSION_PER_F`.
    // `--salt-temp-f` / `--graphite-temp-f` split it, for the fuel and
    // graphite components (each defaults to `--temp-f`).
    let temp_f: f64 = flag(&args, "--temp-f").map(|v| v.parse().expect("°F")).unwrap_or(m::REFERENCE_TEMPERATURE_F);
    let salt_f: f64 = flag(&args, "--salt-temp-f").map(|v| v.parse().expect("°F")).unwrap_or(temp_f);
    let graphite_f: f64 = flag(&args, "--graphite-temp-f").map(|v| v.parse().expect("°F")).unwrap_or(temp_f);
    let (t_k, t_g) = (m::kelvin_from_f(salt_f), m::kelvin_from_f(graphite_f));
    let temp_of = |n: &str| {
        if m::GRAPHITE_NUCLIDES.contains(&n) {
            t_g
        } else if m::SHIELD_NUCLIDES.iter().any(|(k, _)| *k == n) {
            m::SHIELD_TEMPERATURE_K
        } else {
            t_k
        }
    };

    let dims = if hot_dims {
        m::Dims::hot(salt_f, m::GRAPHITE_EXPANSION_PER_F, m::INOR8_EXPANSION_PER_F)
    } else {
        m::Dims::COLD
    };
    let mut mats = match ends {
        m::Ends::VolumeEquivalent => m::materials_with_dims(mo, salt_f, dims),
        m::Ends::Tm0730 => m::materials_with_ends(mo, salt_f, dims),
    };
    let base_materials = mats.len();
    if shield == m::Shield::Tm0728Cylinder {
        mats.extend(if drained { m::shield_materials_drained() } else if packed { m::shield_materials_packed() } else { m::shield_materials() });
    }
    let first_rod_material = mats.len();
    if rodded {
        mats.extend(m::rod_materials());
    }
    // `--li7-atom-percent X`: re-split the salt's lithium (total unchanged)
    // to X % Li-7. The default keeps TM-0728's 99.99 %; TM-0730 quotes
    // 99.9926 % (Table 3.2 footnote) and 99.997 % (survey), gh:#1128. The
    // homogenised sample basket keeps the default split.
    let li7_pct: Option<f64> = flag(&args, "--li7-atom-percent").map(|v| v.parse().expect("percent"));
    if let Some(pct) = li7_pct {
        let salt = &mut mats[m::SALT_IDX].1;
        let li_total: f64 = salt.iter().filter(|(n, _)| *n == "Li6" || *n == "Li7").map(|e| e.1).sum();
        for e in salt.iter_mut() {
            match e.0 {
                "Li7" => e.1 = li_total * pct / 100.0,
                "Li6" => e.1 = li_total * (1.0 - pct / 100.0),
                _ => {}
            }
        }
    }
    // `--u235-scale X`: add (X > 1) or remove (X < 1) ORNL-4233's enriching
    // salt until the salt's U-235 is X times the default, the perturbation
    // the measured concentration coefficient 0.223 comes from (gh:#1128).
    // The homogenised sample basket keeps the default salt.
    let u235_scale: Option<f64> = flag(&args, "--u235-scale").map(|v| v.parse().expect("scale"));
    if let Some(x) = u235_scale {
        mats[m::SALT_IDX].1 = m::salt_with_enriching_salt(&mats[m::SALT_IDX].1, x);
    }
    let mut names: Vec<&str> = Vec::new();
    for (_, comps) in &mats {
        for (n, _) in comps {
            if !names.contains(n) {
                names.push(n);
            }
        }
    }
    let t0 = Instant::now();
    let speed = outram_mc_libs::vv::bench_speed();
    // Nuclides are processed in parallel, `threads` at a time, and kept in
    // `names` order: each is independent, so the result does not depend on
    // the order they finish in.
    let mo_list = m::mo_tapes(mo);
    let load_one = |n: &str| -> Nuclide {
        let file = m::NUCLIDES
            .iter()
            .chain(mo_list.iter())
            .chain(m::SHIELD_NUCLIDES.iter())
            .chain(m::ROD_NUCLIDES.iter())
            .find(|(k, _)| *k == n)
            .unwrap_or_else(|| panic!("no tape for {n}"))
            .1;
        let p = reference_endf(file).unwrap_or_else(|| panic!("missing reference tape {file}"));
        let t = Instant::now();
        let nuc = Nuclide::from_endf_file_with_speed(&p, n, temp_of(n), speed).unwrap_or_else(|e| panic!("{n}: {e}"));
        eprintln!("    {n:<5} {:6.1} s  URR {} DBRC {}", t.elapsed().as_secs_f64(), nuc.has_urr_probability_tables(), nuc.has_dbrc());
        nuc
    };
    let next = std::sync::atomic::AtomicUsize::new(0);
    let slots: Vec<std::sync::Mutex<Option<Nuclide>>> = names.iter().map(|_| std::sync::Mutex::new(None)).collect();
    std::thread::scope(|sc| {
        for _ in 0..threads.min(names.len()) {
            sc.spawn(|| loop {
                let i = next.fetch_add(1, std::sync::atomic::Ordering::SeqCst);
                if i >= names.len() {
                    break;
                }
                let nuc = load_one(names[i]);
                *slots[i].lock().expect("slot") = Some(nuc);
            });
        }
    });
    let mut nuclides: Vec<Nuclide> =
        slots.into_iter().map(|s| s.into_inner().expect("slot").expect("loaded")).collect();
    let sab = !args.iter().any(|a| a == "--no-sab");
    if sab {
        use njoy_outram_park_fork::leapr::decks::SabMaterial;
        let t = Instant::now();
        // `--graphite-law 30p|10p|crystalline`: 30P (the default, every
        // recorded run) or the other ENDF/B-VIII.0 graphite laws, to test
        // the porosity assumption (CGB: 17.7 % total, TM-0728 Table 5.3).
        let (material, tag) = match graphite_law.as_str() {
            "30p" => (SabMaterial::ReactorGraphite30P, "c_Graphite_30p"),
            "10p" => (SabMaterial::ReactorGraphite10P, "c_Graphite_10p"),
            "crystalline" => (SabMaterial::CrystallineGraphite, "c_Graphite"),
            other => panic!("--graphite-law must be 30p|10p|crystalline, got {other}"),
        };
        let law = ThermalScattering::from_embedded_leapr_deck(material, t_g, tag).expect("graphite S(a,b) from LEAPR");
        eprintln!("    C: graphite {graphite_law} S(a,b) by LEAPR at {t_g:.2} K in {:.1} s", t.elapsed().as_secs_f64());
        for c in ["C12", "C13"] {
            let i = names.iter().position(|n| *n == c).expect("carbon");
            let nuc = nuclides.remove(i);
            nuclides.insert(i, nuc.with_thermal_scattering(law.clone()));
        }
    } else {
        eprintln!("  ABLATION: --no-sab, carbon is free gas");
    }
    // The shield's water: H-1 bound in H2O at the shield temperature.
    if let Some(i) = names.iter().position(|n| *n == "H1") {
        let tape = reference_endf("tsl-HinH2O.endf").expect("tsl-HinH2O tape");
        let law = ThermalScattering::from_endf_file(tape.to_str().expect("utf-8 path"), 1, m::SHIELD_TEMPERATURE_K, "c_H_in_H2O")
            .expect("H in H2O S(a,b)");
        let nuc = nuclides.remove(i);
        nuclides.insert(i, nuc.with_thermal_scattering(law));
        eprintln!("    H1: bound in H2O at {:.1} K", m::SHIELD_TEMPERATURE_K);
    }
    // `--no-dbrc` (gh:#1311): resonance elastic scattering off on every
    // nuclide, for the paired DBRC worth against OpenMC's `--no-dbrc`. An
    // explicit ablation; DBRC stays on by default.
    let no_dbrc = args.iter().any(|a| a == "--no-dbrc");
    let entropy_csv: Option<std::path::PathBuf> = args
        .iter()
        .position(|a| a == "--entropy-csv")
        .and_then(|i| args.get(i + 1))
        .map(std::path::PathBuf::from);
    if no_dbrc {
        eprintln!("  ABLATION: --no-dbrc, every nuclide's target is free gas (no 0 K rejection)");
        nuclides = nuclides.into_iter().map(|n| n.without_dbrc()).collect();
    }
    let load_s = t0.elapsed().as_secs_f64();
    let idx = |n: &str| names.iter().position(|k| *k == n).expect("nuclide");
    let materials: Vec<Material> = mats
        .iter()
        .enumerate()
        .map(|(i, (mname, comps))| Material {
            id: i as i32 + 1,
            name: (*mname).into(),
            temperature: if i == m::GRAPHITE_IDX { t_g } else if i >= base_materials && i < first_rod_material { m::SHIELD_TEMPERATURE_K } else { t_k },
            components: comps.iter().map(|(n, d)| NuclideComponent { nuclide_idx: idx(n), atom_density: *d }).collect(),
        })
        .collect();
    let hw = outram_mc_libs::perf_report::HardwareInfo::detect().headline();
    eprintln!("  nuclear data ready in {load_s:.1} s ({} nuclides); hardware: {hw}; threads {threads}", names.len());

    let g = match shield {
        m::Shield::Omitted => m::geometry_with_ends(t_k, t_g, dims, ends),
        m::Shield::Tm0728Cylinder => m::geometry_with_shield(t_k, t_g, dims, ends, base_materials),
    };
    let g = if rodded { m::geometry_with_rods(g, dims, rods, first_rod_material, t_k) } else { g };
    let label = format!("{}{}@salt{salt_f}F/graphite{graphite_f}F", match mo { m::MoTreatment::Omitted => "mo-omitted", m::MoTreatment::Mo95Equivalent => "mo95-equivalent", m::MoTreatment::Natural => "mo-natural" }, if sab { "" } else { "+no-sab" }) + if no_dbrc { "+no-dbrc" } else { "" } + if hot_dims { "+hot-dims" } else { "" } + if graphite_law == "30p" { String::new() } else { format!("+graphite-{graphite_law}") }.as_str() + li7_pct.map_or(String::new(), |p| format!("+li7-{p}")).as_str() + u235_scale.map_or(String::new(), |x| format!("+u235x{x}")).as_str() + if ends == m::Ends::Tm0730 { "+ends-tm0730" } else { "" } + if shield == m::Shield::Tm0728Cylinder { "+shield-tm0728" } else { "" } + if drained { "-drained" } else { "" } + if packed { "-packed" } else { "" } + if rodded { format!("+rods-{rods_spec}") } else { String::new() }.as_str();
    let new_file = !csv.is_file();
    let mut f = std::fs::OpenOptions::new().create(true).append(true).open(&csv).expect("csv");
    if new_file {
        writeln!(f, "arm,seed,k,k_std,particles,inactive,active,threads,wall_s,load_s,hardware").expect("csv");
    }
    for seed in seeds {
        let s = KeffSettings {
            n_particles: np,
            n_inactive: ni,
            n_active: na,
            temperature_k: t_k,
            seed,
            compute: ComputeType::CpuMultiThread(ThreadCount::Fixed(threads)),
            ..KeffSettings::default()
        };
        let t = Instant::now();
        // `--entropy-csv`: the same run through the hybrid driver with no
        // majorants (exactly `run_keff_csg`, per its docs) plus an 8x8x8
        // entropy mesh over the source box, writing k and H per generation.
        // `--axial-csv`: tally fission and flux on an R-Z mesh (inside the
        // graphite radius, and the ring out to the vessel) through the
        // lower plenum, core and upper plenum, for the N-4 line model
        // (gh:#1130). Scoring draws no random number, so k is unchanged.
        let mut axial = axial_csv.as_ref().map(|_| axial_tally());
        let r = match &entropy_csv {
            None => run_keff_csg(&g, &materials, &nuclides, m::source_box(), &s, axial.as_mut()),
            Some(_) => {
                let b = m::source_box();
                let mesh = RegularMesh {
                    lower_left: [b.lower.x, b.lower.y, b.lower.z],
                    upper_right: [b.upper.x, b.upper.y, b.upper.z],
                    dimension: [8, 8, 8],
                };
                run_keff_csg_hybrid(&g, &materials, &nuclides, &[], Some(&mesh), b, &s, axial.as_mut())
            }
        };
        if let Some(path) = &entropy_csv {
            write_entropy_trace(path, &label, seed, ni, &r);
        }
        if let (Some(path), Some(t)) = (&axial_csv, &axial) {
            write_axial(path, &label, seed, t);
        }
        let wall = t.elapsed().as_secs_f64();
        let pcm = 1e5 * (r.k_mean - m::REFERENCE_K) / m::REFERENCE_K;
        eprintln!("  {label} seed {seed}: k = {:.5} +/- {:.5} ({pcm:+.0} pcm vs {:.5}) in {wall:.0} s", r.k_mean, r.k_std, m::REFERENCE_K);
        writeln!(f, "{label},{seed},{:.6},{:.6},{np},{ni},{na},{threads},{wall:.1},{load_s:.1},\"{hw}\"", r.k_mean, r.k_std).expect("csv");
    }
}

/// Append one run's per-generation `k` and Shannon entropy (bits) to `path`,
/// and print `stats::convergence`'s verdict on both traces. CLI glue (the
/// workspace's exception for `main` glue); the diagnostics it calls are
/// tested in their own modules.
fn write_entropy_trace(path: &std::path::Path, label: &str, seed: u64, n_inactive: usize, r: &KeffResult) {
    let new_file = !path.is_file();
    let mut f = std::fs::OpenOptions::new().create(true).append(true).open(path).expect("entropy csv");
    if new_file {
        writeln!(f, "arm,seed,generation,k,entropy_bits").expect("entropy csv");
    }
    for (i, k) in r.k_by_generation.iter().enumerate() {
        let h = r.entropy.get(i).copied().unwrap_or(f64::NAN);
        writeln!(f, "{label},{seed},{},{k:.6},{h:.6}", i + 1).expect("entropy csv");
    }
    let c = SourceConvergence::from_result(r, n_inactive);
    eprintln!("  {label} seed {seed}: source convergence {:?}", c.recommended_inactive);
    if let Some(e) = &c.entropy {
        eprintln!("    entropy: MSER {:?}; Geweke {:?}; change point {:?}", e.mser, e.geweke_after_truncation, e.change_point);
    }
    eprintln!("    k: MSER {:?}; Geweke {:?}; change point {:?}", c.k.mser, c.k.geweke_after_truncation, c.k.change_point);
}

/// Axial z edges for the N-4 tally: 4 bins through the lower plenum, 32
/// through the graphite, 4 through the upper plenum (cold dimensions).
fn axial_edges() -> Vec<f64> {
    let (lp, up, h) = (m::lower_plenum_height(), m::upper_plenum_height(), m::H_CORE);
    let mut z: Vec<f64> = (0..4).map(|i| -lp + lp * i as f64 / 4.0).collect();
    z.extend((0..32).map(|i| h * i as f64 / 32.0));
    z.extend((0..=4).map(|i| h + up * i as f64 / 4.0));
    z
}

/// Fission and flux on an R-Z mesh: r in [0, graphite radius] and
/// [graphite radius, vessel inner radius], one azimuthal bin, [`axial_edges`],
/// split at 0.625 eV.
fn axial_tally() -> Tally {
    let mesh = MeshKind::Cylindrical(CylindricalMesh {
        r_grid: vec![0.0, m::R_GRAPHITE, m::R_VESSEL_IN],
        phi_grid: vec![0.0, 2.0 * std::f64::consts::PI],
        z_grid: axial_edges(),
        origin: Position::ZERO,
    });
    let n = mesh.n_bins();
    Tally {
        id: 1,
        name: "N-4 axial fission and flux".into(),
        // Energy: below / above the conventional two-group thermal cutoff,
        // 0.625 eV, so the flux above it can stand in for a fast importance.
        filters: vec![FilterKind::Mesh(MeshFilter { mesh }), FilterKind::Energy(EnergyFilter { bins: vec![1e-11, 0.625, 2e7] })],
        scores: vec![ScoreType::Fission, ScoreType::Flux],
        bins: vec![TallyBin::default(); n * 2 * 2],
    }
}

/// Append one run's axial tally to `path`: per z bin, the fission and flux
/// sums inside the graphite radius and in the ring outside it. CLI glue (the
/// workspace's exception for `main` glue); the tally machinery is tested in
/// its own modules.
fn write_axial(path: &std::path::Path, label: &str, seed: u64, t: &Tally) {
    let FilterKind::Mesh(MeshFilter { mesh }) = &t.filters[0] else { unreachable!("mesh filter") };
    let z = axial_edges();
    let new_file = !path.is_file();
    let mut f = std::fs::OpenOptions::new().create(true).append(true).open(path).expect("axial csv");
    if new_file {
        writeln!(f, "arm,seed,z_lo_cm,z_hi_cm,fission_inner,fission_outer,flux_inner,flux_outer,flux_fast_inner").expect("axial csv");
    }
    for w in z.windows(2) {
        let zc = 0.5 * (w[0] + w[1]);
        let bin = |r: f64| mesh.bin(Position::new(r, 0.0, zc)).expect("inside the axial mesh");
        let (bi, bo) = (bin(0.5 * m::R_GRAPHITE), bin(0.5 * (m::R_GRAPHITE + m::R_VESSEL_IN)));
        // Layout: [(mesh bin * 2 + energy bin) * 2 + score]; energy 0 thermal, 1 fast.
        let get = |mb: usize, e: usize, sc: usize| t.bins[(mb * 2 + e) * 2 + sc].sum;
        let both = |mb: usize, sc: usize| get(mb, 0, sc) + get(mb, 1, sc);
        writeln!(
            f,
            "{label},{seed},{:.4},{:.4},{:.6e},{:.6e},{:.6e},{:.6e},{:.6e}",
            w[0], w[1], both(bi, 0), both(bo, 0), both(bi, 1), both(bo, 1), get(bi, 1, 1)
        )
        .expect("axial csv");
    }
}
