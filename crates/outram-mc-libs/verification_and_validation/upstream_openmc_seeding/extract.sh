#!/usr/bin/env bash
# Extract overall_generation / compute_particle_id / compute_transport_seed
# VERBATIM from OpenMC src/simulation.cpp (gh:#1386 section 2 item 1), after
# checking the commit and the SHA-256 of the files used. Output: ./generated/
# (gitignored). Fails if a function moved (start line + expected text).
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
up="${OPENMC_SRC:-$here/../../upstream_source/OpenMC}"
want="8f79d9d02483c90e4134f03a9df4b75ce6b062bf"
have="$(cd "$up" && git rev-parse HEAD)"
[ "$have" = "$want" ] || { echo "upstream at $have, expected $want" >&2; exit 1; }
check_sha() { got="$(sha256sum "$up/$1" | cut -d' ' -f1)"; [ "$got" = "$2" ] || { echo "SHA-256 mismatch for $1: $got" >&2; exit 1; }; }
check_sha src/simulation.cpp 5672fc6758aae353a82b664fded5963be9aec64b6534461ca13cbae62ec6d5a1
check_sha src/random_lcg.cpp 0aa9193434b5b0d4b85db4a399d5f44adab8bbf7c500fa11609d16c7a33e0182
check_sha src/random_dist.cpp 4d24807f52c55822b70404d353c507f5f3418eed5275999c6775ae1255dd45c2
out="$here/generated"; mkdir -p "$out"
dest="$out/simulation_seed_extract.inc"
{ echo "// GENERATED by extract.sh from OpenMC $want src/simulation.cpp. Do not edit."; echo "namespace openmc {"; } > "$dest"
fn() {
  local line="$1" expect="$2" got
  got="$(sed -n "${line}p" "$up/src/simulation.cpp")"
  case "$got" in "$expect"*) ;; *) echo "simulation.cpp:$line expected '$expect', found '$got'" >&2; exit 1 ;; esac
  awk -v s="$line" 'NR>=s { print } NR>=s && $0=="}" { exit }' "$up/src/simulation.cpp" >> "$dest"; echo >> "$dest"
}
fn 784 "int overall_generation()"
fn 790 "int64_t compute_particle_id("
fn 800 "int64_t compute_transport_seed("
echo "}" >> "$dest"
echo "wrote $dest"

# synchronize_bank's uniform comb (src/eigenvalue.cpp:150-175), VERBATIM, wrapped
# in a function over a stub fission bank (gh:#1386 task 3).
check_sha src/eigenvalue.cpp 5b184b950c3b84b1079bc748768c2b1f07937c2b21e69d0720b9b71289d00739
check_sha src/distribution_multi.cpp ceeb17e094d7d4f33e66e94518fde2bb6fe0dcd4181b7bd1f1bed4038e7059cf
first="$(sed -n 150p "$up/src/eigenvalue.cpp")"
case "$first" in "  int64_t id = simulation::total_gen + overall_generation();") ;; *) echo "eigenvalue.cpp:150 moved: $first" >&2; exit 1 ;; esac
last="$(sed -n 175p "$up/src/eigenvalue.cpp")"
[ "$last" = "  }" ] || { echo "eigenvalue.cpp:175 moved: $last" >&2; exit 1; }
dest="$out/comb_extract.inc"
{
  echo "// GENERATED by extract.sh from OpenMC $want src/eigenvalue.cpp:150-175 (synchronize_bank comb). Do not edit."
  echo "namespace openmc {"
  echo "std::vector<int> comb_block(int64_t total_in)"
  echo "{"
  echo "  int64_t start = 0;"
  echo "  int64_t total = total_in;"
  echo "  int64_t index_temp = 0;"
  echo "  std::vector<int> temp_sites(3 * settings::n_particles + 3);"
  echo "  std::vector<std::vector<int>> temp_delayed_groups;"
  echo "  std::vector<std::vector<double>> temp_lifetimes;"
  sed -n 150,175p "$up/src/eigenvalue.cpp"
  echo "  temp_sites.resize(index_temp);"
  echo "  return temp_sites;"
  echo "}"
  echo "}"
} > "$dest"
# isotropic_direction (distribution_multi.cpp:160-166), VERBATIM
first="$(sed -n 160p "$up/src/distribution_multi.cpp")"
case "$first" in "Direction isotropic_direction(uint64_t* seed)") ;; *) echo "distribution_multi.cpp:160 moved: $first" >&2; exit 1 ;; esac
{
  echo "// GENERATED by extract.sh from OpenMC $want src/distribution_multi.cpp:160-166. Do not edit."
  echo "namespace openmc {"
  sed -n 160,166p "$up/src/distribution_multi.cpp"
  echo "}"
} > "$out/isotropic_extract.inc"
echo "wrote comb_extract.inc isotropic_extract.inc"
