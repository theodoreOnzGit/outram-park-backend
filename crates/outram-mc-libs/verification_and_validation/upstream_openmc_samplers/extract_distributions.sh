#!/usr/bin/env bash
# Extract OpenMC's univariate and spatial source-distribution implementations
# VERBATIM (by SHA-checked line ranges) for the differential in
# tests/source_distributions_vs_openmc_code_to_code.rs (gh:#1388).
# Output: ./generated/ (gitignored). A moved line makes this fail.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
up="${OPENMC_SRC:-$here/../../upstream_source/OpenMC}"
want="8f79d9d02483c90e4134f03a9df4b75ce6b062bf"
have="$(cd "$up" && git rev-parse HEAD)"
[ "$have" = "$want" ] || { echo "upstream at $have, expected $want" >&2; exit 1; }
check_sha() { got="$(sha256sum "$up/$1" | cut -d' ' -f1)"; [ "$got" = "$2" ] || { echo "SHA-256 mismatch for $1: $got" >&2; exit 1; }; }
check_sha src/random_lcg.cpp 0aa9193434b5b0d4b85db4a399d5f44adab8bbf7c500fa11609d16c7a33e0182
check_sha src/random_dist.cpp 4d24807f52c55822b70404d353c507f5f3418eed5275999c6775ae1255dd45c2
check_sha src/position.cpp efb7dcc8c94adc20ea0df8e2f9cf8b87bd27b07edfc44d31b92cae5a6329afce
check_sha src/math_functions.cpp 8350bf60aaaf1984dbdc69f83952d7267ffeef738b8384de63f8975bc7020f3c
check_sha src/distribution.cpp 688f1afef833a18d37e6696a86b29e040e10432a7f3003f39b73b941edb804c5
check_sha src/distribution_spatial.cpp 189a3d4fbe546344aaf5502e784a9ad16a8b1e51b88fb31e7cb402be35a6f9ff
out="$here/generated"; mkdir -p "$out"
blk() { # dest file first last "text expected on the first line"
  local dest="$1" file="$2" a="$3" b="$4" expect="$5" got
  got="$(sed -n "${a}p" "$up/$file")"
  case "$got" in *"$expect"*) ;; *) echo "$file:$a expected '$expect', found '$got'" >&2; exit 1 ;; esac
  sed -n "${a},${b}p" "$up/$file" >> "$dest"; echo >> "$dest"
}
dest="$out/distribution_full.inc"
{ echo "// GENERATED by extract_distributions.sh from OpenMC $want src/distribution.cpp (lines 26-772: everything before DecaySpectrum). Do not edit."; echo "namespace openmc {"; } > "$dest"
blk "$dest" src/distribution.cpp 26 772 "//====="
echo "}" >> "$dest"
dest="$out/spatial_full.inc"
{ echo "// GENERATED by extract_distributions.sh from OpenMC $want src/distribution_spatial.cpp (Cartesian..Spherical, PointCloud..SpatialPoint; MeshSpatial and create() omitted). Do not edit."; echo "namespace openmc {"; } > "$dest"
blk "$dest" src/distribution_spatial.cpp 43 257 "//====="
blk "$dest" src/distribution_spatial.cpp 376 492 "//====="
echo "}" >> "$dest"
dest="$out/normal_cdf.inc"
{ echo "// GENERATED by extract_distributions.sh from OpenMC $want src/math_functions.cpp:100. Do not edit."; echo "namespace openmc {"; } > "$dest"
blk "$dest" src/math_functions.cpp 100 105 "double standard_normal_cdf("
echo "}" >> "$dest"
echo "wrote $out"
