#!/usr/bin/env bash
# Extract the OpenMC routines that cannot be compiled whole (their .cpp files
# also hold XML / HDF5 / settings code) VERBATIM from the pinned upstream clone,
# after checking the commit and the SHA-256 of every source file used
# (gh:#1386, prio-1 row 4). Whole files compiled unmodified are SHA-checked too.
# Output: ./generated/ (gitignored). A moved function makes this fail.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
up="${OPENMC_SRC:-$here/../../upstream_source/OpenMC}"
want="8f79d9d02483c90e4134f03a9df4b75ce6b062bf"
have="$(cd "$up" && git rev-parse HEAD)"
[ "$have" = "$want" ] || { echo "upstream at $have, expected $want" >&2; exit 1; }
check_sha() { got="$(sha256sum "$up/$1" | cut -d' ' -f1)"; [ "$got" = "$2" ] || { echo "SHA-256 mismatch for $1: $got" >&2; exit 1; }; }
# compiled whole and unmodified (see run.sh)
check_sha src/random_lcg.cpp 0aa9193434b5b0d4b85db4a399d5f44adab8bbf7c500fa11609d16c7a33e0182
check_sha src/random_dist.cpp 4d24807f52c55822b70404d353c507f5f3418eed5275999c6775ae1255dd45c2
check_sha src/distribution_energy.cpp 6eb8ebae13f026bc94e92c8a49c7ea1049e853bbd8997ee5fedbbba92b3fe1c5
check_sha src/distribution_angle.cpp 5b08ac4b53ed65d9a2938901a96fc7fa9c5a7a9c3b96bbb3f84406441c46772d
check_sha src/secondary_uncorrelated.cpp 82dbcc98d03ac16a25eeff64494c9c605585742be1c455988cf6db4e2f4c625b
check_sha src/secondary_kalbach.cpp 3410266fe87b827566f44305c56e976a75a69b0231426996eeae5e0e70b88863
check_sha src/secondary_correlated.cpp c45fe38acf5be0a34613fb456312b5eeae37b6326d9d2da9469b0eb892d6f00e
check_sha src/secondary_nbody.cpp a756746b81f2dad24b4183dacedefca1247b760a21fa1a25e0017504cfc4a65e
check_sha src/secondary_thermal.cpp 57d26c9218300b552a8224c5e7a7e559298b4f5fb36b50f35b2d54bdf91a5618
check_sha src/position.cpp efb7dcc8c94adc20ea0df8e2f9cf8b87bd27b07edfc44d31b92cae5a6329afce
check_sha src/math_functions.cpp 8350bf60aaaf1984dbdc69f83952d7267ffeef738b8384de63f8975bc7020f3c
# extracted
check_sha src/distribution.cpp 688f1afef833a18d37e6696a86b29e040e10432a7f3003f39b73b941edb804c5
check_sha src/endf.cpp 604161ec8079fdb168b67c3419269fb34a89935caf38db3c5139f00587bdefb6

out="$here/generated"; mkdir -p "$out"
fn() { # dest file line "expected text"
  local dest="$1" file="$2" line="$3" expect="$4" got
  got="$(sed -n "${line}p" "$up/$file")"
  case "$got" in "$expect"*) ;; *) echo "$file:$line expected '$expect', found '$got'" >&2; exit 1 ;; esac
  awk -v s="$line" 'NR>=s { print } NR>=s && $0=="}" { exit }' "$up/$file" >> "$dest"; echo >> "$dest"
}
dest="$out/distribution_extract.inc"
{ echo "// GENERATED by extract.sh from OpenMC $want src/distribution.cpp. Do not edit."; echo "namespace openmc {"; } > "$dest"
fn "$dest" src/distribution.cpp 57  "std::pair<double, double> Distribution::sample("
fn "$dest" src/distribution.cpp 72  "double Distribution::evaluate("
fn "$dest" src/distribution.cpp 498 "Tabular::Tabular(const double* x"
fn "$dest" src/distribution.cpp 505 "void Tabular::init("
fn "$dest" src/distribution.cpp 549 "double Tabular::sample_unbiased("
fn "$dest" src/distribution.cpp 604 "double Tabular::evaluate("
echo "}" >> "$dest"
dest="$out/endf_extract.inc"
{ echo "// GENERATED by extract.sh from OpenMC $want src/endf.cpp. Do not edit."; echo "namespace openmc {"; } > "$dest"
fn "$dest" src/endf.cpp 21 "Interpolation int2interp("
fn "$dest" src/endf.cpp 216 "Tabulated1D::Tabulated1D("
fn "$dest" src/endf.cpp 243 "double Tabulated1D::operator()"
fn "$dest" src/endf.cpp 305 "CoherentElasticXS::CoherentElasticXS(hid_t dset)"
fn "$dest" src/endf.cpp 320 "double CoherentElasticXS::operator()"
echo "}" >> "$dest"
dest="$out/math_extract.inc"
{ echo "// GENERATED by extract.sh from OpenMC $want src/math_functions.cpp. Do not edit."; echo "namespace openmc {"; } > "$dest"
fn "$dest" src/math_functions.cpp 931 "double exprel("
fn "$dest" src/math_functions.cpp 940 "double log1prel("
fn "$dest" src/math_functions.cpp 991 "void get_energy_index("
echo "}" >> "$dest"

# ---- collision kinematics (gh:#1444): physics.cpp / math_functions.cpp / nuclide.cpp ----
check_sha src/physics.cpp 6a9e54382e63cca6dc0aa2540801132feea42187e10b0dc9b0f9d933c04fc7b9
check_sha src/nuclide.cpp e5c816cacdd8362ec19ec03114c74ec6915ec966174157bb051b2d808f77f187
blk() { # dest file first last "expected first line text"
  local dest="$1" file="$2" a="$3" b="$4" expect="$5" got
  got="$(sed -n "${a}p" "$up/$file")"
  case "$got" in *"$expect"*) ;; *) echo "$file:$a expected '$expect', found '$got'" >&2; exit 1 ;; esac
  sed -n "${a},${b}p" "$up/$file" >> "$dest"; echo >> "$dest"
}
dest="$out/physics_extract.inc"
{ echo "// GENERATED by extract.sh from OpenMC $want (math_functions.cpp, physics.cpp, nuclide.cpp). Do not edit."; echo "namespace openmc {"; } > "$dest"
fn "$dest" src/math_functions.cpp 772 "Direction rotate_angle("
fn "$dest" src/physics.cpp 792 "void elastic_scatter(int i_nuclide"
fn "$dest" src/physics.cpp 874 "Direction sample_target_velocity("
fn "$dest" src/physics.cpp 1028 "Direction sample_cxs_target_velocity("
fn "$dest" src/nuclide.cpp 589 "double Nuclide::elastic_xs_0K("
# the CM -> lab block of inelastic_scatter (lines 1169-1179), wrapped in a function
{
  echo "void inelastic_cm_to_lab(const Nuclide& nuc, const Reaction& rx, double E_in, double& E, double& mu)"
  echo "{"
} >> "$dest"
blk "$dest" src/physics.cpp 1169 1179 "if (rx.scatter_in_cm_) {"
echo "}" >> "$dest"
# the 0 K cross-section CDF build (nuclide.cpp:477-494), wrapped as a member
{
  echo "void Nuclide::build_xs_cdf()"
  echo "{"
} >> "$dest"
blk "$dest" src/nuclide.cpp 477 494 "double xs_cdf_sum = 0.0;"
echo "}" >> "$dest"
echo "}" >> "$dest"
echo "wrote $out"
