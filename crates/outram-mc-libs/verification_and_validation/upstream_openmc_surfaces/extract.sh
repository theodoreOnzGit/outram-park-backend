#!/usr/bin/env bash
# Extract the OpenMC routines compared in gh:#1386 (prio-1 rows 1 and 2) VERBATIM
# from the pinned upstream clone, after checking the commit and the SHA-256 of
# every source file. Output goes to ./generated/ (gitignored; regenerate any time).
#
# Extraction is by "start line + expected text + copy to the first line that is
# exactly `}`", so a moved or edited function makes the script fail instead of
# silently extracting the wrong text.
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
up="${OPENMC_SRC:-$here/../../upstream_source/OpenMC}"
want="8f79d9d02483c90e4134f03a9df4b75ce6b062bf"
have="$(git -C "$up" rev-parse HEAD)"
[ "$have" = "$want" ] || { echo "upstream at $have, expected $want" >&2; exit 1; }

check_sha() { # file sha
  got="$(sha256sum "$up/$1" | cut -d' ' -f1)"
  [ "$got" = "$2" ] || { echo "SHA-256 mismatch for $1: $got" >&2; exit 1; }
}
check_sha src/surface.cpp 9731a531f27ace1922ae230b54dee93fb742142482a2e942b61279954bbeee68
check_sha src/lattice.cpp 106d289a4525c74b52b009019fdf9e624d37385d04f3afe99ecc7e4ffb62b6bc
check_sha src/math_functions.cpp 8350bf60aaaf1984dbdc69f83952d7267ffeef738b8384de63f8975bc7020f3c
check_sha include/openmc/geometry.h 6b835d3f9ec952a65c469506ce900505ce0fc415923f5f2927cdb320aaba8f60
check_sha include/openmc/constants.h 3adfdd38c05291b8179c4e210747d036b1fed06efc0dc488b7afddfdcbc0350a
check_sha include/openmc/position.h e9af866f422eef393fa14222763f1baffe68d0e71388ebc1eb34bf58162713e7
check_sha src/position.cpp efb7dcc8c94adc20ea0df8e2f9cf8b87bd27b07edfc44d31b92cae5a6329afce
check_sha src/external/quartic_solver.cpp 3883c3b59c82dfdbbd884ae42735dbc65b5e73710b04a6d9dc9a91b059222193
check_sha include/openmc/external/quartic_solver.h 8794740ca555a03da60435b9eb3b5c4af5f945651ce18b1b08a27ef29dd5abad

out="$here/generated"
mkdir -p "$out"

# fn FILE LINE "expected text starting at LINE": append to $dest
fn() {
  local file="$1" line="$2" expect="$3"
  local got
  got="$(sed -n "${line}p" "$up/$file")"
  case "$got" in
    "$expect"*) ;;
    *) echo "$file:$line expected '$expect', found '$got'" >&2; exit 1 ;;
  esac
  awk -v s="$line" 'NR>=s { print } NR>=s && $0=="}" { exit }' "$up/$file" >> "$dest"
  echo >> "$dest"
}

