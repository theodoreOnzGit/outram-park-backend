/// `endf.data.zam` (`endf/data.py:129-151`): `(Z, A, metastable)` from a GNDS
/// name such as `"U235"` or `"Am242_m1"`.
///
/// Implements the full-match of `([A-Zn][a-z]*)(\d+)((?:_[em]\d+)?)` by hand.
pub fn zam(name: &str) -> Option<(u32, u32, u32)> {
    let b = name.as_bytes();
    let mut i = 0;
    if b.is_empty() || !(b[0].is_ascii_uppercase() || b[0] == b'n') {
        return None;
    }
    i += 1;
    while i < b.len() && b[i].is_ascii_lowercase() {
        i += 1;
    }
    let sym = &name[..i];
    let a0 = i;
    while i < b.len() && b[i].is_ascii_digit() {
        i += 1;
    }
    if i == a0 {
        return None;
    }
    let a: u32 = name[a0..i].parse().ok()?;
    let mut m = 0;
    if i < b.len() {
        // `_[em]\d+` and nothing after it
        if b.len() < i + 3 || b[i] != b'_' || !(b[i + 1] == b'e' || b[i + 1] == b'm') {
            return None;
        }
        let rest = &name[i + 2..];
        if rest.is_empty() || !rest.bytes().all(|c| c.is_ascii_digit()) {
            return None;
        }
        m = rest.parse().ok()?;
    }
    let z = ATOMIC_SYMBOL.iter().position(|s| *s == sym)? as u32;
    Some((z, a, m))
}

/// `endf.data.gnds_name` (`endf/data.py:154-172`).
pub fn gnds_name(z: u32, a: u32, m: u32) -> Option<String> {
    let sym = ATOMIC_SYMBOL.get(z as usize)?;
    Some(if m > 0 {
        format!("{sym}{a}_m{m}")
    } else {
        format!("{sym}{a}")
    })
}

/// `re.match(r'{element}\d+', name)`: `name` starts with `element` and then
/// at least one digit. This is upstream's test in `openmc.data.isotopes`
/// (`openmc/data/data.py:537-540`) and `Element.expand`
/// (`openmc/element.py:147`).
pub(crate) fn matches_element(element: &str, name: &str) -> bool {
    name.strip_prefix(element)
        .and_then(|r| r.bytes().next())
        .is_some_and(|c| c.is_ascii_digit())
}

/// `openmc.data.isotopes(element)` (`openmc/data/data.py:513-542`): the
/// naturally-occurring isotopes of `element` with their atom fractions, in
/// `NATURAL_ABUNDANCE` order.
pub fn natural_isotopes(element: &str) -> Vec<(&'static str, f64)> {
    NATURAL_ABUNDANCE
        .iter()
        .filter(|(n, _)| matches_element(element, n))
        .copied()
        .collect()
}

