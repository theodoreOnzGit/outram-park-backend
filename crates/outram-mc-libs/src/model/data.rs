/// Why nuclear data could not be found or processed.
#[derive(Debug, thiserror::Error)]
pub enum DataError {
    /// No tape in the library is this nuclide.
    #[error("the library '{library}' has no incident-neutron tape for {isotope}")]
    NotInLibrary {
        /// The library.
        library: String,
        /// The nuclide.
        isotope: Isotope,
    },
    /// Several tapes are this nuclide and none is preferred.
    #[error(
        "the library '{library}' has several tapes for {isotope}: {files:?}; remove all but one"
    )]
    Ambiguous {
        /// The library.
        library: String,
        /// The nuclide.
        isotope: Isotope,
        /// The candidates.
        files: Vec<String>,
    },
    /// A folder with no readable ENDF tape.
    #[error("no incident-neutron ENDF tape found in {0}")]
    NoTapes(String),
    /// Reading or processing a tape failed.
    #[error("processing {what}: {source}")]
    Njoy {
        /// Which nuclide or law.
        what: String,
        /// The njoy error.
        #[source]
        source: NjoyError,
    },
    /// The ACE files hold no usable table for a nuclide or law at the
    /// model's temperature: none at all, only at other temperatures (a
    /// mismatch is refused, never accepted), or several.
    #[error("the ACE files '{library}' cannot supply {what}: {reason}")]
    Ace {
        /// The ACE set.
        library: String,
        /// The nuclide or law, and the temperature asked for.
        what: String,
        /// Why.
        reason: String,
    },
}

/// Where one tape is.
#[derive(Debug, Clone)]
enum TapeLocation {
    File(PathBuf),
    Bytes(Arc<Vec<u8>>),
    /// Tape `usize` of an indexed library (folder, zip or upload).
    Library(Arc<EndfLibraryIndex>, usize),
}

/// One indexed incident-neutron tape.
#[derive(Debug, Clone)]
struct TapeEntry {
    isotope: Isotope,
    awr: f64,
    nlib: Option<i64>,
    nver: Option<i64>,
    file: String,
    location: TapeLocation,
}

/// Which tapes of a folder count, when several are the same nuclide.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Preference {
    /// Every tape counts; two for one nuclide is an error.
    None,
    /// ENDF/B-VIII (`NLIB = 0`, `NVER = 8`) only; among several, the one
    /// named `*-ENDF8.0.endf`.
    EndfBViii,
}

/// **A nuclear-data library**: the incident-neutron ENDF tapes a model's
/// nuclides are processed from. See the module docs for what it does and
/// what it leaves open.
#[derive(Debug, Clone)]
pub struct NuclearData {
    label: String,
    tapes: Vec<TapeEntry>,
    preference: Preference,
    /// `Some` for the ACE way in ([`Self::from_ace_files`]): `tapes` is then
    /// empty and every lookup goes to the ACE set.
    ace: Option<Arc<ace::AceData>>,
}

/// Header fields read from the first lines of an ENDF tape.
struct Header {
    isotope: Isotope,
    awr: f64,
    nlib: Option<i64>,
    nver: Option<i64>,
}

/// The identity fields of an incident-neutron tape's header, read by
/// `njoy_outram_park_fork::endf_library::EndfHeader` (the one MF1/MT451
/// parser the library index also uses). `None` when this is not an
/// incident-neutron tape (`NSUB != 10`) or is unreadable.
fn read_header(text: &str) -> Option<Header> {
    let h = EndfHeader::parse(text)?;
    if h.sub_library() != SubLibrary::IncidentNeutron {
        return None;
    }
    header_of(&h)
}

fn header_of(h: &EndfHeader) -> Option<Header> {
    let isotope = Isotope::metastable(
        u8::try_from(h.z()).ok()?,
        u16::try_from(h.a()).ok()?,
        h.liso,
    )
    .ok()?;
    Some(Header {
        isotope,
        awr: h.awr,
        nlib: Some(h.nlib),
        nver: h.nver,
    })
}

impl NuclearData {
    fn index(
        label: String,
        preference: Preference,
        entries: Vec<(String, TapeLocation, &str)>,
    ) -> Self {
        let tapes = entries
            .into_iter()
            .filter_map(|(file, location, text)| {
                let h = read_header(text)?;
                Some(TapeEntry {
                    isotope: h.isotope,
                    awr: h.awr,
                    nlib: h.nlib,
                    nver: h.nver,
                    file,
                    location,
                })
            })
            .collect();
        Self {
            label,
            tapes,
            preference,
            ace: None,
        }
    }

    /// **Every incident-neutron ENDF tape in `dir`** (`*.endf`, `*.dat`, and
    /// the `neutrons/` sub-folder of an extracted library). Two tapes of one
    /// nuclide make that nuclide an error when asked for. Native only.
    ///
    /// # Errors
    /// [`DataError::NoTapes`] when the folder holds none.
    pub fn endf_folder(dir: &Path) -> Result<Self, DataError> {
        Self::scan(
            dir,
            Preference::None,
            format!("ENDF folder {}", dir.display()),
        )
    }

    /// **The workspace's reference tapes** (`reference-data/endf/`, or
    /// `$OUTRAM_PARK_ENDF_DIR`), restricted to **ENDF/B-VIII** (`NLIB = 0`,
    /// `NVER = 8` in each header); where two such tapes are one nuclide, the
    /// one named `*-ENDF8.0.endf`. These are the tapes the crate's recorded
    /// ICSBEP benchmarks use (`vv::godiva`, `vv::hst009`). Native only.
    ///
    /// **Not Fe-54 (found 2026-10-18, tutorial 6):** that tape's header says
    /// `NLIB = 8`, so this constructor does not offer it and LCT-008's clad
    /// (Fe-54 among its 35 nuclides) cannot be built from it. Use
    /// [`Self::from_folder`] on the same folder: it identifies the library
    /// by the tapes' `HSUB` line and finds all 35. (Checked: this
    /// constructor finds 34 of LCT-008 case 1's 35 nuclides, Fe-54 missing;
    /// `from_folder` finds all 35.)
    ///
    /// # Errors
    /// [`DataError::NoTapes`] when the folder is missing or empty (a clone
    /// without the reference data).
    pub fn workspace_reference() -> Result<Self, DataError> {
        let dir = njoy_outram_park_fork::reference_data::reference_endf_dir();
        let dir = dir.canonicalize().unwrap_or(dir);
        Self::scan(
            &dir,
            Preference::EndfBViii,
            format!("ENDF/B-VIII reference tapes, {}", dir.display()),
        )
    }

    fn scan(dir: &Path, preference: Preference, label: String) -> Result<Self, DataError> {
        use std::io::{BufRead, BufReader};
        let mut entries = Vec::new();
        for sub in [dir.to_path_buf(), dir.join("neutrons")] {
            let Ok(read) = std::fs::read_dir(&sub) else {
                continue;
            };
            let mut files: Vec<PathBuf> = read
                .flatten()
                .map(|e| e.path())
                .filter(|p| {
                    p.is_file()
                        && p.extension()
                            .and_then(|x| x.to_str())
                            .is_some_and(|x| x == "endf" || x == "dat")
                })
                .collect();
            files.sort();
            for p in files {
                let Ok(f) = std::fs::File::open(&p) else {
                    continue;
                };
                let head: Vec<String> = BufReader::new(f)
                    .lines()
                    .take(4)
                    .map_while(Result::ok)
                    .collect();
                let name = p
                    .file_name()
                    .and_then(|n| n.to_str())
                    .unwrap_or_default()
                    .to_string();
                entries.push((name, p, head.join("\n")));
            }
        }
        let data = Self::index(
            label.clone(),
            preference,
            entries
                .iter()
                .map(|(n, p, t)| (n.clone(), TapeLocation::File(p.clone()), t.as_str()))
                .collect(),
        );
        if data.tapes.is_empty() {
            return Err(DataError::NoTapes(label));
        }
        Ok(data)
    }

    /// **A whole ENDF library from a folder** (#935): the extracted archive
    /// (`ENDF-B-VIII.0/neutrons/...`), NNDC's per-sub-library folder
    /// (`ENDF-B-VIII.0_neutrons/`), the IAEA per-nuclide zips, or any flat
    /// folder of tapes. The layout is read from the names; each tape is
    /// identified by its header; the tapes of the library most of them belong
    /// to are used, and any other library's tapes are left out (the label
    /// says how many). Native only.
    ///
    /// # Errors
    /// The folder cannot be read; [`DataError::NoTapes`] when it holds no
    /// incident-neutron tape.
    pub fn from_folder(dir: &Path) -> Result<Self, DataError> {
        let index = EndfLibraryIndex::from_folder(dir).map_err(|source| DataError::Njoy {
            what: format!("the folder {}", dir.display()),
            source,
        })?;
        Self::from_library(index)
    }

    /// **A whole ENDF library from its zip, as bytes** (#935): the same as
    /// [`Self::from_folder`] on the folder the zip holds, touching no file,
    /// so a browser runs it on an uploaded zip. `label` names the zip in the
    /// run's provenance.
    ///
    /// # Errors
    /// The bytes are not a readable zip; [`DataError::NoTapes`].
    pub fn from_zip_bytes(label: &str, bytes: Vec<u8>) -> Result<Self, DataError> {
        let index = EndfLibraryIndex::from_zip_bytes(bytes).map_err(|source| DataError::Njoy {
            what: format!("the zip {label}"),
            source,
        })?;
        Self::from_library(index).map(|d| d.relabelled(label))
    }

    /// **A library uploaded as files** (`(path, contents)`, paths relative to
    /// the chosen folder): a browser folder upload, several dropped tapes, or
    /// a dropped zip (opened). The same index as [`Self::from_folder`].
    ///
    /// # Errors
    /// [`DataError::NoTapes`].
    pub fn from_files(label: &str, files: Vec<(String, Vec<u8>)>) -> Result<Self, DataError> {
        let index = EndfLibraryIndex::from_files(files).map_err(|source| DataError::Njoy {
            what: format!("the files {label}"),
            source,
        })?;
        Self::from_library(index).map(|d| d.relabelled(label))
    }

    /// The library index's main library's incident-neutron tapes.
    fn from_library(index: EndfLibraryIndex) -> Result<Self, DataError> {
        let index = Arc::new(index);
        let main = index
            .main_library()
            .ok_or_else(|| DataError::NoTapes(index.summary()))?;
        let tapes: Vec<TapeEntry> = index
            .tapes()
            .iter()
            .enumerate()
            .filter(|(_, t)| {
                t.header.sub_library() == SubLibrary::IncidentNeutron && t.header.library() == main
            })
            .filter_map(|(i, t)| {
                let h = header_of(&t.header)?;
                Some(TapeEntry {
                    isotope: h.isotope,
                    awr: h.awr,
                    nlib: h.nlib,
                    nver: h.nver,
                    file: t.path.clone(),
                    location: TapeLocation::Library(index.clone(), i),
                })
            })
            .collect();
        Ok(Self {
            label: index.summary(),
            tapes,
            preference: Preference::None,
            ace: None,
        })
    }

    fn relabelled(mut self, name: &str) -> Self {
        self.label = format!("{name}: {}", self.label);
        self
    }

    /// **The ACE way in** (#936): nuclides read from ACE files **as they
    /// are**, with nothing processed. Each file (Type 1 or 2, gzipped or
    /// not, one or several tables, or a zip of them) is indexed by its
    /// header: ZAID, class and kT, never by its name
    /// (`njoy_outram_park_fork::acer::ace_set`).
    ///
    /// At [`Self::load_nuclide`]:
    ///
    /// - **The temperature is the file's.** The model's temperature must
    ///   match a table's kT (relative 1e-4, the header's print precision with
    ///   margin); a mismatch is a [`DataError::Ace`] listing the temperatures
    ///   the files have, never a silent use of another temperature.
    /// - **DBRC** takes its 0 K elastic from a 0 K table of the same ZA in
    ///   the files (generate one with each table, or drop the library's `0K/`
    ///   folder too). Without one the nuclide carries DBRC **off**, and the
    ///   run's provenance says so for that nuclide; it is never silent.
    /// - **Thermal laws** are thermal (`t`) tables. An ACE header does not
    ///   say which law it is, only a ZAID name, so the name is matched: the
    ///   name njoy's generator gives a law (`tsl` + the LEAPR deck's MAT,
    ///   e.g. `tsl1` for H in H2O), or one bound by hand with
    ///   [`Self::with_thermal_table`] (`hh2o`, `lwtr`, ...).
    ///
    /// # Errors
    /// [`DataError::NoTapes`] when no file holds a continuous-energy neutron
    /// table; the label lists the files skipped.
    pub fn from_ace_files(label: &str, files: Vec<(String, Vec<u8>)>) -> Result<Self, DataError> {
        ace::AceData::new(label, files).map(|a| Self {
            label: a.label(),
            tapes: Vec::new(),
            preference: Preference::None,
            ace: Some(Arc::new(a)),
        })
    }

    /// **Bind a thermal table to a law** by its ZAID name (`stem`, the part
    /// before the `.`: `hh2o` for NJOY's `hh2o.00t`), for ACE files made
    /// elsewhere. Only meaningful for [`Self::from_ace_files`]; on ENDF data
    /// the law is always regenerated by LEAPR and this does nothing.
    #[must_use]
    pub fn with_thermal_table(mut self, law: SabMaterial, stem: &str) -> Self {
        if let Some(a) = self.ace.take() {
            let mut a = (*a).clone();
            a.bind(law, stem);
            self.label = a.label();
            self.ace = Some(Arc::new(a));
        }
        self
    }

    /// **Tapes given as bytes** (`(file name, contents)`), for a browser
    /// upload or any caller that already holds them. Touches no file. Tapes
    /// that are not incident-neutron ENDF are ignored.
    ///
    /// # Errors
    /// [`DataError::NoTapes`] when none is an incident-neutron tape.
    pub fn from_endf_bytes(
        label: &str,
        tapes: impl IntoIterator<Item = (String, Vec<u8>)>,
    ) -> Result<Self, DataError> {
        let owned: Vec<(String, Arc<Vec<u8>>)> =
            tapes.into_iter().map(|(n, b)| (n, Arc::new(b))).collect();
        let texts: Vec<String> = owned
            .iter()
            .map(|(_, b)| String::from_utf8_lossy(&b[..b.len().min(400)]).into_owned())
            .collect();
        let data = Self::index(
            label.to_string(),
            Preference::None,
            owned
                .iter()
                .zip(&texts)
                .map(|((n, b), t)| (n.clone(), TapeLocation::Bytes(b.clone()), t.as_str()))
                .collect(),
        );
        if data.tapes.is_empty() {
            return Err(DataError::NoTapes(label.to_string()));
        }
        Ok(data)
    }

    /// What this library is, for a run's provenance.
    pub fn label(&self) -> &str {
        &self.label
    }

    fn entry(&self, isotope: Isotope) -> Result<&TapeEntry, DataError> {
        let mut hits: Vec<&TapeEntry> =
            self.tapes.iter().filter(|t| t.isotope == isotope).collect();
        if self.preference == Preference::EndfBViii {
            hits.retain(|t| t.nlib == Some(0) && t.nver == Some(8));
            if hits.len() > 1 {
                let named: Vec<&TapeEntry> = hits
                    .iter()
                    .copied()
                    .filter(|t| t.file.ends_with("-ENDF8.0.endf"))
                    .collect();
                if named.len() == 1 {
                    hits = named;
                }
            }
        }
        match hits.as_slice() {
            [] => Err(DataError::NotInLibrary {
                library: self.label.clone(),
                isotope,
            }),
            [one] => Ok(one),
            many => Err(DataError::Ambiguous {
                library: self.label.clone(),
                isotope,
                files: many.iter().map(|t| t.file.clone()).collect(),
            }),
        }
    }

    /// The file name of the tape `isotope` is processed from.
    ///
    /// # Errors
    /// [`DataError::NotInLibrary`] or [`DataError::Ambiguous`].
    pub fn tape_file(&self, isotope: Isotope) -> Result<&str, DataError> {
        if let Some(a) = &self.ace {
            return a.file_of(isotope);
        }
        self.entry(isotope).map(|t| t.file.as_str())
    }

    /// **The nuclides this library can supply, with their masses** (each
    /// tape's AWR × the neutron mass): what [`super::Material::resolve`]
    /// needs. A nuclide with two equally preferred tapes is left out, so a
    /// material needing it fails to resolve rather than using either.
    pub fn atomic_masses(&self) -> AtomicMasses {
        if let Some(a) = &self.ace {
            return a.atomic_masses();
        }
        let mut seen: Vec<Isotope> = self.tapes.iter().map(|t| t.isotope).collect();
        seen.sort();
        seen.dedup();
        let pairs: Vec<(Isotope, f64)> = seen
            .into_iter()
            .filter_map(|i| self.entry(i).ok().map(|t| (i, t.awr)))
            .collect();
        AtomicMasses::from_awr(pairs, &self.label)
    }

    /// **Process one nuclide** at `temperature_k`, with the thermal law `law`
    /// attached when given. Correct physics on (URR, DBRC, the law); nothing
    /// here can switch it off.
    ///
    /// # Errors
    /// The nuclide is not in the library, or processing failed.
    pub fn load_nuclide(
        &self,
        isotope: Isotope,
        temperature_k: f64,
        law: Option<SabMaterial>,
    ) -> Result<Nuclide, DataError> {
        if let Some(a) = &self.ace {
            return a.load_nuclide(isotope, temperature_k, law);
        }
        let t = self.entry(isotope)?;
        let what = format!("{isotope} from {}", t.file);
        let wrap = |source| DataError::Njoy {
            what: what.clone(),
            source,
        };
        let tape = match &t.location {
            TapeLocation::File(p) => Tape::read_file(p).map_err(wrap)?,
            TapeLocation::Bytes(b) => {
                Tape::read(std::io::Cursor::new(b.as_slice())).map_err(wrap)?
            }
            TapeLocation::Library(index, i) => {
                let entry = index.tapes().get(*i).ok_or_else(|| {
                    wrap(NjoyError::InvalidInput("tape index out of range".into()))
                })?;
                index.read_tape(entry).map_err(wrap)?
            }
        };
        let mat = tape
            .materials()
            .first()
            .copied()
            .ok_or_else(|| wrap(NjoyError::InvalidInput("tape holds no material".into())))?;
        let nuc = Nuclide::from_tape_with_speed(
            &tape,
            mat,
            &isotope.name(),
            temperature_k,
            SpeedTier::default(),
        )
        .map_err(wrap)?;
        match law {
            None => Ok(nuc),
            Some(m) => {
                let sab = ThermalScattering::from_embedded_leapr_deck(
                    m,
                    temperature_k,
                    &format!("{m:?}"),
                )
                .map_err(|source| DataError::Njoy {
                    what: format!("thermal law {m:?} at {temperature_k} K"),
                    source,
                })?;
                Ok(nuc.with_thermal_scattering(sab))
            }
        }
    }
}

