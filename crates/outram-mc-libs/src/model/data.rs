//! **Where the nuclear data comes from**: one small handle,
//! [`NuclearData`], over today's loading path.
//!
//! # What this is, and what it deliberately does not settle
//!
//! The njoy → outram-mc contract is **open on epic #925**: (a) one
//! njoy-owned processed object, (b) ACE as the interchange format, or (c)
//! both with one master copy; and the library-from-a-zip loader is #935.
//! This handle does not choose. It wraps the path the crate's recorded
//! benchmarks use today, so it can be swapped later without touching a
//! model:
//!
//! - each needed nuclide's ENDF tape is found **by the identity in its own
//!   header** (Z, A and `LISO` from the MF1/MT451 HEAD records, sub-library
//!   `NSUB = 10`), never by file name;
//! - it is processed by [`Nuclide::from_tape_with_speed`] at the model's
//!   temperature with the default (exact) [`SpeedTier::Fast`]: RECONR +
//!   BROADR at NJOY's 0.001, with URR probability tables and DBRC **on**, as
//!   every ordinary constructor gives them;
//! - a thermal law is regenerated by LEAPR from the ENDF/B-VIII.0 deck
//!   compiled into njoy ([`ThermalScattering::from_embedded_leapr_deck`];
//!   LEAPR always, the `tsl-*` tapes are oracles, maintainer 2026-10-14).
//!
//! # Native and browser
//!
//! [`NuclearData::endf_folder`] and [`NuclearData::workspace_reference`]
//! read files and are **native only** (`std::fs` compiles on
//! `wasm32-unknown-unknown` and then fails at run time).
//! [`NuclearData::from_endf_bytes`] takes tapes as bytes and touches no
//! file: the in-memory path a browser upload would use.

use std::path::{Path, PathBuf};
use std::sync::Arc;

use njoy_outram_park_fork::endf::parse::parse_endf_float;
use njoy_outram_park_fork::endf::tape::Tape;
use njoy_outram_park_fork::leapr::decks::SabMaterial;
use njoy_outram_park_fork::NjoyError;

use super::isotope::Isotope;
use super::masses::AtomicMasses;
use crate::material::nuclide::Nuclide;
use crate::material::speed::SpeedTier;
use crate::material::thermal::ThermalScattering;

/// Why nuclear data could not be found or processed.
#[derive(Debug, thiserror::Error)]
pub enum DataError {
    /// No tape in the library is this nuclide.
    #[error("the library '{library}' has no incident-neutron tape for {isotope}")]
    NotInLibrary {
        /// The library.
        library: String,
        /// The nuclide.
        isotope: Isotope,
    },
    /// Several tapes are this nuclide and none is preferred.
    #[error(
        "the library '{library}' has several tapes for {isotope}: {files:?}; remove all but one"
    )]
    Ambiguous {
        /// The library.
        library: String,
        /// The nuclide.
        isotope: Isotope,
        /// The candidates.
        files: Vec<String>,
    },
    /// A folder with no readable ENDF tape.
    #[error("no incident-neutron ENDF tape found in {0}")]
    NoTapes(String),
    /// Reading or processing a tape failed.
    #[error("processing {what}: {source}")]
    Njoy {
        /// Which nuclide or law.
        what: String,
        /// The njoy error.
        #[source]
        source: NjoyError,
    },
}

/// Where one tape is.
#[derive(Debug, Clone)]
enum TapeLocation {
    File(PathBuf),
    Bytes(Arc<Vec<u8>>),
}

/// One indexed incident-neutron tape.
#[derive(Debug, Clone)]
struct TapeEntry {
    isotope: Isotope,
    awr: f64,
    nlib: Option<i64>,
    nver: Option<i64>,
    file: String,
    location: TapeLocation,
}

/// Which tapes of a folder count, when several are the same nuclide.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Preference {
    /// Every tape counts; two for one nuclide is an error.
    None,
    /// ENDF/B-VIII (`NLIB = 0`, `NVER = 8`) only; among several, the one
    /// named `*-ENDF8.0.endf`.
    EndfBViii,
}

/// **A nuclear-data library**: the incident-neutron ENDF tapes a model's
/// nuclides are processed from. See the module docs for what it does and
/// what it leaves open.
#[derive(Debug, Clone)]
pub struct NuclearData {
    label: String,
    tapes: Vec<TapeEntry>,
    preference: Preference,
}

/// Header fields read from the first lines of an ENDF tape.
struct Header {
    isotope: Isotope,
    awr: f64,
    nlib: Option<i64>,
    nver: Option<i64>,
}

/// Read `(Z, A, LISO, AWR, NLIB, NSUB, NVER)` from the TPID line and the
/// first three MF1/MT451 records (ENDF-102 section 1.1). `None` when this is
/// not an incident-neutron tape (`NSUB != 10`) or is unreadable.
fn read_header(text: &str) -> Option<Header> {
    let lines: Vec<&str> = text.lines().take(4).collect();
    fn field(l: &str, i: usize) -> &str {
        l.get(11 * i..(11 * i + 11).min(l.len())).unwrap_or("")
    }
    let int = |s: &str| s.trim().parse::<i64>().ok();
    let head = lines.get(1)?;
    let za = parse_endf_float(field(head, 0)).ok()?;
    let awr = parse_endf_float(field(head, 1)).ok()?;
    let nlib = int(field(head, 4));
    let liso = lines.get(2).and_then(|l| int(field(l, 3))).unwrap_or(0);
    let l4 = lines.get(3)?;
    if int(field(l4, 4)) != Some(10) {
        return None;
    }
    let nver = int(field(l4, 5));
    let za = za.round() as i64;
    let (z, a) = (
        u8::try_from(za / 1000).ok()?,
        u16::try_from(za % 1000).ok()?,
    );
    let isotope = Isotope::metastable(z, a, u8::try_from(liso).ok()?).ok()?;
    (awr > 0.0).then_some(Header {
        isotope,
        awr,
        nlib,
        nver,
    })
}

impl NuclearData {
    fn index(
        label: String,
        preference: Preference,
        entries: Vec<(String, TapeLocation, &str)>,
    ) -> Self {
        let tapes = entries
            .into_iter()
            .filter_map(|(file, location, text)| {
                let h = read_header(text)?;
                Some(TapeEntry {
                    isotope: h.isotope,
                    awr: h.awr,
                    nlib: h.nlib,
                    nver: h.nver,
                    file,
                    location,
                })
            })
            .collect();
        Self {
            label,
            tapes,
            preference,
        }
    }

    /// **Every incident-neutron ENDF tape in `dir`** (`*.endf`, `*.dat`, and
    /// the `neutrons/` sub-folder of an extracted library). Two tapes of one
    /// nuclide make that nuclide an error when asked for. Native only.
    ///
    /// # Errors
    /// [`DataError::NoTapes`] when the folder holds none.
    pub fn endf_folder(dir: &Path) -> Result<Self, DataError> {
        Self::scan(
            dir,
            Preference::None,
            format!("ENDF folder {}", dir.display()),
        )
    }

    /// **The workspace's reference tapes** (`reference-data/endf/`, or
    /// `$OUTRAM_PARK_ENDF_DIR`), restricted to **ENDF/B-VIII** (`NLIB = 0`,
    /// `NVER = 8` in each header); where two such tapes are one nuclide, the
    /// one named `*-ENDF8.0.endf`. These are the tapes the crate's recorded
    /// ICSBEP benchmarks use (`vv::godiva`, `vv::hst009`). Native only.
    ///
    /// # Errors
    /// [`DataError::NoTapes`] when the folder is missing or empty (a clone
    /// without the reference data).
    pub fn workspace_reference() -> Result<Self, DataError> {
        let dir = njoy_outram_park_fork::reference_data::reference_endf_dir();
        let dir = dir.canonicalize().unwrap_or(dir);
        Self::scan(
            &dir,
            Preference::EndfBViii,
            format!("ENDF/B-VIII reference tapes, {}", dir.display()),
        )
    }

    fn scan(dir: &Path, preference: Preference, label: String) -> Result<Self, DataError> {
        use std::io::{BufRead, BufReader};
        let mut entries = Vec::new();
        for sub in [dir.to_path_buf(), dir.join("neutrons")] {
            let Ok(read) = std::fs::read_dir(&sub) else {
                continue;
            };
            let mut files: Vec<PathBuf> = read
                .flatten()
                .map(|e| e.path())
                .filter(|p| {
                    p.is_file()
                        && p.extension()
                            .and_then(|x| x.to_str())
                            .is_some_and(|x| x == "endf" || x == "dat")
                })
                .collect();
            files.sort();
            for p in files {
                let Ok(f) = std::fs::File::open(&p) else {
                    continue;
                };
                let head: Vec<String> = BufReader::new(f)
                    .lines()
                    .take(4)
                    .map_while(Result::ok)
                    .collect();
                let name = p
                    .file_name()
                    .and_then(|n| n.to_str())
                    .unwrap_or_default()
                    .to_string();
                entries.push((name, p, head.join("\n")));
            }
        }
        let data = Self::index(
            label.clone(),
            preference,
            entries
                .iter()
                .map(|(n, p, t)| (n.clone(), TapeLocation::File(p.clone()), t.as_str()))
                .collect(),
        );
        if data.tapes.is_empty() {
            return Err(DataError::NoTapes(label));
        }
        Ok(data)
    }

    /// **Tapes given as bytes** (`(file name, contents)`), for a browser
    /// upload or any caller that already holds them. Touches no file. Tapes
    /// that are not incident-neutron ENDF are ignored.
    ///
    /// # Errors
    /// [`DataError::NoTapes`] when none is an incident-neutron tape.
    pub fn from_endf_bytes(
        label: &str,
        tapes: impl IntoIterator<Item = (String, Vec<u8>)>,
    ) -> Result<Self, DataError> {
        let owned: Vec<(String, Arc<Vec<u8>>)> =
            tapes.into_iter().map(|(n, b)| (n, Arc::new(b))).collect();
        let texts: Vec<String> = owned
            .iter()
            .map(|(_, b)| String::from_utf8_lossy(&b[..b.len().min(400)]).into_owned())
            .collect();
        let data = Self::index(
            label.to_string(),
            Preference::None,
            owned
                .iter()
                .zip(&texts)
                .map(|((n, b), t)| (n.clone(), TapeLocation::Bytes(b.clone()), t.as_str()))
                .collect(),
        );
        if data.tapes.is_empty() {
            return Err(DataError::NoTapes(label.to_string()));
        }
        Ok(data)
    }

    /// What this library is, for a run's provenance.
    pub fn label(&self) -> &str {
        &self.label
    }

    fn entry(&self, isotope: Isotope) -> Result<&TapeEntry, DataError> {
        let mut hits: Vec<&TapeEntry> =
            self.tapes.iter().filter(|t| t.isotope == isotope).collect();
        if self.preference == Preference::EndfBViii {
            hits.retain(|t| t.nlib == Some(0) && t.nver == Some(8));
            if hits.len() > 1 {
                let named: Vec<&TapeEntry> = hits
                    .iter()
                    .copied()
                    .filter(|t| t.file.ends_with("-ENDF8.0.endf"))
                    .collect();
                if named.len() == 1 {
                    hits = named;
                }
            }
        }
        match hits.as_slice() {
            [] => Err(DataError::NotInLibrary {
                library: self.label.clone(),
                isotope,
            }),
            [one] => Ok(one),
            many => Err(DataError::Ambiguous {
                library: self.label.clone(),
                isotope,
                files: many.iter().map(|t| t.file.clone()).collect(),
            }),
        }
    }

    /// The file name of the tape `isotope` is processed from.
    ///
    /// # Errors
    /// [`DataError::NotInLibrary`] or [`DataError::Ambiguous`].
    pub fn tape_file(&self, isotope: Isotope) -> Result<&str, DataError> {
        self.entry(isotope).map(|t| t.file.as_str())
    }

    /// **The nuclides this library can supply, with their masses** (each
    /// tape's AWR × the neutron mass): what [`super::Material::resolve`]
    /// needs. A nuclide with two equally preferred tapes is left out, so a
    /// material needing it fails to resolve rather than using either.
    pub fn atomic_masses(&self) -> AtomicMasses {
        let mut seen: Vec<Isotope> = self.tapes.iter().map(|t| t.isotope).collect();
        seen.sort();
        seen.dedup();
        let pairs: Vec<(Isotope, f64)> = seen
            .into_iter()
            .filter_map(|i| self.entry(i).ok().map(|t| (i, t.awr)))
            .collect();
        AtomicMasses::from_awr(pairs, &self.label)
    }

    /// **Process one nuclide** at `temperature_k`, with the thermal law `law`
    /// attached when given. Correct physics on (URR, DBRC, the law); nothing
    /// here can switch it off.
    ///
    /// # Errors
    /// The nuclide is not in the library, or processing failed.
    pub fn load_nuclide(
        &self,
        isotope: Isotope,
        temperature_k: f64,
        law: Option<SabMaterial>,
    ) -> Result<Nuclide, DataError> {
        let t = self.entry(isotope)?;
        let what = format!("{isotope} from {}", t.file);
        let wrap = |source| DataError::Njoy {
            what: what.clone(),
            source,
        };
        let tape = match &t.location {
            TapeLocation::File(p) => Tape::read_file(p).map_err(wrap)?,
            TapeLocation::Bytes(b) => {
                Tape::read(std::io::Cursor::new(b.as_slice())).map_err(wrap)?
            }
        };
        let mat = tape
            .materials()
            .first()
            .copied()
            .ok_or_else(|| wrap(NjoyError::InvalidInput("tape holds no material".into())))?;
        let nuc = Nuclide::from_tape_with_speed(
            &tape,
            mat,
            &isotope.name(),
            temperature_k,
            SpeedTier::default(),
        )
        .map_err(wrap)?;
        match law {
            None => Ok(nuc),
            Some(m) => {
                let sab = ThermalScattering::from_embedded_leapr_deck(
                    m,
                    temperature_k,
                    &format!("{m:?}"),
                )
                .map_err(|source| DataError::Njoy {
                    what: format!("thermal law {m:?} at {temperature_k} K"),
                    source,
                })?;
                Ok(nuc.with_thermal_scattering(sab))
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::super::isotope::isotopes::*;
    use super::*;

    fn fake_tape(za: &str, awr: &str, nlib: i64, liso: i64, nsub: i64, nver: i64) -> Vec<u8> {
        format!(
            " TPID line\n{za:>11}{awr:>11}{:>11}{:>11}{nlib:>11}{:>11}\n{:>11}{:>11}{:>11}{liso:>11}{:>11}{:>11}\n{:>11}{:>11}{:>11}{:>11}{nsub:>11}{nver:>11}\n",
            0, 0, 0, "0.0", "0.0", 0, 0, 6, "1.0", "2.0+7", 0, 0
        )
        .into_bytes()
    }

    /// Tapes are identified by their header, not their name; duplicates are
    /// an error unless the library has a stated preference; non-neutron
    /// sub-libraries are ignored; masses are AWR x m_n.
    #[test]
    fn in_memory_library_indexes_by_header_identity() {
        let d = NuclearData::from_endf_bytes(
            "test",
            [
                (
                    "anything.endf".to_string(),
                    fake_tape("9.223500+4", "2.330248+2", 0, 0, 10, 8),
                ),
                (
                    "u238-a.endf".to_string(),
                    fake_tape("9.223800+4", "2.360058+2", 0, 0, 10, 8),
                ),
                (
                    "u238-b.endf".to_string(),
                    fake_tape("9.223800+4", "2.360058+2", 0, 0, 10, 7),
                ),
                (
                    "tsl.endf".to_string(),
                    fake_tape("1.000000+0", "1.0", 0, 0, 12, 8),
                ),
                (
                    "am.endf".to_string(),
                    fake_tape("9.524200+4", "2.39e+2", 0, 1, 10, 8),
                ),
            ],
        )
        .unwrap();
        assert_eq!(d.label(), "test");
        assert_eq!(d.tape_file(U235).unwrap(), "anything.endf");
        assert!(matches!(
            d.tape_file(U238),
            Err(DataError::Ambiguous { .. })
        ));
        assert!(matches!(
            d.tape_file(H1),
            Err(DataError::NotInLibrary { .. })
        ));
        assert_eq!(
            d.tape_file(Isotope::metastable(95, 242, 1).unwrap())
                .unwrap(),
            "am.endf"
        );
        let m = d.atomic_masses();
        assert!(
            (m.mass_u(U235).unwrap() - 233.0248 * super::super::masses::NEUTRON_MASS_U).abs()
                < 1e-9
        );
        assert!(
            !m.contains(U238),
            "an ambiguous nuclide gets no mass, so nothing uses either tape"
        );
        assert!(NuclearData::from_endf_bytes("empty", Vec::new()).is_err());
        assert!(matches!(
            d.load_nuclide(U235, 293.6, None),
            Err(DataError::Njoy { .. })
        ));
        assert!(NuclearData::endf_folder(Path::new("/nonexistent-outram-dir")).is_err());
    }

    /// The workspace reference library resolves the Godiva nuclides to the
    /// same tapes `vv::godiva` names, by header identity (skips without the
    /// reference data).
    #[test]
    fn workspace_reference_picks_the_recorded_godiva_tapes() {
        let Ok(d) = NuclearData::workspace_reference() else {
            eprintln!("SKIP: no reference-data/endf in this checkout");
            return;
        };
        for (name, file, _) in crate::vv::godiva::NUCLIDES {
            let i = Isotope::from_name(name).unwrap();
            assert_eq!(d.tape_file(i).unwrap(), file, "{name}");
        }
        assert!(d.atomic_masses().contains(H1));
        assert!(d.label().contains("ENDF/B-VIII"));
    }
}
