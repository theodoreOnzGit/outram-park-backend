//! # Non-coherent fault trees, verified against compiled SCRAM
//!
//! A tree is **non-coherent** when a component *working* can contribute to the
//! top event — a `not`, `nand`, `nor` or `xor` somewhere in its logic. The
//! cut sets then involve complemented literals, and getting from those to the
//! minimal cut sets needs a step the coherent case does not: deleting the
//! complements and re-minimising.
//!
//! [`raffles::scram::mocus`] does that, and this file checks it against
//! upstream. The other SCRAM test files cover coherent trees only, and are
//! kept separate because **non-coherent models need different expectations**
//! — see [`our_exact_value_exceeds_scrams_because_cut_sets_are_conservative`],
//! which is the reason the split exists rather than a footnote to it.
//!
//! ## Where the models come from
//!
//! | model | source | why |
//! |---|---|---|
//! | `models-for-this-port/noncoherent_small` | **written here** | upstream has no small non-coherent model |
//! | `Aralia/das9601` | upstream's `input/` suite | 288 gates, 14 `not`, 12 `xor`, 4,259 products |
//!
//! Writing one of the inputs needs saying plainly. Of upstream's seven models
//! containing a negating connective, four produce no products, two are
//! event-tree or alignment models this port does not handle, and the only
//! usable one is `das9601` — at 288 gates and 4,259 products, not something a
//! failure can be diagnosed from. **SCRAM is still the oracle either way**:
//! every expected value below came from running the compiled binary. Only the
//! question is ours, and the model is committed at
//! `reference-data/scram/models-for-this-port/noncoherent_small.xml` with its
//! reasoning in an XML comment.
//!
//! ## What `das9601` does and does not contribute
//!
//! Its 4,259 products exercise the **quantification** layer at a scale nothing
//! else here reaches. Its cut sets are **not** generated by this port:
//! `scram::mocus` exceeds its expansion ceiling on it, which is measured and
//! recorded rather than hidden — see
//! [`das9601_is_beyond_this_algorithm_and_says_so`].

use raffles::scram::fault_tree::{Connective, FaultTreeBuilder, FaultTreeModel};
use raffles::scram::mocus::{minimal_cut_sets, DEFAULT_LIMIT_ORDER};
use raffles::scram::probability::{top_event_probability, Approximation, CutSet};
use std::collections::{BTreeSet, HashMap};

const FIXTURE: &str = "oracle-noncoherent.txt";

// ---------------------------------------------------------------------------
// Fixture loading — the same format as the coherent oracle, different file.
// ---------------------------------------------------------------------------

struct Oracle {
    events: HashMap<String, f64>,
    products: Vec<BTreeSet<String>>,
    totals: HashMap<String, f64>,
}

struct ModelSpec {
    gates: Vec<(String, String, Option<usize>, Vec<String>)>,
    top: Option<String>,
    unparsed: Vec<String>,
}

fn fixture(name: &str) -> String {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../reference-data/scram")
        .join(name);
    std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("reading {}: {e}", path.display()))
}

fn load_oracles() -> HashMap<String, Oracle> {
    let mut out = HashMap::new();
    let mut name = String::new();
    let mut cur: Option<Oracle> = None;
    for line in fixture(FIXTURE).lines() {
        let f: Vec<&str> = line.split_whitespace().collect();
        if f.is_empty() {
            continue;
        }
        match f[0] {
            "MODEL" => {
                name = f[1].to_string();
                cur = Some(Oracle {
                    events: HashMap::new(),
                    products: Vec::new(),
                    totals: HashMap::new(),
                });
            }
            "EVENT" => {
                if let Some(o) = cur.as_mut() {
                    o.events.insert(f[1].to_string(), f[2].parse().unwrap());
                }
            }
            "PRODUCT" => {
                if let Some(o) = cur.as_mut() {
                    o.products
                        .push(f[2..].iter().map(|s| s.to_string()).collect());
                }
            }
            "TOTAL" => {
                if let Some(o) = cur.as_mut() {
                    o.totals.insert(f[1].to_string(), f[2].parse().unwrap());
                }
            }
            "END" => {
                if let Some(o) = cur.take() {
                    out.insert(std::mem::take(&mut name), o);
                }
            }
            _ => {}
        }
    }
    out
}

fn load_model(wanted: &str) -> ModelSpec {
    let mut cur: Option<ModelSpec> = None;
    let mut found = None;
    for line in fixture("models.txt").lines() {
        let f: Vec<&str> = line.split_whitespace().collect();
        if f.is_empty() {
            continue;
        }
        match f[0] {
            "MODEL" => {
                cur = (f[1] == wanted).then(|| ModelSpec {
                    gates: Vec::new(),
                    top: None,
                    unparsed: Vec::new(),
                })
            }
            "GATE" => {
                if let Some(m) = cur.as_mut() {
                    let min = (f[3] != "-").then(|| f[3].parse().expect("a number"));
                    m.gates.push((
                        f[1].to_string(),
                        f[2].to_string(),
                        min,
                        f[4..].iter().map(|s| s.to_string()).collect(),
                    ));
                }
            }
            "TOP" => {
                if let Some(m) = cur.as_mut() {
                    m.top = Some(f[1].to_string())
                }
            }
            "CANNOT-PARSE" => {
                if let Some(m) = cur.as_mut() {
                    m.unparsed.push(f[1..].join(" "))
                }
            }
            "END" => {
                if let Some(m) = cur.take() {
                    found = Some(m)
                }
            }
            _ => {}
        }
    }
    found.unwrap_or_else(|| panic!("`{wanted}` is not in models.txt"))
}

/// Builds the tree from the structure fixture, with probabilities from the
/// oracle.
///
/// An event the model names but SCRAM never priced gets `0.5` and is returned
/// in the second slot; every caller asserts no generated cut set touches one.
/// `noncoherent_small`'s `b` is exactly that case — it appears only under a
/// `not`, so it survives in no minimal cut set and SCRAM's report never
/// mentions it.
fn build(name: &str, oracle: &Oracle) -> (FaultTreeModel, Vec<usize>) {
    let spec = load_model(name);
    assert!(
        spec.unparsed.is_empty(),
        "{name}: structure not readable: {:?}",
        spec.unparsed
    );

    let gate_names: BTreeSet<&str> = spec.gates.iter().map(|(n, ..)| n.as_str()).collect();
    let mut event_names: Vec<&str> = oracle.events.keys().map(|s| s.as_str()).collect();
    for (_, _, _, args) in &spec.gates {
        for a in args {
            let n = &a[2..];
            if !gate_names.contains(n)
                && !oracle.events.contains_key(n)
                && !event_names.contains(&n)
            {
                event_names.push(n);
            }
        }
    }
    event_names.sort_unstable();

    let mut b = FaultTreeBuilder::new();
    let mut unpriced = Vec::new();
    for (i, n) in event_names.iter().enumerate() {
        let p = match oracle.events.get(*n) {
            Some(&p) => p,
            None => {
                unpriced.push(i);
                0.5
            }
        };
        b.basic_event(n, p).expect("valid probability");
    }
    for (gate, connective, min, args) in &spec.gates {
        let c = match connective.as_str() {
            "and" => Connective::And,
            "or" => Connective::Or,
            "null" => Connective::Null,
            "not" => Connective::Not,
            "nand" => Connective::Nand,
            "nor" => Connective::Nor,
            "xor" => Connective::Xor,
            "atleast" => Connective::Atleast {
                min: min.expect("atleast carries its min"),
            },
            other => panic!("{name}: unhandled connective `{other}`"),
        };
        let arg_names: Vec<&str> = args.iter().map(|a| &a[2..]).collect();
        b.gate(gate, c, &arg_names)
            .unwrap_or_else(|e| panic!("{name} gate `{gate}`: {e}"));
    }
    let model = b
        .build(spec.top.as_ref().expect("a top gate"))
        .unwrap_or_else(|e| panic!("{name}: {e}"));
    assert!(
        !model.tree().is_coherent(),
        "{name} is in the non-coherent fixture but every gate is coherent"
    );
    (model, unpriced)
}

/// Turns an oracle's named products into indexed cut sets, with probabilities.
fn indexed(o: &Oracle) -> (Vec<f64>, Vec<CutSet>) {
    let mut names: Vec<&String> = o.events.keys().collect();
    names.sort();
    let index: HashMap<&str, usize> = names
        .iter()
        .enumerate()
        .map(|(i, n)| (n.as_str(), i))
        .collect();
    let probs: Vec<f64> = names.iter().map(|n| o.events[*n]).collect();
    let cut_sets = o
        .products
        .iter()
        .map(|p| {
            let members: Vec<usize> = p.iter().map(|n| index[n.as_str()]).collect();
            CutSet::new(&members).unwrap()
        })
        .collect();
    (probs, cut_sets)
}

fn agrees(ours: f64, theirs: f64, tol: f64) -> bool {
    (ours - theirs).abs() / theirs.abs().max(1.0) < tol
}

