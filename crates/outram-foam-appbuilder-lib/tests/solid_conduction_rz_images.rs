//! Drawings of the R-Z solid conduction test geometry (gh:#1149), per the
//! crate's "reactor geometry is DRAWN" HARD RULE.
//!
//! **What is drawn.** A generic four-region R-Z test body — **illustrative
//! numbers, not HTR-10 data** (that geometry comes in a later part of
//! gh:#1149): a heated core (`r < 0.8 m`, `1 < z < 3 m`, `lambda(T)` linear),
//! top and bottom axial reflectors above and below it, a side reflector
//! `0.8 < r < 1.5 m`, and a barrel `1.5 < r < 1.7 m` separated from the side
//! reflector by a radiating 2 cm gas gap carried on the faces at `r = 1.5 m`.
//! The outer surface radiates to 320 K, the bottom is cooled convectively,
//! the top and the axis are adiabatic.
//!
//! Every pixel is coloured from the **assembled mesh**: `RzMesh::cell_at`
//! at the pixel centre, then that cell's region (or temperature). Mesh lines
//! are drawn where neighbouring pixels fall in different cells; gap faces in
//! red where the two cells are a gap pair according to the solver's own
//! face list (`SolidConductionField::gap_faces`). Nothing is drawn from the
//! named constants.
//!
//! **Output** (committed, regenerated by this test, deterministic):
//! `verification_and_validation/solid_conduction_rz/rz_region_map_and_mesh.png`
//! and `.../rz_steady_temperature.png`.
//!
//! **What to check in them.** Region boundaries sit on mesh lines (cells are
//! assigned by centre, so a boundary off a mesh line would show as a
//! staircase); the gap (red) runs the full height at `r = 1.5 m` and nowhere
//! else; the core is the hottest region and the temperature falls across the
//! gap in a visible step. The images cannot show the wedge angle or the
//! zero-area axis face (both are checked numerically in the unit tests).

use std::collections::HashSet;

use outram_blender::csg::plot::annotate::draw_text;
use outram_blender::csg::plot::colour::{Rgb, BLACK, WHITE};
use outram_blender::csg::plot::image::ImageData;
use outram_blender::csg::plot::{annotate_image, LegendEntry};
use outram_foam_appbuilder_lib::genfoam::thermal_hydraulics::solid_conduction::{
    AxisEdges, ConductivityModel, GapConductance, HeatCapacityModel, RegionGap, RegionMap,
    RzBoundaries, RzGeometry, RzMesh, RzRect, SolidBoundary, SolidConductionField, SolidRegion,
};
use uom::si::angle::radian;
use uom::si::f64::{
    Angle, HeatTransfer, Length, Ratio, TemperatureCoefficient, ThermalConductivity,
    ThermodynamicTemperature, VolumetricHeatCapacity, VolumetricPowerDensity,
};
use uom::si::heat_transfer::watt_per_square_meter_kelvin;
use uom::si::length::meter;
use uom::si::ratio::ratio;
use uom::si::temperature_coefficient::per_kelvin;
use uom::si::thermal_conductivity::watt_per_meter_kelvin;
use uom::si::thermodynamic_temperature::kelvin;
use uom::si::volumetric_heat_capacity::joule_per_cubic_meter_kelvin;
use uom::si::volumetric_power_density::watt_per_cubic_meter;

fn m(x: f64) -> Length {
    Length::new::<meter>(x)
}
fn kel(x: f64) -> ThermodynamicTemperature {
    ThermodynamicTemperature::new::<kelvin>(x)
}
fn lam(x: f64) -> ConductivityModel {
    ConductivityModel::constant(ThermalConductivity::new::<watt_per_meter_kelvin>(x))
}

const NAMES: [&str; 4] = ["CORE", "AXIAL REFLECTOR", "SIDE REFLECTOR", "BARREL"];
const COLOURS: [Rgb; 4] = [
    Rgb::new(230, 120, 60),
    Rgb::new(120, 170, 220),
    Rgb::new(90, 140, 90),
    Rgb::new(160, 160, 170),
];
const GAP_RED: Rgb = Rgb::new(220, 0, 0);
const MESH_GREY: Rgb = Rgb::new(60, 60, 60);

fn test_body() -> SolidConductionField {
    let map = RegionMap {
        default_region: 1,
        rects: vec![
            RzRect {
                r: [m(0.8), m(1.5)],
                z: [m(0.0), m(4.0)],
                region: 2,
            },
            RzRect {
                r: [m(1.5), m(1.7)],
                z: [m(0.0), m(4.0)],
                region: 3,
            },
            RzRect {
                r: [m(0.0), m(0.8)],
                z: [m(1.0), m(3.0)],
                region: 0,
            },
        ],
    };
    let mesh = RzMesh::from_region_map(
        RzGeometry::Axisymmetric {
            wedge_angle: Angle::new::<radian>(0.1),
        },
        AxisEdges::segments(m(0.0), &[(m(0.8), 16), (m(1.5), 14), (m(1.7), 4)]).unwrap(),
        AxisEdges::segments(m(0.0), &[(m(1.0), 10), (m(3.0), 20), (m(4.0), 10)]).unwrap(),
        4,
        &map,
    )
    .unwrap();
    let cap = HeatCapacityModel::constant(VolumetricHeatCapacity::new::<joule_per_cubic_meter_kelvin>(2.0e6));
    let reg = |name: &str, k: ConductivityModel, q: f64| SolidRegion {
        name: name.into(),
        conductivity: k,
        heat_capacity: cap.clone(),
        heat_source: VolumetricPowerDensity::new::<watt_per_cubic_meter>(q),
    };
    let core_k = ConductivityModel::linear(
        ThermalConductivity::new::<watt_per_meter_kelvin>(15.0),
        TemperatureCoefficient::new::<per_kelvin>(5.0e-4),
        kel(300.0),
    );
    let gap = GapConductance::new(Ratio::new::<ratio>(0.8), Ratio::new::<ratio>(0.7), lam(0.25), m(0.02)).unwrap();
    SolidConductionField::new(
        mesh,
        vec![
            reg(NAMES[0], core_k, 3.0e4),
            reg(NAMES[1], lam(30.0), 0.0),
            reg(NAMES[2], lam(30.0), 0.0),
            reg(NAMES[3], lam(20.0), 0.0),
        ],
        RzBoundaries {
            inner: SolidBoundary::Adiabatic,
            outer: SolidBoundary::Radiative {
                emissivity: Ratio::new::<ratio>(0.8),
                ambient: kel(320.0),
            },
            bottom: SolidBoundary::Convective {
                coefficient: HeatTransfer::new::<watt_per_square_meter_kelvin>(10.0),
                ambient: kel(320.0),
            },
            top: SolidBoundary::Adiabatic,
        },
        vec![RegionGap {
            region_a: 2,
            region_b: 3,
            gap,
        }],
        kel(400.0),
    )
    .unwrap()
}

/// Pixels per metre and the plot window `[0, 1.8] x [0, 4.2] m`.
const PX_PER_M: f64 = 160.0;
const R_MAX: f64 = 1.8;
const Z_MAX: f64 = 4.2;

/// Cell under each pixel, from the assembled mesh's lookup.
fn cell_raster(f: &SolidConductionField) -> (usize, usize, Vec<Option<usize>>) {
    let w = (R_MAX * PX_PER_M) as usize;
    let h = (Z_MAX * PX_PER_M) as usize;
    let mut cells = Vec::with_capacity(w * h);
    for y in 0..h {
        for x in 0..w {
            let r = (x as f64 + 0.5) / PX_PER_M;
            let z = Z_MAX - (y as f64 + 0.5) / PX_PER_M;
            cells.push(f.mesh().cell_at(m(r), m(z)));
        }
    }
    (w, h, cells)
}

/// Overlay mesh lines and gap faces where neighbouring pixels change cell.
fn overlay_mesh(img: &mut ImageData, f: &SolidConductionField, cells: &[Option<usize>], gap_pairs: &HashSet<(usize, usize)>) {
    let (w, h) = (img.width, img.height);
    for y in 0..h {
        for x in 0..w {
            let here = cells[y * w + x];
            for (dx, dy) in [(1usize, 0usize), (0, 1)] {
                if x + dx >= w || y + dy >= h {
                    continue;
                }
                let there = cells[(y + dy) * w + x + dx];
                if here != there {
                    let colour = match (here, there) {
                        (Some(a), Some(b)) if gap_pairs.contains(&(a.min(b), a.max(b))) => GAP_RED,
                        _ => MESH_GREY,
                    };
                    img.set(x, y, colour);
                    if colour == GAP_RED && x + 1 < w {
                        img.set(x + 1, y, colour);
                    }
                }
            }
        }
    }
    let _ = f;
}

/// Add a left/bottom margin with tick labels every 0.5 m, then the title
/// and legend frame.
fn frame(img: &ImageData, title: &str, legend: &[LegendEntry]) -> ImageData {
    let (left, bottom) = (70usize, 50usize);
    let mut out = ImageData::filled(img.width + left + 10, img.height + bottom + 10, WHITE);
    for y in 0..img.height {
        for x in 0..img.width {
            out.set(left + x, 10 + y, img.get(x, y));
        }
    }
    let mut v = 0.0;
    while v <= Z_MAX + 1e-9 {
        let y = 10 + img.height - (v * PX_PER_M) as usize;
        for x in left - 8..left {
            out.set(x, y.min(out.height - 1), BLACK);
        }
        draw_text(&mut out, 5, y as i64 - 7, &format!("{v:.1}"), BLACK);
        v += 0.5;
    }
    let mut v = 0.0;
    while v <= R_MAX + 1e-9 {
        let x = left + ((v * PX_PER_M) as usize).min(img.width - 1);
        for y in 10 + img.height..10 + img.height + 8 {
            out.set(x, y, BLACK);
        }
        draw_text(&mut out, x as i64 - 15, (img.height + 22) as i64, &format!("{v:.1}"), BLACK);
        v += 0.5;
    }
    draw_text(&mut out, (left + img.width / 2 - 40) as i64, (img.height + 42) as i64, "R [M]", BLACK);
    let mut titled = annotate_image(&out, title, legend);
    draw_text(&mut titled, 10, 30, "Z [M]", BLACK);
    titled
}

fn ramp(t: f64) -> Rgb {
    // Blue -> cyan -> yellow -> red.
    let t = t.clamp(0.0, 1.0);
    let (r, g, b) = if t < 1.0 / 3.0 {
        let s = 3.0 * t;
        (0.0, s, 1.0)
    } else if t < 2.0 / 3.0 {
        let s = 3.0 * t - 1.0;
        (s, 1.0, 1.0 - s)
    } else {
        let s = 3.0 * t - 2.0;
        (1.0, 1.0 - s, 0.0)
    };
    Rgb::new((255.0 * r) as u8, (255.0 * g) as u8, (255.0 * b) as u8)
}

/// Draw the region map and mesh, solve, draw the temperature field; write
/// both PNGs into `verification_and_validation/solid_conduction_rz/`.
#[test]
fn draw_rz_region_map_mesh_and_temperature() {
    let mut f = test_body();
    let fv = f.mesh().mesh().clone();
    let gap_pairs: HashSet<(usize, usize)> = f
        .gap_faces()
        .into_iter()
        .map(|face| (fv.owner[face], fv.neighbour[face]))
        .collect();
    assert_eq!(gap_pairs.len(), 40, "one gap face per axial row");

    let (w, h, cells) = cell_raster(&f);
    let mut img = ImageData::filled(w, h, WHITE);
    for (p, c) in cells.iter().enumerate() {
        if let Some(c) = c {
            img.pixels[p] = COLOURS[f.mesh().cell_region(*c)];
        }
    }
    overlay_mesh(&mut img, &f, &cells, &gap_pairs);
    let mut legend: Vec<LegendEntry> = NAMES
        .iter()
        .zip(COLOURS)
        .map(|(n, c)| LegendEntry::new(c, *n))
        .collect();
    legend.push(LegendEntry::new(GAP_RED, "GAS GAP (FACES)"));
    legend.push(LegendEntry::new(MESH_GREY, "MESH 34X40"));
    let regions = frame(&img, "SOLID CONDUCTION TEST BODY: REGIONS AND MESH (R-Z)", &legend);

    let rep = f.solve_steady().unwrap();
    let bal = f.energy_balance();
    let (t_min, t_max) = (0..f.mesh().n_cells())
        .map(|c| f.temperature(c).get::<kelvin>())
        .fold((f64::INFINITY, f64::NEG_INFINITY), |(a, b), t| (a.min(t), b.max(t)));
    println!(
        "test body: picard {}, T {t_min:.2}..{t_max:.2} K, generated {:.1} W, imbalance {:.2e}",
        rep.iterations,
        bal.generated.get::<uom::si::power::watt>(),
        bal.relative_imbalance()
    );
    assert!(bal.relative_imbalance() < 1e-9);
    let mut timg = ImageData::filled(w, h, WHITE);
    for (p, c) in cells.iter().enumerate() {
        if let Some(c) = c {
            let t = f.temperature(*c).get::<kelvin>();
            timg.pixels[p] = ramp((t - t_min) / (t_max - t_min));
        }
    }
    overlay_mesh(&mut timg, &f, &cells, &gap_pairs);
    let tlegend: Vec<LegendEntry> = (0..=4)
        .map(|i| {
            let s = f64::from(i) / 4.0;
            LegendEntry::new(ramp(s), format!("{:.0} K", t_min + s * (t_max - t_min)))
        })
        .collect();
    let temps = frame(&timg, "STEADY TEMPERATURE (CELL VALUES)", &tlegend);

    let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("verification_and_validation")
        .join("solid_conduction_rz");
    std::fs::create_dir_all(&dir).unwrap();
    regions.write_png(dir.join("rz_region_map_and_mesh.png")).unwrap();
    temps.write_png(dir.join("rz_steady_temperature.png")).unwrap();
}
