const DT: f64 = 0.1;
const N_STEPS: usize = 50;
const NAMES: [&str; 4] = ["left", "interface", "walls", "frontAndBack"];
const EMISSIVITY: [f64; 4] = [0.9, 0.8, 0.5, 0.6];

fn vf_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("verification_and_validation/upstream_view_factor_gh1541")
}

fn solid_case() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("verification_and_validation/upstream_openfoam_gh1363/cht/constant/solid/polyMesh")
}

fn gunzip(name: &str) -> String {
    let bytes = std::fs::read(vf_root().join("reference").join(name)).expect("reference");
    String::from_utf8(decompress_to_vec(&bytes[10..bytes.len() - 8]).expect("inflate")).expect("utf8")
}

type Fields = BTreeMap<String, Vec<f64>>;

struct Reference {
    steps: BTreeMap<usize, Fields>,
    scalars: BTreeMap<usize, BTreeMap<String, f64>>,
}

fn read_reference() -> Reference {
    let text = gunzip("cht_vf_v2506.txt.gz");
    let mut r = Reference { steps: BTreeMap::new(), scalars: BTreeMap::new() };
    let bits = |h: &str| f64::from_bits(u64::from_str_radix(h, 16).unwrap());
    for line in text.lines() {
        let tok: Vec<&str> = line.split_whitespace().collect();
        match tok[0] {
            "S" => {
                let step: usize = tok[1].parse().unwrap();
                r.steps.entry(step).or_default().entry(format!("{} {}", tok[2], tok[3])).or_default().push(bits(tok[5]));
            }
            "C" => {
                r.scalars.entry(tok[1].parse().unwrap()).or_default().insert(tok[2].to_string(), bits(tok[3]));
            }
            _ => {}
        }
    }
    r
}

fn patch_index(mesh: &FvMesh, name: &str) -> usize {
    mesh.patches.iter().position(|p| p.name == name).unwrap_or_else(|| panic!("no patch {name}"))
}

/// Which radiation the fluid carries in `build_port`, and where its `F` comes from.
#[derive(Clone, Copy, PartialEq)]
enum Rad {
    None,
    /// `F` regenerated by the Rust `viewFactorsGen` port.
    ViewFactor,
    /// `F` and `globalFaceFaces` as ESI's `viewFactorsGen` wrote them (isolates the coupling from the generator).
    ViewFactorEsiF,
}

/// The coupling with ESI's own `F` / `globalFaceFaces` files.
fn coupling_with_esi_f(mf: &FvMesh, t: &VolScalarField) -> ViewFactorCoupling {
    let up_f = parse_scalar_list_list(&gunzip("F.gz")).expect("F");
    let up_g = parse_label_list_list(&gunzip("globalFaceFaces.gz")).expect("gff");
    let idx: Vec<usize> = NAMES.iter().map(|n| patch_index(mf, n)).collect();
    let vp: Vec<ViewFactorPatch> = idx
        .iter()
        .zip(NAMES)
        .map(|(&mi, name)| {
            let p = &mf.patches[mi];
            let areas: Vec<f64> = (p.start..p.start + p.size).map(|f| mf.face_areas[f]).collect();
            ViewFactorPatch { name: name.to_string(), agglom: (0..areas.len()).collect(), fine_areas: areas }
        })
        .collect();
    let model = ViewFactorModel::new(vp, &up_g, &up_f, false, false).expect("model");
    ViewFactorCoupling::new(model, t, idx, &EMISSIVITY, &[0.0; 4]).expect("coupling")
}

fn build_port(reference: &Reference, rad: Rad, qr_coupling: bool) -> ChtMultiRegionFoam {
    let k = &reference.scalars[&0];
    let fdir = vf_root().join("fluid/polyMesh");
    let mf = read_poly_mesh(&fdir).expect("fluid polyMesh");
    let ms = read_poly_mesh(&solid_case()).expect("solid polyMesh");
    let control = ControlDict { delta_t: DT, ..ControlDict::default() };
    let mut sol = FvSolution::default();
    sol.pimple.frozen_flow = true;
    let mut f = PimpleFoam::new(mf.clone(), control, FvSchemes::default(), sol);
    let mut e = EnergyEquation::uniform(mf.clone(), IncompressibleThermo::si(k["fluid_rho"], k["fluid_Cp"], k["fluid_kappa"]), 300.0);
    e.solver = SolverSettings { tolerance: 1e-16, max_iter: 10_000 };
    e.set_patch("left", BoundaryCondition::FixedValue(300.0));
    if rad == Rad::ViewFactor {
        let poly = PolyMesh::read(&fdir).expect("PolyMesh");
        let v = ViewFactorCoupling::generate(&poly, &e.t, &NAMES, &EMISSIVITY, &[0.0; 4]).expect("coupling");
        e = e.with_view_factor_radiation(v).expect("attach");
    }
    if rad == Rad::ViewFactorEsiF {
        let v = coupling_with_esi_f(&mf, &e.t);
        e = e.with_view_factor_radiation(v).expect("attach");
    }
    f.energy = Some(e);
    let mut s = SolidRegion::new("solid", ms.clone(), IncompressibleThermo::si(k["solid_rho"], k["solid_Cp"], k["solid_kappa"]), 300.0);
    s.energy.solver = SolverSettings { tolerance: 1e-16, max_iter: 10_000 };
    s.energy.set_patch("right", BoundaryCondition::FixedValue(360.0));
    let (pf, ps) = (patch_index(&mf, "interface"), patch_index(&ms, "interface"));
    let c = CoupledTemperature::new(RegionId::Fluid(0), mf, pf, RegionId::Solid(0), ms, ps);
    let mut cht = ChtMultiRegionFoam::new(vec![f], vec![s], vec![c]).expect("port");
    cht.solid_delta_t = uom::si::f64::Time::new::<uom::si::time::second>(DT);
    cht.energy_outer_correctors = 1;
    if qr_coupling {
        cht
    } else {
        cht.without_radiative_flux_coupling()
    }
}

fn worst_abs(port: &[f64], up: &[f64]) -> (f64, usize) {
    assert_eq!(port.len(), up.len(), "length");
    let mut w = 0.0_f64;
    let mut same = 0;
    for (a, b) in port.iter().zip(up) {
        w = w.max((a - b).abs());
        if a.to_bits() == b.to_bits() {
            same += 1;
        }
    }
    (w, same)
}

#[derive(Debug, Default, Clone, Copy)]
struct Worst {
    t_fluid: f64,
    t_solid: f64,
    qr_rel: f64,
    qr_identical: usize,
    qr_total: usize,
    qr_first_step_identical: bool,
    max_abs_qr: f64,
}

fn run(cht: &mut ChtMultiRegionFoam, reference: &Reference, steps: usize, verbose: bool) -> Worst {
    let mut w = Worst::default();
    for step in 1..=steps {
        cht.step().expect("step");
        let up = &reference.steps[&step];
        let e = cht.fluids[0].energy.as_ref().unwrap();
        let (tf, _) = worst_abs(e.t.internal.as_slice(), &up["f T"]);
        let (ts, _) = worst_abs(cht.solids[0].energy.t.internal.as_slice(), &up["s T"]);
        w.t_fluid = w.t_fluid.max(tf);
        w.t_solid = w.t_solid.max(ts);
        let mut qrr = 0.0_f64;
        if let Some(v) = e.view_factor.as_ref() {
            let mut all_same_step = true;
            for name in NAMES {
                let pi = patch_index(&e.t.mesh, name);
                let key = format!("f qr_{name}");
                let qmax = up[&key].iter().fold(0.0_f64, |m, x| m.max(x.abs())).max(1e-300);
                let (d, same) = worst_abs(v.qr[pi].as_slice(), &up[&key]);
                qrr = qrr.max(d / qmax);
                w.qr_identical += same;
                w.qr_total += up[&key].len();
                w.max_abs_qr = w.max_abs_qr.max(qmax);
                all_same_step &= same == up[&key].len();
            }
            if step == 1 {
                w.qr_first_step_identical = all_same_step;
            }
            w.qr_rel = w.qr_rel.max(qrr);
        }
        if verbose {
            eprintln!("step {step:2}: T fluid {tf:.2e} solid {ts:.2e} qr rel {qrr:.2e}");
        }
    }
    w
}

fn verbose() -> bool {
    std::env::var("RAD_VERBOSE").is_ok()
}

/// Prediction 1 (WRONG first time, ~~kept as a pinned known residual, gh:#1564~~ **CORRECTED 2026-11-14
/// (gh:#1564)**: fixed). With brute-force ray visibility the Rust `viewFactorsGen` did not reproduce every
/// visible list of the fluid box: 209/250 rows equal, upstream listed 86 pairs Rust did not (largest |F|
/// 3.5e-6), Rust listed 44 pairs upstream did not (largest |F| 1.62e-4); on the 41,853 common pairs F was
/// bit-identical. Cause: upstream's `indexedOctree::findLine` hands the triangle test a different
/// (start, end) per leaf (README of the basic-lib V&V record, "gh:#1564"); ported. Re-measured 2026-11-14:
/// 250/250 rows equal (after also reproducing upstream's row ORDER: self-hit-continued rays are listed
/// after the rays that missed on the first `findLine`), 41,939 = 41,939 pairs, 41,939 bit-identical.
#[test]
fn generated_f_for_the_fluid_box_matches_viewfactorsgen() {
    let fdir = vf_root().join("fluid/polyMesh");
    let poly = PolyMesh::read(&fdir).expect("PolyMesh");
    let patch_faces: Vec<Vec<Vec<usize>>> = NAMES
        .iter()
        .map(|n| {
            let p = poly.patches.iter().find(|p| p.name == *n).expect("patch");
            (p.start..p.start + p.size).map(|f| poly.faces[f].verts.clone()).collect()
        })
        .collect();
    let g = generate_view_factors(&ViewFactorGenInput { points: poly.points.clone(), patch_faces }, ViewFactorGenSettings::default()).expect("gen");
    let up_f = parse_scalar_list_list(&gunzip("F.gz")).expect("F");
    let up_g = parse_label_list_list(&gunzip("globalFaceFaces.gz")).expect("gff");
    assert_eq!(up_f.len(), 250);
    let lists_equal = (0..250).filter(|&i| g.global_face_faces[i] == up_g[i]).count();
    let mut common = 0;
    let mut identical = 0;
    let mut worst = 0.0_f64;
    for i in 0..250 {
        for (k, j) in g.global_face_faces[i].iter().enumerate() {
            if let Some(m) = up_g[i].iter().position(|x| x == j) {
                common += 1;
                let (a, b) = (g.f[i][k], up_f[i][m]);
                if a.to_bits() == b.to_bits() {
                    identical += 1;
                } else {
                    worst = worst.max(((a - b) / b).abs());
                }
            }
        }
    }
    let n_up: usize = up_g.iter().map(Vec::len).sum();
    let n_rs: usize = g.global_face_faces.iter().map(Vec::len).sum();
    let (mut up_only_max, mut rs_only_max) = (0.0_f64, 0.0_f64);
    for i in 0..250 {
        for (k, j) in up_g[i].iter().enumerate() {
            if !g.global_face_faces[i].contains(j) {
                up_only_max = up_only_max.max(up_f[i][k].abs());
            }
        }
        for (k, j) in g.global_face_faces[i].iter().enumerate() {
            if !up_g[i].contains(j) {
                rs_only_max = rs_only_max.max(g.f[i][k].abs());
            }
        }
    }
    let sums: Vec<f64> = up_f.iter().map(|r| r.iter().sum::<f64>()).collect();
    eprintln!(
        "fluid box F: rows equal {lists_equal}/250, pairs up {n_up} rust {n_rs} common {common} bit-identical {identical} worst {worst:e}; largest |F| listed by upstream only {up_only_max:e}, by Rust only {rs_only_max:e}; ESI row sums {:.4}..{:.4}",
        sums.iter().cloned().fold(f64::MAX, f64::min),
        sums.iter().cloned().fold(f64::MIN, f64::max)
    );
    assert_eq!(identical, common, "F on the common pairs must stay bit-identical");
    assert_eq!((lists_equal, n_up, n_rs, common), (250, 41939, 41939, 41939));
}

/// The coupled case with ESI's own `F`: isolates the coupling (qr into the interface, boundary-T lag, order
/// of `correct()`) from the generator residual. Prediction 2 of `PREDICTIONS.md`.
#[test]
fn coupled_view_factor_with_esi_f_matches_upstream_chtmultiregionfoam() {
    let reference = read_reference();
    let mut cht = build_port(&reference, Rad::ViewFactorEsiF, true);
    let w = run(&mut cht, &reference, N_STEPS, verbose());
    eprintln!("cht+viewFactor, ESI F, default qr coupling vs ESI v2506: {w:?}");
    assert!(w.max_abs_qr > 1.0, "qr must be resolved by the case: {w:?}");
    assert!(w.t_fluid < 5e-11, "{w:?}");
    assert!(w.t_solid < 2e-11, "{w:?}");
    assert!(w.qr_rel < 1e-9, "{w:?}");
}

