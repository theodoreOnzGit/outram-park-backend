//! `ChtMultiRegionFoam` with opt-in `viewFactor` radiation in the fluid, against upstream
//! OpenFOAM-v2506 `chtMultiRegionFoam` with `radiationModel viewFactor` (gh:#1541, epic gh:#1379).
//!
//! # Method
//! The gh:#1363 two-region case with ONE change: the fluid `frontAndBack` is a `wall` patch, so the
//! fluid boundary is a closed 3-D box of 250 faces (left 5, interface 5, walls 40, frontAndBack 200)
//! and ESI's `viewFactorsGen` takes its 3-D branch. `scripts/run_cht_vf.sh` builds the case, runs
//! upstream `viewFactorsGen -region fluid`, then the gh:#1531 driver `chtRadDump.C` (real
//! `heRhoThermo`, `radiationModel viewFactor`, real `turbulentTemperatureRadCoupledMixed` with
//! `qr qr` / `qrNbr qr`) for 50 steps of 0.1 s, dumping T, `qr` on every fluid patch (bit patterns).
//! The port generates `F` itself (`view_factor_generation`, gh:#1540), attaches
//! `ViewFactorCoupling` to the fluid energy equation and takes `qr` into the interface by default.
//! Predictions: `verification_and_validation/upstream_view_factor_gh1541/PREDICTIONS.md`
//! (commit `7e9f474d8`, before the reference was generated); results: `README.md` there.

