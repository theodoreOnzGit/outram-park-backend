/// Prediction 4 (WRONG: predicted within 3 %): closed-enclosure energy balance of ESI's own qr at the last step.
/// Measured 2026-11-14: sum(A q)/sum(A |q|) = 0.2859, with upstream F row sums 0.9989 to 1.0586. ESI's own F is not
/// reciprocal on this thin graded box (qro = 0, so an exact F would give 0); the port reproduces that F, so the
/// imbalance is upstream's, not a port defect. Pinned to the recorded value (the reference is frozen data).
#[test]
fn esi_qr_energy_balance_of_the_enclosure() {
    let reference = read_reference();
    let mf = read_poly_mesh(&vf_root().join("fluid/polyMesh")).expect("fluid polyMesh");
    let up = &reference.steps[&N_STEPS];
    let (mut net, mut mag) = (0.0, 0.0);
    for name in NAMES {
        let p = &mf.patches[patch_index(&mf, name)];
        for (i, q) in up[&format!("f qr_{name}")].iter().enumerate() {
            let a = mf.face_areas[p.start + i];
            net += a * q;
            mag += a * q.abs();
        }
    }
    eprintln!("ESI qr balance at step {N_STEPS}: sum(A q)/sum(A|q|) = {:.4e}", net / mag);
    assert!((net / mag - 0.28587).abs() < 1e-4, "{}", net / mag);
}

/// Prediction 5/6: off by default (no radiation, no `view_factor`), and the two models exclude each other.
#[test]
fn off_by_default_and_exclusive_with_p1() {
    let reference = read_reference();
    let cht = build_port(&reference, Rad::None, true);
    assert!(cht.fluids[0].energy.as_ref().unwrap().view_factor.is_none());
    // attach viewFactor first, then P1: refused; and P1 first, then viewFactor: refused
    let mf = read_poly_mesh(&vf_root().join("fluid/polyMesh")).expect("fluid polyMesh");
    let poly = PolyMesh::read(vf_root().join("fluid/polyMesh")).expect("PolyMesh");
    let k = &reference.scalars[&0];
    let base = EnergyEquation::uniform(mf.clone(), IncompressibleThermo::si(k["fluid_rho"], k["fluid_Cp"], k["fluid_kappa"]), 300.0);
    let p1 = P1Model::new(
        ConstantAbsorptionEmission { absorptivity: 1.0, emissivity: 1.0, emission_source: 0.0 },
        mf.patches.iter().map(|_| P1PatchModel::ZeroGradient).collect(),
    );
    let v = ViewFactorCoupling::generate(&poly, &base.t, &NAMES, &EMISSIVITY, &[0.0; 4]).expect("coupling");
    let with_vf = base.clone().with_view_factor_radiation(v.clone()).expect("vf");
    assert!(with_vf.with_radiation(p1.clone(), 0.0).is_err());
    let with_p1 = base.with_radiation(p1, 0.0).expect("p1");
    assert!(with_p1.with_view_factor_radiation(v).is_err());
}
