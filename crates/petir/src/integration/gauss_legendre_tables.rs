//! Gauss-Legendre nodes and weights for orders 2 through 30.
//!
//! Ported from `peroxide`. These are **data**, not an algorithm: upstream
//! carries them as static tables rather than computing them, and so does this.
//!
//! # Why tabulated rather than computed
//!
//! The nodes are the roots of the Legendre polynomial `P_n` and the weights
//! follow from `P_n'` at each node, so [`crate::poly::dense::legendre`] and
//! [`crate::poly::companion`] could in principle generate them. They are
//! tabulated anyway, for two reasons. Computing them would be writing a
//! routine from scratch rather than porting one, which this crate does not do
//! (see its `CLAUDE.md`). And the recurrence loses about one digit per two
//! degrees in `f64` -- measured in `poly::dense`'s orthogonality test -- so a
//! computed order-30 node would be worse than the tabulated one, not better.
//!
//! What the two *are* good for is **checking** the table, and the tests below
//! do exactly that: every tabulated node must be a root of the `P_n` this
//! crate generates independently. Neither upstream has that check.
//!
//! # Three upstream values are wrong, and are corrected here
//!
//! `tests/gauss_legendre_table_audit.rs` checks every one of the 928 values
//! against Bonnet's three-term recurrence, which shares no code and no data
//! with the table. It found three bad **node** values in `peroxide` 0.41.2.
//! Each appears twice, once per sign, so six entries differ from upstream:
//!
//! | order | upstream | corrected here | error |
//! |---|---|---|---|
//! | 11 | `0.519096129110681` | `0.5190961292068118` | 9.613e-11 |
//! | 12 | `0.36783149891818` | `0.3678314989981802` | 8.000e-11 |
//! | 12 | `0.125333408511469` | `0.1252334085114689` | **1.000e-04** |
//!
//! The third is a plain single-digit typo — a `2` became a `3` in the fourth
//! decimal, every other digit correct — and it is serious: it costs upstream's
//! 12-point rule about ten significant figures, so a caller asking for
//! Gauss-Legendre at order 12 gets roughly five correct digits instead of
//! fifteen, with nothing to indicate it.
//!
//! All six replacements agree with the standard published Gauss-Legendre
//! tables **and** with the audit's Newton polish, to every digit printed. All
//! **weights are correct** at every order, including 11 and 12; an early run
//! of the audit appeared to show otherwise, and that was the audit evaluating
//! the weight formula at the bad node.
//!
//! Reported upstream; see the crate NOTICE.
//!
//! # Precision, stated plainly
//!
//! Upstream's values carry **15 significant figures**, not the ~17 an `f64`
//! holds. They are therefore accurate to about 1e-15 relative, not to the last
//! bit. That is a property of the data and applies to the corrected values
//! too, which are quoted to 16.
//!
//! # Units
//!
//! Nodes are abscissae on the reference interval `[-1, 1]`; weights are
//! dimensionless and sum to 2. Both bare `f64`.

