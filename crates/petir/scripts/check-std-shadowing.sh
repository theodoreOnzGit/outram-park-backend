# gh #1001: prove PETIR's numbers do not depend on the build graph.
#
# PETIR is #![no_std], but when any crate in its graph links `std` (for
# example `num-traits/std`, which most downstream graphs and petir's own
# `faer` dev-dependency turn on), std's inherent f64/f32 methods become
# visible and beat `real::Real`'s methods of the same name. `x.hypot(y)` then
# calls the platform C library. PETIR therefore writes `Real::hypot(x, y)`.
# `cargo test -p petir` cannot build the std-absent graph (dev-dependency
# features always unify), so this script checks what the test cannot:
#
#   1. clippy, with std forced into the graph (`--features uom/std`), denying
#      `clippy::disallowed_methods` (the list is in crates/petir/clippy.toml);
#   2. a throwaway crate that runs tests/std_shadowing/digest.rs against
#      petir in four graphs: num-traits with and without `std`, crossed with
#      libm's `arch` on and `force-soft-floats` on. All four must print the
#      digests pinned in tests/std_shadowing_digest.rs;
#   3. the petir rlib of the std-present build must import no C maths
#      routine (only exact ones are allowed: fmod, floor, ceil, round, trunc
#      and sqrt, whose results IEEE 754 fixes).
#
# Needs: cargo (offline registry cache is enough), nm (binutils). Linux or
# macOS. Run from anywhere:   crates/petir/scripts/check-std-shadowing.sh
# Cores: JOBS (default 2).

set -euo pipefail

petir_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
root=$(cd -- "$petir_dir/../.." && pwd)
jobs=${JOBS:-2}
probe="$root/target/petir-std-shadowing-probe"
fail=0

echo "== 1/3 clippy: no std-shadowable method calls in petir's library"
(cd -- "$root" && cargo clippy --release -j "$jobs" -p petir --lib --features uom/std \
    -- -A clippy::all -D clippy::disallowed_methods)

echo "== 2/3 digests in four build graphs"
mkdir -p "$probe/src"
cat > "$probe/Cargo.toml" <<EOF
[package]
name = "petir-std-shadowing-probe"
version = "0.0.0"
edition = "2021"
publish = false

[workspace]

[dependencies]
petir = { path = "$petir_dir" }
uom = { version = "0.38.0", default-features = false, features = ["autoconvert", "f32", "f64", "si"] }
num-traits = { version = "0.2", default-features = false, features = ["libm"] }
libm = { version = "0.2", default-features = false }

[features]
std-in-graph = ["num-traits/std"]
libm-arch = ["libm/arch"]
libm-soft = ["libm/force-soft-floats"]

[profile.release]
overflow-checks = true
EOF
cat > "$probe/src/main.rs" <<EOF
// Generated by crates/petir/scripts/check-std-shadowing.sh (gh #1001).
#[path = "$petir_dir/tests/std_shadowing/digest.rs"]
mod digest;

fn main() {
    for (name, value) in digest::digests() {
        println!("DIGEST {name} {value:#018x}");
    }
}
EOF
cp -- "$root/Cargo.lock" "$probe/Cargo.lock"

# The pinned values, as "DIGEST name 0x..." lines.
expected=$(grep -oE '\("[a-z_]+", 0x[0-9a-f]{16}\)' "$petir_dir/tests/std_shadowing_digest.rs" \
    | sed -E 's/\("([a-z_]+)", (0x[0-9a-f]{16})\)/DIGEST \1 \2/')
if [ -z "$expected" ]; then
    echo "could not read EXPECTED from tests/std_shadowing_digest.rs" >&2
    exit 2
fi

for features in "libm-arch" "libm-soft" "std-in-graph,libm-arch" "std-in-graph,libm-soft"; do
    got=$(cd -- "$probe" && cargo run --release --offline -q -j "$jobs" --features "$features")
    if [ "$got" = "$expected" ]; then
        echo "   [$features] all digests match"
    else
        echo "   [$features] MISMATCH" >&2
        diff <(echo "$expected") <(echo "$got") >&2 || true
        fail=1
    fi
    if [ "$features" = "std-in-graph,libm-arch" ]; then
        rlib=$(ls -t "$probe"/target/release/deps/libpetir-*.rlib | head -n 1)
    fi
done

echo "== 3/3 the std-present rlib imports no inexact C maths routine"
bad=$(nm -u "$rlib" 2>/dev/null | awk '{ print $NF }' | grep -E \
    '^(acos|acosh|asin|asinh|atan|atan2|atanh|cbrt|cos|cosh|erf|erfc|exp|exp2|exp10|expm1|fma|hypot|lgamma|log|log10|log1p|log2|pow|sin|sincos|sinh|tan|tanh|tgamma)f?$|^__powi[sd]f2$' \
    | sort | uniq -c || true)
if [ -n "$bad" ]; then
    echo "   $rlib imports:" >&2
    echo "$bad" >&2
    fail=1
else
    echo "   none ($(basename -- "$rlib"))"
fi

if [ "$fail" -ne 0 ]; then
    echo "FAILED: PETIR's output depends on the build graph (gh #1001)" >&2
    exit 1
fi
echo "OK: PETIR's output is independent of std in the graph and of libm's arch feature"
