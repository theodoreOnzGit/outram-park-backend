//! **The HEU-SOL-THERM-009 rung's model**: case 1, a sphere of highly
//! enriched uranium oxyfluoride solution in a thin aluminium tank, reflected
//! by water (gh:#859; moved 2026-11-25, gh:#1742, from `dhoby-ghaut/
//! examples/monte_carlo_web/hst009/mod.rs`).
//!
//! **Nothing is retyped here.** Geometry, materials and tapes are
//! [`outram_mc_libs::vv::hst009`], the model the recorded result (route 4 of
//! the five-route study) and the acceptance check were measured on, with
//! that model's stated approximations (the tank's Cu and Zn omitted, O-17
//! folded into O-16). U-236 is in the model (gh:#875).

#[cfg(not(any(feature = "std", test)))]
#[allow(unused_imports)]
use crate::nostd_prelude::*;
use super::{uniform_in_sphere, CsgModel, ThermalLaw, LEAPR_H_IN_H2O};
use outram_mc_libs::geometry::geometry::Geometry;
use outram_mc_libs::geometry::position::Position;
use outram_mc_libs::material::material::Material;
use outram_mc_libs::physics::transport_csg::SourceBox;
use outram_mc_libs::vv::hst009 as model;

/// The case: the type the `hst009` rung names.
pub struct Hst009;

/// `(label shown, nuclide name, tape)` in [`model::NUCLIDES`] order.
pub const NUCLIDES: [(&str, &str, &str); 12] = [
    ("U-234", model::NUCLIDES[0].0, model::NUCLIDES[0].1),
    ("U-235", model::NUCLIDES[1].0, model::NUCLIDES[1].1),
    ("U-238", model::NUCLIDES[2].0, model::NUCLIDES[2].1),
    ("F-19", model::NUCLIDES[3].0, model::NUCLIDES[3].1),
    ("O-16", model::NUCLIDES[4].0, model::NUCLIDES[4].1),
    ("H-1", model::NUCLIDES[5].0, model::NUCLIDES[5].1),
    ("Al-27", model::NUCLIDES[6].0, model::NUCLIDES[6].1),
    ("Si-28", model::NUCLIDES[7].0, model::NUCLIDES[7].1),
    ("Si-29", model::NUCLIDES[8].0, model::NUCLIDES[8].1),
    ("Si-30", model::NUCLIDES[9].0, model::NUCLIDES[9].1),
    ("Mn-55", model::NUCLIDES[10].0, model::NUCLIDES[10].1),
    ("U-236", model::NUCLIDES[11].0, model::NUCLIDES[11].1),
];
/// Label of the water's thermal scattering law.
pub const SAB_LABEL: &str = "H in H2O S(a,b)";
/// Every tape, `(label, file)`: the twelve nuclides, then the S(α,β) law.
pub const JOBS: [(&str, &str); 13] = [
    (NUCLIDES[0].0, NUCLIDES[0].2),
    (NUCLIDES[1].0, NUCLIDES[1].2),
    (NUCLIDES[2].0, NUCLIDES[2].2),
    (NUCLIDES[3].0, NUCLIDES[3].2),
    (NUCLIDES[4].0, NUCLIDES[4].2),
    (NUCLIDES[5].0, NUCLIDES[5].2),
    (NUCLIDES[6].0, NUCLIDES[6].2),
    (NUCLIDES[7].0, NUCLIDES[7].2),
    (NUCLIDES[8].0, NUCLIDES[8].2),
    (NUCLIDES[9].0, NUCLIDES[9].2),
    (NUCLIDES[10].0, NUCLIDES[10].2),
    (NUCLIDES[11].0, NUCLIDES[11].2),
    (SAB_LABEL, LEAPR_H_IN_H2O),
];
/// Index of U-235 in [`NUCLIDES`].
pub const N_U235: usize = 1;

impl CsgModel for Hst009 {
    const TEMPERATURE_K: f64 = model::TEMPERATURE_K;
    const N_U235: usize = N_U235;
    /// A fresh chain starts from a thermal fission: this is a thermal system.
    const FRESH_INCIDENT_EV: f64 = 0.0253;
    /// A neutron thermalising in water scatters a few hundred times at most.
    const MAX_STATES: usize = 200_000;
    fn nuclides() -> &'static [(&'static str, &'static str, &'static str)] {
        &NUCLIDES
    }
    fn thermal() -> Option<ThermalLaw> {
        // Generated by LEAPR (maintainer direction 2026-10-14), as route 4.
        Some(ThermalLaw { label: SAB_LABEL, tape: LEAPR_H_IN_H2O, name: "c_H_in_H2O", nuclide: model::N_H1 })
    }
    fn materials() -> Vec<Material> {
        model::materials()
    }
    fn geometry() -> Geometry {
        model::geometry()
    }
    fn source_box() -> SourceBox {
        model::source_box()
    }
    /// A uniform point of the solution.
    fn fresh_birth(rng: &mut u64) -> Position {
        uniform_in_sphere(rng, model::R_SOLUTION * (1.0 - 1.0e-9))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Twelve nuclides and the generated water law, born in the solution.
    #[test]
    fn the_case_is_the_benchmark_model() {
        assert_eq!(Hst009::nuclides().len(), 12);
        let law = Hst009::thermal().expect("the water law");
        assert_eq!((law.tape, law.nuclide), (LEAPR_H_IN_H2O, model::N_H1));
        assert_eq!(JOBS[12].1, LEAPR_H_IN_H2O);
        assert_eq!(Hst009::materials().len(), model::materials().len());
        assert!(!Hst009::geometry().cells.is_empty());
        let mut rng = 3u64;
        let p = Hst009::fresh_birth(&mut rng);
        assert!(p.x * p.x + p.y * p.y + p.z * p.z < model::R_SOLUTION * model::R_SOLUTION);
        assert_eq!(Hst009::entropy_box().lower.x, Hst009::source_box().lower.x);
    }
}
