/// Rings of the bed tiling the recorded runs use.
pub const RECORD_RINGS: usize = 14;

/// Şeker layers of the default bed: N = 12, 16 681 core balls.
pub const DEFAULT_LAYERS: usize = 12;

/// The bed a study builds.
#[derive(Debug, Clone, PartialEq)]
pub enum StudyBed {
    /// Şeker & Çolak (2003)'s ordered bed at `layers` layers (10..=20).
    Seker {
        /// Şeker layers N.
        layers: usize,
    },
    /// An explicit ball list in the DEM frame (a LIGGGHTS-port pour).
    Explicit {
        /// Ball centres.
        centres: Vec<[Length; 3]>,
        /// Whether each ball is a fuel pebble.
        is_fuel: Vec<bool>,
    },
}

/// **Every setting of an HTR-10 whole-core run.**
#[derive(Debug, Clone, PartialEq)]
pub struct ParametricStudy {
    /// The bed.
    pub bed: StudyBed,
    /// Each control rod's insertion, `0` withdrawn (the benchmark) to `1`
    /// fully inserted.
    pub rod_insertions: [f64; N_CONTROL_RODS],
    /// The eight zones' temperatures.
    pub temperatures: ZoneTemperatures,
    /// Particles, generations and seed.
    pub statistics: SweepStatistics,
    /// The nuclear-data choices. Its `temperature` is not read: each zone's
    /// is.
    pub data: Htr10DataConfig,
    /// The material choices. Its `temperature_k` is not read either.
    pub materials: Htr10MaterialConfig,
}

impl Default for ParametricStudy {
    /// The recorded model at N = 12, rods withdrawn, every zone at 300.15 K,
    /// the quick statistics, every bound law by LEAPR.
    fn default() -> Self {
        Self {
            bed: StudyBed::Seker {
                layers: DEFAULT_LAYERS,
            },
            rod_insertions: [0.0; N_CONTROL_RODS],
            temperatures: ZoneTemperatures::record(),
            statistics: SweepStatistics::QUICK,
            // Every bound law by LEAPR at its zone's temperature: the data
            // default since 2026-11-03 (`ThermalLawSource::Leapr`).
            data: Htr10DataConfig::default(),
            materials: Htr10MaterialConfig::benchmark_default(300.15),
        }
    }
}

/// What a study needs before any data is processed: the materials, the
/// nuclide array's entries and the jobs that make them.
#[derive(Debug, Clone)]
pub struct StudyPlan {
    /// The nuclide slots (one per nuclide, at no temperature).
    pub layout: Htr10NuclideLayout,
    /// The materials, every slot of a zoned design (`mat::ZONED_COUNT`), each
    /// at its zone's temperature, its components indexing [`Self::entries`].
    pub materials: Vec<Material>,
    /// The nuclide array: `(slot of layout, temperature K)` per nuclide.
    pub entries: Vec<(usize, f64)>,
    /// The processing jobs, as [`Htr10NuclideLayout::tempered_jobs`] lists
    /// them for [`Self::entries`].
    pub jobs: Vec<TemperedJob>,
}

impl ParametricStudy {
    /// **Settings from command-line words**, on top of [`Self::default`]:
    ///
    /// | word | sets |
    /// |---|---|
    /// | `--layers N` | Şeker layers (10..=20) |
    /// | `--bank F` | every rod at insertion `F` (0 withdrawn, 1 inserted) |
    /// | `--rod I=F` | rod `I` (1..=10) at insertion `F` |
    /// | `--temp-all C` | every zone at `C` °C |
    /// | `--temp ZONE=C` | one zone at `C` °C; `ZONE` is `fuel`, `moderator`, `coolant`, `top`, `side`, `bottom`, `rods` or `bricks` |
    /// | `--particles N`, `--inactive N`, `--active N`, `--seed S` | the statistics |
    /// | `--laws leapr` / `--laws tapes` | graphite and SiC laws by LEAPR at each temperature (default) or from the published tapes |
    ///
    /// Words it does not know are returned, for the caller's own flags.
    ///
    /// # Errors
    /// A malformed or unknown value, naming the word.
    pub fn from_args(words: &[String]) -> Result<(Self, Vec<String>), String> {
        use super::zones::Htr10Zone;
        use uom::si::f64::ThermodynamicTemperature;
        use uom::si::thermodynamic_temperature::degree_celsius;
        let mut s = Self::default();
        let mut rest = Vec::new();
        let mut it = words.iter();
        let num = |w: &str, v: Option<&String>| -> Result<f64, String> {
            v.ok_or_else(|| format!("{w} needs a value"))?
                .parse::<f64>()
                .map_err(|e| format!("{w}: {e}"))
        };
        let count = |w: &str, v: Option<&String>| -> Result<usize, String> {
            v.ok_or_else(|| format!("{w} needs a value"))?
                .parse::<usize>()
                .map_err(|e| format!("{w}: {e}"))
        };
        let pair = |w: &str, v: Option<&String>| -> Result<(String, f64), String> {
            let v = v.ok_or_else(|| format!("{w} needs KEY=VALUE"))?;
            let (k, x) = v.split_once('=').ok_or_else(|| format!("{w} {v}: not KEY=VALUE"))?;
            Ok((k.to_string(), x.parse::<f64>().map_err(|e| format!("{w} {v}: {e}"))?))
        };
        let celsius = |c: f64| ThermodynamicTemperature::new::<degree_celsius>(c);
        while let Some(w) = it.next() {
            match w.as_str() {
                "--layers" => s.bed = StudyBed::Seker { layers: count(w, it.next())? },
                "--bank" => s.rod_insertions = [num(w, it.next())?; N_CONTROL_RODS],
                "--rod" => {
                    let (k, f) = pair(w, it.next())?;
                    let i: usize = k.parse().map_err(|e| format!("--rod {k}: {e}"))?;
                    if !(1..=N_CONTROL_RODS).contains(&i) {
                        return Err(format!("--rod {i}: rods are 1..={N_CONTROL_RODS}"));
                    }
                    s.rod_insertions[i - 1] = f;
                }
                "--temp-all" => s.temperatures = ZoneTemperatures::uniform(celsius(num(w, it.next())?)),
                "--temp" => {
                    let (k, c) = pair(w, it.next())?;
                    let z = Htr10Zone::from_key(&k).ok_or_else(|| {
                        format!("--temp {k}: zones are fuel, moderator, coolant, top, side, bottom, rods, bricks")
                    })?;
                    s.temperatures.set(z, celsius(c));
                }
                "--particles" => s.statistics.particles = count(w, it.next())?,
                "--inactive" => s.statistics.inactive = count(w, it.next())?,
                "--active" => s.statistics.active = count(w, it.next())?,
                "--seed" => {
                    s.statistics.seed = it
                        .next()
                        .ok_or("--seed needs a value")?
                        .parse()
                        .map_err(|e| format!("--seed: {e}"))?;
                }
                "--laws" => {
                    s.data.thermal_laws = match it.next().map(String::as_str) {
                        Some("leapr") => ThermalLawSource::Leapr,
                        Some("tapes") => ThermalLawSource::Tapes,
                        v => return Err(format!("--laws {v:?}: leapr or tapes")),
                    };
                }
                _ => rest.push(w.clone()),
            }
        }
        s.statistics.name = "parametric";
        Ok((s, rest))
    }

    /// Refuse a setting the model cannot build: a temperature out of
    /// 20..=1800 °C, a rod insertion outside `[0, 1]`, a bed of the wrong
    /// size.
    ///
    /// # Errors
    /// A message naming the setting.
    pub fn check(&self) -> Result<(), String> {
        self.temperatures.check()?;
        self.design().check()?;
        match &self.bed {
            StudyBed::Seker { layers } if !(10..=20).contains(layers) => {
                Err(format!("Şeker layers N = {layers}: the model builds N = 10..=20"))
            }
            StudyBed::Explicit { centres, is_fuel } if centres.len() != is_fuel.len() => {
                Err("one fuel flag per ball centre".into())
            }
            _ => Ok(()),
        }
    }

    /// The core design: the rods, with the temperature-zone slots placed.
    #[must_use]
    pub fn design(&self) -> Htr10CoreDesign {
        Htr10CoreDesign {
            rod_insertions: self.rod_insertions,
            // A DEM (explicit) bed packs its TRISO at random (gh:#1243,
            // maintainer 2026-11-05); the Şeker bed keeps the lattice.
            triso_packing: match self.bed {
                StudyBed::Seker { .. } => TrisoPacking::Lattice,
                StudyBed::Explicit { .. } => TrisoPacking::DEM_DEFAULT,
            },
            ..Htr10CoreDesign::default()
        }
        .with_temperature_zones()
    }

    /// **The plan**: materials at their zones' temperatures, the nuclide
    /// array, the jobs.
    ///
    /// # Errors
    /// The nuclide plan refuses the data configuration.
    pub fn plan(&self) -> Result<StudyPlan, Htr10DataError> {
        self.plan_with_slot_temperatures(&[])
    }

    /// **The plan with some material slots off their zone's temperature**
    /// (gh:#1174): as [`Self::plan`], then each `(slot, T)` of `slots` sets
    /// that slot's material temperature, so its nuclides are processed, its
    /// bound laws generated and its cells placed at `T`. This is how a part
    /// of a zone is perturbed alone, e.g. the fuel pebbles' graphite
    /// ([`mat::GRAPHITE`]: the fuel-zone matrix and the shell) without their
    /// kernels and coatings, for the moderator-coefficient split of
    /// [`graphite_worth_cases`]. With `slots` empty it is [`Self::plan`].
    ///
    /// # Errors
    /// As [`Self::plan`]; [`Htr10DataError::InvalidConfig`] for a slot of
    /// no zoned material or a temperature outside the zones' range.
    pub fn plan_with_slot_temperatures(
        &self,
        slots: &[(usize, ThermodynamicTemperature)],
    ) -> Result<StudyPlan, Htr10DataError> {
        let layout = Htr10NuclideLayout::plan(&self.data)?;
        let mut materials = zoned_material_set(&layout, self.materials, &self.temperatures);
        let (lo, hi) = (min_temperature().get::<kelvin>(), max_temperature().get::<kelvin>());
        for (slot, t) in slots {
            let tk = t.get::<kelvin>();
            if !(lo..=hi).contains(&tk) {
                return Err(Htr10DataError::InvalidConfig(format!(
                    "slot {slot}: {tk} K is outside {lo}-{hi} K"
                )));
            }
            materials
                .get_mut(*slot)
                .ok_or_else(|| Htr10DataError::InvalidConfig(format!("no zoned material slot {slot}")))?
                .temperature = tk;
        }
        let entries = split_by_temperature(&mut materials, layout.len());
        let jobs = layout.tempered_jobs(&entries);
        Ok(StudyPlan {
            layout,
            materials,
            entries,
            jobs,
        })
    }

    /// Run job `i` of `plan`. `tape` is the tape [`Self::job_tape`] names,
    /// already read (`None` for a LEAPR law).
    ///
    /// # Errors
    /// As [`process_job_at`]; and `i` out of range.
    pub fn process_job(
        &self,
        plan: &StudyPlan,
        i: usize,
        tape: Option<&EndfTape>,
    ) -> Result<JobProduct, Htr10DataError> {
        let j = plan
            .jobs
            .get(i)
            .ok_or_else(|| Htr10DataError::InvalidConfig(format!("no job {i}")))?;
        process_job_at(&j.job, &self.data, tape, j.temperature)
    }

    /// The tape job `i` reads, or `None` for a LEAPR law.
    ///
    /// # Errors
    /// As `ProcessingJob::tape`; and `i` out of range.
    pub fn job_tape(&self, plan: &StudyPlan, i: usize) -> Result<Option<Tape>, Htr10DataError> {
        plan.jobs
            .get(i)
            .ok_or_else(|| Htr10DataError::InvalidConfig(format!("no job {i}")))?
            .job
            .tape(&self.data)
    }

    /// Build the nuclide array from the jobs' products (`product(i)` for job
    /// `i`) and the tapes (`read_tape`).
    ///
    /// # Errors
    /// As [`assemble_entries`].
    pub fn assemble_nuclides(
        &self,
        plan: &StudyPlan,
        product: impl FnMut(usize) -> Result<JobProduct, Htr10DataError>,
        read_tape: impl FnMut(&Tape) -> Result<EndfTape, Htr10DataError>,
    ) -> Result<Vec<Nuclide>, Htr10DataError> {
        assemble_entries(&plan.layout, &plan.entries, &plan.jobs, product, read_tape)
    }

    /// **The core**: the bed, the rods and the zone slots, every material
    /// cell at its material's temperature (gh:#313).
    ///
    /// # Errors
    /// [`Self::check`] refuses the settings.
    pub fn core(&self, plan: &StudyPlan) -> Result<AssembledCore, String> {
        self.check()?;
        let design = self.design();
        let mut core = match &self.bed {
            StudyBed::Seker { layers } => {
                assemble_explicit_triso_with(RECORD_RINGS, *layers, 0, &design)
            }
            StudyBed::Explicit { centres, is_fuel } => assemble_explicit_triso_from_centres_with(
                centres,
                is_fuel,
                RECORD_RINGS,
                0,
                &design,
            ),
        };
        set_cell_temperatures(&mut core.geometry, &plan.materials);
        Ok(core)
    }

    /// **The bed majorant**: as [`super::keff_vs_height::bed_majorant`], over
    /// the bed's materials, which with zones include the moderator balls'
    /// own slot.
    #[must_use]
    pub fn majorant(plan: &StudyPlan, nuclides: &[Nuclide]) -> Majorant {
        let mut bed: Vec<usize> = (0..=mat::HELIUM).collect();
        bed.push(mat::MODERATOR_BALL);
        Majorant::over_indices(&plan.materials, &bed, nuclides, &majorant_energy_grid(), 0.3)
    }

    /// **Process every job natively and assemble the nuclide array**: the
    /// jobs on `threads` threads, tapes from the workspace. `progress` gets a
    /// line per finished job.
    ///
    /// # Errors
    /// A tape that is missing or fails, or tapes from a folder
    /// (`TapeSource::Folder`, not supported here yet).
    pub fn process_all(
        &self,
        plan: &StudyPlan,
        threads: usize,
        progress: impl Fn(&str) + Sync,
    ) -> Result<Vec<Nuclide>, String> {
        if !matches!(self.data.tapes, TapeSource::Workspace) {
            return Err("ParametricStudy reads the workspace's tapes only".into());
        }
        let read = |t: &Tape| {
            EndfTape::read_file(&t.path())
                .map_err(|e| Htr10DataError::InvalidConfig(format!("{}: {e}", t.file)))
        };
        let products: Mutex<Vec<Option<Result<JobProduct, String>>>> =
            Mutex::new((0..plan.jobs.len()).map(|_| None).collect());
        let next = AtomicUsize::new(0);
        std::thread::scope(|s| {
            for _ in 0..threads.max(1) {
                s.spawn(|| loop {
                    let i = next.fetch_add(1, Ordering::Relaxed);
                    if i >= plan.jobs.len() {
                        break;
                    }
                    let t0 = std::time::Instant::now();
                    let r = self
                        .job_tape(plan, i)
                        .and_then(|t| t.map(|t| read(&t)).transpose())
                        .and_then(|t| self.process_job(plan, i, t.as_ref()))
                        .map_err(|e| e.to_string());
                    progress(&format!(
                        "{} {} in {:.1} s",
                        plan.jobs[i].label(),
                        if r.is_ok() { "processed" } else { "FAILED" },
                        t0.elapsed().as_secs_f64()
                    ));
                    products.lock().expect("no panics while held")[i] = Some(r);
                });
            }
        });
        let mut products = products.into_inner().expect("no panics while held");
        self.assemble_nuclides(
            plan,
            |i| match products[i].take() {
                Some(Ok(p)) => Ok(p),
                Some(Err(e)) => Err(Htr10DataError::InvalidConfig(e)),
                None => Err(Htr10DataError::InvalidConfig(format!("job {i} did not run"))),
            },
            read,
        )
        .map_err(|e| e.to_string())
    }

    /// **Transport the core on `nuclides`** (the array of `plan`) with
    /// `run_keff_csg_hybrid`, as the recorded runs: the bed majorant, the
    /// whole fissile region as source box and entropy mesh.
    ///
    /// # Errors
    /// [`Self::check`] refuses the settings.
    pub fn transport(
        &self,
        plan: &StudyPlan,
        nuclides: &[Nuclide],
        threads: usize,
    ) -> Result<KeffResult, String> {
        self.transport_with_tally(plan, nuclides, threads, None)
    }

    /// **As [`Self::transport`], scoring `tally` on the active generations**
    /// (gh:#1186): e.g. a power tally of `crate::power_shape::McPowerTally`,
    /// whose filters are in the Monte Carlo frame (cm, `z` up, `0` at the bed
    /// mid-height). With `None` it is [`Self::transport`], bit for bit (the
    /// same call). In the delta-tracked bed the tally is scored at every
    /// tentative collision (`DeltaTallyEstimator`, gh:#598).
    ///
    /// # Errors
    /// [`Self::check`] refuses the settings.
    pub fn transport_with_tally(
        &self,
        plan: &StudyPlan,
        nuclides: &[Nuclide],
        threads: usize,
        tally: Option<&mut Tally>,
    ) -> Result<KeffResult, String> {
        let core = self.core(plan)?;
        let majorant = Self::majorant(plan, nuclides);
        let mesh = fissile_entropy_mesh(&core);
        Ok(run_keff_csg_hybrid(
            &core.geometry,
            &plan.materials,
            nuclides,
            std::slice::from_ref(&majorant),
            Some(&mesh),
            fissile_source_box(&core),
            &self.statistics.keff_settings(threads.max(1)),
            tally,
        ))
    }

    /// **Run it natively**: [`Self::plan`], [`Self::process_all`],
    /// [`Self::transport`].
    ///
    /// # Errors
    /// As those.
    pub fn run_keff(
        &self,
        threads: usize,
        progress: impl Fn(&str) + Sync,
    ) -> Result<KeffResult, String> {
        self.check()?;
        let plan = self.plan().map_err(|e| e.to_string())?;
        let nuclides = self.process_all(&plan, threads, progress)?;
        self.transport(&plan, &nuclides, threads)
    }
}

/// One case of the graphite-zone worth measurement (gh:#1174).
#[derive(Debug, Clone, PartialEq)]
pub struct GraphiteWorthCase {
    /// Short name (`BASE`, `FUEL-GRAPHITE`, ...).
    pub name: &'static str,
    /// The zone temperatures.
    pub temperatures: ZoneTemperatures,
    /// Slots moved off their zone's temperature
    /// ([`ParametricStudy::plan_with_slot_temperatures`]).
    pub slots: Vec<(usize, ThermodynamicTemperature)>,
}

/// **The cases that split the graphite temperature worth by zone**
/// (gh:#1174): every zone at `base`, then one part at `base + delta_k` at a
/// time:
///
/// - `FUEL-GRAPHITE`: the fuel pebbles' graphite ([`mat::GRAPHITE`]: the
///   fuel-zone matrix and the shell), kernels and coatings kept at `base`;
/// - `DUMMIES`: the moderator (dummy) pebbles;
/// - `TOP`, `SIDE`, `BOTTOM`: the three reflector zones;
/// - `KERNEL`: the rest of the fuel-pebble zone (kernel and the four
///   coatings), the fuel coefficient's own part, as a check against
///   TECDOC-1694's fuel coefficient.
///
/// The reactivity worth of each part is `1/k_base - 1/k_case`.
#[must_use]
pub fn graphite_worth_cases(base: ThermodynamicTemperature, delta_k: f64) -> Vec<GraphiteWorthCase> {
    let hot = ThermodynamicTemperature::new::<kelvin>(base.get::<kelvin>() + delta_k);
    let uniform = ZoneTemperatures::uniform(base);
    let zone = |name, z| GraphiteWorthCase { name, temperatures: uniform.with(z, hot), slots: vec![] };
    vec![
        GraphiteWorthCase { name: "BASE", temperatures: uniform, slots: vec![] },
        GraphiteWorthCase { name: "FUEL-GRAPHITE", temperatures: uniform, slots: vec![(mat::GRAPHITE, hot)] },
        zone("DUMMIES", Htr10Zone::ModeratorPebble),
        zone("TOP", Htr10Zone::TopReflector),
        zone("SIDE", Htr10Zone::SideReflector),
        zone("BOTTOM", Htr10Zone::BottomReflector),
        GraphiteWorthCase {
            name: "KERNEL",
            temperatures: uniform.with(Htr10Zone::FuelPebble, hot),
            slots: vec![(mat::GRAPHITE, base)],
        },
    ]
}

