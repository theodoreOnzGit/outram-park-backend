//! The `CSL` object of citeproc-js (src/load.js): its constants (term lists,
//! regular expressions, the lookup tables) and the helper functions that
//! hang off it (`CSL.parseLocator`, `CSL.parseNoteFieldHacks`,
//! `CSL.checkNestedBrace`, `CSL.normalizeLocaleStr`, the punctuation-spacing
//! checks, `CSL.TITLE_SPLIT`, `CSL.SET_COURT_CLASSES`, ...).
//!
//! **Names.** `CSL.NAME_VARIABLES` is [`NAME_VARIABLES`], `CSL.Foo()` is
//! `load::foo()`. Constant tables that upstream keeps in an object keyed by
//! string are `&[(&str, &str)]` slices with a lookup function next to them
//! (their order is upstream's insertion order); the tables themselves are
//! generated from the bundled citeproc-js by `scripts/csl-units/load_tables.cjs`.
//!
//! **Regular expressions** are `LazyLock<Regex>` statics. JS `\s` is
//! [`WS_CLASS`], JS `.` is [`DOT`], and `\d` is written `[0-9]` (PORTING.md §5).
//! `tests/data/csl/units/load.json` (generated by `scripts/csl-units/load.cjs`
//! from citeproc-js) holds what each does on a battery of strings.
//!
//! **What is not here.** `CSL.Engine.*` (build.rs, util_locale.rs, ...) and
//! `CSL.Util`/`CSL.Output`/`CSL.Node` live in their own files.
//! `CSL.error` is `Err(EngineError::Csl(..))`; `CSL.debug` is dropped.

