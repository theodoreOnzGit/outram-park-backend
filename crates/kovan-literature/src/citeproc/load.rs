/// `CSL.demoteNoiseWords(state, fld, drop_or_demote)`: drop, or move to the
/// end after a comma, the leading noise words of a name or title.
///
/// For a `drop_or_demote` that is neither `"drop"` nor `"demote"` upstream
/// returns the (reversed-twice, noise-trimmed) *array*; here its
/// comma-joined string, which is what JS string coercion gives.
pub fn demote_noise_words(state: &State, fld: &str, drop_or_demote: &str) -> String {
    if fld.is_empty() || drop_or_demote.is_empty() {
        return fld.to_string();
    }
    let skip: Vec<String> = state
        .locale
        .get(js::get_str(&state.opt, "lang").unwrap_or(""))
        .and_then(|l| l.opts.get("leading-noise-words"))
        .and_then(Value::as_array)
        .map(|a| a.iter().map(js::to_js_string).collect())
        .unwrap_or_default();
    static WS_RUN: LazyLock<Regex> =
        LazyLock::new(|| Regex::new(&format!("{WS_CLASS}+")).expect("static"));
    let mut words = js::split(&WS_RUN, fld);
    words.reverse();
    let mut to_end: Vec<String> = Vec::new();
    let mut j = words.len() as i64 - 1;
    while j > -1 {
        let w = words[j as usize].to_lowercase();
        if skip.contains(&w) {
            if let Some(popped) = words.pop() {
                to_end.push(popped);
            }
        } else {
            break;
        }
        j -= 1;
    }
    words.reverse();
    let start = words.join(" ");
    let end = to_end.join(" ");
    if drop_or_demote == "drop" || end.is_empty() {
        start
    } else if drop_or_demote == "demote" {
        [start, end].join(", ")
    } else {
        words.join(",")
    }
}

/// `Regex::new` of a pattern that is a compile-time constant of this file.
fn rx_static(src: &str) -> Regex {
    Regex::new(src).unwrap_or_else(|e| panic!("invalid static regex {src:?}: {e}"))
}

/// `development_extensions[name]` of `state.opt`, `None` when absent.
pub(crate) fn dev_ext<'a>(state: &'a State, name: &str) -> Option<&'a Value> {
    state
        .opt
        .get("development_extensions")
        .and_then(|d| d.get(name))
}

/// Truthiness of `state.opt.development_extensions[name]`.
pub(crate) fn dev_ext_truthy(state: &State, name: &str) -> bool {
    dev_ext(state, name).map(js::truthy).unwrap_or(false)
}

/// `obj[key] = value` where `value` may be JS `undefined` (the key is then
/// dropped from this data model).
pub(crate) fn set_or_remove(obj: &mut Obj, key: &str, value: Option<Value>) {
    match value {
        Some(v) => {
            obj.insert(key.to_string(), v);
        }
        None => {
            obj.remove(key);
        }
    }
}

/// A JS `TypeError` raised by reading a property of `undefined` and the like,
/// as the message JS gives it (no `citeproc-js error:` prefix: it is not a
/// `CSL.error`).
pub(crate) fn type_error(msg: &str) -> EngineError {
    EngineError::BadInput(msg.to_string())
}


/// A JS object of title parts whose values may be `undefined` (`None`),
/// `false` or strings.
type TitleVals = BTreeMap<String, Option<Value>>;

fn vals_str(vals: &TitleVals, key: &str) -> Option<String> {
    match vals.get(key) {
        Some(Some(Value::String(s))) => Some(s.clone()),
        _ => None,
    }
}

fn vals_truthy(vals: &TitleVals, key: &str) -> bool {
    matches!(vals.get(key), Some(Some(v)) if js::truthy(v))
}

/// `CSL.extractTitleAndSubtitle.call(state, Item, narrowSpaceLocale)` (load.js)
/// (`main_title_from_short_title`): fill `title-main`, `title-sub`,
/// `title-subjoin` (and `container-` variants with `split_container_title`)
/// from `title` and `title-short`, per language of `Item.multi`.
pub fn extract_title_and_subtitle(
    state: &State,
    item: &mut Obj,
    narrow_space_locale: bool,
) -> CslResult<()> {
    let narrow_space = if narrow_space_locale { "\u{202f}" } else { "" };
    let mut segments = vec![""];
    if dev_ext_truthy(state, "split_container_title") {
        segments.push("container-");
    }
    for seg in segments {
        let t_title = format!("{seg}title");
        let t_short = format!("{seg}title-short");
        let t_main = format!("{seg}title-main");
        let t_sub = format!("{seg}title-sub");
        let t_subjoin = format!("{seg}title-subjoin");
        let mut langs: Vec<Option<String>> = vec![None];
        let has_multi = js::truthy_opt(item.get("multi"));
        if has_multi {
            let keys = item
                .get("multi")
                .and_then(|m| m.get("_keys"))
                .ok_or_else(|| {
                    type_error(&format!(
                        "Cannot read properties of undefined (reading '{t_short}')"
                    ))
                })?;
            if let Some(Value::Object(o)) = keys.get(&t_short) {
                for lang in o.keys() {
                    langs.push(Some(lang.clone()));
                }
            }
        }
        for lang in langs {
            let mut vals: TitleVals = BTreeMap::new();
            if let Some(lang) = &lang {
                let keys = item
                    .get("multi")
                    .and_then(|m| m.get("_keys"))
                    .cloned()
                    .unwrap_or(Value::Null);
                if js::truthy_opt(keys.get(&t_title)) {
                    vals.insert(
                        t_title.clone(),
                        keys.get(&t_title)
                            .and_then(|k| k.get(lang.as_str()))
                            .cloned(),
                    );
                }
                if js::truthy_opt(keys.get(&t_short)) {
                    vals.insert(
                        t_short.clone(),
                        keys.get(&t_short)
                            .and_then(|k| k.get(lang.as_str()))
                            .cloned(),
                    );
                }
            } else {
                vals.insert(t_title.clone(), item.get(&t_title).cloned());
                vals.insert(t_short.clone(), item.get(&t_short).cloned());
            }
            vals.insert(t_main.clone(), vals.get(&t_title).cloned().flatten());
            vals.insert(t_sub.clone(), Some(Value::Bool(false)));
            let short_title = vals_str(&vals, &t_short);
            if vals_truthy(&vals, &t_title) {
                let title = vals_str(&vals, &t_title)
                    .ok_or_else(|| type_error("vals[title.title].toLowerCase is not a function"))?;
                let set = |vals: &mut TitleVals, k: &str, v: String| {
                    vals.insert(k.to_string(), Some(Value::String(v)));
                };
                match short_title.as_deref().filter(|s| !s.is_empty()) {
                    Some(st) if st.to_lowercase() == title.to_lowercase() => {
                        set(&mut vals, &t_main, title.clone());
                        set(&mut vals, &t_subjoin, String::new());
                        set(&mut vals, &t_sub, String::new());
                    }
                    Some(st) => {
                        // check for valid match to shortTitle
                        static TRAIL_Q: LazyLock<Regex> = LazyLock::new(|| rx_static("[?!]+$"));
                        static LEAD_Q: LazyLock<Regex> = LazyLock::new(|| rx_static("^[?!]+"));
                        static TRAIL_Q_WS: LazyLock<Regex> =
                            LazyLock::new(|| rx_static(&format!("[?!]+([{}]*)$", js::WS)));
                        let cut = TRAIL_Q.replace(st, "").into_owned();
                        let tail = js::slice(&title, js::len(&cut) as i64, None);
                        let tail_nolead = LEAD_Q.replace(&tail, "").into_owned();
                        let top = js::trim(&title.replacen(&tail_nolead, "", 1)).to_string();
                        let m = TITLE_SPLIT_REGEXP.matchfirst.captures(&tail);
                        if m.is_some() && top.to_lowercase() == st.to_lowercase() {
                            let m1 = m
                                .as_ref()
                                .and_then(|c| c.get(1))
                                .map(|x| x.as_str())
                                .unwrap_or("");
                            set(&mut vals, &t_main, top.clone());
                            set(
                                &mut vals,
                                &t_subjoin,
                                TRAIL_Q_WS.replace(m1, "${1}").into_owned(),
                            );
                            set(
                                &mut vals,
                                &t_sub,
                                TITLE_SPLIT_REGEXP.matchfirst.replace(&tail, "").into_owned(),
                            );
                            if dev_ext_truthy(state, "force_short_title_casing_alignment") {
                                vals.insert(t_short.clone(), vals.get(&t_main).cloned().flatten());
                            }
                        } else {
                            let split_title = title_split(&title);
                            if split_title.len() == 3 {
                                set(&mut vals, &t_main, split_title[0].clone());
                                set(&mut vals, &t_subjoin, split_title[1].clone());
                                set(&mut vals, &t_sub, split_title[2].clone());
                            } else {
                                set(&mut vals, &t_main, title.clone());
                                set(&mut vals, &t_subjoin, String::new());
                                set(&mut vals, &t_sub, String::new());
                            }
                        }
                    }
                    None => {
                        let split_title = title_split(&title);
                        if split_title.len() == 3 {
                            set(&mut vals, &t_main, split_title[0].clone());
                            set(&mut vals, &t_subjoin, split_title[1].clone());
                            set(&mut vals, &t_sub, split_title[2].clone());
                            if dev_ext_truthy(state, "implicit_short_title")
                                && item.get("type").and_then(Value::as_str) != Some("legal_case")
                            {
                                static MAIN_PUNCT_ONLY: LazyLock<Regex> =
                                    LazyLock::new(|| rx_static("^[-.\\[0-9]+$"));
                                let main = vals_str(&vals, &t_main).unwrap_or_default();
                                if !js::truthy_opt(item.get(&t_short))
                                    && !MAIN_PUNCT_ONLY.is_match(&main)
                                {
                                    let mut punct =
                                        js::trim(&vals_str(&vals, &t_subjoin).unwrap_or_default())
                                            .to_string();
                                    if punct != "?" && punct != "!" {
                                        punct = String::new();
                                    }
                                    set(&mut vals, &t_short, format!("{main}{punct}"));
                                }
                            }
                        } else {
                            set(&mut vals, &t_main, title.clone());
                            set(&mut vals, &t_subjoin, String::new());
                            set(&mut vals, &t_sub, String::new());
                        }
                    }
                }
                if vals_truthy(&vals, &t_subjoin) {
                    let subjoin = vals_str(&vals, &t_subjoin).unwrap_or_default();
                    static QE: LazyLock<Regex> = LazyLock::new(|| rx_static("([?!])"));
                    static TRAIL_WS: LazyLock<Regex> =
                        LazyLock::new(|| rx_static(&format!("([{}]*)$", js::WS)));
                    if QE.is_match(&subjoin) {
                        let m1 = TRAIL_WS
                            .captures(&subjoin)
                            .and_then(|c| c.get(1))
                            .map(|x| x.as_str())
                            .unwrap_or("")
                            .to_string();
                        let main = vals_str(&vals, &t_main).unwrap_or_default();
                        vals.insert(
                            t_main.clone(),
                            Some(Value::String(format!(
                                "{main}{narrow_space}{}",
                                js::trim(&subjoin)
                            ))),
                        );
                        vals.insert(t_subjoin.clone(), Some(Value::String(m1)));
                    }
                }
            }
            if vals_truthy(&vals, &t_subjoin) {
                let mut subjoin = vals_str(&vals, &t_subjoin).unwrap_or_default();
                if subjoin.contains(':') {
                    subjoin = format!("{narrow_space}: ");
                }
                if subjoin.contains('-') || subjoin.contains('\u{2014}') {
                    subjoin = "\u{2014}".to_string();
                }
                vals.insert(t_subjoin.clone(), Some(Value::String(subjoin)));
            }
            if let Some(lang) = &lang {
                for (key, v) in &vals {
                    let multi = item
                        .get_mut("multi")
                        .and_then(Value::as_object_mut)
                        .ok_or_else(|| type_error("Item.multi is undefined"))?;
                    let keys = multi
                        .get_mut("_keys")
                        .and_then(Value::as_object_mut)
                        .ok_or_else(|| type_error("Item.multi._keys is undefined"))?;
                    let slot = keys
                        .entry(key.clone())
                        .or_insert_with(|| Value::Object(Obj::new()));
                    if !js::truthy(slot) {
                        *slot = Value::Object(Obj::new());
                    }
                    if let Some(o) = slot.as_object_mut() {
                        set_or_remove(o, lang, v.clone());
                    }
                }
            } else {
                for (key, v) in &vals {
                    set_or_remove(item, key, v.clone());
                }
            }
        }
    }
    Ok(())
}


/// `CSL.TITLE_SPLIT(str)`: split a title at its sub-title joins, returning
/// `[main, join, sub, join, sub, ...]`. A split point preceded by a word
/// that ends in a capital is recombined into the preceding text, so
/// "U.S. Foo" is not split.
pub fn title_split(s: &str) -> Vec<String> {
    if s.is_empty() {
        return Vec::new();
    }
    let m: Vec<String> = TITLE_SPLIT_REGEXP
        .match_
        .find_iter(s)
        .map(|m| m.as_str().to_string())
        .collect();
    let mut lst = js::split(&TITLE_SPLIT_REGEXP.split, s);
    let mut i = lst.len() as i64 - 2;
    while i > -1 {
        let iu = i as usize;
        lst[iu] = js::trim(&lst[iu]).to_string();
        let last = js::slice(&lst[iu], -1, None);
        let m_i = m
            .get(iu)
            .cloned()
            .unwrap_or_else(|| "undefined".to_string());
        if !lst[iu].is_empty() && last.to_lowercase() != last {
            // recombine
            let next = lst.remove(iu + 1);
            lst[iu] = format!("{}{}{}", lst[iu], m_i, next);
        } else {
            // merge
            lst.insert(iu + 1, m_i);
        }
        i -= 1;
    }
    lst
}

fn js_type_error(what: &str) -> EngineError {
    EngineError::Csl(format!("TypeError: {what}"))
}

/// A value of an item field as the string JS methods would be called on;
/// `Err` (a TypeError upstream) for a non-string.
fn text_of(v: &Value) -> CslResult<&str> {
    v.as_str()
        .ok_or_else(|| js_type_error("toLowerCase is not a function"))
}

impl State {
    /// `CSL.extractTitleAndSubtitle.call(state, Item, narrowSpaceLocale)`:
    /// split each title (and, with `split_container_title`, container
    /// title) into `title-main`, `title-sub` and `title-subjoin`, and
    /// possibly a short title, on the item and its `multi._keys` languages.
    ///
    /// Follows upstream's rules: an exactly matching short title makes the
    /// whole title the main title; a short title that is a prefix of the
    /// title, followed by a split point, splits there; otherwise
    /// [`title_split`] must find exactly one join. Joins containing `?`/`!`
    /// move that mark into the main title; `:` becomes ": " and `-`/`—`
    /// becomes an em dash.
    pub fn extract_title_and_subtitle(
        &self,
        item: &mut Obj,
        narrow_space_locale: bool,
    ) -> CslResult<()> {
        let narrow_space = if narrow_space_locale { "\u{202f}" } else { "" };
        let dev = |k: &str| {
            self.opt
                .get("development_extensions")
                .and_then(|d| d.get(k))
                .map(js::truthy)
                .unwrap_or(false)
        };
        let mut segments = vec![""];
        if dev("split_container_title") {
            segments.push("container-");
        }
        for seg in segments {
            let title = title_field_splits(seg);
            let mut langs: Vec<Option<String>> = vec![None];
            if js::get_truthy(item, "multi") {
                let keys = item.get("multi").and_then(|m| m.get("_keys"));
                match keys {
                    None => {
                        return Err(js_type_error(&format!(
                            "Cannot read properties of undefined (reading '{}')",
                            title.short
                        )))
                    }
                    Some(k) => {
                        if let Some(Value::Object(m)) = k.get(&title.short) {
                            for lang in m.keys() {
                                langs.push(Some(lang.clone()));
                            }
                        }
                    }
                }
            }
            for lang in langs {
                // vals: key -> Option<Value>; None is JS undefined.
                let mut vals: Vec<(String, Option<Value>)> = Vec::new();
                fn set(vals: &mut Vec<(String, Option<Value>)>, k: &str, v: Option<Value>) {
                    if let Some(s) = vals.iter_mut().find(|(a, _)| a == k) {
                        s.1 = v;
                    } else {
                        vals.push((k.to_string(), v));
                    }
                }
                fn get(vals: &[(String, Option<Value>)], k: &str) -> Option<Value> {
                    vals.iter()
                        .find(|(a, _)| a == k)
                        .and_then(|(_, v)| v.clone())
                }
                if let Some(lang) = &lang {
                    let keys = item
                        .get("multi")
                        .and_then(|m| m.get("_keys"))
                        .cloned()
                        .unwrap_or(Value::Null);
                    if js::truthy_opt(keys.get(&title.title)) {
                        set(
                            &mut vals,
                            &title.title,
                            keys[&title.title].get(lang).cloned(),
                        );
                    }
                    if js::truthy_opt(keys.get(&title.short)) {
                        set(
                            &mut vals,
                            &title.short,
                            keys[&title.short].get(lang).cloned(),
                        );
                    }
                } else {
                    set(&mut vals, &title.title, item.get(&title.title).cloned());
                    set(&mut vals, &title.short, item.get(&title.short).cloned());
                }
                let t = get(&vals, &title.title);
                set(&mut vals, &title.main, t.clone());
                set(&mut vals, &title.sub, Some(Value::Bool(false)));
                let short_title = get(&vals, &title.short);
                if js::truthy_opt(t.as_ref()) {
                    let t = t.clone().unwrap_or(Value::Null);
                    let title_text = text_of(&t)?.to_string();
                    // Rules
                    // TITLE_SPLIT eliminates split-points of period-space
                    // preceded by a capital letter. If short title exists and
                    // matches exactly to a split-point, use that split-point
                    // only. Otherwise if there is just one split-point, use
                    // that as main/sub split.
                    let set_str = |vals: &mut Vec<(String, Option<Value>)>, k: &str, v: &str| {
                        set(vals, k, Some(Value::String(v.to_string())))
                    };
                    if js::truthy_opt(short_title.as_ref())
                        && text_of(short_title.as_ref().unwrap_or(&Value::Null))?.to_lowercase()
                            == title_text.to_lowercase()
                    {
                        set_str(&mut vals, &title.main, &title_text);
                        set_str(&mut vals, &title.subjoin, "");
                        set_str(&mut vals, &title.sub, "");
                    } else if js::truthy_opt(short_title.as_ref()) {
                        let short_text =
                            text_of(short_title.as_ref().unwrap_or(&Value::Null))?.to_string();
                        static QE_END: LazyLock<Regex> =
                            LazyLock::new(|| Regex::new(r"[?!]+$").expect("static"));
                        static QE_START: LazyLock<Regex> =
                            LazyLock::new(|| Regex::new(r"^[?!]+").expect("static"));
                        // check for valid match to shortTitle
                        let short_trim = QE_END.replace(&short_text, "").into_owned();
                        let tail = js::slice(&title_text, js::len(&short_trim) as i64, None);
                        let tail_stripped = QE_START.replace(&tail, "").into_owned();
                        let top = js::trim(&title_text.replacen(&tail_stripped, "", 1)).to_string();
                        let m = TITLE_SPLIT_REGEXP.matchfirst.captures(&tail);
                        if m.is_some() && top.to_lowercase() == short_text.to_lowercase() {
                            let m1 = m.as_ref().map(|c| c[1].to_string()).unwrap_or_default();
                            static QE_WS: LazyLock<Regex> = LazyLock::new(|| {
                                Regex::new(&format!("[?!]+({WS_CLASS}*)$")).expect("static")
                            });
                            set_str(&mut vals, &title.main, &top);
                            set_str(&mut vals, &title.subjoin, &QE_WS.replace(&m1, "${1}"));
                            set_str(
                                &mut vals,
                                &title.sub,
                                &TITLE_SPLIT_REGEXP.matchfirst.replace(&tail, ""),
                            );
                            if dev("force_short_title_casing_alignment") {
                                let main = get(&vals, &title.main);
                                set(&mut vals, &title.short, main);
                            }
                        } else {
                            let split_title = title_split(&title_text);
                            if split_title.len() == 3 {
                                set_str(&mut vals, &title.main, &split_title[0]);
                                set_str(&mut vals, &title.subjoin, &split_title[1]);
                                set_str(&mut vals, &title.sub, &split_title[2]);
                            } else {
                                set_str(&mut vals, &title.main, &title_text);
                                set_str(&mut vals, &title.subjoin, "");
                                set_str(&mut vals, &title.sub, "");
                            }
                        }
                    } else {
                        let split_title = title_split(&title_text);
                        if split_title.len() == 3 {
                            set_str(&mut vals, &title.main, &split_title[0]);
                            set_str(&mut vals, &title.subjoin, &split_title[1]);
                            set_str(&mut vals, &title.sub, &split_title[2]);
                            if dev("implicit_short_title")
                                && js::get_str(item, "type") != Some("legal_case")
                            {
                                static NUMERIC_MAIN: LazyLock<Regex> =
                                    LazyLock::new(|| Regex::new(r"^[\-.\[0-9]+$").expect("static"));
                                if !js::get_truthy(item, &title.short)
                                    && !NUMERIC_MAIN.is_match(&split_title[0])
                                {
                                    let mut punct = js::trim(&split_title[1]).to_string();
                                    if punct != "?" && punct != "!" {
                                        punct = String::new();
                                    }
                                    set_str(
                                        &mut vals,
                                        &title.short,
                                        &format!("{}{}", split_title[0], punct),
                                    );
                                }
                            }
                        } else {
                            set_str(&mut vals, &title.main, &title_text);
                            set_str(&mut vals, &title.subjoin, "");
                            set_str(&mut vals, &title.sub, "");
                        }
                    }
                    let subjoin = get(&vals, &title.subjoin);
                    if js::truthy_opt(subjoin.as_ref()) {
                        let sj = text_of(subjoin.as_ref().unwrap_or(&Value::Null))?.to_string();
                        if sj.contains('?') || sj.contains('!') {
                            static TRAIL_WS: LazyLock<Regex> = LazyLock::new(|| {
                                Regex::new(&format!("({WS_CLASS}*)$")).expect("static")
                            });
                            let m1 = TRAIL_WS
                                .captures(&sj)
                                .map(|c| c[1].to_string())
                                .unwrap_or_default();
                            let main = get(&vals, &title.main)
                                .map(|v| js::to_js_string(&v))
                                .unwrap_or_else(|| "undefined".to_string());
                            set_str(
                                &mut vals,
                                &title.main,
                                &format!("{main}{narrow_space}{}", js::trim(&sj)),
                            );
                            set_str(&mut vals, &title.subjoin, &m1);
                        }
                    }
                }
                let subjoin = get(&vals, &title.subjoin);
                if js::truthy_opt(subjoin.as_ref()) {
                    let mut sj = js::to_js_string(subjoin.as_ref().unwrap_or(&Value::Null));
                    if sj.contains(':') {
                        sj = format!("{narrow_space}: ");
                    }
                    if sj.contains('-') || sj.contains('\u{2014}') {
                        sj = "\u{2014}".to_string();
                    }
                    set(&mut vals, &title.subjoin, Some(Value::String(sj)));
                }
                if let Some(lang) = &lang {
                    let multi = item
                        .entry("multi".to_string())
                        .or_insert_with(|| Value::Object(Obj::new()));
                    let keys = match multi.get_mut("_keys") {
                        Some(k) if k.is_object() => k,
                        _ => {
                            return Err(js_type_error(
                                "Cannot read properties of undefined (reading '_keys')",
                            ))
                        }
                    };
                    for (key, v) in vals {
                        let slot = keys
                            .as_object_mut()
                            .map(|o| o.entry(key).or_insert_with(|| Value::Object(Obj::new())));
                        if let Some(Value::Object(o)) = slot {
                            match v {
                                Some(v) => {
                                    o.insert(lang.clone(), v);
                                }
                                None => {
                                    o.remove(lang);
                                }
                            }
                        }
                    }
                } else {
                    for (key, v) in vals {
                        match v {
                            Some(v) => {
                                item.insert(key, v);
                            }
                            None => {
                                item.remove(&key);
                            }
                        }
                    }
                }
            }
        }
        Ok(())
    }

    /// `CSL.titlecaseSentenceOrNormal(state, Item, seg, lang, sentenceCase)`:
    /// the title, optionally sentence-cased, rebuilt from its main/sub parts
    /// (or, for `uppercase_subtitles`, with each part capitalised). Always the
    /// full title, never the short one (upstream's comment).
    pub fn titlecase_sentence_or_normal(
        &self,
        item: &Obj,
        seg: &str,
        lang: Option<&str>,
        sentence_case: bool,
    ) -> CslResult<String> {
        let title = title_field_splits(seg);
        let mut vals: Vec<(String, Option<Value>)> = Vec::new();
        let multi = item.get("multi").filter(|m| js::truthy(m));
        if let (Some(lang), Some(multi)) = (lang.filter(|l| !l.is_empty()), multi) {
            let keys = multi.get("_keys").cloned().unwrap_or(Value::Null);
            for k in [&title.title, &title.main, &title.sub, &title.subjoin] {
                if js::truthy_opt(keys.get(k)) {
                    vals.push((k.clone(), keys[k].get(lang).cloned()));
                }
            }
        } else {
            for k in [&title.title, &title.main, &title.sub, &title.subjoin] {
                vals.push((k.clone(), item.get(k).cloned()));
            }
        }
        let get = |k: &str| {
            vals.iter()
                .find(|(a, _)| a == k)
                .and_then(|(_, v)| v.clone())
        };
        let s = |v: Option<Value>| v.map(|v| js::to_js_string(&v)).unwrap_or_default();
        if js::truthy_opt(get(&title.main).as_ref()) && js::truthy_opt(get(&title.sub).as_ref()) {
            let mut main_title = s(get(&title.main));
            let sub_join = s(get(&title.subjoin));
            let mut sub_title = s(get(&title.sub));
            if sentence_case {
                main_title = formatters::sentence(self, &main_title);
                sub_title = formatters::sentence(self, &sub_title);
            } else if self
                .opt
                .get("development_extensions")
                .and_then(|d| d.get("uppercase_subtitles"))
                .map(js::truthy)
                .unwrap_or(false)
            {
                sub_title = formatters::capitalize_first(self, &sub_title);
            }
            Ok(format!("{main_title}{sub_join}{sub_title}"))
        } else if js::truthy_opt(get(&title.title).as_ref()) {
            let whole = s(get(&title.title));
            if sentence_case {
                Ok(formatters::sentence(self, &whole))
            } else if self
                .opt
                .get("development_extensions")
                .and_then(|d| d.get("uppercase_subtitles"))
                .map(js::truthy)
                .unwrap_or(false)
            {
                // Split and apply everywhere.
                let mut splits = title_split(&whole);
                let mut i = 0;
                while i < splits.len() {
                    splits[i] = formatters::capitalize_first(self, &splits[i]);
                    i += 2;
                }
                let mut i = 1;
                while i + 1 < splits.len() {
                    static QSEP: LazyLock<Regex> =
                        LazyLock::new(|| Regex::new(r"([:?!] )").expect("static"));
                    if let Some(m) = QSEP.captures(&splits[i]) {
                        let fr = js::get_str(&self.opt, "default-locale").is_some()
                            || self
                                .opt
                                .get("default-locale")
                                .and_then(|d| d.get(0))
                                .and_then(Value::as_str)
                                .map(|d| js::slice(d, 0, Some(2)).to_lowercase() == "fr")
                                .unwrap_or(false);
                        let narrow = if self
                            .opt
                            .get("default-locale")
                            .and_then(|d| d.get(0))
                            .and_then(Value::as_str)
                            .map(|d| js::slice(d, 0, Some(2)).to_lowercase() == "fr")
                            .unwrap_or(false)
                        {
                            "\u{202f}"
                        } else {
                            ""
                        };
                        let _ = fr;
                        splits[i] = format!("{narrow}{}", &m[1]);
                    }
                    if splits[i].contains('-') || splits[i].contains('\u{2014}') {
                        splits[i] = "\u{2014}".to_string();
                    }
                    i += 2;
                }
                Ok(splits.concat())
            } else {
                Ok(whole)
            }
        } else {
            Ok(String::new())
        }
    }
}

/// What `CSL.getSafeEscape(state)` returns: the escaper to use for the
/// current area (load.js:1026). Evaluate it with [`SafeEscape::escape`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SafeEscape {
    /// `false`: the identity function (area is not citation/bibliography).
    active: bool,
    format: Format,
    /// The `thin_non_breaking_space_html_hack` callback is on.
    thin_hack: bool,
}

impl SafeEscape {
    /// Apply the escaper.
    pub fn escape(&self, txt: &str) -> String {
        if !self.active {
            return txt.to_string();
        }
        if self.thin_hack {
            let t = txt.replace(
                '\u{202f}',
                "<span style=\"white-space:nowrap\">&thinsp;</span>",
            );
            return text_escape(self.format, &t);
        }
        text_escape(self.format, txt)
    }
}

/// `CSL.getSafeEscape(state)`.
///
/// Reads `state.tmp.area`, `state.opt.mode` and
/// `state.opt.development_extensions.thin_non_breaking_space_html_hack`
/// (an object inside `state.opt`).
pub fn get_safe_escape(state: &State) -> SafeEscape {
    let area = state.tmp.area.as_str();
    let active = area == "bibliography" || area == "citation";
    let format = current_format(state);
    let thin = state
        .opt
        .get("development_extensions")
        .and_then(Value::as_object)
        .and_then(|o| o.get("thin_non_breaking_space_html_hack"))
        .map(js::truthy)
        .unwrap_or(false);
    SafeEscape {
        active,
        format,
        thin_hack: active && thin && format == Format::Html,
    }
}


