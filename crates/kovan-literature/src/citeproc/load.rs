fn strip_tags_and_trailing_space(prefix: &str) -> String {
    static TAGS: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"<[^>]+>").expect("static"));
    static TRAIL: LazyLock<Regex> = LazyLock::new(|| {
        Regex::new("[\"'\u{201d}\u{2019}\u{00bb}\u{202f}\u{00a0} ]+$").expect("static")
    });
    let s = TAGS.replace_all(prefix, "");
    TRAIL.replace_all(&s, "").into_owned()
}

/// `CSL.checkPrefixSpaceAppend(state, prefix)`: `prefix` with a space
/// appended when it ends in a letter, terminal punctuation, `)`, `]`, `,` or
/// a digit (after stripping markup and trailing quotes), and runs of white
/// space collapsed.
pub fn check_prefix_space_append(_state: &State, prefix: &str) -> String {
    let mut sp = "";
    let test_prefix = strip_tags_and_trailing_space(prefix);
    let test_char = js::slice(&test_prefix, -1, None);
    static BRACKET_DIGIT: LazyLock<Regex> =
        LazyLock::new(|| Regex::new(r"[\)\],0-9]").expect("static"));
    if ENDSWITH_ROMANESQUE_REGEXP.is_match(&test_prefix) {
        sp = " ";
    } else if TERMINAL_PUNCTUATION[..TERMINAL_PUNCTUATION.len() - 1].contains(&test_char.as_str()) {
        sp = " ";
    } else if BRACKET_DIGIT.is_match(&test_char) {
        sp = " ";
    }
    // Protect against double spaces, which would trigger an extra,
    // explicit, non-breaking space.
    static RUNS: LazyLock<Regex> =
        LazyLock::new(|| Regex::new(&format!("{WS_CLASS}+")).expect("static"));
    RUNS.replace_all(&format!("{prefix}{sp}"), " ").into_owned()
}

/// `CSL.checkIgnorePredecessor(state, prefix)`: true (and
/// `state.tmp.term_predecessor = false`) when the prefix ends in terminal
/// punctuation and holds a space.
pub fn check_ignore_predecessor(state: &mut State, prefix: &str) -> bool {
    let test_prefix = strip_tags_and_trailing_space(prefix);
    let test_char = js::slice(&test_prefix, -1, None);
    if TERMINAL_PUNCTUATION[..TERMINAL_PUNCTUATION.len() - 1].contains(&test_char.as_str())
        && js::index_of(js::trim(prefix), " ", 0) > -1
    {
        state.tmp.term_predecessor = false;
        return true;
    }
    false
}

/// `CSL.checkSuffixSpacePrepend(state, suffix)`: a space before a suffix
/// that starts with a letter, `&`, `[` or `(`.
pub fn check_suffix_space_prepend(_state: &State, suffix: &str) -> String {
    if suffix.is_empty() {
        return String::new();
    }
    let first = js::slice(suffix, 0, Some(1));
    if STARTSWITH_ROMANESQUE_REGEXP.is_match(suffix) || first == "[" || first == "(" {
        return format!(" {suffix}");
    }
    suffix.to_string()
}

