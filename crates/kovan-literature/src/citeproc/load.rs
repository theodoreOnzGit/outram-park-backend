/// `CSL.GET_COURT_CLASS.call(token, state, Item, sortKey)`: the class a
/// court belongs to, looked up in the token's locale (`lang`, the `this.lang`
/// of the attribute handler) and then in the default locale. `""` when none.
pub fn get_court_class(state: &State, lang: Option<&str>, item: &Value, sort_key: bool) -> String {
    let jurisdiction = item.get("jurisdiction").and_then(Value::as_str);
    let country = jurisdiction
        .filter(|j| !j.is_empty())
        .map(|j| j.split(':').next().unwrap_or("").to_string());
    let class_type = if sort_key {
        "court_key_classes"
    } else {
        "court_condition_classes"
    };
    let mut authority: Option<String> = None;
    if country.is_some() && js::truthy_opt(item.get("authority")) {
        match item.get("authority") {
            Some(Value::String(a)) => authority = Some(a.clone()),
            Some(a) => {
                if let Some(lit) = a.get(0).and_then(|f| f.get("literal")) {
                    if js::truthy(lit) {
                        authority = Some(js::to_js_string(lit));
                    }
                }
            }
            None => {}
        }
    }
    if let (Some(authority), Some(country)) = (authority, country) {
        let find = |tag: &str| -> Option<String> {
            state
                .locale
                .get(tag)
                .and_then(|l| l.opts.get(class_type))
                .and_then(|c| c.get(&country))
                .and_then(|c| c.get(&authority))
                .filter(|v| js::truthy(v))
                .map(js::to_js_string)
        };
        if let Some(l) = lang.filter(|l| !l.is_empty()) {
            if let Some(c) = find(l) {
                return c;
            }
        }
        let default_locale = state
            .opt
            .get("default-locale")
            .and_then(|d| d.get(0))
            .and_then(Value::as_str)
            .unwrap_or("");
        if let Some(c) = find(default_locale) {
            return c;
        }
    }
    String::new()
}

/// `CSL.SET_COURT_CLASSES(state, lang, myxml, dataObj)`: record the
/// `court-class` nodes of `data_obj` in `state.locale[lang].opts`, under
/// `court_key_classes` (in-style declarations, before the registry exists) or
/// `court_condition_classes` (in-module).
pub fn set_court_classes(
    state: &mut State,
    lang: &str,
    myxml: &XmlJson,
    data_obj: Option<NodeId>,
) -> CslResult<()> {
    let nodes = myxml.get_nodes_by_name(data_obj, "court-class", "");
    for node in nodes {
        let attributes = myxml.attributes(node);
        let attr = |k: &str| {
            attributes
                .iter()
                .find(|(a, _)| a == k)
                .map(|(_, v)| js::to_js_string(v))
        };
        let cls = attr("@name");
        let country = attr("@country");
        let courts = attr("@courts");

        // Okay, this is a hack.
        // If state.registry IS NOT yet defined, this is an in-style declaration.
        // If state.registry IS defined, this is an in-module declaration.
        let class_type = if state.has_registry {
            "court_condition_classes"
        } else {
            "court_key_classes"
        };
        if let (Some(cls), Some(country), Some(courts)) = (
            cls.filter(|s| !s.is_empty()),
            country.filter(|s| !s.is_empty()),
            courts.filter(|s| !s.is_empty()),
        ) {
            static WS_RUN: LazyLock<Regex> =
                LazyLock::new(|| Regex::new(&format!("{WS_CLASS}+")).expect("static"));
            let courts = js::split(&WS_RUN, js::trim(&courts));
            let locale = state.locale.get_mut(lang).ok_or_else(|| {
                js_type_error("Cannot read properties of undefined (reading 'opts')")
            })?;
            let by_type = locale
                .opts
                .entry(class_type.to_string())
                .or_insert_with(|| Value::Object(Obj::new()));
            let by_country = by_type.as_object_mut().map(|o| {
                o.entry(country)
                    .or_insert_with(|| Value::Object(Obj::new()))
            });
            if let Some(Value::Object(by_country)) = by_country {
                for court in courts {
                    by_country.insert(court, Value::String(cls.clone()));
                }
            }
        }
    }
    Ok(())
}

/// `CSL.INIT_JURISDICTION_MACROS(state, Item, item, macroName)`: load the
/// style modules for the item's jurisdiction and record the best one in
/// `Item["best-jurisdiction"]`; true when the item's type is covered.
///
/// With no `sys.retrieveStyleModule` hook (`Sys::has_retrieve_style_module`
/// is false) this returns false right after the `best-jurisdiction` check,
/// as upstream does.
pub fn init_jurisdiction_macros(
    state: &mut State,
    item_full: &mut Value,
    cite_item: Option<&Value>,
    macro_name: &str,
) -> CslResult<bool> {
    if js::truthy_opt(item_full.get("best-jurisdiction")) {
        return Ok(true);
    }
    let jurisdiction = item_full
        .get("jurisdiction")
        .filter(|j| js::truthy(j))
        .map(js::to_js_string);
    let Some(jurisdiction) = jurisdiction else {
        return Ok(false);
    };
    if !state.sys.has_retrieve_style_module() || !is_module_macro(macro_name) {
        return Ok(false);
    }
    let jurisdiction_list = state.get_jurisdiction_list(&jurisdiction);
    let seen = state
        .opt
        .get("jurisdictions_seen")
        .and_then(|s| s.get(&jurisdiction_list[0]))
        .map(js::truthy)
        .unwrap_or(false);
    if !seen {
        let mut res = state.retrieve_all_style_modules(&jurisdiction_list);
        // Okay. We have code for each of the novel modules in the
        // hierarchy. Load them all into the processor.
        let keys: Vec<String> = res.iter().map(|(k, _)| k.clone()).collect();
        for j in keys {
            let src = res.iter().find(|(k, _)| *k == j).map(|(_, v)| v.clone());
            let fallback = state.load_style_module(&j, src.as_deref().unwrap_or(""), false)?;
            if let Some(fallback) = fallback {
                if !res.iter().any(|(k, _)| *k == fallback) {
                    for (k, v) in state.retrieve_all_style_modules(&[fallback.clone()]) {
                        if let Some(s) = res.iter_mut().find(|(a, _)| *a == k) {
                            s.1 = v;
                        } else {
                            res.push((k, v));
                        }
                    }
                    let src = res
                        .iter()
                        .find(|(k, _)| *k == fallback)
                        .map(|(_, v)| v.clone());
                    state.load_style_module(&fallback, src.as_deref().unwrap_or(""), true)?;
                }
            }
        }
    }
    let jurisdiction_list = state.get_jurisdiction_list(&jurisdiction);
    if state
        .opt
        .get("parallel")
        .and_then(|p| p.get("enable"))
        .map(js::truthy)
        .unwrap_or(false)
        && state.parallel.is_none()
    {
        state.parallel = Some(Default::default());
    }
    // Identify the best jurisdiction for the item and return true, otherwise return false
    let item_type = item_full
        .get("type")
        .map(js::to_js_string)
        .unwrap_or_default();
    for j in jurisdiction_list {
        if let Some(juris) = state.juris.get(&j) {
            if cite_item.is_some()
                && !js::truthy_opt(cite_item.and_then(|c| c.get("best-jurisdiction")))
                && juris.types.contains("locator")
            {
                if let Some(o) = item_full.as_object_mut() {
                    o.insert("best-jurisdiction".into(), Value::String(j.clone()));
                }
            }
            if juris.types.contains(item_type.as_str()) {
                if let Some(o) = item_full.as_object_mut() {
                    o.insert("best-jurisdiction".into(), Value::String(j.clone()));
                }
                return Ok(true);
            }
        }
    }
    Ok(false)
}

