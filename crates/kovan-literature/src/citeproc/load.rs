/// `CSL.UPDATE_GROUP_CONTEXT_CONDITION(state, str, valueTerm, token, value)`.
pub fn update_group_context_condition(
    state: &mut State,
    s: Option<&str>,
    value_term: bool,
    token: Option<&Token>,
    value: Option<&str>,
) {
    if !js::get_truthy(&state.opt, "use_context_condition") {
        return;
    }
    let has_condition = state
        .tmp
        .group_context
        .tip()
        .map(|f| f.condition.is_some())
        .unwrap_or(false);
    if has_condition {
        if let Some(flags) = state.tmp.group_context.tip_mut() {
            let mut numbers_only_value_seen = false;
            if let Some(cond) = flags.condition.as_mut() {
                if cond.termtxt.as_deref().map(str::is_empty).unwrap_or(true) {
                    cond.termtxt = s.map(str::to_string);
                    cond.value_term = value_term;
                }
                numbers_only_value_seen =
                    !flags.value_seen && cond.test == "comma-safe-numbers-only";
            }
            if numbers_only_value_seen {
                if let Some(v) = value.filter(|v| !v.is_empty()) {
                    flags.value_seen = true;
                    if !v.starts_with(|c: char| c.is_ascii_digit()) {
                        state.tmp.just_did_number = false;
                    }
                }
            }
        }
    } else {
        // If not inside a conditional group, raise numeric flag
        // if and only if the current term string ends in a number.
        if token
            .map(|t| t.decorations.iter().any(|d| d.name == "@vertical-align"))
            .unwrap_or(false)
        {
            state.tmp.just_did_number = false;
        } else if token
            .map(|t| js::truthy_opt(t.strings.get("suffix")))
            .unwrap_or(false)
        {
            state.tmp.just_did_number = false;
        } else if let Some(s) = s.filter(|s| !s.is_empty()) {
            state.tmp.just_did_number = s.ends_with(|c: char| c.is_ascii_digit());
        }
    }
}

/// `CSL.EVALUATE_GROUP_CONDITION(state, flags)`: `force_suppress` for a
/// conditional group once its content is known. `None` is upstream's early
/// `return;` (the context condition is not enabled).
pub fn evaluate_group_condition(state: &State, flags: &super::state::GroupContext) -> Option<bool> {
    if !js::get_truthy(&state.opt, "use_context_condition") {
        return None;
    }
    let cond = flags.condition.as_ref()?;
    let numbers_only = cond.test == "comma-safe-numbers-only";
    let termtxt = cond.termtxt.as_deref().unwrap_or("");
    let mut testres = false;
    if cond.test == "empty-label" {
        testres = termtxt.is_empty();
    } else if cond.test == "empty-label-no-decor" {
        testres = termtxt.is_empty() || termtxt.contains("%s");
    } else if cond.test == "comma-safe" || cond.test == "comma-safe-numbers-only" {
        let locale_term = !termtxt.is_empty();
        let term_start_alpha =
            locale_term && ALL_ROMANESQUE_REGEXP.is_match(&js::slice(termtxt, 0, Some(1)));
        let require = js::get_str(&state.opt, "require_comma_on_symbol");
        if state.tmp.just_did_number {
            if cond.value_term {
                testres = !numbers_only;
            } else if !locale_term {
                testres = true;
            } else if term_start_alpha {
                testres = !numbers_only;
            } else {
                testres = matches!(require, Some("always") | Some("after-number"));
            }
        } else if cond.value_term {
            testres = false;
        } else if !locale_term {
            testres = false;
        } else if term_start_alpha {
            testres = !numbers_only;
        } else {
            testres = require == Some("always");
        }
    }
    let mut force_suppress = !testres;
    if cond.not {
        force_suppress = !force_suppress;
    }
    Some(force_suppress)
}

