/// Whether the first language tag of `arr` selects Turkic casing.
fn turkic(arr: &[String]) -> bool {
    arr.first()
        .map(|t| {
            let p = t.split(['-', '_']).next().unwrap_or("").to_lowercase();
            p == "tr" || p == "az"
        })
        .unwrap_or(false)
}

/// `CSL.toLocaleUpperCase.call(state, str)`: `str.toLocaleUpperCase(
/// state.tmp.lang_array)`. Locale-sensitive casing is implemented for the
/// Turkic languages (`i` to `İ`); other tags use the root mapping, which is
/// what ICU does for them except Lithuanian and Greek (not ported).
pub fn to_locale_upper_case(state: &State, s: &str) -> String {
    if turkic(&state.tmp.lang_array) {
        let mut out = String::new();
        for c in s.chars() {
            match c {
                'i' => out.push('\u{130}'),
                'ı' => out.push('I'),
                c => out.extend(c.to_uppercase()),
            }
        }
        out
    } else {
        s.to_uppercase()
    }
}

/// `CSL.toLocaleLowerCase.call(state, str)`; see [`to_locale_upper_case`]
/// (Turkic: `I` to `ı`, `İ` to `i`).
pub fn to_locale_lower_case(state: &State, s: &str) -> String {
    if turkic(&state.tmp.lang_array) {
        let mut out = String::new();
        for c in s.chars() {
            match c {
                'I' => out.push('\u{131}'),
                '\u{130}' => out.push('i'),
                c => out.extend(c.to_lowercase()),
            }
        }
        out
    } else {
        s.to_lowercase()
    }
}

// ----------------------------------------------------------------------
// Brace nesting.

/// `new CSL.checkNestedBrace(state)`: flips the parentheses of nested
/// affixes in a note style (`(a (b))` to `(a [b])`).
#[derive(Debug, Clone, Default, PartialEq)]
pub struct CheckNestedBrace {
    /// `depth`.
    pub depth: i64,
    /// Whether `state.opt.xclass === "note"` (otherwise `update` is the identity).
    note: bool,
}

impl CheckNestedBrace {
    /// `new CSL.checkNestedBrace(state)`.
    pub fn new(state: &State) -> CheckNestedBrace {
        CheckNestedBrace {
            depth: 0,
            note: js::get_str(&state.opt, "xclass") == Some("note"),
        }
    }

    /// `this.update(str)`: receives an affix string, returns it with
    /// parentheses flipped to brackets at odd nesting depths.
    pub fn update(&mut self, s: &str) -> String {
        if !self.note {
            return s.to_string();
        }
        let mut out = String::with_capacity(s.len());
        for c in s.chars() {
            match c {
                '(' => {
                    out.push(if self.depth % 2 == 1 { '[' } else { '(' });
                    self.depth += 1;
                }
                ')' => {
                    out.push(if self.depth % 2 == 0 { ']' } else { ')' });
                    self.depth -= 1;
                }
                c => out.push(c),
            }
        }
        out
    }
}

