/// `CSL.normalizeLocaleStr(str)`: language lower-case, region upper-case
/// (`en-us` to `en-US`). `None` is JS `undefined` (empty input).
pub fn normalize_locale_str(s: &str) -> Option<String> {
    if s.is_empty() {
        return None;
    }
    let mut lst: Vec<String> = s.split('-').map(str::to_string).collect();
    lst[0] = lst[0].to_lowercase();
    if lst.len() > 1 && !lst[1].is_empty() {
        lst[1] = lst[1].to_uppercase();
    }
    Some(lst.join("-"))
}

/// `CSL.getAbbrevsDomain(state, country, lang)`: the jurisdiction domain
/// whose abbreviations apply, from the item's locale's and the engine's
/// `jurisdiction-preference` (last preferred first).
pub fn get_abbrevs_domain(state: &State, country: &str, lang: &str) -> Option<String> {
    let available = state.opt.get("availableAbbrevDomains");
    if js::truthy_opt(available) && !country.is_empty() && country != "default" {
        let pref_of = |tag: &str| -> Option<Vec<Value>> {
            match state
                .locale
                .get(tag)
                .and_then(|l| l.opts.get("jurisdiction-preference"))
            {
                Some(Value::Array(a)) => Some(a.clone()),
                _ => None,
            }
        };
        let global = pref_of(js::get_str(&state.opt, "lang").unwrap_or(""));
        let item = pref_of(lang);
        let domains: Vec<Value> = match available.and_then(|a| a.get(country)) {
            Some(Value::Array(a)) => a.clone(),
            _ => Vec::new(),
        };
        for pref in [item, global].into_iter().flatten() {
            for j in (0..pref.len()).rev() {
                if domains.contains(&pref[j]) {
                    return pref[j].as_str().map(str::to_string);
                }
            }
        }
    }
    None
}

