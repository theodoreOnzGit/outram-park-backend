/// `CSL.parseLocator.call(state, item)`: splits `locator|date extra` into
/// `locator`, `locator-date` and `locator-extra` when
/// `locator_date_and_revision` is on, and trims trailing space of `locator`.
pub fn parse_locator(state: &State, item: &mut Obj) {
    let ext_on = state
        .opt
        .get("development_extensions")
        .and_then(|d| d.get("locator_date_and_revision"))
        .map(js::truthy)
        .unwrap_or(false);
    if ext_on && js::get_truthy(item, "locator") {
        let loc = js::get_string(item, "locator").unwrap_or_default();
        item.insert("locator".into(), Value::String(loc.clone()));
        let idx = js::index_of(&loc, "|", 0);
        if idx > -1 {
            let mut raw_locator = loc.clone();
            item.insert(
                "locator".into(),
                Value::String(js::slice(&raw_locator, 0, Some(idx))),
            );
            raw_locator = js::slice(&raw_locator, idx + 1, None);
            static DATE: LazyLock<Regex> =
                LazyLock::new(|| Regex::new(r"^([0-9]{4}-[0-9]{2}-[0-9]{2})").expect("static"));
            if let Some(m) = DATE.captures(&raw_locator) {
                let m1 = m[1].to_string();
                item.insert(
                    "locator-date".into(),
                    Value::Object(state.fun.dateparser.parse_date_to_object(&m1)),
                );
                raw_locator = js::slice(&raw_locator, js::len(&m1) as i64, None);
            }
            item.insert(
                "locator-extra".into(),
                Value::String(js::trim(&raw_locator).to_string()),
            );
        }
    }
    if js::get_truthy(item, "locator") {
        static TRAILING: LazyLock<Regex> =
            LazyLock::new(|| Regex::new(&format!("{WS_CLASS}+$")).expect("static"));
        let loc = js::get_string(item, "locator").unwrap_or_default();
        item.insert(
            "locator".into(),
            Value::String(TRAILING.replace(&loc, "").into_owned()),
        );
    }
}

/// `CSL.parseNoteFieldHacks(Item, validFieldsForType, allowDateOverride)`:
/// lift `{:key:value}` and `key: value` lines of the `note` field into the
/// item. The engine calls it with `validFieldsForType = false`; a non-`None`
/// set reaches `this.isDateString`, which does not exist on `CSL`, so a date
/// field with one throws, as upstream.
pub fn parse_note_field_hacks(
    state: &State,
    item: &mut Obj,
    valid_fields_for_type: Option<&Obj>,
    allow_date_override: bool,
) -> CslResult<()> {
    let note = match item.get("note") {
        Some(Value::String(s)) => s.clone(),
        _ => return Ok(()),
    };
    let mut lines: Vec<String> = note.split('\n').map(str::to_string).collect();
    // Normalize entries
    for i in 0..lines.len() {
        let line = lines[i].clone();
        let m: Vec<String> = NOTE_FIELDS_REGEXP
            .find_iter(&line)
            .map(|m| m.as_str().to_string())
            .collect();
        if !m.is_empty() {
            let splt = js::split(&NOTE_FIELDS_REGEXP, &line);
            let mut elems: Vec<String> = Vec::new();
            for j in 0..splt.len() - 1 {
                elems.push(splt[j].clone());
                elems.push(m.get(j).cloned().unwrap_or_else(|| "undefined".to_string()));
            }
            elems.push(splt[splt.len() - 1].clone());
            let mut j = 1;
            while j < elems.len() {
                // Abort conversions if preceded by unparseable text
                if !js::trim(&elems[j - 1]).is_empty()
                    && (i > 0 || j > 1)
                    && !NOTE_FIELD_REGEXP.is_match(&elems[j - 1])
                {
                    break;
                } else {
                    let inner = js::slice(&elems[j], 2, Some(-1));
                    elems[j] = format!("\n{}\n", js::trim(&inner));
                }
                j += 2;
            }
            lines[i] = elems.concat();
        }
    }
    // Resplit
    let joined = lines.join("\n");
    let mut lines: Vec<String> = joined.split('\n').map(str::to_string).collect();
    let mut names: Vec<(String, Vec<Value>)> = Vec::new();
    for i in 0..lines.len() {
        let line = lines[i].clone();
        let mm = NOTE_FIELD_REGEXP.captures(&line);
        if js::trim(&line).is_empty() {
            continue;
        }
        let Some(mm) = mm else {
            if i == 0 {
                continue;
            } else {
                break;
            }
        };
        let key = mm[1].to_string();
        let val = js::trim(&mm[2]).to_string();
        let bare = key.strip_prefix("alt-").unwrap_or(&key);
        if key == "type" {
            item.insert("type".into(), Value::String(val));
            lines[i] = String::new();
        } else if DATE_VARIABLES.contains(&bare) {
            if !js::get_truthy(item, &key) || allow_date_override {
                item.insert(
                    key.clone(),
                    Value::Object(state.fun.dateparser.parse_date_to_array(&val)),
                );
                let ok = match valid_fields_for_type {
                    None => true,
                    Some(v) => {
                        if js::get_truthy(v, &key) {
                            return Err(EngineError::Csl(
                                "TypeError: this.isDateString is not a function".to_string(),
                            ));
                        }
                        false
                    }
                };
                if ok {
                    lines[i] = String::new();
                }
            }
        } else if !js::get_truthy(item, &key) {
            if NAME_VARIABLES.contains(&bare) {
                if !names.iter().any(|(k, _)| *k == key) {
                    names.push((key.clone(), Vec::new()));
                }
                static SPLIT: LazyLock<Regex> = LazyLock::new(|| {
                    Regex::new(&format!(r"{WS_CLASS}*\|\|{WS_CLASS}*")).expect("static")
                });
                let lst = js::split(&SPLIT, &val);
                let slot = names.iter_mut().find(|(k, _)| *k == key).map(|(_, v)| v);
                if let Some(slot) = slot {
                    if lst.len() == 1 {
                        let mut o = Obj::new();
                        o.insert("literal".into(), Value::String(lst[0].clone()));
                        slot.push(Value::Object(o));
                    } else if lst.len() == 2 {
                        let mut name = Obj::new();
                        name.insert("family".into(), Value::String(lst[0].clone()));
                        name.insert("given".into(), Value::String(lst[1].clone()));
                        parse_particles(&mut name)?;
                        slot.push(Value::Object(name));
                    }
                }
            } else {
                item.insert(key.clone(), Value::String(val));
            }
            if valid_fields_for_type
                .map(|v| js::get_truthy(v, &key))
                .unwrap_or(true)
            {
                lines[i] = String::new();
            }
        }
    }
    for (key, v) in names {
        item.insert(key, Value::Array(v));
    }
    // (The "final cleanup for validCslFields only" block runs only when
    // validFieldsForType is truthy; the engine never passes one.)
    item.insert(
        "note".into(),
        Value::String(js::trim(&lines.join("\n")).to_string()),
    );
    Ok(())
}

