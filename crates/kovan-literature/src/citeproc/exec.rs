//! The closures citeproc-js stores on tokens, as enums (PORTING.md §4).
//!
//! [`Exec`] is a token's `execs` entry, [`Test`] a `tests` entry or its
//! `test` evaluator. Each has one variant per JS file that creates such
//! closures, wrapping that file's own enum (`NodeTextExec`, ...), whose
//! variants carry the captured variables and whose `run`/`eval` holds the
//! translated body. Do not edit this file to add a closure: add a variant to
//! your file's enum.

use serde_json::Value;

use super::obj_token::Token;
use super::state::State;
use super::CslResult;

/// One entry of `token.execs`.
#[derive(Debug, Clone, PartialEq)]
pub enum Exec {
    Attributes(super::attributes::AttributesExec),
    NodeAlternative(super::node_alternative::NodeAlternativeExec),
    NodeAlternativetext(super::node_alternativetext::NodeAlternativetextExec),
    NodeBibliography(super::node_bibliography::NodeBibliographyExec),
    NodeChoose(super::node_choose::NodeChooseExec),
    NodeCitation(super::node_citation::NodeCitationExec),
    NodeDate(super::node_date::NodeDateExec),
    NodeDatepart(super::node_datepart::NodeDatepartExec),
    NodeEtal(super::node_etal::NodeEtalExec),
    NodeGroup(super::node_group::NodeGroupExec),
    NodeInstitution(super::node_institution::NodeInstitutionExec),
    NodeInstitutionpart(super::node_institutionpart::NodeInstitutionpartExec),
    NodeIntext(super::node_intext::NodeIntextExec),
    NodeKey(super::node_key::NodeKeyExec),
    NodeLabel(super::node_label::NodeLabelExec),
    NodeLayout(super::node_layout::NodeLayoutExec),
    NodeName(super::node_name::NodeNameExec),
    NodeNames(super::node_names::NodeNamesExec),
    NodeNumber(super::node_number::NodeNumberExec),
    NodeSort(super::node_sort::NodeSortExec),
    NodeSubstitute(super::node_substitute::NodeSubstituteExec),
    NodeText(super::node_text::NodeTextExec),
    UtilConditions(super::util_conditions::UtilConditionsExec),
    UtilNodes(super::util_nodes::UtilNodesExec),
    UtilSubstitute(super::util_substitute::UtilSubstituteExec),
    UtilDatenode(super::util_datenode::UtilDatenodeExec),
}

impl Exec {
    /// Run the closure: `exec.call(token, state, Item, item)`. A returned
    /// `Some(i)` is the JS closure returning a jump index.
    pub fn run(
        &self,
        state: &mut State,
        token: &mut Token,
        item: &Value,
        cite_item: &Value,
    ) -> CslResult<Option<usize>> {
        match self {
            Exec::Attributes(e) => e.run(state, token, item, cite_item),
            Exec::NodeAlternative(e) => e.run(state, token, item, cite_item),
            Exec::NodeAlternativetext(e) => e.run(state, token, item, cite_item),
            Exec::NodeBibliography(e) => e.run(state, token, item, cite_item),
            Exec::NodeChoose(e) => e.run(state, token, item, cite_item),
            Exec::NodeCitation(e) => e.run(state, token, item, cite_item),
            Exec::NodeDate(e) => e.run(state, token, item, cite_item),
            Exec::NodeDatepart(e) => e.run(state, token, item, cite_item),
            Exec::NodeEtal(e) => e.run(state, token, item, cite_item),
            Exec::NodeGroup(e) => e.run(state, token, item, cite_item),
            Exec::NodeInstitution(e) => e.run(state, token, item, cite_item),
            Exec::NodeInstitutionpart(e) => e.run(state, token, item, cite_item),
            Exec::NodeIntext(e) => e.run(state, token, item, cite_item),
            Exec::NodeKey(e) => e.run(state, token, item, cite_item),
            Exec::NodeLabel(e) => e.run(state, token, item, cite_item),
            Exec::NodeLayout(e) => e.run(state, token, item, cite_item),
            Exec::NodeName(e) => e.run(state, token, item, cite_item),
            Exec::NodeNames(e) => e.run(state, token, item, cite_item),
            Exec::NodeNumber(e) => e.run(state, token, item, cite_item),
            Exec::NodeSort(e) => e.run(state, token, item, cite_item),
            Exec::NodeSubstitute(e) => e.run(state, token, item, cite_item),
            Exec::NodeText(e) => e.run(state, token, item, cite_item),
            Exec::UtilConditions(e) => e.run(state, token, item, cite_item),
            Exec::UtilNodes(e) => e.run(state, token, item, cite_item),
            Exec::UtilSubstitute(e) => e.run(state, token, item, cite_item),
            Exec::UtilDatenode(e) => e.run(state, token, item, cite_item),
        }
    }
}

/// One entry of `token.tests`, or a token's `test` evaluator.
#[derive(Debug, Clone, PartialEq)]
pub enum Test {
    Attributes(super::attributes::AttributesTest),
    NodeGroup(super::node_group::NodeGroupTest),
    NodeSubstitute(super::node_substitute::NodeSubstituteTest),
    UtilConditions(super::util_conditions::UtilConditionsTest),
    UtilSubstitute(super::util_substitute::UtilSubstituteTest),
    /// `CSL.Util.Match`'s evaluators (any/none/all/nand over `tests`); added by
    /// wave1-build (src/util.js).
    Util(super::util::UtilTest),
}

impl Test {
    /// Evaluate: `test(Item, item)` (the JS closure captured `state` at
    /// build time; here it is passed in).
    pub fn eval(
        &self,
        state: &mut State,
        token: &mut Token,
        item: &Value,
        cite_item: &Value,
    ) -> CslResult<bool> {
        match self {
            Test::Attributes(t) => t.eval(state, token, item, cite_item),
            Test::NodeGroup(t) => t.eval(state, token, item, cite_item),
            Test::NodeSubstitute(t) => t.eval(state, token, item, cite_item),
            Test::UtilConditions(t) => t.eval(state, token, item, cite_item),
            Test::UtilSubstitute(t) => t.eval(state, token, item, cite_item),
            Test::Util(t) => t.eval(state, token, item, cite_item),
        }
    }
}
