///   [`calcpar_inputs_identical_in_both_builds`]) that spread is upstream's
///   arithmetic alone.
/// - `v_d` at `u* = 1e-8`: `1.26e-40 m/s` in real(8) and the port, `0` in the
///   shipped build, where the stable-branch `psi_h ~ (z/L)^1.5` overflows
