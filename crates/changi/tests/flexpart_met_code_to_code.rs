struct WetSetup {
    /// [grid][storage slot] fields
    fields: [[WetFields; 2]; 2],
    nest: NestFrame,
    height: Vec<f64>,
    species: Vec<WetScavSpecies>,
    frame_mother: OutputFrame,
    frame_nest: OutputFrame,
    out_dims: [(usize, usize); 2],
}

fn wet_setup(rows: &[Row]) -> WetSetup {
    let nestrow = &one(rows, "wet.nest", |_| true).args;
    let dims = [(6usize, 5usize), (nestrow[6] as usize, nestrow[7] as usize)];
    let height = one(rows, "wet.height", |_| true).args.clone();
    let nz = height.len();
    let mk = |g: usize| {
        let (nx, ny) = dims[g];
        WetFields {
            lsprec: Field2::filled(nx, ny, 0.0),
            convprec: Field2::filled(nx, ny, 0.0),
            tcc: Field2::filled(nx, ny, 0.0),
            clouds: CloudField {
                nx,
                ny,
                nz,
                data: vec![0; nx * ny * nz],
            },
            tt: Field3::filled(nx, ny, nz, 0.0),
            ctwc: Field2::filled(nx, ny, 0.0),
        }
    };
    let mut fields = [[mk(0), mk(0)], [mk(1), mk(1)]];
    for name in ["wet.field", "wet.clouds", "wet.tt"] {
        for r in find(rows, name) {
            let (g, m, k) = (
                r.args[0] as usize,
                r.args[1] as usize - 1,
                r.args[2] as usize,
            );
            let f = &mut fields[g][m];
            match name {
                "wet.field" => {
                    let t = match k {
                        1 => &mut f.lsprec,
                        2 => &mut f.convprec,
                        3 => &mut f.tcc,
                        _ => &mut f.ctwc,
                    };
                    t.data.copy_from_slice(&r.outs);
                }
                "wet.clouds" => {
                    let n = f.clouds.nx * f.clouds.ny;
                    for (i, v) in r.outs.iter().enumerate() {
                        f.clouds.data[i + n * (k - 1)] = *v as i8;
                    }
                }
                _ => {
                    let n = f.tt.nx * f.tt.ny;
                    f.tt.data[n * (k - 1)..n * k].copy_from_slice(&r.outs);
                }
            }
        }
    }
    let mut species = vec![
        WetScavSpecies {
            dquer: 0.0,
            weta_gas: 0.0,
            wetb_gas: 0.0,
            crain_aero: 0.0,
            csnow_aero: 0.0,
            ccn_aero: 0.0,
            in_aero: 0.0,
            henry: 0.0,
        };
        6
    ];
    for r in find(rows, "wet.species") {
        let o = &r.outs;
        species[r.args[0] as usize - 1] = WetScavSpecies {
            dquer: o[0],
            weta_gas: o[1],
            wetb_gas: o[2],
            crain_aero: o[3],
            csnow_aero: o[4],
            ccn_aero: o[5],
            in_aero: o[6],
            henry: o[7],
        };
    }
    let o = &one(rows, "out.grid", |_| true).args;
    WetSetup {
        fields,
        nest: NestFrame {
            xl: nestrow[0],
            xr: nestrow[1],
            yl: nestrow[2],
            yr: nestrow[3],
            xresol: nestrow[4],
            yresol: nestrow[5],
        },
        height,
        species,
        frame_mother: OutputFrame {
            dx: o[0],
            dy: o[1],
            xoutshift: o[2],
            youtshift: o[3],
            dxout: o[4],
            dyout: o[5],
        },
        frame_nest: OutputFrame {
            dx: o[0],
            dy: o[1],
            xoutshift: o[8],
            youtshift: o[9],
            dxout: o[10],
            dyout: o[11],
        },
        out_dims: [
            (o[6] as usize, o[7] as usize),
            (o[12] as usize, o[13] as usize),
        ],
    }
}

impl WetSetup {
    /// `memind1` is the storage slot (1-based) of the earlier field.
    fn met(&self, memind1: usize, readclouds: bool) -> WetScavMet {
        let order = |g: usize| {
            let (a, b) = if memind1 == 1 { (0, 1) } else { (1, 0) };
            WetGrid {
                slots: [self.fields[g][a].clone(), self.fields[g][b].clone()],
                readclouds,
            }
        };
        WetScavMet {
            memtime: [0, 10801],
            height: self.height.clone(),
            mother: order(0),
            nests: vec![(self.nest, order(1))],
        }
    }

    fn grid(&self, g: usize) -> DepositionGrid {
        let (nx, ny) = self.out_dims[g];
        DepositionGrid::zeros(nx, ny, 1, 2, 1, 1)
    }

    fn slice(grid: &DepositionGrid, kp: usize) -> Vec<f64> {
        let mut v = Vec::with_capacity(grid.nx * grid.ny);
        for jy in 0..grid.ny {
            for ix in 0..grid.nx {
                v.push(f64::from(grid.data[grid.index(ix, jy, 0, kp - 1, 0, 0)]));
            }
        }
        v
    }
}

struct WetDepoRun {
    masses: Vec<f64>,
    grids: [DepositionGrid; 2],
    counts: ScavCounts,
}

/// The driver echoes the integer `itra1` through `real()`. The inactive
/// marker `-999999999` is not representable in `f32` and prints as `-1e9` in
/// the real(4) fixture; it is the only such value (the others are small
/// multiples of 100 s), so it is mapped back here.
fn itra1_of(v: f64) -> i64 {
    if v <= -999_999_000.0 {
        -999_999_999
    } else {
        v as i64
    }
}

fn run_wetdepo(rows: &[Row], ws: &WetSetup, run: usize) -> WetDepoRun {
    let a = &one(rows, "wd.run", |r| r.args[0] as usize == run).args;
    let (itime, ltsample, loutnext, loutstep, ldirect) = (
        a[1] as i64,
        a[2] as i64,
        a[3] as i64,
        a[4] as i64,
        a[5] as i64,
    );
    let mut particles: Vec<ParticleRecord> = find(rows, "wd.particle")
        .filter(|r| r.args[0] as usize == run)
        .map(|r| {
            let p = &r.args;
            ParticleRecord {
                itra1: itra1_of(p[2]),
                itramem: p[3] as i64,
                xtra1: p[4],
                ytra1: p[5],
                ztra1: p[6],
                npoint: p[7] as usize,
                nclass: p[8] as usize,
                xmass1: vec![p[9]],
            }
        })
        .collect();
    let mut species = vec![ws.species[a[11] as usize - 1]];
    let met = ws.met(a[12] as usize, false);
    let settings = WetDepoSettings {
        ldirect,
        loutstep,
        lage: vec![86400],
        ioutputforeachrelease: a[8] == 1.0,
        decay: vec![a[9]],
        wetdepspec: vec![a[10] == 1.0],
    };
    let mut mother = WetOutputGrid {
        grid: ws.grid(0),
        frame: ws.frame_mother,
        rule: KernelRule::Mother { use_kernel: true },
    };
    let mut nested = WetOutputGrid {
        grid: ws.grid(1),
        frame: ws.frame_nest,
        rule: KernelRule::Nest,
    };
    let mut counts = ScavCounts {
        blc: vec![0],
        inc: vec![0],
    };
    wetdepo(
        itime,
        ltsample,
        loutnext,
        &mut particles,
        &mut species,
        &met,
        &settings,
        &mut mother,
        (a[7] == 1.0).then_some(&mut nested),
        &mut counts,
    )
    .expect("wetdepo");
    WetDepoRun {
        masses: particles.iter().map(|p| p.xmass1[0]).collect(),
        grids: [mother.grid, nested.grid],
        counts,
    }
}

// ── OH ────────────────────────────────────────────────────────────────────────

fn jr_formula(i: usize, j: usize, m: usize) -> f64 {
    // the driver's jr_formula: integer / 2^20, exact at both precisions
    ((i * 7 + j * 13 + m * 5) % 11) as f64 / 1_048_576.0
}

struct OhSetup {
    clim: OhClimatology,
    jr: JrateClimatology,
    bdate: f64,
    /// gethourlyOH results by (ldirect, itime)
    hourly: HashMap<(i64, i64), HourlyOh>,
    /// ohreaction masses by run
    masses: HashMap<usize, Vec<f64>>,
}

fn oh_setup(rows: &[Row]) -> OhSetup {
    let c = &one(rows, "oh.coords", |_| true).args;
    let (lon, lat, alt) = (c[0..8].to_vec(), c[8..14].to_vec(), c[14..18].to_vec());
    let (nx, ny, nz) = (8, 6, 4);
    let mut field = vec![0.0; nx * ny * nz * 12];
    for r in find(rows, "oh.field") {
        let (m, kz) = (r.args[0] as usize, r.args[1] as usize);
        let off = nx * ny * ((kz - 1) + nz * (m - 1));
        field[off..off + nx * ny].copy_from_slice(&r.outs);
    }
    let clim = OhClimatology {
        lon,
        lat,
        alt,
        field,
    };
    let mut average = vec![0.0; 360 * 180 * 12];
    for m in 1..=12 {
        for j in 1..=180 {
            for i in 1..=360 {
                average[(i - 1) + 360 * ((j - 1) + 180 * (m - 1))] = jr_formula(i, j, m);
            }
        }
    }
    let jr = JrateClimatology {
        lon: one(rows, "oh.lonjr", |_| true).args.clone(),
        lat: one(rows, "oh.latjr", |_| true).args.clone(),
        average,
    };
    let bdate = one(rows, "oh.bdate", |_| true).args[0];

    // replay the gethourlyOH sequences; the driver resets the state when the
    // direction changes
    let mut hourly = HashMap::new();
    let mut state = HourlyOh::empty(&clim);
    let mut last_dir = 0;
    for r in find(rows, "gethourlyOH") {
        let (ld, it) = (r.args[0] as i64, r.args[1] as i64);
        if ld != last_dir {
            state = HourlyOh::empty(&clim);
            last_dir = ld;
        }
        gethourly_oh(&mut state, it, ld, bdate, &clim, &jr);
        hourly.insert((ld, it), state.clone());
    }

    // ohreaction from the echoed state
    let st = &one(rows, "oh.state", |_| true).outs;
    let n3 = nx * ny * nz;
    let state = HourlyOh {
        memtime: [st[0], st[1]],
        hourly: [st[2..2 + n3].to_vec(), st[2 + n3..2 + 2 * n3].to_vec()],
    };
    let m = &one(rows, "oh.met", |_| true).args;
    let (mnx, mny) = (m[4] as usize, m[5] as usize);
    let height = m[6..12].to_vec();
    let mut tt_slots = [
        Field3::filled(mnx, mny, 6, 0.0),
        Field3::filled(mnx, mny, 6, 0.0),
    ];
    for r in find(rows, "oh.tt") {
        let (s, k) = (r.args[0] as usize - 1, r.args[1] as usize - 1);
        let n = mnx * mny;
        tt_slots[s].data[n * k..n * (k + 1)].copy_from_slice(&r.outs);
    }
    let met = OhMet {
        memtime: [0, 10801],
        height,
        tt_slots,
        dx: m[0],
        dy: m[1],
        xlon0: m[2],
        ylat0: m[3],
        nests: vec![NestFrame {
            xl: m[12],
            xr: m[13],
            yl: m[14],
            yr: m[15],
            xresol: m[16],
            yresol: m[17],
        }],
    };
    let mut masses = HashMap::new();
    for r in find(rows, "oh.run") {
        let a = &r.args;
        let run = a[0] as usize;
        let mut particles: Vec<ParticleRecord> = find(rows, "oh.particle")
            .filter(|p| p.args[0] as usize == run)
            .map(|p| ParticleRecord {
                itra1: itra1_of(p.args[2]),
                itramem: 0,
                xtra1: p.args[3],
                ytra1: p.args[4],
                ztra1: p.args[5],
                npoint: 1,
                nclass: 1,
                xmass1: vec![p.args[6]],
            })
            .collect();
        let sp = [OhSpecies {
            ohcconst: a[3],
            ohdconst: a[4],
            ohnconst: a[5],
        }];
        ohreaction(
            a[1] as i64,
            a[2] as i64,
            &mut particles,
            &sp,
            &met,
            &clim,
            &state,
        )
        .expect("ohreaction");
        masses.insert(run, particles.iter().map(|p| p.xmass1[0]).collect());
    }
    OhSetup {
        clim,
        jr,
        bdate,
        hourly,
        masses,
    }
}

// ── landuse ───────────────────────────────────────────────────────────────────

/// The driver's `fill_landinvent` (integers, so exact).
fn inventory() -> LanduseInventory {
    let mut classes = vec![[0i8; 3]; LUMAXX * LUMAXY];
    let mut weights = vec![[0i8; 3]; LUMAXX * LUMAXY];
    for j in 1..=LUMAXY {
        for i in 1..=LUMAXX {
            let c = (i - 1) + LUMAXX * (j - 1);
            classes[c] = [
                (1 + (i * 7 + j * 3) % 13) as i8,
                (1 + (i * 5 + j * 11 + 4) % 13) as i8,
                (1 + (i + j * 2 + 9) % 13) as i8,
            ];
            weights[c] = if i <= 25 {
                [0, 0, 0]
            } else {
                [
                    ((i + 2 * j) % 16) as i8,
                    ((3 * i + j) % 11) as i8,
                    ((i * j) % 7) as i8,
                ]
            };
        }
    }
    LanduseInventory { classes, weights }
}

/// `assignland` results by (call, grid): (nx, fractions per point).
type LanduseResults = HashMap<(usize, usize), (usize, Vec<[f64; NUMCLASS]>)>;

fn landuse_results(rows: &[Row], inv: &LanduseInventory) -> LanduseResults {
    let mut out = HashMap::new();
    for g in find(rows, "lu.grid") {
        let a = &g.args;
        let (c, gr) = (a[0] as usize, a[1] as usize);
        let geom = GridGeometry {
            nx: a[2] as usize,
            ny: a[3] as usize,
            dx: a[4],
            dy: a[5],
            xlon0: a[6],
            ylat0: a[7],
        };
        let lsm_row = one(rows, "lu.lsm", |r| {
            r.args[0] as usize == c && r.args[1] as usize == gr
        });
        let lsm = Field2 {
            nx: geom.nx,
            ny: geom.ny,
            data: lsm_row.outs.clone(),
        };
        let kind = if gr == 1 {
            LanduseGrid::Nest
        } else {
            LanduseGrid::Mother
        };
        let lu = assignland(inv, &geom, &lsm, kind).expect("assignland");
        out.insert((c, gr), (geom.nx, lu));
    }
    out
}

// ── setup per precision ───────────────────────────────────────────────────────

struct PrecisionSetup {
    calcpar: HashMap<usize, CalcparScenario>,
    wet: WetSetup,
    wetdepo: HashMap<usize, WetDepoRun>,
    oh: OhSetup,
    landuse: LanduseResults,
}

fn build(rows: &[Row], inv: &LanduseInventory) -> PrecisionSetup {
    let calcpar = (1..=7).map(|sc| (sc, run_scenario(rows, sc))).collect();
    let wet = wet_setup(rows);
    let wetdepo = (1..=4)
        .map(|run| (run, run_wetdepo(rows, &wet, run)))
        .collect();
    let oh = oh_setup(rows);
    let landuse = landuse_results(rows, inv);
    PrecisionSetup {
        calcpar,
        wet,
        wetdepo,
        oh,
        landuse,
    }
}

struct Setup {
    fx: Fixtures,
    s4: PrecisionSetup,
    s8: PrecisionSetup,
    inv: LanduseInventory,
}

fn setup() -> &'static Setup {
    static S: OnceLock<Setup> = OnceLock::new();
    S.get_or_init(|| {
        let fx = Fixtures::new(FIXTURE_REAL4, FIXTURE_REAL8, DP_FUNCTIONS);
        let inv = inventory();
        let s4 = build(&fx.real4, &inv);
        let s8 = build(&fx.real8, &inv);
        Setup { fx, s4, s8, inv }
    })
}

fn ps(p: Precision) -> &'static PrecisionSetup {
    let s = setup();
    match p {
        Precision::Real4 => &s.s4,
        Precision::Real8 => &s.s8,
    }
}

fn evaluate(r: &Row, p: Precision) -> Option<Vec<f64>> {
    let s = ps(p);
    let a = &r.args;
    Some(match r.function.as_str() {
        "calcpar" => {
            let sc = &s.calcpar[&(a[0] as usize)];
            let (ix, jy) = (a[1] as usize, a[2] as usize);
            let o = &sc.out;
            vec![
                o.ustar.at(ix, jy),
                o.oli.at(ix, jy),
                o.hmix.at(ix, jy),
                o.wstar.at(ix, jy),
                o.vdep.first().map_or(SENTINEL, |v| v.at(ix, jy)),
                o.tropopause[ix + sc.nx * jy].unwrap_or(SENTINEL),
            ]
        }
        "calcpv" => {
            let sc = &s.calcpar[&(a[0] as usize)];
            sc.out.pv.column(a[1] as usize, a[2] as usize)
        }
        "calcpar.z0water" => {
            let sc = &s.calcpar[&(a[0] as usize)];
            vec![sc.out.z0_water_last.unwrap_or(sc.z0_table7)]
        }
        "interpol_rain" => {
            let (g, m) = (a[0] as usize, a[1] as usize - 1);
            let f = &s.wet.fields[g][m];
            let q = interpol_rain(&f.lsprec, &f.convprec, &f.tcc, a[2], a[3]).expect("inside");
            vec![q.lsp, q.convp, q.cc, q.xt, q.yt]
        }
        "get_wetscav" => {
            // itime, ltsample, memind(1), readclouds, x, y, z, species id
            let met = s.wet.met(a[2] as usize, a[3] == 1.0);
            let mut sp = s.wet.species[a[7] as usize - 1];
            let w = get_wetscav(a[0] as i64, a[1] as i64, a[4], a[5], a[6], &mut sp, &met)
                .expect("defined");
            vec![
                w.wetscav,
                w.grfraction.unwrap_or(SENTINEL),
                f64::from(u8::from(w.counted == Some(ScavengingRegime::BelowCloud))),
                f64::from(u8::from(w.counted == Some(ScavengingRegime::InCloud))),
                sp.ccn_aero,
                sp.in_aero,
            ]
        }
        "wetdepokernel" => {
            // variant (0 mother, 2 nest), x, y, deposit, kp
            let (g, rule, frame) = if a[0] == 2.0 {
                (1, KernelRule::Nest, &s.wet.frame_nest)
            } else {
                (
                    0,
                    KernelRule::Mother { use_kernel: true },
                    &s.wet.frame_mother,
                )
            };
            let mut grid = s.wet.grid(g);
            let kp = a[4] as usize;
            wetdepokernel(rule, frame, a[1], a[2], &[a[3]], &mut grid, kp, 1, 1).expect("in range");
            WetSetup::slice(&grid, kp)
        }
        "wetdepo.mass" => vec![s.wetdepo[&(a[0] as usize)].masses[a[1] as usize - 1]],
        "wetdepo.grid" => WetSetup::slice(
            &s.wetdepo[&(a[0] as usize)].grids[a[1] as usize],
            a[2] as usize,
        ),
        "wetdepo.counts" => {
            let c = &s.wetdepo[&(a[0] as usize)].counts;
            vec![c.blc[0] as f64, c.inc[0] as f64]
        }
        "gethourlyOH" => {
            let h = &s.oh.hourly[&(a[0] as i64, a[1] as i64)];
            let mut v = vec![h.memtime[0], h.memtime[1]];
            v.extend(&h.hourly[0]);
            v.extend(&h.hourly[1]);
            v
        }
        "ohreaction" => vec![s.oh.masses[&(a[0] as usize)][a[1] as usize - 1]],
        "assignland" => {
            let (nx, lu) = &s.landuse[&(a[0] as usize, a[1] as usize)];
            lu[a[2] as usize + nx * a[3] as usize].to_vec()
        }
        _ => return None,
    })
}

