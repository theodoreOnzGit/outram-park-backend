struct CalcparScenario {
    out: CalcparOutput,
    nx: usize,
    z0_table7: f64,
}

fn wesely(rows: &[Row]) -> ([[SurfaceResistances; NUMCLASS]; NSEASON], [f64; NUMCLASS]) {
    let mut t = [[SurfaceResistances::default(); NUMCLASS]; NSEASON];
    let mut z0 = [0.0; NUMCLASS];
    for r in find(rows, "wesely") {
        let a = &r.args;
        let (i, j) = (a[0] as usize - 1, a[1] as usize - 1);
        t[i][j] = SurfaceResistances {
            ri: a[2],
            rac: a[3],
            rcl: a[4],
            rgs: a[5],
            rlu: a[6],
        };
        z0[j] = a[7];
    }
    (t, z0)
}

fn bins(rows: &[Row]) -> AerosolBins {
    let a = &one(rows, "particle_bins", |_| true).args;
    let mut b = AerosolBins {
        mass_fraction: [0.0; NI],
        schmidt_factor: [0.0; NI],
        settling_velocity: [0.0; NI],
        cunningham: [0.0; NI],
    };
    for j in 0..NI {
        b.settling_velocity[j] = a[j];
        b.schmidt_factor[j] = a[NI + j];
        b.mass_fraction[j] = a[2 * NI + j];
    }
    b
}

fn drydep_species(rows: &[Row], kind: usize) -> DepositionSpecies {
    // cp.species: kind, reldiff, henry, f0, rm, density, dryvel
    let a = &one(rows, "cp.species", |r| r.args[0] as usize == kind).args;
    match kind {
        1 | 4 => DepositionSpecies::Gas(GasSpecies {
            reldiff: a[1],
            henry: a[2],
            f0: a[3],
            rm: a[4],
        }),
        2 => DepositionSpecies::Particle {
            density: a[5],
            bins: bins(rows),
        },
        _ => DepositionSpecies::Prescribed(a[6]),
    }
}

fn run_scenario(rows: &[Row], sc: usize) -> CalcparScenario {
    let g = &one(rows, "cp.grid", |r| r.args[0] as usize == sc).args;
    let kind = if g[1] == 1.0 {
        GridKind::Nest
    } else {
        GridKind::Mother
    };
    let (nx, ny) = (g[3] as usize, g[4] as usize);
    let geom = GridGeometry {
        nx,
        ny,
        dx: g[5],
        dy: g[6],
        xlon0: g[7],
        ylat0: g[8],
    };
    let lev = &one(rows, "cp.levels", |r| r.args[0] as usize == sc).args;
    let n = lev[1] as usize;
    let akz = lev[2..2 + n].to_vec();
    let bkz = lev[2 + n..2 + 2 * n].to_vec();
    let (akm, bkm) = (
        [lev[2 + 2 * n], lev[3 + 2 * n]],
        [lev[4 + 2 * n], lev[5 + 2 * n]],
    );
    let format = if g[2] == 1.0 {
        MetDataFormat::Ncep
    } else {
        MetDataFormat::Ecmwf { akm, bkm }
    };
    let domain = find(rows, "cp.global")
        .find(|r| r.args[0] as usize == sc)
        .map_or(GlobalDomain::LIMITED, |r| GlobalDomain {
            xglobal: r.args[1] == 1.0,
            sglobal: r.args[2] == 1.0,
            nglobal: r.args[3] == 1.0,
        });
    // scenarios 4 and 5 rerun the fields of scenario 1
    let col_sc = if sc == 4 || sc == 5 { 1 } else { sc };
    let f2 = || Field2::filled(nx, ny, 0.0);
    let f3 = || Field3::filled(nx, ny, n, 0.0);
    let mut inp = CalcparInput {
        ps: f2(),
        tt2: f2(),
        td2: f2(),
        surfstr: f2(),
        sshf: f2(),
        ssr: f2(),
        lsprec: f2(),
        convprec: f2(),
        sd: f2(),
        excessoro: f2(),
        hmix_in: f2(),
        tth: f3(),
        qvh: f3(),
        uuh: f3(),
        vvh: f3(),
        akz: akz.clone(),
        bkz: bkz.clone(),
    };
    let mut landuse = vec![[0.0; NUMCLASS]; nx * ny];
    for r in find(rows, "cp.column").filter(|r| r.args[0] as usize == col_sc) {
        let a = &r.args;
        let (ix, jy) = (a[1] as usize, a[2] as usize);
        let s = &a[3..14];
        for (f, v) in [
            &mut inp.ps,
            &mut inp.tt2,
            &mut inp.td2,
            &mut inp.surfstr,
            &mut inp.sshf,
            &mut inp.ssr,
            &mut inp.lsprec,
            &mut inp.convprec,
            &mut inp.sd,
            &mut inp.excessoro,
            &mut inp.hmix_in,
        ]
        .into_iter()
        .zip(s)
        {
            f.set(ix, jy, *v);
        }
        for k in 0..n {
            inp.tth.set(ix, jy, k, a[14 + k]);
            inp.qvh.set(ix, jy, k, a[14 + n + k]);
            inp.uuh.set(ix, jy, k, a[14 + 2 * n + k]);
            inp.vvh.set(ix, jy, k, a[14 + 3 * n + k]);
        }
        landuse[ix + nx * jy].copy_from_slice(&a[14 + 4 * n..14 + 4 * n + NUMCLASS]);
    }
    let (table, z0) = wesely(rows);
    if sc >= 6 {
        let pv = calcpv(
            &geom, domain, &akz, &bkz, &inp.ps, &inp.tth, &inp.uuh, &inp.vvh,
        )
        .expect("calcpv");
        let out = CalcparOutput {
            ustar: f2(),
            oli: f2(),
            hmix: f2(),
            wstar: f2(),
            vdep: Vec::new(),
            tropopause: Vec::new(),
            z0_water_last: None,
            pv,
        };
        return CalcparScenario {
            out,
            nx,
            z0_table7: z0[6],
        };
    }
    let t = &one(rows, "cp.time", |r| r.args[0] as usize == sc).args;
    let drydep = (g[10] == 1.0).then(|| DryDepositionInput {
        jul: t[1] + t[2] / 86400.0,
        season_lat0: g[13],
        season_dy: g[12],
        landuse,
        z0,
        species: vec![(drydep_species(rows, g[11] as usize), table)],
    });
    let opts = CalcparOptions {
        format,
        kind,
        lsubgrid: g[9] == 1.0,
        domain,
    };
    let out = calcpar(&geom, &opts, &inp, drydep.as_ref()).expect("calcpar");
    CalcparScenario {
        out,
        nx,
        z0_table7: z0[6],
    }
}

