//! # V&V: FLEXPART stage `met` — boundary-layer parameters, PV, wet deposition, OH, landuse
//!
//! ## Methodology
//!
//! `dev/flexpart_reference_met.f90` links upstream's `calcpar`,
//! `calcpar_nests`, `calcpv`, `calcpv_nests`, `interpol_rain`,
//! `interpol_rain_nests`, `get_wetscav`, `wetdepo`, `wetdepokernel`,
//! `wetdepokernel_nest`, `ohreaction`, `gethourlyOH` and `assignland`
//! **verbatim**, with everything they call. It writes synthetic fields into
//! `com_mod` / `oh_mod` and echoes them as setup rows (`cp.*`, `wet.*`,
//! `wd.*`, `oh.*`, `lu.*`). Two large tables are instead generated by an
//! integer formula reproduced here exactly (the 360 x 180 x 12
//! `jrate_average` and the 1200 x 600 landuse inventory); each is
//! cross-checked against sample rows (`oh.jrcheck`, `lu.check`).
//!
//! The nest routines need one configuration change: the build compiles a
//! copy of `par_mod.f90` with `maxnests=1, nxmaxn=12, nymaxn=12` instead of
//! the shipped zeros. Every routine under test is verbatim.
//!
//! Built twice by `dev/build_reference_met.sh`: real(4) as FLEXPART ships,
//! and `-fdefault-real-8 -fdefault-double-8`. The real(8) comparison proves
//! the translation; the real(4) comparison measures FLEXPART as shipped.
//!
//! Each Rust function that replaces a `_nests` twin is driven against both
//! upstream routines: a nest row (`calcpar` scenario 3, `interpol_rain` grid
//! 1, `get_wetscav` points inside the nest, `wetdepokernel` variant 2) is
//! evaluated by the same Rust function on the nest's fields.
//!
//! ## Results
//!
//! Re-print with `cargo test --release -p changi --test
//! flexpart_met_code_to_code -- --nocapture`. Recorded, with the
//! interpretation, in `docs/flexpart-code-to-code.md`.
//!
//! ## What this does NOT establish
//!
//! Verification, not validation, on synthetic fields. Nothing here supports
//! emergency response or dose assessment for real populations.

