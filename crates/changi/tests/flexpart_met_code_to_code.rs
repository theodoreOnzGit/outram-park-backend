/// `ohreaction` refuses the unassigned level index (particle above the top
/// level while OH is present).
#[test]
fn ohreaction_refuses_undefined_level() {
    use changi::flexpart::oh_chemistry::OhError;
    let s = ps(Precision::Real8);
    let clim = &s.oh.clim;
    let n3 = clim.lon.len() * clim.lat.len() * clim.alt.len();
    let hourly = HourlyOh {
        memtime: [0.0, 3600.0],
        hourly: [vec![1.0e6; n3], vec![1.0e6; n3]],
    };
    let met = OhMet {
        memtime: [0, 3600],
        height: vec![0.0, 500.0, 1500.0],
        tt_slots: [
            Field3::filled(3, 3, 3, 280.0),
            Field3::filled(3, 3, 3, 280.0),
        ],
        dx: 1.0,
        dy: 1.0,
        xlon0: 0.0,
        ylat0: 0.0,
        nests: Vec::new(),
    };
    let sp = [OhSpecies {
        ohcconst: 1e-17,
        ohdconst: 1500.0,
        ohnconst: 2.0,
    }];
    let mut p = vec![ParticleRecord {
        itra1: 0,
        itramem: 0,
        xtra1: 1.0,
        ytra1: 1.0,
        ztra1: 2000.0,
        npoint: 1,
        nclass: 1,
        xmass1: vec![1.0],
    }];
    assert_eq!(
        ohreaction(1800, 900, &mut p, &sp, &met, clim, &hourly),
        Err(OhError::AboveTopLevel)
    );
    p[0].ztra1 = 100.0;
    assert!(ohreaction(1800, 900, &mut p, &sp, &met, clim, &hourly).is_ok());
    assert!(p[0].xmass1[0] < 1.0);
}

/// `assignland` refuses an inventory class outside 1..=13 (written outside
/// the array upstream) and a sample left of the inventory (upstream stops).
#[test]
fn assignland_refuses_out_of_range() {
    use changi::flexpart::landuse::LanduseError;
    let s = setup();
    let lsm = Field2::filled(1, 1, 0.5);
    let geom = |xlon0: f64| GridGeometry {
        nx: 1,
        ny: 1,
        dx: 0.1,
        dy: 0.1,
        xlon0,
        ylat0: 10.0,
    };
    assert!(assignland(&s.inv, &geom(10.0), &lsm, LanduseGrid::Mother).is_ok());
    assert_eq!(
        assignland(&s.inv, &geom(-181.0), &lsm, LanduseGrid::Mother),
        Err(LanduseError::SamplingStop)
    );
    let mut bad = s.inv.clone();
    for c in &mut bad.classes {
        c[1] = 0;
    }
    assert_eq!(
        assignland(&bad, &geom(10.0), &lsm, LanduseGrid::Mother),
        Err(LanduseError::ClassOutOfRange)
    );
}
