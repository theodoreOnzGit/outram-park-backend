fn find<'a>(rows: &'a [Row], name: &str) -> impl Iterator<Item = &'a Row> + 'a {
    let name = name.to_string();
    rows.iter().filter(move |r| r.function == name)
}

fn one<'a>(rows: &'a [Row], name: &str, pred: impl Fn(&Row) -> bool) -> &'a Row {
    rows.iter()
        .find(|r| r.function == name && pred(r))
        .unwrap_or_else(|| panic!("no `{name}` setup row"))
}

