! FLEXPART code-to-code reference driver, stage 2: meteorological interpolation.
!
! Links upstream FLEXPART v10.4 (3d7eebf, GPL-3.0-or-later) VERBATIM:
!   interpol_all, interpol_all_nests, interpol_misslev, interpol_misslev_nests,
!   interpol_wind, interpol_wind_nests, interpol_wind_short,
!   interpol_wind_short_nests, interpol_vdep, interpol_vdep_nests
! plus the modules they read (par_mod, com_mod, interpol_mod, hanna_mod).
!
! NEST CONFIGURATION. The shipped par_mod.f90 sets maxnests=0, nxmaxn=0,
! nymaxn=0, so nest arrays are zero-sized and the *_nests routines cannot be
! driven. par_mod.f90 is FLEXPART's user-edited configuration file; the build
! (dev/build_reference.sh) compiles a copy with only that line changed to
! maxnests=1, nxmaxn=12, nymaxn=12. Every other upstream file is verbatim.
!
! The wind fields are SYNTHETIC: written straight into com_mod, on a 7 x 7
! patch of the grid and 8 levels, at the two time levels in memory. Each field
! is echoed as setup rows (`field`) so the Rust test builds identical fields:
!   field,<grid>;<id>;<slot>;<k>,<49 values, i fastest>
! grid 0 = mother, 1 = nest 1. ids: 1 uu 2 vv 3 ww 4 uupol 5 vvpol 6 rho
! 7 drhodz 11 ustar 12 wstar 13 oli 14 hmix 15 tropopause 16 vdep (k=1).
!
! DO NOT EDIT the generated fixtures by hand; regenerate with
! dev/build_reference.sh.
program flexpart_reference_interp
  use par_mod
  use com_mod
  use interpol_mod
  use hanna_mod
  implicit none

  integer, parameter :: NXP = 7, NYP = 7, NZP = 8

  write(*,'(A)') '# FLEXPART stage-2 interpolation reference, generated by dev/flexpart_reference_interp.f90'
  write(*,'(A)') '# upstream: github.com/flexpart/flexpart v10.4 @ 3d7eebf (GPL-3.0-or-later)'
  write(*,'(A)') '# DO NOT EDIT BY HAND -- regenerate with dev/build_reference.sh'
  write(*,'(A)') 'function,args,outputs'

  call setup_fields()
  call emit_interp()

contains

  subroutine fmtnum(x, buf)
    double precision, intent(in) :: x
    character(len=32), intent(out) :: buf
    if (kind(1.0) == 4) then
      write(buf,'(ES16.8E3)') x
    else
      write(buf,'(ES25.17E3)') x
    end if
    buf = adjustl(buf)
  end subroutine fmtnum

  subroutine rowv(name, args, nargs, outs, nouts)
    character(len=*), intent(in) :: name
    integer, intent(in) :: nargs, nouts
    real, intent(in) :: args(nargs), outs(nouts)
    character(len=8192) :: line
    character(len=32) :: buf
    integer :: i
    line = trim(name) // ','
    do i = 1, nargs
      call fmtnum(dble(args(i)), buf)
      line = trim(line) // trim(adjustl(buf))
      if (i < nargs) line = trim(line) // ';'
    end do
    line = trim(line) // ','
    do i = 1, nouts
      call fmtnum(dble(outs(i)), buf)
      line = trim(line) // trim(adjustl(buf))
      if (i < nouts) line = trim(line) // ';'
    end do
    write(*,'(A)') trim(line)
  end subroutine rowv

  ! A smooth but non-separable synthetic value for field `id`.
  real function synth(id, i, j, k, m)
    integer, intent(in) :: id, i, j, k, m
    real :: x, y, z, t
    x = real(i); y = real(j); z = real(k); t = real(m - 1)
    select case (id)
    case (1)   ! uu
      synth = 2.0 + 0.9*x - 0.35*y + 0.6*sin(0.7*x + 0.3*y + 0.2*z) + 0.5*t + 0.4*z
    case (2)   ! vv
      synth = -1.5 + 0.25*x + 0.8*y + 0.5*cos(0.4*x - 0.9*y + 0.3*z) - 0.3*t + 0.2*z
    case (3)   ! ww: constant for i >= 5 so the sigma guard is exercised
      if (i >= 5) then
        synth = 0.01
      else
        synth = 0.02*sin(0.5*x + 0.8*y - 0.6*z + t) - 0.003*z
      end if
    case (4)   ! uupol
      synth = -3.0 + 0.5*x + 0.7*y + 0.3*sin(x*y + z) + 0.2*t
    case (5)   ! vvpol
      synth = 4.0 - 0.6*x + 0.2*y - 0.4*cos(x - y + z) - 0.1*t
    case (6)   ! rho
      synth = 1.2*exp(-z*0.12) + 0.01*x - 0.005*y + 0.002*t
    case (7)   ! drhodz
      synth = -1.1e-4*exp(-z*0.12) + 1.e-6*(x - y) + 1.e-6*t
    case (11)  ! ustar
      synth = 0.2 + 0.05*x + 0.03*y + 0.04*t
    case (12)  ! wstar
      synth = 0.8 + 0.1*x - 0.05*y + 0.3*t
    case (13)  ! oli: zero along i = 3 so ol = 99999 is exercised
      synth = 0.002*(x - 3.)*(1. + 0.2*t)
    case (14)  ! hmix
      synth = 600. + 40.*x + 25.*y + 150.*t
    case (15)  ! tropopause
      synth = 11000. + 100.*x - 50.*y
    case (16)  ! vdep
      synth = 2.e-3 + 3.e-4*x - 1.e-4*y + 5.e-4*t
    case default
      synth = 0.
    end select
  end function synth

  subroutine echo(grid, id, m, k, vals)
    integer, intent(in) :: grid, id, m, k
    real, intent(in) :: vals(NXP*NYP)
    call rowv('field', (/ real(grid), real(id), real(m), real(k) /), 4, vals, NXP*NYP)
  end subroutine echo

  subroutine setup_fields()
    integer :: i, j, k, m, id, ids3(7), ids2(6)
    real :: vals(NXP*NYP)
    nz = NZP
    height(1:NZP) = (/ 0., 25., 80., 180., 400., 900., 2000., 5000. /)
    memtime(1) = 0
    memtime(2) = 10800
    numbnests = 1
    call com_mod_allocate_nests()
    ids3 = (/ 1, 2, 3, 4, 5, 6, 7 /)
    ids2 = (/ 11, 12, 13, 14, 15, 16 /)
    ! setup rows: the level heights
    call rowv('height', height(1:NZP), NZP, (/ 0. /), 1)
    do m = 1, 2
      do k = 1, NZP
        do id = 1, 7
          do j = 0, NYP-1
            do i = 0, NXP-1
              vals(1 + i + NXP*j) = synth(ids3(id), i, j, k, m)
              ! the nest gets a different (shifted) pattern
              select case (ids3(id))
              case (1)
                uu(i,j,k,m) = synth(1, i, j, k, m)
                uun(i,j,k,m,1) = synth(1, i+2, j+1, k, m)
              case (2)
                vv(i,j,k,m) = synth(2, i, j, k, m)
                vvn(i,j,k,m,1) = synth(2, i+2, j+1, k, m)
              case (3)
                ww(i,j,k,m) = synth(3, i, j, k, m)
                wwn(i,j,k,m,1) = synth(3, i+2, j+1, k, m)
              case (4)
                uupol(i,j,k,m) = synth(4, i, j, k, m)
              case (5)
                vvpol(i,j,k,m) = synth(5, i, j, k, m)
              case (6)
                rho(i,j,k,m) = synth(6, i, j, k, m)
                rhon(i,j,k,m,1) = synth(6, i+2, j+1, k, m)
              case (7)
                drhodz(i,j,k,m) = synth(7, i, j, k, m)
                drhodzn(i,j,k,m,1) = synth(7, i+2, j+1, k, m)
              end select
            end do
          end do
          call echo(0, ids3(id), m, k, vals)
          if (ids3(id) /= 4 .and. ids3(id) /= 5) then
            do j = 0, NYP-1
              do i = 0, NXP-1
                vals(1 + i + NXP*j) = synth(ids3(id), i+2, j+1, k, m)
              end do
            end do
            call echo(1, ids3(id), m, k, vals)
          end if
        end do
      end do
      do id = 1, 6
        do j = 0, NYP-1
          do i = 0, NXP-1
            vals(1 + i + NXP*j) = synth(ids2(id), i, j, 1, m)
            select case (ids2(id))
            case (11)
              ustar(i,j,1,m) = vals(1 + i + NXP*j)
              ustarn(i,j,1,m,1) = synth(11, i+2, j+1, 1, m)
            case (12)
              wstar(i,j,1,m) = vals(1 + i + NXP*j)
              wstarn(i,j,1,m,1) = synth(12, i+2, j+1, 1, m)
            case (13)
              oli(i,j,1,m) = vals(1 + i + NXP*j)
              olin(i,j,1,m,1) = synth(13, i+2, j+1, 1, m)
            case (14)
              hmix(i,j,1,m) = vals(1 + i + NXP*j)
              hmixn(i,j,1,m,1) = synth(14, i+2, j+1, 1, m)
            case (15)
              tropopause(i,j,1,m) = vals(1 + i + NXP*j)
              tropopausen(i,j,1,m,1) = synth(15, i+2, j+1, 1, m)
            case (16)
              vdep(i,j,1,m) = vals(1 + i + NXP*j)
              vdepn(i,j,1,m,1) = synth(16, i+2, j+1, 1, m)
            end select
          end do
        end do
        call echo(0, ids2(id), m, 1, vals)
        do j = 0, NYP-1
          do i = 0, NXP-1
            vals(1 + i + NXP*j) = synth(ids2(id), i+2, j+1, 1, m)
          end do
        end do
        call echo(1, ids2(id), m, 1, vals)
      end do
    end do
  end subroutine setup_fields

  ! Position the cell as advance.f90 does before calling an interpol routine.
  subroutine place(xt, yt, g)
    real, intent(in) :: xt, yt
    integer, intent(in) :: g
    ix = int(xt)
    jy = int(yt)
    ixp = ix + 1
    jyp = jy + 1
    ngrid = g
  end subroutine place

  subroutine emit_interp()
    real :: xs(6), ys(6), zs(6), o(23), a(7)
    integer :: its(2), ip, iz, it, ig, im, g, n, grids(3), lev
    real :: vd
    xs = (/ 0.0, 2.37, 3.0, 5.5, 4.999, 1.5 /)
    ys = (/ 0.0, 1.81, 4.6, 5.25, 0.001, 3.0 /)
    zs = (/ 0., 25., 60., 333., 1500., 4999. /)
    its = (/ 0, 4321 /)
    grids = (/ 0, -1, 1 /)
    do im = 1, 2
      if (im == 1) then
        memind(1) = 1; memind(2) = 2
      else
        memind(1) = 2; memind(2) = 1
      end if
      do ig = 1, 3
        g = grids(ig)
        do it = 1, 2
          do ip = 1, 6
            do iz = 1, 6
              a = (/ real(g), real(memind(1)), real(its(it)), xs(ip), ys(ip), zs(iz), 0. /)
              ! interpol_all (+ hanna_mod ust, wst, ol)
              call place(xs(ip), ys(ip), g)
              indzindicator(:) = .true.
              depoindicator(:) = .true.
              if (g > 0) then
                call interpol_all_nests(its(it), xs(ip), ys(ip), zs(iz))
              else
                call interpol_all(its(it), xs(ip), ys(ip), zs(iz))
              end if
              o(1) = ust; o(2) = wst; o(3) = ol
              o(4) = real(indz); o(5) = real(indzp)
              o(6:13) = (/ uprof(indz), vprof(indz), wprof(indz), rhoprof(indz), &
                           rhogradprof(indz), usigprof(indz), vsigprof(indz), wsigprof(indz) /)
              o(14:21) = (/ uprof(indzp), vprof(indzp), wprof(indzp), rhoprof(indzp), &
                            rhogradprof(indzp), usigprof(indzp), vsigprof(indzp), wsigprof(indzp) /)
              ! the "already interpolated" flags it must clear (1 = still set)
              o(22) = real(merge(1, 0, indzindicator(indz)))
              o(23) = real(merge(1, 0, indzindicator(indzp)))
              call rowv('interpol_all', a, 6, o, 23)
              ! interpol_misslev at every level, with the weights just set
              if (iz == 1) then
                do n = 1, NZP
                  a(7) = real(n)
                  indzindicator(n) = .true.
                  if (g > 0) then
                    call interpol_misslev_nests(n)
                  else
                    call interpol_misslev(n)
                  end if
                  o(1:8) = (/ uprof(n), vprof(n), wprof(n), rhoprof(n), &
                              rhogradprof(n), usigprof(n), vsigprof(n), wsigprof(n) /)
                  o(9) = real(merge(1, 0, indzindicator(n)))
                  call rowv('interpol_misslev', a, 7, o, 9)
                end do
                ! interpol_vdep for the one species
                if (g > 0) then
                  call interpol_vdep_nests(1, vd)
                else
                  call interpol_vdep(1, vd)
                end if
                call rowv('interpol_vdep', a, 6, (/ vd, real(merge(1, 0, depoindicator(1))) /), 2)
              end if
              ! interpol_wind
              call place(xs(ip), ys(ip), g)
              usig = -1.; vsig = -1.; wsig = -1.
              if (g > 0) then
                call interpol_wind_nests(its(it), xs(ip), ys(ip), zs(iz))
              else
                call interpol_wind(its(it), xs(ip), ys(ip), zs(iz))
              end if
              call rowv('interpol_wind', a, 6, (/ u, v, w, usig, vsig, wsig, real(indz) /), 7)
              ! interpol_wind_short (usig etc. must be left untouched: sentinel -2)
              call place(xs(ip), ys(ip), g)
              usig = -2.; vsig = -2.; wsig = -2.
              if (g > 0) then
                call interpol_wind_short_nests(its(it), xs(ip), ys(ip), zs(iz))
              else
                call interpol_wind_short(its(it), xs(ip), ys(ip), zs(iz))
              end if
              call rowv('interpol_wind_short', a, 6, (/ u, v, w, usig, vsig, wsig, real(indz) /), 7)
            end do
          end do
        end do
      end do
    end do
    lev = 0
  end subroutine emit_interp

end program flexpart_reference_interp
