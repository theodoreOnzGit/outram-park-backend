! Every routine called here is UPSTREAM FLEXPART v10.4 @ 3d7eebf, compiled
! verbatim from upstream_source/FLEXPART/src by dev/build_reference.sh. Nothing
! below reimplements physics: the driver only sets inputs (scalar arguments and,
! where a routine reads them from com_mod, the module arrays directly -- that is
! how the file-free synthetic met is supplied) and prints what upstream returns.
!
! Row format, one row per CALL:
!     function,a1;a2;...;an,o1;o2;...;om
! Values are promoted with dble() before printing, so the real(4) build writes
! the exact f32 value rather than a re-rounded decimal.
!
