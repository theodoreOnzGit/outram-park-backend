contains

  ! ------------------------------------------------------------------------
  ! A value as the shortest decimal that is still exact for this build's
  ! default real: 9 significant digits identify a real(4) uniquely (parse it as
  ! f32), 17 identify a real(8).
  subroutine fmtnum(x, buf)
    double precision, intent(in) :: x
    character(len=32), intent(out) :: buf
    if (kind(1.0) == 4) then
      write(buf,'(ES16.8E3)') x
    else
      write(buf,'(ES25.17E3)') x
    end if
    buf = adjustl(buf)
  end subroutine fmtnum

  ! ------------------------------------------------------------------------
  ! Output: name, args ';'-joined, outputs ';'-joined.
  subroutine rowv(name, args, nargs, outs, nouts)
    character(len=*), intent(in) :: name
    integer, intent(in) :: nargs, nouts
    real, intent(in) :: args(nargs), outs(nouts)
    character(len=8192) :: line
    character(len=32) :: buf
    integer :: i
    line = trim(name) // ','
    do i = 1, nargs
      call fmtnum(dble(args(i)), buf)
      line = trim(line) // trim(adjustl(buf))
      if (i < nargs) line = trim(line) // ';'
    end do
    line = trim(line) // ','
    do i = 1, nouts
      call fmtnum(dble(outs(i)), buf)
      line = trim(line) // trim(adjustl(buf))
      if (i < nouts) line = trim(line) // ';'
    end do
    write(*,'(A)') trim(line)
  end subroutine rowv

  ! Same, with double-precision arguments (the Julian date is real(kind=dp)
  ! in upstream at both precisions).
  subroutine rowvd(name, args, nargs, outs, nouts)
    character(len=*), intent(in) :: name
    integer, intent(in) :: nargs, nouts
    double precision, intent(in) :: args(nargs), outs(nouts)
    character(len=8192) :: line
    character(len=32) :: buf
    integer :: i
    line = trim(name) // ','
    do i = 1, nargs
      write(buf,'(ES25.17E3)') args(i)
      line = trim(line) // trim(adjustl(buf))
      if (i < nargs) line = trim(line) // ';'
    end do
    line = trim(line) // ','
    do i = 1, nouts
      write(buf,'(ES25.17E3)') outs(i)
      line = trim(line) // trim(adjustl(buf))
      if (i < nouts) line = trim(line) // ';'
    end do
    write(*,'(A)') trim(line)
  end subroutine rowvd

  ! ------------------------------------------------------------------------
  ! hanna, hanna1, hanna_short.
  !
  ! The three routines read and write hanna_mod module state. Two of their
  ! outputs depend on state left over from a PREVIOUS call: hanna_short
  ! applies max(10.,tlu) / max(10.,tlv) to tlu/tlv it never assigns, and
  ! hanna1 leaves sigw/dsigw2dz unassigned for an unstable layer with
  ! zeta >= 1. So the prior state is set to fixed sentinels before every call
  ! and recorded in the row, which makes the carry-over part of what is
  ! verified rather than an accident of call order.
  !
  ! args:    ust, wst, ol, h, z, prior sigw, prior dsigw2dz, prior tlu, prior tlv
  ! outputs: ust (possibly clamped), sigu, sigv, sigw, dsigwdz|dsigw2dz, tlu, tlv, tlw
  subroutine emit_hanna()
    real :: usts(3), wsts(3), ols(8), hs(2), zf(10)
    real :: a(9), o(8), z
    integer :: iu, iw, io, ih, iz, which
    usts = (/ 1.e-6, 0.6, 0.6 /)
    wsts = (/ 0.0, 2.2, 2.2 /)
    ols  = (/ -3., -40., -400., -8000., 15., 150., 1500., 1.e5 /)
    hs   = (/ 250., 1600. /)
    zf   = (/ 0.0007, 0.02, 0.05, 0.2, 0.35, 0.6, 0.95, 0.98, 1.0, 1.2 /)
    do which = 1, 3
      do iu = 1, 2
        do iw = 1, 2
          do io = 1, 8
            do ih = 1, 2
              do iz = 1, 10
                ust = usts(iu); wst = wsts(iw); ol = ols(io); h = hs(ih)
                z = zf(iz) * h
                zeta = z / h
                ! sentinels for the state the routines may not overwrite
                sigu = -1.; sigv = -2.; sigw = 0.123
                dsigwdz = 0.; dsigw2dz = 0.456
                tlu = 5.; tlv = 50.; tlw = 7.
                a = (/ ust, wst, ol, h, z, sigw, dsigw2dz, tlu, tlv /)
                if (which == 1) then
                  call hanna(z)
                  o = (/ ust, sigu, sigv, sigw, dsigwdz, tlu, tlv, tlw /)
                  call rowv('hanna', a, 9, o, 8)
                else if (which == 2) then
                  call hanna1(z)
                  o = (/ ust, sigu, sigv, sigw, dsigw2dz, tlu, tlv, tlw /)
                  call rowv('hanna1', a, 9, o, 8)
                else
                  call hanna_short(z)
                  o = (/ ust, sigu, sigv, sigw, dsigwdz, tlu, tlv, tlw /)
                  call rowv('hanna_short', a, 9, o, 8)
                end if
              end do
            end do
          end do
        end do
      end do
    end do
  end subroutine emit_hanna

  ! ------------------------------------------------------------------------
  ! cbl: the skewed-PDF drift of the convective boundary layer.
  !
  ! args:    wp, zp, ust, wst, h, rhoa, rhograd, sigmaw, dsigmawdz, tlw, ol, ldirect
  ! outputs: ptot, Q, phi, ath, bth, flagrein
  subroutine emit_cbl()
    real :: wps(5), zfs(5), wsts(3), ols(4), sws(2), dsws(2)
    real :: a(12), o(6)
    real :: wp, zp, hh, ptot, qq, phi, ath, bth, rhoa, rhograd, tlwv, ustv
    integer :: flagrein, iw, iz, is, io, isg, idir
    wps  = (/ -2.5, -0.4, 0.0, 0.4, 2.5 /)
    zfs  = (/ 0.04, 0.2, 0.5, 0.8, 0.96 /)
    wsts = (/ 0.0, 0.8, 2.4 /)
    ! -75.5 puts -h/L = 14.57, inside the sine taper's last unit below 15
    ols  = (/ -8., -75.5, -90., -900. /)
    sws  = (/ 0.35, 1.1 /)
    dsws = (/ -1.5e-3, 2.e-4 /)
    hh = 1100.; rhoa = 1.18; rhograd = -1.1e-4; tlwv = 120.; ustv = 0.35
    do idir = -1, 1, 2
      ldirect = idir
      do iw = 1, 5
        do iz = 1, 5
          do is = 1, 3
            do io = 1, 4
              do isg = 1, 2
                wp = wps(iw); zp = zfs(iz) * hh
                flagrein = 0
                call cbl(wp, zp, ustv, wsts(is), hh, rhoa, rhograd, sws(isg), &
                         dsws(isg), tlwv, ptot, qq, phi, ath, bth, ols(io), flagrein)
                a = (/ wp, zp, ustv, wsts(is), hh, rhoa, rhograd, sws(isg), &
                       dsws(isg), tlwv, ols(io), real(idir) /)
                o = (/ ptot, qq, phi, ath, bth, real(flagrein) /)
                call rowv('cbl', a, 12, o, 6)
              end do
            end do
          end do
        end do
      end do
    end do
  end subroutine emit_cbl

  ! ------------------------------------------------------------------------
  ! getrb: quasi-laminar sublayer resistance.
  ! args: ustar, nyl, diffh2o, reldiff ; outputs: rb (rb is left untouched
  ! when reldiff <= 0 -- the sentinel -7 records that)
  subroutine emit_getrb()
    real :: usts(4), nyls(2), rds(4), rb(maxspec), rd(maxspec)
    integer :: iu, in, ir
    usts = (/ 0.01, 0.1, 0.4, 1.2 /)
    nyls = (/ 1.3e-5, 1.6e-5 /)
    rds  = (/ -1.0, 0.0, 0.8, 2.5 /)
    do iu = 1, 4
      do in = 1, 2
        do ir = 1, 4
          rb = -7.; rd(1) = rds(ir)
          call getrb(1, usts(iu), nyls(in), 2.4e-5, rd, rb)
          call rowv('getrb', (/ usts(iu), nyls(in), 2.4e-5, rds(ir) /), 4, &
                    (/ rb(1) /), 1)
        end do
      end do
    end do
  end subroutine emit_getrb

  ! ------------------------------------------------------------------------
  ! getrc: Wesely (1989) bulk surface resistance for gases.
  !
  ! getrc reads the season x landuse resistance tables from com_mod. Those
  ! tables are DATA (FLEXPART reads them from options/surfdepo.t); the port
  ! takes them as an input struct, so here they are set to sweep values in
  ! slot (season=1, class=1) and recorded in the row.
  !
  ! args: t(degC), gr, rh, rr, ri, rac, rcl, rgs, rlu, rm, henry, f0, reldiff
  ! outputs: rc (sentinel -7 when reldiff <= 0)
  subroutine emit_getrc()
    real :: ts(4), grs(2), rhs(2), rrs(2), sets(5,5), sp(4,3)
    real :: rc(maxspec), a(13)
    integer :: it, ig, ih, ir, is, isp
    ts  = (/ -6., 0.5, 27., 44. /)
    grs = (/ 0., 820. /)
    rhs = (/ 0.55, 0.96 /)
    rrs = (/ 0., 2.e-4 /)
    ! columns: ri, rac, rcl, rgs, rlu
    sets(:,1) = (/ 9999., 2000., 1.e25, 1000., 1.e25 /)
    sets(:,2) = (/ 60., 100., 2000., 300., 2000. /)
    sets(:,3) = (/ 120., 1500., 2000., 500., 2000. /)
    sets(:,4) = (/ 400., 300., 1.e25, 0., 9999. /)
    sets(:,5) = (/ 9999., 0., 1.e25, 2000., 1.e25 /)
    ! species rows: rm, henry, f0, reldiff
    sp(:,1) = (/ 0., 1.e14, 0., 1.9 /)       ! HNO3-like
    sp(:,2) = (/ 0., 1.e-2, 1., 1.6 /)       ! O3-like
    sp(:,3) = (/ 100., 1.e5, 0.1, 1.3 /)     ! with mesophyll resistance
    do isp = 1, 3
      do is = 1, 5
        do it = 1, 4
          do ig = 1, 2
            do ih = 1, 2
              do ir = 1, 2
                ri(1,1) = sets(1,is); rac(1,1) = sets(2,is)
                rcl(1,1,1) = sets(3,is); rgs(1,1,1) = sets(4,is)
                rlu(1,1,1) = sets(5,is)
                rm(1) = sp(1,isp); henry(1) = sp(2,isp); f0(1) = sp(3,isp)
                reldiff(1) = sp(4,isp)
                rc = -7.
                call getrc(1, 1, 1, ts(it), grs(ig), rhs(ih), rrs(ir), rc)
                a = (/ ts(it), grs(ig), rhs(ih), rrs(ir), sets(1,is), sets(2,is), &
                       sets(3,is), sets(4,is), sets(5,is), sp(1,isp), sp(2,isp), &
                       sp(3,isp), sp(4,isp) /)
                call rowv('getrc', a, 13, (/ rc(1) /), 1)
              end do
            end do
          end do
        end do
      end do
    end do
    ! reldiff <= 0: rc must be left untouched
    reldiff(1) = -1.
    rc = -7.
    call getrc(1, 1, 1, 12., 140., 0.55, 0., rc)
    a = (/ 12., 140., 0.55, 0., sets(1,2), sets(2,2), sets(3,2), sets(4,2), &
           sets(5,2), 0., 1.e5, 0.1, -1. /)
    ri(1,1) = sets(1,2); rac(1,1) = sets(2,2); rcl(1,1,1) = sets(3,2)
    rgs(1,1,1) = sets(4,2); rlu(1,1,1) = sets(5,2); rm(1) = 0.; henry(1) = 1.e5
    f0(1) = 0.1
    rc = -7.
    call getrc(1, 1, 1, 12., 140., 0.55, 0., rc)
    call rowv('getrc', a, 13, (/ rc(1) /), 1)
  end subroutine emit_getrc

  ! ------------------------------------------------------------------------
  ! Size distribution used by partdep / getvdep for a particle species:
  ! ni bins with increasing settling velocity and decreasing Schmidt factor.
  subroutine particle_bins(scale)
    real, intent(in) :: scale
    integer :: j
    real :: s
    s = 0.
    do j = 1, ni
      vset(1,j)  = scale * 1.e-5 * real(j)**2.3
      schmi(1,j) = (0.9 / real(j))**0.66667
      fract(1,j) = real(j) * exp(-0.35 * real(j))
      s = s + fract(1,j)
    end do
    do j = 1, ni
      fract(1,j) = fract(1,j) / s
    end do
  end subroutine particle_bins

  ! partdep: particle deposition velocity (Slinn / Seinfeld-Pandis form).
  ! args: ustar, ra, nyl, scale, initial vdep, density ; outputs: vdep
  subroutine emit_partdep()
    real :: usts(5), ras(3), scales(3), vdep(maxspec), dens(2), a(6), b(1+3*ni)
    integer :: iu, ir, is, id, j
    usts   = (/ 5.e-6, 0.02, 0.15, 0.6, 1.8 /)
    ras    = (/ 8., 90., 1100. /)
    scales = (/ 0.01, 1., 300. /)
    dens   = (/ -1., 2300. /)
    ! the size bins, once per scale: scale, vset(1:ni), schmi(1:ni), fract(1:ni)
    do is = 1, 3
      call particle_bins(scales(is))
      b(1) = scales(is)
      do j = 1, ni
        b(1+j) = vset(1,j); b(1+ni+j) = schmi(1,j); b(1+2*ni+j) = fract(1,j)
      end do
      call rowv('particle_bins', b, 1+3*ni, (/ 0. /), 1)
    end do
    do id = 1, 2
      do is = 1, 3
        call particle_bins(scales(is))
        do iu = 1, 5
          do ir = 1, 3
            density(1) = dens(id)
            vdep(1) = 3.e-4
            call partdep(1, density, fract, schmi, vset, ras(ir), usts(iu), &
                         1.5e-5, vdep)
            a = (/ usts(iu), ras(ir), 1.5e-5, scales(is), 3.e-4, dens(id) /)
            call rowv('partdep', a, 6, (/ vdep(1) /), 1)
          end do
        end do
      end do
    end do
  end subroutine emit_partdep

  ! ------------------------------------------------------------------------
  ! getvdep: the full dry deposition velocity for one grid cell.
  !
  ! Composes caldate (season), getrb, raerod (per landuse class), getrc and
  ! partdep. The Wesely tables are filled with a deterministic synthetic
  ! pattern over all 5 seasons x 13 classes; the landuse fractions and z0 per
  ! class are recorded as part of the case (they are inputs the port takes).
  !
  ! args: jul(as offset from bdate=0 baseline via bdate), lat, ust, temp, pa,
  !       L, gr, rh, rr, snow, species kind
  ! outputs: vdepo, plus the season the port must derive (from caldate)
  subroutine fill_wesely()
    integer :: i, j
    do i = 1, 5
      do j = 1, numclass
        ri(i,j)  = 60. + 37.*real(i) + 11.*real(j)
        rac(i,j) = 10. * real(mod(i*j, 7)) * real(j)
        rcl(1,i,j) = 500. + 83.*real(i+j)
        rgs(1,i,j) = 100. + 41.*real(mod(3*i+j, 11))
        rlu(1,i,j) = 1000. + 125.*real(j) - 30.*real(i)
      end do
    end do
    ! a few classes with the 'inactive' 9999 / 1.e25 markers of surfdepo.t
    ri(:,1) = 9999.; rac(:,1) = 0.; rlu(1,:,1) = 1.e25
    ri(:,12) = 9999.; rcl(1,:,12) = 1.e25
    do j = 1, numclass
      z0(j) = 1.e-4 * 10.**(real(j)*0.27)
    end do
  end subroutine fill_wesely

  subroutine emit_getvdep()
    double precision :: juls(7)
    real :: lats(3), usts(2), temps(2), Ls(2), snows(2), vdepo(maxspec)
    real :: a(13), out(1)
    integer :: id, ilat, iu, it, iobk, isn, ik, i, j, jy
    ! dates (Julian days at 12 UTC): Jan, Mar 15, May 1, Jul, Oct, Nov 20 of 2021
    ! the last, May 2, lands on Oct 31 after the southern-hemisphere +182 d
    ! shift, one half day before the Nov 1 season boundary
    juls = (/ 2459216.5d0, 2459289.5d0, 2459336.5d0, 2459397.5d0, &
              2459489.5d0, 2459539.5d0, 2459337.5d0 /)
    lats = (/ 52., 4., -37. /)
    usts = (/ 0.08, 0.55 /)
    temps = (/ 268., 304. /)
    Ls = (/ -60., 400. /)
    snows = (/ 0., 0.02 /)
    call fill_wesely()
    nspec = 1
    dy = 1.; ylat0 = -90.
    wftime(1) = 0
    do j = 1, numclass
      xlanduse(3, :, j) = 0.
    end do
    ! landuse at the cell: classes 1, 4, 7, 12 present (fractions sum to 1)
    xlanduse(3, :, 1) = 0.1
    xlanduse(3, :, 4) = 0.45
    xlanduse(3, :, 7) = 0.3
    xlanduse(3, :, 12) = 0.15
    ! the tables, once: season, class, ri, rac, rcl, rgs, rlu, z0, landuse fraction
    do i = 1, 5
      do j = 1, numclass
        call rowv('wesely', (/ real(i), real(j), ri(i,j), rac(i,j), rcl(1,i,j), &
             rgs(1,i,j), rlu(1,i,j), z0(j), xlanduse(3,1,j) /), 9, (/ 0. /), 1)
      end do
    end do
    do ik = 1, 3
      ! species kind: 1 gas, 2 particle, 3 prescribed dryvel
      if (ik == 1) then
        reldiff(1) = 1.6; density(1) = -1.; henry(1) = 1.e-2; f0(1) = 1.
        rm(1) = 0.; dryvel(1) = -1.
      else if (ik == 2) then
        reldiff(1) = -1.; density(1) = 2300.; dryvel(1) = -1.
        call particle_bins(1.)
      else
        reldiff(1) = -1.; density(1) = -1.; dryvel(1) = 4.e-3
      end if
      do id = 1, 7
        do ilat = 1, 3
          do iu = 1, 2
            do it = 1, 2
              do iobk = 1, 2
                do isn = 1, 2
                  bdate = juls(id)
                  jy = nint(lats(ilat) - ylat0)
                  call getvdep(1, 3, jy, usts(iu), temps(it), 99000., Ls(iobk), &
                               420., 0.7, 0., snows(isn), vdepo)
                  out(1) = vdepo(1)
                  a(1:13) = (/ real(juls(id) - 2459000.d0), lats(ilat), usts(iu), &
                       temps(it), 99000., Ls(iobk), 420., 0.7, 0., snows(isn), &
                       real(ik), real(jy), real(ylat0) /)
                  call rowv('getvdep', a, 13, out, 1)
                end do
              end do
            end do
          end do
        end do
      end do
    end do
  end subroutine emit_getvdep

  ! ------------------------------------------------------------------------
  ! get_settling: iterative settling velocity with a Reynolds-dependent drag.
  ! Reads height/rho/tt from com_mod; a 6-level synthetic column is set at
  ! (nix,njy) = (2,2).
  ! args: zt, dquer, density, cunningham, vsetaver ; outputs: settling
  subroutine emit_settling()
    real :: zts(5), dq(7), dens(2), settling, a(5)
    integer :: iz, idq, idn, k
    nz = 6
    height(1:6) = (/ 0., 40., 150., 500., 1500., 4000. /)
    do k = 1, 6
      tt(2,2,k,1)  = 293. - 0.0065*height(k)
      rho(2,2,k,1) = 1.2 * exp(-height(k)/8500.)
    end do
    zts = (/ 2., 95., 420., 1499., 3000. /)
    ! 900 um iterates through Re = 400..500 (18.5/Re**0.6 regime, next to the
    ! 0.44 switch at 500); 1500 um ends in the 0.44 regime
    dq  = (/ 0.4, 4., 25., 90., 400., 900., 1500. /)
    dens = (/ 1000., 2650. /)
    do idn = 1, 2
      do idq = 1, 7
        do iz = 1, 5
          dquer(1) = dq(idq); density(1) = dens(idn)
          cunningham(1) = 1. + 0.16 / dq(idq)
          ! Stokes first guess, as part0 provides it (negative = downward)
          vsetaver(1) = -dens(idn) * ga * (dq(idq)*1.e-6)**2 / (18.*1.8e-5)
          call get_settling(0, 2.3, 2.6, zts(iz), 1, settling)
          a = (/ zts(iz), dq(idq), dens(idn), cunningham(1), vsetaver(1) /)
          call rowv('get_settling', a, 5, (/ settling /), 1)
        end do
      end do
    end do
  end subroutine emit_settling

  ! ------------------------------------------------------------------------
  ! pbl_profile: surface stress and sensible heat flux from the profile method.
  ! args: ps, td2m, zml1, t2m, tml1, u10m, uml1 ; outputs: stress, hf
  subroutine emit_pbl_profile()
    real :: dts(7), dus(4), zmls(2), stress, hf, a(7)
    integer :: it, iu, iz
    ! tml1 - t2m offsets: unstable, slightly unstable, neutral band, stable
    dts  = (/ -3.0, -0.8, -0.2, 0.0, 0.25, 0.9, 4.0 /)
    dus  = (/ 0.0005, 0.6, 3.5, 11. /)
    zmls = (/ 30., 75. /)
    do iz = 1, 2
      do it = 1, 7
        do iu = 1, 4
          a = (/ 100500., 279., zmls(iz), 288., 288. + dts(it) - 0.0098*(zmls(iz)-2.), &
                 2.5, 2.5 + dus(iu) /)
          call pbl_profile(a(1), a(2), a(3), a(4), a(5), a(6), a(7), stress, hf)
          call rowv('pbl_profile', a, 7, (/ stress, hf /), 2)
        end do
      end do
    end do
  end subroutine emit_pbl_profile

  ! ------------------------------------------------------------------------
  ! richardson: bulk-Richardson mixing height, with the convective excess
  ! iteration, on synthetic columns, in both the ECMWF (hybrid) and NCEP
  ! (pressure-level) branches.
  !
  ! args: metformat, psurf, ust, hf, tt2, td2, nuvz, then the columns
  !       akz(1:n), bkz(1:n), tt(1:n), qv(1:n), u(1:n), v(1:n)
  ! outputs: h, wst, hmixplus
  subroutine emit_richardson()
    integer, parameter :: n = 24
    real :: akz(n), bkz(n), ttl(n), qvl(n), ul(n), vl(n), zk(n)
    real :: hfs(3), usts(2), h_out, wst_out, hmixplus, a(7), col(2+6*n)
    integer :: ip, ifm, ih, iu, k, fmt
    hfs  = (/ -180., 0., 40. /)
    usts = (/ 0.12, 0.55 /)
    do k = 1, n
      zk(k) = 30. * (real(k-1))**1.6
    end do
    do ifm = 1, 2
      do ip = 1, 3
        do k = 1, n
          ! temperature profile: 1 = mixed layer capped at ~900 m,
          ! 2 = surface-based stable, 3 = deep near-adiabatic
          if (ip == 1) then
            if (zk(k) < 900.) then
              ttl(k) = 300. - 0.0098*zk(k)
            else
              ttl(k) = 300. - 0.0098*900. + 3. - 0.004*(zk(k)-900.)
            end if
          else if (ip == 2) then
            ttl(k) = 283. + 0.012*min(zk(k), 300.) - 0.0055*max(zk(k)-300., 0.)
          else
            ttl(k) = 305. - 0.0095*zk(k)
          end if
          qvl(k) = 0.011 * exp(-zk(k)/2200.)
          ul(k) = 2. + 9. * (1. - exp(-zk(k)/400.))
          vl(k) = 1. - 4. * (1. - exp(-zk(k)/700.))
          if (ifm == 1) then
            ! ECMWF hybrid: pure sigma levels, level 1 at the surface
            akz(k) = 0.
            bkz(k) = exp(-zk(k)/8200.)
          else
            ! NCEP: pressure levels, the lowest ones below ground
            akz(k) = 103000. * exp(-zk(k)/8200.)
            bkz(k) = 0.
          end if
        end do
        if (ifm == 1) then
          fmt = GRIBFILE_CENTRE_ECMWF
        else
          fmt = GRIBFILE_CENTRE_NCEP
        end if
        ! the column, once: format, profile id, akz, bkz, tt, qv, u, v
        col(1) = real(fmt); col(2) = real(ip)
        col(3:2+n) = akz; col(3+n:2+2*n) = bkz; col(3+2*n:2+3*n) = ttl
        col(3+3*n:2+4*n) = qvl; col(3+4*n:2+5*n) = ul; col(3+5*n:2+6*n) = vl
        call rowv('richardson.column', col, 2+6*n, (/ 0. /), 1)
        do ih = 1, 3
          do iu = 1, 2
            call richardson(101300., usts(iu), ttl, qvl, ul, vl, n, akz, bkz, &
                 hfs(ih), ttl(1) + 0.4, ttl(1) - 6., h_out, wst_out, hmixplus, fmt)
            a = (/ real(fmt), real(ip), 101300., usts(iu), hfs(ih), ttl(1)+0.4, ttl(1)-6. /)
            call rowv('richardson', a, 7, (/ h_out, wst_out, hmixplus /), 3)
          end do
        end do
      end do
    end do
  end subroutine emit_richardson

