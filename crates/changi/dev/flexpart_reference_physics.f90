  ! ------------------------------------------------------------------------
  ! juldate / caldate. The port does NOT translate these -- caldate.f90 is
  ! "adapted from Numerical Recipes" -- but it must produce the same
  ! conversion, so upstream's answers are recorded here for comparison.
  !   julian: args yyyymmdd, hhmmss ; outputs juldate
  !   caldate: args jul ; outputs yyyymmdd, hhmmss
  subroutine emit_calendar()
    integer :: dates(14), times(6), i, j, ymd, hms
    double precision :: juldate, jul, fracs(9)
    dates = (/ 15821015, 16000229, 18991231, 19000101, 19700101, 19991231, &
               20000229, 20000301, 20210615, 20211231, 21000228, 21000301, &
               23440704, 19830418 /)
    times = (/ 0, 1, 115959, 120000, 235959, 81530 /)
    do i = 1, 14
      do j = 1, 6
        call rowvd('juldate', (/ dble(dates(i)), dble(times(j)) /), 2, &
                   (/ juldate(dates(i), times(j)) /), 1)
      end do
    end do
    ! fractional days, including values a hair either side of a minute so the
    ! ss == 60 rollover path is exercised
    fracs = (/ 0.d0, 0.25d0, 0.5d0, 0.999999d0, 0.6944444444d0, &
               0.69444444444444d0 - 1.d-9, 0.0006944444d0 + 1.d-7, &
               59.5d0/86400.d0, 0.123456789d0 /)
    do i = 1, 14
      do j = 1, 9
        jul = dble(int(juldate(dates(i), 0))) + fracs(j)
        call caldate(jul, ymd, hms)
        call rowvd('caldate', (/ jul /), 1, (/ dble(ymd), dble(hms) /), 2)
      end do
    end do
  end subroutine emit_calendar

