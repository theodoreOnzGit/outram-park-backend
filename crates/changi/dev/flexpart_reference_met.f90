  ! ------------------------------------------------------------------------
  ! wetdepo over 14 particles, four runs:
  !   1 forward, itime <= loutnext, nested output, per-release output,
  !     aerosol species 3, decay 1e-5
  !   2 forward, itime > loutnext, no nested output, gas species 1
  !   3 backward, WETDEPSPEC false
  !   4 backward, aerosol species 3 (masses only; no gridding backward)
  ! wd.particle: run, jpart, itra1, itramem, x, y, z, npoint, nclass, mass
  ! wd.run: run, itime, ltsample, loutnext, loutstep, ldirect, kernel, nested,
  !         per-release, decay, wetdepspec, species id, memind(1)
  ! outs: wetdepo.mass (run, jpart ; mass), wetdepo.grid (run, grid, kp ; values),
  !       wetdepo.counts (run ; tot_blc, tot_inc)
  subroutine emit_wetdepo()
    real :: px(14), py(14), pz(14), sp(8)
    integer :: it1(14), run, j, isp
    integer :: itime, ltsample, loutnext
    px = (/ 0.5, 1.2, 2.25, 3.0, 4.6, 1.8, 2.6, 3.4, 0.2, 4.95, 2.1, 1.1, 3.9, 2.9 /)
    py = (/ 0.5, 2.3, 1.75, 3.1, 0.4, 1.3, 2.2, 1.6, 3.9, 3.3, 2.9, 0.9, 1.1, 3.4 /)
    pz = (/ 120., 640., 299., 1700., 2800., 450., 1000., 2100., 60., 4500., 880., 310., &
            3300., 1500. /)
    it1 = (/ 0, 600, 1200, -999999999, 5400, 7200, 9000, 100, 2000, 4000, 5000, &
             6000, 5400, 7000 /)
    dx = 0.5; dy = 0.5
    call setup_outgrids()
    memtime(1) = 0; memtime(2) = 10801
    memind(1) = 2; memind(2) = 1
    loutstep = 10800
    lage(1) = 86400
    numpart = 14
    do run = 1, 4
      if (run == 1) then
        ldirect = 1; itime = 7200; ltsample = 900; loutnext = 10800
        nested_output = 1; ioutputforeachrelease = 1
        decay(1) = 1.e-5; WETDEPSPEC(1) = .true.; isp = 3
      else if (run == 2) then
        ldirect = 1; itime = 14400; ltsample = 900; loutnext = 10800
        nested_output = 0; ioutputforeachrelease = 0
        decay(1) = 0.; WETDEPSPEC(1) = .true.; isp = 1
      else if (run == 3) then
        ldirect = -1; itime = 3600; ltsample = 900; loutnext = 0
        nested_output = 0; ioutputforeachrelease = 0
        decay(1) = 0.; WETDEPSPEC(1) = .false.; isp = 3
      else
        ldirect = -1; itime = 3600; ltsample = 900; loutnext = 0
        nested_output = 0; ioutputforeachrelease = 0
        decay(1) = 2.e-6; WETDEPSPEC(1) = .true.; isp = 3
      end if
      call wet_species(isp, sp)
      call set_species(sp)
      wetgridunc = 0.; wetgriduncn = 0.
      tot_blc_count = 0; tot_inc_count = 0
      call rowv('wd.run', (/ real(run), real(itime), real(ltsample), real(loutnext), &
           real(loutstep), real(ldirect), 1., real(nested_output), &
           real(ioutputforeachrelease), decay(1), merge(1.,0.,WETDEPSPEC(1)), real(isp), &
           real(memind(1)) /), 13, (/ 0. /), 1)
      do j = 1, 14
        itra1(j) = it1(j)
        if (ldirect == -1 .and. it1(j) /= -999999999) itra1(j) = 9000 - it1(j)
        itramem(j) = 0
        xtra1(j) = dble(px(j)); ytra1(j) = dble(py(j)); ztra1(j) = pz(j)
        npoint(j) = 1 + mod(j, 2); nclass(j) = 1
        xmass1(j,1) = 1.0 + 0.1*real(j)
        call rowv('wd.particle', (/ real(run), real(j), real(itra1(j)), real(itramem(j)), &
             px(j), py(j), pz(j), real(npoint(j)), real(nclass(j)), xmass1(j,1) /), 10, &
             (/ 0. /), 1)
      end do
      call wetdepo(itime, ltsample, loutnext)
      do j = 1, 14
        call rowv('wetdepo.mass', (/ real(run), real(j) /), 2, (/ xmass1(j,1) /), 1)
      end do
      call dump_grids('wetdepo.grid', run)
      call rowv('wetdepo.counts', (/ real(run) /), 1, &
           (/ real(tot_blc_count(1)), real(tot_inc_count(1)) /), 2)
    end do
    ldirect = 1
    memind(1) = 1; memind(2) = 2
  end subroutine emit_wetdepo

  ! ------------------------------------------------------------------------
  ! OH: an 8 x 6 x 4 climatology; jrate_average from an integer formula
  ! (exact in f32), checked by oh.jrcheck rows.
  real function jr_formula(i, j, m)
    integer, intent(in) :: i, j, m
    jr_formula = real(mod(i*7 + j*13 + m*5, 11)) / 1048576.
  end function jr_formula

  subroutine dump_oh_state(tag, a1, a2)
    character(len=*), intent(in) :: tag
    real, intent(in) :: a1, a2
    real :: v(2 + 2*8*6*4)
    integer :: ix, jy, kz, h, c
    v(1) = memOHtime(1); v(2) = memOHtime(2)
    c = 2
    do h = 1, 2
      do kz = 1, nzOH
        do jy = 1, nyOH
          do ix = 1, nxOH
            c = c + 1
            v(c) = OH_hourly(ix,jy,kz,h)
          end do
        end do
      end do
    end do
    call rowv(tag, (/ a1, a2 /), 2, v, c)
  end subroutine dump_oh_state

  subroutine emit_oh()
    integer :: i, j, m, kz, ix, jy, k, run, its(10), itsb(4)
    real :: v(120), lt
    real :: px(10), py(10), pz(10)
    integer :: it1(10)
    nxOH = 8; nyOH = 6; nzOH = 4
    allocate(lonOH(nxOH), latOH(nyOH), altOH(nzOH), OH_field(nxOH,nyOH,nzOH,12), &
             OH_hourly(nxOH,nyOH,nzOH,2))
    lonOH = (/ -158., -112.5, -67.5, -22.5, 22.5, 67.5, 112.5, 157.3 /)
    latOH = (/ -75., -45., -15., 15., 45., 75. /)
    altOH = (/ 500., 1500., 3500., 7000. /)
    do i = 1, 360
      lonjr(i) = -179.5 + real(i-1)
    end do
    do j = 1, 180
      latjr(j) = -89.5 + real(j-1)
    end do
    do m = 1, 12
      do j = 1, 180
        do i = 1, 360
          jrate_average(i,j,m) = jr_formula(i, j, m)
        end do
      end do
    end do
    do m = 1, 12
      do kz = 1, nzOH
        do jy = 1, nyOH
          do ix = 1, nxOH
            OH_field(ix,jy,kz,m) = 1.e5 * real(1 + mod(ix + 2*jy + 3*kz + m, 7)) &
                 * (1. + 0.1*real(m))
          end do
        end do
      end do
    end do
    call rowv('oh.coords', (/ lonOH, latOH, altOH /), nxOH+nyOH+nzOH, (/ 0. /), 1)
    do m = 1, 12
      do kz = 1, nzOH
        call rowv('oh.field', (/ real(m), real(kz) /), 2, &
             reshape(OH_field(:,:,kz,m), (/ nxOH*nyOH /)), nxOH*nyOH)
      end do
    end do
    call rowv('oh.lonjr', lonjr, 360, (/ 0. /), 1)
    call rowv('oh.latjr', latjr, 180, (/ 0. /), 1)
    do k = 1, 40
      i = 1 + mod(k*37, 360); j = 1 + mod(k*53, 180); m = 1 + mod(k, 12)
      call rowv('oh.jrcheck', (/ real(i), real(j), real(m) /), 3, &
           (/ jrate_average(i,j,m) /), 1)
    end do

    ! gethourlyOH sequences
    bdate = 2459246.1666666665d0   ! 2021-01-31 16:00 (juldate)
    call rowvd('oh.bdate', (/ bdate /), 1, (/ 0.d0 /), 1)
    ! hourly steps up to 32400 s cross into February (m2 = 2); 60000 is a
    ! jump of more than an hour (only one step is taken); -100 re-initialises
    its = (/ 0, 1800, 3600, 7200, 14400, 21600, 28800, 32400, 60000, -100 /)
    memOHtime = 0.; OH_hourly = 0.
    ldirect = 1
    do i = 1, 10
      call gethourlyOH(its(i))
      call dump_oh_state('gethourlyOH', real(ldirect), real(its(i)))
    end do
    itsb = (/ 0, -1800, -3600, -7200 /)
    memOHtime = 0.; OH_hourly = 0.
    ldirect = -1
    do i = 1, 4
      call gethourlyOH(itsb(i))
      call dump_oh_state('gethourlyOH', real(ldirect), real(itsb(i)))
    end do

    ! ohreaction: state after the initial forward call (fields at 0 and 3600 s)
    ldirect = 1
    memOHtime = 0.; OH_hourly = 0.
    call gethourlyOH(0)
    call dump_oh_state('oh.state', 0., 0.)
    nx = 10; ny = 12; nxmin1 = 9; nymin1 = 11
    dx = 10.; dy = 5.; xlon0 = 100.; ylat0 = -40.
    nz = 6
    height(1:6) = (/ 0., 250., 800., 2000., 4500., 9000. /)
    memtime(1) = 0; memtime(2) = 10801
    xln(1) = 2.5; xrn(1) = 5.0; yln(1) = 3.0; yrn(1) = 6.0
    xresoln(1) = 2.; yresoln(1) = 2.
    call rowv('oh.met', (/ dx, dy, xlon0, ylat0, real(nx), real(ny), height(1:6), &
         xln(1), xrn(1), yln(1), yrn(1), xresoln(1), yresoln(1) /), 18, (/ 0. /), 1)
    do m = 1, 2
      do k = 1, 6
        do jy = 0, ny-1
          do ix = 0, nx-1
            tt(ix,jy,k,m) = 285. + 1.5*real(ix) - 0.8*real(jy) - 0.006*height(k) &
                 + 7.*real(m-1)
            v(1+ix+nx*jy) = tt(ix,jy,k,m)
          end do
        end do
        call rowv('oh.tt', (/ real(m), real(k) /), 2, v, nx*ny)
      end do
    end do
    px = (/ 0.5, 3.2, 8.9, 4.0, 6.3, 1.1, 9.5, 2.0, 7.7, 3.6 /)
    py = (/ 0.5, 4.4, 2.1, 5.2, 10.6, 7.3, 11.2, 0.2, 6.6, 3.5 /)
    pz = (/ 100., 900., 2600., 30., 4400., 1999., 6000., 5000., 1000., 260. /)
    it1 = (/ 0, 600, -999999999, 99999, 1800, 2400, 3000, 0, 100, 200 /)
    numpart = 10
    do run = 1, 4
      ! 1: moderate rate, itime inside the OH interval, earlier met field
      ! 2: itime beyond the OH interval (extrapolation), later met field
      ! 3: no reaction (ohcconst = 0)
      ! 4: rate so large the mass underflows to 0 in both precisions
      ohcconst(1) = 1.e-17; ohdconst(1) = 1500.; ohnconst(1) = 2.
      lt = 900.
      k = 1800
      if (run == 2) k = 9000
      if (run == 3) ohcconst(1) = 0.
      if (run == 4) then
        ohcconst(1) = 1.e-6; lt = 3600.
      end if
      call rowv('oh.run', (/ real(run), real(k), lt, ohcconst(1), ohdconst(1), &
           ohnconst(1) /), 6, (/ 0. /), 1)
      do j = 1, 10
        itra1(j) = it1(j)
        xtra1(j) = dble(px(j)); ytra1(j) = dble(py(j)); ztra1(j) = pz(j)
        xmass1(j,1) = 2.0 - 0.05*real(j)
        call rowv('oh.particle', (/ real(run), real(j), real(itra1(j)), px(j), py(j), &
             pz(j), xmass1(j,1) /), 7, (/ 0. /), 1)
      end do
      call ohreaction(k, nint(lt), 0)
      do j = 1, 10
        call rowv('ohreaction', (/ real(run), real(j) /), 2, (/ xmass1(j,1) /), 1)
      end do
    end do
  end subroutine emit_oh

  ! ------------------------------------------------------------------------
  ! assignland: landinvent from an integer formula (zero weights for
  ! inventory columns 1..25, i.e. 180W..172.5W), two calls:
  !   A: mother 6 x 5 at 179W.., 40.1N.., plus a nest 8 x 5 crossing 180E
  !   B: mother 6 x 4 from 150E (crossing 180), top row 89.99N whose samples
  !      reach 93.6N (wrapped to the South Pole rows), no nest
  ! The origins and spacings are chosen so that no sample falls exactly on an
  ! inventory cell boundary, where the cell would be decided by rounding.
  ! lu.grid: call, grid(0/1), nx, ny, dx, dy, xlon0, ylat0
  ! lu.lsm: call, grid ; values      assignland: call, grid, ix, jy ; 13 fractions
  subroutine fill_landinvent()
    integer :: i, j
    do j = 1, 600
      do i = 1, 1200
        landinvent(i,j,1) = int(1 + mod(i*7 + j*3, 13), 1)
        landinvent(i,j,2) = int(1 + mod(i*5 + j*11 + 4, 13), 1)
        landinvent(i,j,3) = int(1 + mod(i + j*2 + 9, 13), 1)
        if (i <= 25) then
          landinvent(i,j,4:6) = 0_1
        else
          landinvent(i,j,4) = int(mod(i + 2*j, 16), 1)
          landinvent(i,j,5) = int(mod(3*i + j, 11), 1)
          landinvent(i,j,6) = int(mod(i*j, 7), 1)
        end if
      end do
    end do
  end subroutine fill_landinvent

  subroutine emit_assignland()
    integer :: c, ix, jy, k, g, i, j
    real :: v(60)
    call fill_landinvent()
    do k = 1, 30
      i = 1 + mod(k*97, 1200); j = 1 + mod(k*41, 600)
      if (k == 1) i = 10
      call rowv('lu.check', (/ real(i), real(j) /), 2, real(landinvent(i,j,1:6)), 6)
    end do
    do c = 1, 2
      if (c == 1) then
        nx = 6; ny = 5; dx = 1.5; dy = 1.27; xlon0 = -179.; ylat0 = 40.1
        numbnests = 1
        nxn(1) = 8; nyn(1) = 5; dxn(1) = 0.41; dyn(1) = 0.353
        xlon0n(1) = 178.23; ylat0n(1) = -12.37
      else
        nx = 6; ny = 4; dx = 7.53; dy = 3.98; xlon0 = 150.07; ylat0 = 78.05
        numbnests = 0
      end if
      nxmin1 = nx - 1; nymin1 = ny - 1
      do jy = 0, ny-1
        do ix = 0, nx-1
          lsm(ix,jy) = 0.05 + 0.05*real(mod(ix + jy, 3))
          if (mod(ix+jy,3) == 2) lsm(ix,jy) = 0.6
          v(1+ix+nx*jy) = lsm(ix,jy)
        end do
      end do
      call rowv('lu.grid', (/ real(c), 0., real(nx), real(ny), dx, dy, xlon0, ylat0 /), 8, &
           (/ 0. /), 1)
      call rowv('lu.lsm', (/ real(c), 0. /), 2, v, nx*ny)
      if (numbnests == 1) then
        do jy = 0, nyn(1)-1
          do ix = 0, nxn(1)-1
            lsmn(ix,jy,1) = 0.05 + 0.05*real(mod(ix + 2*jy, 3))
            v(1+ix+nxn(1)*jy) = lsmn(ix,jy,1)
          end do
        end do
        call rowv('lu.grid', (/ real(c), 1., real(nxn(1)), real(nyn(1)), dxn(1), dyn(1), &
             xlon0n(1), ylat0n(1) /), 8, (/ 0. /), 1)
        call rowv('lu.lsm', (/ real(c), 1. /), 2, v, nxn(1)*nyn(1))
      end if
      call assignland()
      do jy = 0, ny-1
        do ix = 0, nx-1
          call rowv('assignland', (/ real(c), 0., real(ix), real(jy) /), 4, &
               xlanduse(ix,jy,:), numclass)
        end do
      end do
      do g = 1, numbnests
        do jy = 0, nyn(1)-1
          do ix = 0, nxn(1)-1
            call rowv('assignland', (/ real(c), 1., real(ix), real(jy) /), 4, &
                 xlandusen(ix,jy,:,1), numclass)
          end do
        end do
      end do
    end do
  end subroutine emit_assignland

