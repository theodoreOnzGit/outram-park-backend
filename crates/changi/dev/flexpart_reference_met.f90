  ! ------------------------------------------------------------------------
  ! Species table for the wet-deposition sweeps:
  ! dquer, weta_gas, wetb_gas, crain_aero, csnow_aero, ccn_aero, in_aero, henry
  subroutine wet_species(isp, sp)
    integer, intent(in) :: isp
    real, intent(out) :: sp(8)
    select case (isp)
    case (1); sp = (/ -1., 1.e-4, 0.62, 0., 0., -1., -1., 1.e5 /)      ! gas, below + Henry
    case (2); sp = (/ -1., 0., 0., 0., 0., -1., -1., 0. /)             ! gas, nothing
    case (3); sp = (/ 0.4, 0., 0., 1., 1., 0.9, 0.1, 0. /)             ! aerosol
    case (4); sp = (/ 25., 0., 0., 0.5, 0., -1., 0.2, 0. /)            ! coarse, rain only, ccn<0
    case (5); sp = (/ 2., 0., 0., 0., 0.8, -1., -1., 0. /)             ! snow only, in-cloud off
    case (6); sp = (/ -1., 0., 0.5, 0., 0., -1., -1., 1.e14 /)         ! gas B only, very soluble
    end select
  end subroutine wet_species

  subroutine set_species(sp)
    real, intent(in) :: sp(8)
    dquer(1) = sp(1); weta_gas(1) = sp(2); wetb_gas(1) = sp(3)
    crain_aero(1) = sp(4); csnow_aero(1) = sp(5); ccn_aero(1) = sp(6)
    in_aero(1) = sp(7); henry(1) = sp(8)
  end subroutine set_species

  ! get_wetscav over species x positions x times x readclouds (readclouds
  ! only with memind = (1,2)).
  ! wet.species: id ; dquer, weta, wetb, crain, csnow, ccn, in, henry
  ! args: itime, ltsample, memind(1), readclouds (= readclouds_nest), x, y, z,
  !       species id
  ! outs: wetscav, grfraction(1) (-7 if unassigned), d blc_count, d inc_count,
  !       ccn_aero after, in_aero after
  subroutine emit_get_wetscav()
    real :: px(14), py(14), pz(14), sp(8), grf(3), ws, a(8)
    integer :: itimes(3), lts(3), ip, isp, it, im, irc
    integer(selected_int_kind(16)) :: blc(1), inc(1), b0, i0
    ! positions: nodes, cell interiors, last line, nest interior
    px = (/ 0., 1., 2., 3., 4., 5., 2.5, 0.75, 1., 4.5, 2.0, 2.75, 3.25, 1.75 /)
    py = (/ 0., 1., 1., 3., 2., 4., 0.5, 3.75, 4., 0.25, 2.0, 1.25, 3.0, 1.5 /)
    pz = (/ 100., 650., 299.99, 300., 1500., 4999., 50., 2500., 900., 4000., 1200., 350., &
            2000., 800. /)
    itimes = (/ 3600, 9000, 5850 /)
    lts = (/ 900, 900, 899 /)
    memtime(1) = 0; memtime(2) = 10801
    do isp = 1, 6
      call wet_species(isp, sp)
      call rowv('wet.species', (/ real(isp) /), 1, sp, 8)
    end do
    do irc = 0, 1
      readclouds = (irc == 1); readclouds_nest(1) = (irc == 1)
      do im = 1, 2 - irc
        memind(1) = im; memind(2) = 3 - im
        do it = 1, 3
          do isp = 1, 6
            do ip = 1, 14
              call wet_species(isp, sp)
              call set_species(sp)
              xtra1(1) = dble(px(ip)); ytra1(1) = dble(py(ip)); ztra1(1) = pz(ip)
              grf = -7.
              blc = 0; inc = 0
              call get_wetscav(itimes(it), lts(it), 0, 1, 1, grf, inc, blc, ws)
              a = (/ real(itimes(it)), real(lts(it)), real(im), real(irc), &
                     px(ip), py(ip), pz(ip), real(isp) /)
              call rowv('get_wetscav', a, 8, (/ ws, grf(1), real(blc(1)), real(inc(1)), &
                   ccn_aero(1), in_aero(1) /), 6)
            end do
          end do
        end do
      end do
    end do
    readclouds = .false.; readclouds_nest(1) = .false.
    memind(1) = 1; memind(2) = 2
  end subroutine emit_get_wetscav

