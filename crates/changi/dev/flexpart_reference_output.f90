! Stage "output" code-to-code reference driver for `changi::flexpart`:
! concentration gridding (conccalc: uniform kernel on the output grids,
! parabolic kernel at receptors), the dry-deposition gridding kernel
! (drydepokernel, drydepokernel_nest), the plume-trajectory statistics
! (plumetraj with clustering, centerofmass and mean_mod's `mean`) and the
! particle-dump averaging (partpos_average).
!
! Every routine called here is UPSTREAM FLEXPART v10.4 @ 3d7eebf, compiled
! verbatim from upstream_source/FLEXPART/src by dev/build_reference_output.sh.
! Nothing below reimplements physics: the driver writes synthetic particles,
! output grids and meteorological fields straight into com_mod (no GRIB, no
! NetCDF) and prints what upstream returns.
!
! par_mod.f90 VARIANTS. par_mod.f90 is FLEXPART's user-edited configuration
! file, and three of its compile-time PARAMETERS gate branches of the routines
! under test: lusekerneloutput (kernel on/off), lparticlecountoutput (particle
! counts instead of mass) and the array bounds maxspec / maxageclass /
! nclassunc (the shipped values, 1/1/1, allow only one species, one age class
! and one uncertainty class). The build script therefore compiles this driver
! four times per precision:
!   V0  par_mod.f90 VERBATIM (as shipped);
!   V1  a COPY with maxspec=2, maxageclass=3, nclassunc=2 (kernel on);
!   V2  as V1 and lusekerneloutput=.false., lparticlecountoutput=.true.
!   V3  as V1 and lparticlecountoutput=.true. (kernel still on; conccalc only)
! Only those parameter lines differ (sed in the build script); every routine
! under test is the upstream file, untouched. The nested OUTPUT grids
! (griduncn, drygriduncn) are allocatable in unc_mod and sized by the run-time
! numxgridn/numygridn, so no maxnests change is needed for them.
!
! Synthetic meteorology: every field is an exact dyadic function of integer
! indices, value = base + scale * mod(a*ix + b*jy + c*k + d*m, q), so it is the
! same number in real(4), real(8) and the Rust test, which rebuilds it from the
! same formula (the `setup.met` row echoes nz and the level heights, and
! `setup.metcheck` rows echo sample values so a formula mismatch is caught).
!
! Row format, one row per CALL (or per non-zero grid cell for the gridding
! routines): function,a1;a2;...,o1;o2;...   real(4) builds print 9 significant
! digits (parse as f32); rows carrying real(kind=dp) particle positions are
! printed with 17 digits (rowvd) and are parsed as f64.
program flexpart_reference_output

  use par_mod
  use com_mod
  use unc_mod
  use outg_mod
  use point_mod
  use mean_mod
  implicit none

  integer :: variant

  if (maxspec == 1) then
    variant = 0
  else if (lusekerneloutput .and. .not. lparticlecountoutput) then
    variant = 1
  else if (.not. lusekerneloutput) then
    variant = 2
  else
    variant = 3
  end if

  write(*,'(A)') '# FLEXPART stage "output" reference, generated by dev/flexpart_reference_output.f90'
  write(*,'(A)') '# upstream: github.com/flexpart/flexpart v10.4 @ 3d7eebf (GPL-3.0-or-later)'
  write(*,'(A)') '# DO NOT EDIT BY HAND -- regenerate with dev/build_reference_output.sh'
  write(*,'(A)') 'function,args,outputs'

  call rowi('setup.variant', (/ variant, maxspec, maxageclass, nclassunc, &
       merge(1,0,lusekerneloutput), merge(1,0,lparticlecountoutput) /), 6)

  ipout = 3          ! so com_mod_allocate_part also allocates part_av_*
  call com_mod_allocate_part(maxpart)
  allocate(xscav_frac1(maxpart, maxspec))
  call setup_met()

  call emit_conccalc(variant)
  if (variant /= 3) call emit_drydepokernel(variant)
  if (variant == 0) then
    call emit_mean()
    call emit_centerofmass()
    call emit_clustering()
    call emit_plumetraj()
    call emit_partpos_average()
  end if

contains

  ! ------------------------------------------------------------------------
  ! Helpers copied from flexpart_reference_physics.f90.
  subroutine fmtnum(x, buf)
    double precision, intent(in) :: x
    character(len=32), intent(out) :: buf
    if (kind(1.0) == 4) then
      write(buf,'(ES16.8E3)') x
    else
      write(buf,'(ES25.17E3)') x
    end if
    buf = adjustl(buf)
  end subroutine fmtnum

  subroutine rowv(name, args, nargs, outs, nouts)
    character(len=*), intent(in) :: name
    integer, intent(in) :: nargs, nouts
    real, intent(in) :: args(nargs), outs(nouts)
    character(len=8192) :: line
    character(len=32) :: buf
    integer :: i
    line = trim(name) // ','
    do i = 1, nargs
      call fmtnum(dble(args(i)), buf)
      line = trim(line) // trim(adjustl(buf))
      if (i < nargs) line = trim(line) // ';'
    end do
    line = trim(line) // ','
    do i = 1, nouts
      call fmtnum(dble(outs(i)), buf)
      line = trim(line) // trim(adjustl(buf))
      if (i < nouts) line = trim(line) // ';'
    end do
    write(*,'(A)') trim(line)
  end subroutine rowv

  subroutine rowvd(name, args, nargs, outs, nouts)
    character(len=*), intent(in) :: name
    integer, intent(in) :: nargs, nouts
    double precision, intent(in) :: args(nargs), outs(nouts)
    character(len=8192) :: line
    character(len=32) :: buf
    integer :: i
    line = trim(name) // ','
    do i = 1, nargs
      write(buf,'(ES25.17E3)') args(i)
      line = trim(line) // trim(adjustl(buf))
      if (i < nargs) line = trim(line) // ';'
    end do
    line = trim(line) // ','
    do i = 1, nouts
      write(buf,'(ES25.17E3)') outs(i)
      line = trim(line) // trim(adjustl(buf))
      if (i < nouts) line = trim(line) // ';'
    end do
    write(*,'(A)') trim(line)
  end subroutine rowvd

  ! Integer-only setup row (args only, one dummy output).
  subroutine rowi(name, iargs, nargs)
    character(len=*), intent(in) :: name
    integer, intent(in) :: nargs, iargs(nargs)
    real :: a(nargs), o(1)
    a = real(iargs)
    o(1) = 0.
    call rowv(name, a, nargs, o, 1)
  end subroutine rowi

  ! ------------------------------------------------------------------------
  ! Synthetic meteorology (see the header). Index conventions as upstream:
  ! ix 0:nxmax-1, jy 0:nymax-1, level k 1:nz, memory slot m 1:2.
  integer function nf(ix, jy, k, m, a, b, c, d, q)
    integer, intent(in) :: ix, jy, k, m, a, b, c, d, q
    nf = mod(a*ix + b*jy + c*k + d*m, q)
  end function nf

  subroutine setup_met()
    integer :: ix, jy, k, m
    real :: o(1)
    nz = 8
    height(1:8) = (/ 0., 50., 150., 400., 900., 1800., 3500., 8000. /)
    do m = 1, 2
      do k = 1, nz
        do jy = 0, nymax-1
          do ix = 0, nxmax-1
            rho(ix,jy,k,m) = 1.25 - 0.0625*real(k) + real(nf(ix,jy,k,m,37,101,53,17,97))/256.
            pv(ix,jy,k,m)  = -6.0 + real(nf(ix,jy,k,m,41,13,29,7,97))/8.
            qv(ix,jy,k,m)  = real(nf(ix,jy,k,m,11,61,3,23,89))/4096.
            tt(ix,jy,k,m)  = 300. - 4.*real(k) + real(nf(ix,jy,k,m,19,7,31,5,83))/32.
            uu(ix,jy,k,m)  = -8. + real(nf(ix,jy,k,m,23,17,11,3,101))/8.
            vv(ix,jy,k,m)  = 6. - real(nf(ix,jy,k,m,13,29,37,41,103))/16.
          end do
        end do
      end do
      do jy = 0, nymax-1
        do ix = 0, nxmax-1
          tropopause(ix,jy,1,m) = 2000. + 96.*real(nf(ix,jy,0,m,7,19,0,13,79))
          hmix(ix,jy,1,m) = 150. + 16.*real(nf(ix,jy,0,m,31,3,0,11,73))
        end do
      end do
    end do
    do jy = 0, nymax-1
      do ix = 0, nxmax-1
        oro(ix,jy) = 8.*real(nf(ix,jy,0,0,29,43,0,0,89))
      end do
    end do
    o(1) = 0.
    call rowv('setup.met', (/ real(nz), height(1:8) /), 9, o, 1)
    ! sample values: ix, jy, k, m -> rho, pv, qv, tt, uu, vv, tropopause, hmix, oro
    call metcheck(0, 0, 1, 1)
    call metcheck(17, 33, 4, 2)
    call metcheck(360, 180, 8, 1)
    call metcheck(123, 77, 6, 2)
  end subroutine setup_met

  subroutine metcheck(ix, jy, k, m)
    integer, intent(in) :: ix, jy, k, m
    call rowv('setup.metcheck', (/ real(ix), real(jy), real(k), real(m) /), 4, &
         (/ rho(ix,jy,k,m), pv(ix,jy,k,m), qv(ix,jy,k,m), tt(ix,jy,k,m), &
            uu(ix,jy,k,m), vv(ix,jy,k,m), tropopause(ix,jy,1,m), hmix(ix,jy,1,m), &
            oro(ix,jy) /), 9)
  end subroutine metcheck

  ! ------------------------------------------------------------------------
  ! conccalc.
  !
  ! One particle set (setup.particle rows) is gridded under several
  ! configurations of the com_mod switches (setup.conccalc rows). After each
  ! configuration every NON-ZERO cell of gridunc (conccalc.grid) and griduncn
  ! (conccalc.gridn) is printed, and every creceptor value (conccalc.receptor).
  ! The Rust test checks the cell values row by row AND that the port's set of
  ! non-zero cells is the fixture's set.
  !
  ! The sweep straddles: itra1 /= itime (skipped); every age class boundary
  ! (lage = 7200, 21600, 999999999 when maxageclass = 3); the 10800 s
  ! kernel threshold (10799/10800); backward ages (itramem > itra1, abs());
  ! positions west/south of the grid (negative xl, the int()-1 correction),
  ! inside the half-cell boundary strips, east/north of it, ddx above and below
  ! one half; heights in each of the 3 output levels and above the top;
  ! ind_samp 0 and -1 with memind(2) = 1 and 2 (upstream reads the first
  ! density corner from memind(2) and the other three from slot 2); the
  ! north-pole jyp >= nymax clamp (two particles at jy = 179, 180); the
  ! east/north half-cell strips (two particles); negative
  ! xscav_frac1 (max(.,0)); DRYBKDEP and WETBKDEP; ioutputforeachrelease 0/1;
  ! mdomainfill 1; nested_output 0/1; weights 1, 0.5 and 0.7 (0.7 makes the
  ! mother/nest product-order difference visible); a repeated call
  ! (accumulation); and, at the receptors, the hzmax / hxmax / hymax caps and
  ! each early exit (zd > 1, xd^2 > 1, yd^2 > 1, r2 >= 1).
  subroutine emit_conccalc(variant)
    integer, intent(in) :: variant
    integer, parameter :: np = 66, nptot = 70
    double precision :: xs(12), ys(11)
    real :: zs(8)
    integer :: ages(11), i, itime, n, ncfg, icfg, cid, age, ix, jy, kz, ks, kp, ncl, nag
    ! config: ind_samp, memind2, bk(0 none 1 dry 2 wet), foreach, domainfill,
    !         nested, weight*10, polar shift, repeat
    integer :: cfg(9, 8)
    real :: o(1)
    double precision :: pa(13), po(1)

    ! Positions are >= 0 in met grid units (the density interpolation of
    ! ind_samp = -1 indexes rho(int(xtra1),...), which would read outside the
    ! array for xtra1 <= -1); the negative shifts below put the westmost and
    ! southmost particles at negative output-grid coordinates instead.
    xs = (/ 0.13d0, 0.66d0, 1.43d0, 2.58d0, 3.91d0, 5.12d0, 6.74d0, 8.29d0, &
            10.63d0, 12.85d0, 14.47d0, 16.2d0 /)
    ys = (/ 0.21d0, 0.88d0, 1.71d0, 2.46d0, 3.33d0, 4.62d0, 5.9d0, 7.38d0, &
            9.12d0, 10.45d0, 11.8d0 /)
    zs = (/ 4., 22., 61., 140., 480., 1250., 2600., 6200. /)
    ages = (/ 0, 1800, 7199, 7200, 10799, 10800, 21599, 21600, 45000, 140000, 600000 /)

    itime = 86400
    dx = 0.5
    dy = 0.4
    nspec = maxspec
    maxpointspec_act = 3
    nageclass = maxageclass
    if (maxageclass == 3) then
      lage(1:3) = (/ 7200, 21600, 999999999 /)
    else
      lage(1) = 999999999
    end if
    numzgrid = 3
    allocate(outheight(numzgrid))
    outheight = (/ 100., 500., 2000. /)
    numxgrid = 9
    numygrid = 7
    numxgridn = 12
    numygridn = 10
    dxoutn = 0.3
    dyoutn = 0.25
    xoutshiftn = -0.4
    youtshiftn = 0.35
    allocate(gridunc(0:numxgrid-1,0:numygrid-1,numzgrid,maxspec, &
         maxpointspec_act,nclassunc,maxageclass))
    allocate(griduncn(0:numxgridn-1,0:numygridn-1,numzgrid,maxspec, &
         maxpointspec_act,nclassunc,maxageclass))

    numpart = nptot
    do i = 1, np
      xtra1(i) = xs(mod(i*5,12)+1)
      ytra1(i) = ys(mod(i*7,11)+1)
      ztra1(i) = zs(mod(i*3,8)+1)
      age = ages(mod(i*13,11)+1)
      itra1(i) = itime
      if (mod(i,13) == 0) itra1(i) = itime + 900
      if (mod(i,4) == 1) then
        itramem(i) = itime + age
      else
        itramem(i) = itime - age
      end if
      npoint(i) = mod(i,3) + 1
      nclass(i) = mod(i,nclassunc) + 1
      xmass1(i,1) = 0.5 + 0.13*real(i)
      xscav_frac1(i,1) = -0.2 + 0.05*real(mod(i,9))
      if (maxspec >= 2) then
        xmass1(i,2) = 2.0 - 0.017*real(i)
        xscav_frac1(i,2) = 0.3 + 0.01*real(i)
      end if
    end do
    ! two particles by the north pole (jy = 180 -> jyp clamped; jy = 179)
    xtra1(67) = 4.37d0
    ytra1(67) = 180.3d0
    xtra1(68) = 6.81d0
    ytra1(68) = 179.62d0
    ztra1(67) = 22.
    ztra1(68) = 140.
    do i = 67, 68
      itra1(i) = itime
      itramem(i) = itime - 45000
      npoint(i) = i - 65
      nclass(i) = mod(i,nclassunc) + 1
      xmass1(i,1) = 3.1 + 0.2*real(i-67)
      xscav_frac1(i,1) = 0.45
      if (maxspec >= 2) then
        xmass1(i,2) = 0.9
        xscav_frac1(i,2) = -0.1
      end if
    end do
    ! two particles inside the east / north half-cell boundary strips of the
    ! mother grid (xl = 7.55 > numxgrid-1.5; yl = 5.55 > numygrid-1.5)
    xtra1(69) = 13.28d0
    ytra1(69) = 4.4d0
    xtra1(70) = 6.1d0
    ytra1(70) = 9.2d0
    ztra1(69) = 61.
    ztra1(70) = 480.
    do i = 69, 70
      itra1(i) = itime
      itramem(i) = itime - 30000
      npoint(i) = 1
      nclass(i) = 1
      xmass1(i,1) = 1.7
      xscav_frac1(i,1) = 0.8
      if (maxspec >= 2) then
        xmass1(i,2) = 0.35
        xscav_frac1(i,2) = 0.6
      end if
    end do
    do i = 1, nptot
      pa(1) = dble(i)
      pa(2) = dble(itra1(i))
      pa(3) = dble(itramem(i))
      pa(4) = xtra1(i)
      pa(5) = ytra1(i)
      pa(6) = dble(ztra1(i))
      pa(7) = dble(npoint(i))
      pa(8) = dble(nclass(i))
      pa(9) = dble(xmass1(i,1))
      pa(10) = dble(xscav_frac1(i,1))
      pa(11) = dble(xmass1(i,min(2,maxspec)))
      pa(12) = dble(xscav_frac1(i,min(2,maxspec)))
      pa(13) = dble(itime)
      po(1) = 0d0
      call rowvd('setup.particle', pa, 13, po, 1)
    end do

    ! receptors: three next to low particles of different ages, one far away
    numreceptor = 4
    xreceptor(1:4) = (/ 2.61, 6.69, 10.9, 30.0 /)
    yreceptor(1:4) = (/ 1.66, 4.71, 7.6, 30.0 /)
    receptorarea(1:4) = (/ 1.1e9, 2.3e9, 0.7e9, 1.9e9 /)

    o(1) = 0.
    call rowv('setup.grid', (/ real(numxgrid), real(numygrid), real(numzgrid), &
         outheight(1:3), real(numxgridn), real(numygridn), dxoutn, dyoutn, &
         xoutshiftn, youtshiftn, dx, dy, real(nageclass), real(lage(1:nageclass)) /), &
         15 + nageclass, o, 1)
    do n = 1, numreceptor
      call rowv('setup.receptor', (/ real(n), xreceptor(n), yreceptor(n), &
           receptorarea(n) /), 4, o, 1)
    end do

    if (variant == 3) then
      ncfg = 2
      cfg(:,1) = (/  0, 2, 0, 1, 0, 1, 10, 0, 0 /)
      cfg(:,2) = (/ -1, 1, 0, 1, 0, 1,  5, 0, 0 /)
    else if (variant == 2) then
      ncfg = 3
      cfg(:,1) = (/  0, 2, 0, 1, 0, 1, 10, 0, 0 /)
      cfg(:,2) = (/ -1, 2, 1, 0, 0, 1,  7, 0, 0 /)
      cfg(:,3) = (/  0, 2, 0, 1, 0, 0,  5, 1, 0 /)
    else
      ncfg = 7
      cfg(:,1) = (/  0, 2, 0, 0, 0, 1, 10, 0, 0 /)
      cfg(:,2) = (/ -1, 2, 0, 1, 0, 1,  5, 0, 0 /)
      cfg(:,3) = (/ -1, 1, 1, 1, 1, 1,  7, 0, 0 /)
      cfg(:,4) = (/  0, 2, 2, 1, 0, 1,  7, 0, 0 /)
      cfg(:,5) = (/ -1, 1, 0, 1, 0, 0,  7, 1, 0 /)
      cfg(:,6) = (/  0, 2, 0, 1, 0, 1,  5, 0, 1 /)
      cfg(:,7) = (/ -1, 2, 1, 1, 0, 1, 10, 1, 0 /)
    end if

    memind(1) = 1
    memind(2) = 2
    do icfg = 1, ncfg
      ind_samp = cfg(1,icfg)
      memind(2) = cfg(2,icfg)
      memind(1) = 3 - memind(2)
      DRYBKDEP = (cfg(3,icfg) == 1)
      WETBKDEP = (cfg(3,icfg) == 2)
      ioutputforeachrelease = cfg(4,icfg)
      mdomainfill = cfg(5,icfg)
      nested_output = cfg(6,icfg)
      dxout = 0.8
      dyout = 0.6
      xoutshift = -0.6
      if (cfg(8,icfg) == 1) then
        youtshift = -71.5
      else
        youtshift = -0.35
      end if
      cid = 100*variant + icfg
      call rowv('setup.conccalc', (/ real(cid), real(ind_samp), real(memind(2)), &
           real(cfg(3,icfg)), real(ioutputforeachrelease), real(mdomainfill), &
           real(nested_output), real(cfg(7,icfg))/10., dxout, dyout, xoutshift, &
           youtshift, real(cfg(9,icfg)) /), 13, o, 1)
      gridunc = 0.
      griduncn = 0.
      creceptor = 0.
      call conccalc(itime, real(cfg(7,icfg))/10.)
      if (cfg(9,icfg) == 1) call conccalc(itime, 1.0)
      do nag = 1, nageclass
        do ncl = 1, nclassunc
          do kp = 1, maxpointspec_act
            do ks = 1, nspec
              do kz = 1, numzgrid
                do jy = 0, numygrid-1
                  do ix = 0, numxgrid-1
                    if (gridunc(ix,jy,kz,ks,kp,ncl,nag) /= 0.) then
                      call rowv('conccalc.grid', (/ real(cid), real(ix), real(jy), &
                           real(kz), real(ks), real(kp), real(ncl), real(nag) /), 8, &
                           (/ gridunc(ix,jy,kz,ks,kp,ncl,nag) /), 1)
                    end if
                  end do
                end do
                do jy = 0, numygridn-1
                  do ix = 0, numxgridn-1
                    if (griduncn(ix,jy,kz,ks,kp,ncl,nag) /= 0.) then
                      call rowv('conccalc.gridn', (/ real(cid), real(ix), real(jy), &
                           real(kz), real(ks), real(kp), real(ncl), real(nag) /), 8, &
                           (/ griduncn(ix,jy,kz,ks,kp,ncl,nag) /), 1)
                    end if
                  end do
                end do
              end do
            end do
          end do
        end do
      end do
      do n = 1, numreceptor
        do ks = 1, nspec
          call rowv('conccalc.receptor', (/ real(cid), real(n), real(ks) /), 3, &
               (/ creceptor(n,ks) /), 1)
        end do
      end do
    end do
    deallocate(gridunc, griduncn, outheight)
  end subroutine emit_conccalc

  ! ------------------------------------------------------------------------
  ! drydepokernel / drydepokernel_nest.
  !
  ! One call row per (position, deposit, geometry); both grids are zeroed before
  ! every call, so each printed cell is that call's contribution alone. Then
  ! every non-zero cell of drygridunc (drydepokernel.cell) and drygriduncn
  ! (drydepokernel_nest.cell).
  !
  ! Geometry 1 is a general one; geometry 2 makes xl = x exactly (dx = dxout,
  ! zero shift) so that ddx = 0.5 exactly (the tie takes the ELSE branch) and
  ! negative x in (-1, 0) (int() truncates toward zero, ix = 0) are hit
  ! exactly. The deposits include a zero, a negative and DRYDEPSPEC false.
  subroutine emit_drydepokernel(variant)
    integer, intent(in) :: variant
    real :: xg1(9), yg1(8), xg2(5), yg2(4), deps(2,4), x, y, o(1)
    logical :: specs(2,3)
    integer :: icall, cid, ig, ix, jy, ks, kp, nunc, nage, id, is, i, j, ni, nj
    real(dep_prec) :: deposit(maxspec)

    xg1 = (/ -2.13, -0.61, -0.29, 0.23, 1.37, 4.41, 7.96, 13.62, 15.27 /)
    yg1 = (/ -1.07, -0.33, 0.41, 2.29, 5.58, 9.17, 10.36, 11.9 /)
    xg2 = (/ -0.25, 0.25, 2.5, 3.0, 8.75 /)
    yg2 = (/ -0.75, 1.5, 4.25, 6.5 /)
    deps(:,1) = (/ 0.37, 1.4 /)
    deps(:,2) = (/ -0.12, 0.0 /)
    deps(:,3) = (/ 2.5e-3, 7.1 /)
    deps(:,4) = (/ 0.0, 0.0 /)
    specs(:,1) = (/ .true., .true. /)
    specs(:,2) = (/ .true., .false. /)
    specs(:,3) = (/ .false., .true. /)

    nspec = maxspec
    maxpointspec_act = 3
    numxgrid = 9
    numygrid = 7
    numxgridn = 12
    numygridn = 10
    allocate(drygridunc(0:numxgrid-1,0:numygrid-1,maxspec,maxpointspec_act, &
         nclassunc,maxageclass))
    allocate(drygriduncn(0:numxgridn-1,0:numygridn-1,maxspec,maxpointspec_act, &
         nclassunc,maxageclass))
    o(1) = 0.

    icall = 0
    do ig = 1, 2
      if (ig == 1) then
        dx = 0.5
        dy = 0.4
        dxout = 0.8
        dyout = 0.6
        xoutshift = 0.25
        youtshift = 0.1
        dxoutn = 0.3
        dyoutn = 0.25
        xoutshiftn = -0.4
        youtshiftn = 0.35
        ni = 9
        nj = 8
      else
        dx = 0.5
        dy = 0.5
        dxout = 0.5
        dyout = 0.5
        xoutshift = 0.
        youtshift = 0.
        dxoutn = 0.5
        dyoutn = 0.5
        xoutshiftn = 0.
        youtshiftn = 0.
        ni = 5
        nj = 4
      end if
      do i = 1, ni
        do j = 1, nj
          if (ig == 1) then
            x = xg1(i)
            y = yg1(j)
          else
            x = xg2(i)
            y = yg2(j)
          end if
          icall = icall + 1
          cid = 1000*variant + icall
          id = mod(icall,4) + 1
          is = mod(icall,3) + 1
          deposit(1) = deps(1,id)
          if (maxspec >= 2) deposit(2) = deps(2,id)
          DRYDEPSPEC(1) = specs(1,is)
          if (maxspec >= 2) DRYDEPSPEC(2) = specs(2,is)
          nunc = mod(icall,nclassunc) + 1
          nage = mod(icall,maxageclass) + 1
          kp = mod(icall,maxpointspec_act) + 1
          call rowv('setup.drydepokernel', (/ real(cid), x, y, &
               real(deposit(1)), real(deposit(min(2,maxspec))), merge(1.,0.,specs(1,is)), &
               merge(1.,0.,specs(2,is)), real(nunc), real(nage), real(kp), &
               dx, dy, dxout, dyout, xoutshift, youtshift, dxoutn, dyoutn, &
               xoutshiftn, youtshiftn, real(numxgrid), real(numygrid), &
               real(numxgridn), real(numygridn) /), 24, o, 1)
          drygridunc = 0.
          drygriduncn = 0.
          call drydepokernel(nunc, deposit, x, y, nage, kp)
          call drydepokernel_nest(nunc, deposit, x, y, nage, kp)
          do ks = 1, nspec
            do jy = 0, numygrid-1
              do ix = 0, numxgrid-1
                if (drygridunc(ix,jy,ks,kp,nunc,nage) /= 0.) then
                  call rowv('drydepokernel.cell', (/ real(cid), real(ix), real(jy), &
                       real(ks) /), 4, (/ real(drygridunc(ix,jy,ks,kp,nunc,nage)) /), 1)
                end if
              end do
            end do
            do jy = 0, numygridn-1
              do ix = 0, numxgridn-1
                if (drygriduncn(ix,jy,ks,kp,nunc,nage) /= 0.) then
                  call rowv('drydepokernel_nest.cell', (/ real(cid), real(ix), &
                       real(jy), real(ks) /), 4, &
                       (/ real(drygriduncn(ix,jy,ks,kp,nunc,nage)) /), 1)
                end if
              end do
            end do
          end do
        end do
      end do
    end do
    deallocate(drygridunc, drygriduncn)
  end subroutine emit_drydepokernel

