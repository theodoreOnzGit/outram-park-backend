  ! ------------------------------------------------------------------------
  ! plumetraj. Upstream's only output is the formatted record it writes to
  ! unit unitouttraj (96). The driver attaches that unit to a scratch file,
  ! reads each record back field by field with the SAME edit descriptors, and
  ! prints the values (plumetraj.out, double precision); a field upstream
  ! printed as asterisks is printed as NaN. These values are therefore exact
  ! only to the precision of upstream's own format (e.g. f8.1); the Rust test
  ! checks the port against them to half a unit of the last printed digit.
  !
  ! Release points: 1 -- 40 particles in three blobs; 2 -- 3 particles
  ! (n < ncluster: clustering returns at once and upstream writes cluster
  ! fields it never assigned); 3 -- released too long ago (|ireleasestart -
  ! itime| > lage(nageclass): skipped); 4 -- exactly ncluster particles;
  ! 5 -- no particles (no record); 6 -- |ireleasestart - itime| equal to
  ! lage(nageclass) exactly (kept: the test is a strict >). (start+end)/2 is integer division of a
  ! negative odd sum for point 4. Particles straddle both hemispheres (the
  ! PV sign test), pvi = +-2, the tropopause and the mixing height.
  subroutine emit_plumetraj()
    integer, parameter :: npl = 67
    real :: zs2(7)
    integer :: i, k, ic, itime, ios, ifield, ipos, w(41), d(41)
    double precision :: pa(13), po(1), vals(41)
    character(len=400) :: line
    character(len=16) :: fmtf
    real :: o(1)

    zs2 = (/ 12., 85., 340., 760., 1500., 2900., 5200. /)
    xlon0 = -12.0
    ylat0 = -6.0
    dx = 0.5
    dy = 0.4
    nageclass = maxageclass
    lage(nageclass) = 200000
    numpoint = 6
    allocate(ireleasestart(numpoint), ireleaseend(numpoint))
    memtime(1) = 0
    memtime(2) = 10800

    ! field widths / decimals of the record:
    ! i5,i8,2f9.4,4f8.1,f8.2,4f8.1,3f6.1,5(2f8.3,f7.0,f6.1,f8.1)
    w(1) = 5;  d(1) = -1
    w(2) = 8;  d(2) = -1
    w(3:4) = 9;   d(3:4) = 4
    w(5:8) = 8;   d(5:8) = 1
    w(9) = 8;     d(9) = 2
    w(10:13) = 8; d(10:13) = 1
    w(14:16) = 6; d(14:16) = 1
    do k = 0, 4
      w(17+5*k) = 8; d(17+5*k) = 3
      w(18+5*k) = 8; d(18+5*k) = 3
      w(19+5*k) = 7; d(19+5*k) = 0
      w(20+5*k) = 6; d(20+5*k) = 1
      w(21+5*k) = 8; d(21+5*k) = 1
    end do

    open(unitouttraj, status='scratch', form='formatted')
    do ic = 1, 2
      if (ic == 1) then
        itime = 3600
        memind(1) = 1
        memind(2) = 2
      else
        itime = 9000
        memind(1) = 2
        memind(2) = 1
      end if
      ireleasestart(1:6) = (/ itime-7200, itime-3600, itime-300000, itime-10800, itime-100, &
           itime-200000 /)
      ireleaseend(1:6) = ireleasestart(1:6) + (/ 3600, 0, 3600, 7201, 0, 50 /)
      numpart = npl
      do i = 1, npl
        if (i <= 40) then
          npoint(i) = 1
          select case (mod(i,3))
          case (0)
            xtra1(i) = 10.d0 + 0.37d0*dble(mod(i*7,9))
            ytra1(i) = 8.d0 + 0.53d0*dble(mod(i*5,7))
          case (1)
            xtra1(i) = 30.d0 + 0.61d0*dble(mod(i*3,8))
            ytra1(i) = 22.d0 + 0.29d0*dble(mod(i*2,5))
          case (2)
            xtra1(i) = 55.d0 + 0.83d0*dble(mod(i,6))
            ytra1(i) = 14.d0 + 0.47d0*dble(mod(i*4,7))
          end select
        else if (i <= 43) then
          npoint(i) = 2
          xtra1(i) = 20.3d0 + 1.7d0*dble(i-41)
          ytra1(i) = 3.1d0 + 2.3d0*dble(i-41)
        else if (i <= 49) then
          npoint(i) = 3
          xtra1(i) = 40.1d0 + 0.5d0*dble(i-44)
          ytra1(i) = 18.2d0
        else if (i <= 54) then
          npoint(i) = 4
          xtra1(i) = 5.4d0 + 6.1d0*dble(i-50)
          ytra1(i) = 2.2d0 + 5.3d0*dble(mod((i-50)*3,5))
        else if (i <= 60) then
          npoint(i) = 1        ! these six are at another time step
          xtra1(i) = 33.3d0
          ytra1(i) = 9.9d0
        else if (i <= 66) then
          npoint(i) = 6
          xtra1(i) = 70.2d0 + 0.9d0*dble(i-61)
          ytra1(i) = 25.4d0 - 1.3d0*dble(i-61)
        else
          ! On grid point (75, 17) = (25.5 E, 0.8 N) and on level 2 (50 m):
          ! pv(75,17,2,m) = -6 + (63 + 7m mod 97)/8, so the time-interpolated
          ! pvi is 2.17 (call 1) and 2.02 (call 2) -- just north of the
          ! equator and just above the 2 pvu threshold.
          npoint(i) = 1
          xtra1(i) = 75.d0
          ytra1(i) = 17.d0
        end if
        ztra1(i) = zs2(mod(i*3,7)+1)
        if (i == 67) ztra1(i) = 50.
        itra1(i) = itime
        if (i > 54 .and. i <= 60) itra1(i) = itime + 300
      end do
      do i = 1, npl
        pa(1) = dble(ic)
        pa(2) = dble(i)
        pa(3) = dble(itra1(i))
        pa(4) = xtra1(i)
        pa(5) = ytra1(i)
        pa(6) = dble(ztra1(i))
        pa(7) = dble(npoint(i))
        pa(8) = dble(itime)
        pa(9) = dble(memind(1))
        pa(10) = dble(memind(2))
        pa(11) = dble(memtime(1))
        pa(12) = dble(memtime(2))
        pa(13) = dble(lage(nageclass))
        po(1) = 0d0
        call rowvd('setup.plume_particle', pa, 13, po, 1)
      end do
      do k = 1, numpoint
        call rowi('setup.release', (/ ic, k, ireleasestart(k), ireleaseend(k) /), 4)
      end do
      call plumetraj(itime)
    end do
    o(1) = 0.
    call rowv('setup.plume_grid', (/ xlon0, ylat0, dx, dy /), 4, o, 1)

    rewind(unitouttraj)
    ic = 0
    do
      read(unitouttraj, '(A)', iostat=ios) line
      if (ios /= 0) exit
      ic = ic + 1
      ipos = 1
      do ifield = 1, 41
        if (ifield <= 2) then
          read(line(ipos:ipos+w(ifield)-1), *, iostat=ios) vals(ifield)
        else
          write(fmtf, '(A,I0,A,I0,A)') '(F', w(ifield), '.', d(ifield), ')'
          read(line(ipos:ipos+w(ifield)-1), fmtf, iostat=ios) vals(ifield)
        end if
        if (ios /= 0 .or. index(line(ipos:ipos+w(ifield)-1), '*') > 0) &
             vals(ifield) = transfer(-2251799813685248_8, 1d0)   ! a quiet NaN
        ipos = ipos + w(ifield)
      end do
      call rowvd('plumetraj.out', (/ dble(ic), vals(1), vals(2) /), 3, vals(3:41), 39)
    end do
    close(unitouttraj)
    deallocate(ireleasestart, ireleaseend)
  end subroutine emit_plumetraj

  ! ------------------------------------------------------------------------
  ! partpos_average. For each particle the part_av_* accumulators are zeroed,
  ! then the routine is called twice (itime 3600 with memind = (1,2), itime 9000
  ! with memind = (2,1)) and the accumulators are printed after each call.
